#!/usr/bin/env python3
"""Generate SDK model enums from the ``everything`` repo's canonical sources.

Several enums (``JobType``, ``ExportFormat``, ``TableColumnType``,
``RendererCodes``, ``EntityTypes``, ``JobStatus``) are defined canonically in the
``everything`` monorepo and have historically been hand-copied into this SDK,
where they drift out of sync. This script regenerates the SDK copies from the
canonical sources so the drift is mechanical rather than manual.

Reconciliation rules (so regeneration is safe and non-breaking):

* Exposure is **fail closed**: a canonical member is only included if it is in
  the per-enum ``allowlist`` (customer-facing). Members in the ``denylist`` are
  internal/support values that must never be exposed (see agent.md
  "Customer-Facing Focus"). Enums marked ``expose_all`` skip this gate and
  expose every canonical member.
* Every canonical member of a gated enum must be explicitly classified as either
  ``allowlist`` or ``denylist``. A canonical member that is in neither is a
  **failure** (see ``_classification_errors``): a newly added server enum value
  cannot leak to customers by default - someone must decide. This is the key
  safety property: doing nothing leaves a new value out of the SDK.
* Any member already present in the SDK copy but absent from the canonical
  source is **preserved** (unless denied), so we never remove a value customers
  may already depend on.

This means the generator never exposes a value unless it was deliberately
allowlisted, and never silently drops a public enum member.

Some enums are additionally enriched with per-member documentation: when a
target sets ``descriptions_source_rel``, the JSDoc comments on the matching
TypeScript enum are folded into the generated class docstring (and so into the
``llms`` artifacts and ``help()``).

Usage (from the repository root):

    python scripts/generate_models.py                       # regenerate
    python scripts/generate_models.py --check               # fail if stale
    python scripts/generate_models.py --everything-dir DIR  # locate everything

The ``everything`` checkout is located via (in order): ``--everything-dir``, the
``EVERYTHING_DIR`` environment variable, then the sibling ``../everything``.
"""

