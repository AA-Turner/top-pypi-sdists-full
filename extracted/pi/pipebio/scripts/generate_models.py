def _resolve_everything_dir(explicit: Optional[str]) -> Path:
    """Locate the everything checkout, raising a clear error if not found."""
    candidates = []
    if explicit:
        candidates.append(Path(explicit))
    env_dir = os.environ.get("EVERYTHING_DIR")
    if env_dir:
        candidates.append(Path(env_dir))
    candidates.append(REPO_ROOT.parent / "everything")

    for candidate in candidates:
        if candidate.is_dir():
            return candidate.resolve()

    raise SystemExit(
        "Could not locate the 'everything' repo. Pass --everything-dir, set "
        "EVERYTHING_DIR, or check out everything as a sibling of this repo."
    )


def _parse_python_enum(source: str, enum_class: str) -> List[Tuple[str, str]]:
    """Return ``(name, value)`` pairs for a Python ``Enum`` class, in order."""
    tree = ast.parse(source)
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == enum_class:
            members: List[Tuple[str, str]] = []
            for stmt in node.body:
                if not isinstance(stmt, ast.Assign):
                    continue
                if len(stmt.targets) != 1 or not isinstance(stmt.targets[0], ast.Name):
                    continue
                value_node = stmt.value
                if isinstance(value_node, ast.Constant) and isinstance(value_node.value, str):
                    members.append((stmt.targets[0].id, value_node.value))
            return members
    raise SystemExit(f"Enum class '{enum_class}' not found in source.")


# Matches `NAME = 'VALUE',` / `NAME = "VALUE"` lines inside a TS enum body.
_TS_MEMBER_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*['\"]([^'\"]*)['\"]")


def _typescript_enum_body(source: str, enum_class: str) -> Optional[str]:
    """Return the text between the braces of a TS ``enum`` block, or ``None``.

    Scans for the brace that balances the opening ``{`` so a brace inside a
    member value or comment does not truncate the body.
    """
    match = re.search(rf"export\s+enum\s+{re.escape(enum_class)}\s*\{{", source)
    if not match:
        return None
    rest = source[match.end():]
    depth = 1
    for index, char in enumerate(rest):
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return rest[:index]
    return None


def _parse_typescript_enum(source: str, enum_class: str) -> List[Tuple[str, str]]:
    """Return ``(name, value)`` pairs for a TS ``enum`` block, in order."""
    body = _typescript_enum_body(source, enum_class)
    if body is None:
        raise SystemExit(f"Enum '{enum_class}' not found in TypeScript source.")

    members: List[Tuple[str, str]] = []
    for line in body.splitlines():
        member = _TS_MEMBER_RE.match(line)
        if member:
            members.append((member.group(1), member.group(2)))
    return members


def _parse_typescript_descriptions(source: str, enum_class: str) -> Dict[str, str]:
    """Return ``name -> description`` from JSDoc comments on TS enum members.

    Each ``/** ... */`` block (single- or multi-line) immediately preceding a
    member is associated with that member. JSDoc markers are stripped, the text
    is collapsed to a single line, and the ``@deprecated`` tag is normalised to a
    human-readable ``Deprecated:`` prefix. Members without a JSDoc comment are
    simply absent from the result.
    """
    body = _typescript_enum_body(source, enum_class)
    if body is None:
        return {}

    descriptions: Dict[str, str] = {}
    parts: List[str] = []
    collecting = False
    for raw_line in body.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("/**"):
            collecting = True
            inner = line[3:]
            if inner.endswith("*/"):
                inner = inner[:-2]
                collecting = False
            inner = inner.strip().lstrip("*").strip()
            parts = [inner] if inner else []
            continue
        if collecting:
            if line.endswith("*/"):
                collecting = False
                inner = line[:-2].strip().lstrip("*").strip()
            else:
                inner = line.lstrip("*").strip()
            if inner:
                parts.append(inner)
            continue
        member = _TS_MEMBER_RE.match(raw_line)
        if member:
            if parts:
                text = re.sub(r"\s+", " ", " ".join(parts)).strip()
                text = text.replace("@deprecated", "Deprecated:").strip()
                descriptions[member.group(1)] = text
            parts = []
    return descriptions


def _existing_sdk_members(output_path: Path, enum_class: str) -> List[Tuple[str, str]]:
    """Return the members currently committed in the SDK copy (empty if absent)."""
    if not output_path.exists():
        return []
    try:
        return _parse_python_enum(output_path.read_text(encoding="utf-8"), enum_class)
    except SystemExit as exc:
        raise SystemExit(
            f"Could not parse existing SDK enum '{enum_class}' in {output_path}."
        ) from exc


def _reconcile(
    canonical: List[Tuple[str, str]],
    existing: List[Tuple[str, str]],
    allowlist: Set[str],
    denylist: Set[str],
    expose_all: bool = False,
) -> List[Tuple[str, str]]:
    """Merge canonical and existing members, failing closed on exposure.

    A canonical member is only emitted if ``expose_all`` is set or it is in the
    ``allowlist`` (and never if it is in the ``denylist``). Canonical members
    come first in source order, followed by any existing SDK-only members, which
    are preserved for backwards compatibility regardless of the allowlist (so we
    never drop a value customers may already import) unless they are denied.
    """
    result: List[Tuple[str, str]] = []
    seen: Set[str] = set()

    for name, value in canonical:
        if name in seen or name in denylist:
            continue
        if not expose_all and name not in allowlist:
            # Fail closed: unlisted canonical members are not exposed.
            continue
        result.append((name, value))
        seen.add(name)

    for name, value in existing:
        if name in seen or name in denylist:
            continue
        result.append((name, value))
        seen.add(name)

    return result


def _classification_errors(target: Target, canonical: List[Tuple[str, str]]) -> List[str]:
    """Return canonical member names that are neither allowlisted nor denied.

    Gated enums must classify every canonical member so a newly added server
    value cannot leak to customers (or be silently dropped) by default.
    """
    if target.expose_all:
        return []
    classified = target.allowlist | target.denylist
    return [name for name, _ in canonical if name not in classified]


def _escape_docstring(text: str) -> str:
    """Neutralise characters that could break the generated triple-quoted docstring.

    A member description sourced from canonical JSDoc could otherwise contain a
    ``\"\"\"`` run that prematurely terminates the class docstring, or end in a
    backslash that escapes its closing quote. Backslashes are doubled first (so a
    trailing one cannot escape the delimiter) and any embedded triple-quote run is
    escaped.
    """
    text = text.replace("\\", "\\\\")
    text = text.replace('"""', '\\"\\"\\"')
    return text


def _build_class_doc(target: Target, members: List[Tuple[str, str]], descriptions: Dict[str, str]) -> str:
    """Return the class docstring, with a ``Members:`` section when documented.

    Per-member descriptions (sourced from the canonical TypeScript JSDoc) are
    appended so they surface in ``help()`` and the generated llms artifacts. Only
    emitted members that have a description are listed.
    """
    described = [(name, descriptions[name]) for name, _ in members if name in descriptions]
    if not described:
        return target.class_doc
    member_lines = "\n".join(f"      {name}: {_escape_docstring(desc)}" for name, desc in described)
    return f"{target.class_doc}\n\n    Members:\n{member_lines}"


def _render(target: Target, members: List[Tuple[str, str]], descriptions: Optional[Dict[str, str]] = None) -> str:
    """Render the full generated module text for a target."""
    class_doc = _build_class_doc(target, members, descriptions or {})
    lines: List[str] = [
        GENERATED_BANNER.rstrip("\n"),
        f'"""{target.module_doc}"""',
        "",
        "from enum import Enum",
        "",
        "",
        f"class {target.enum_class}(Enum):",
        f'    """{class_doc}"""',
        "",
    ]
    for name, value in members:
        # Use repr() so a value containing a quote or trailing backslash cannot
        # produce an invalid (unimportable) enum module.
        lines.append(f"    {name} = {value!r}")
    if target.extra_body:
        lines.append(target.extra_body.rstrip("\n"))
    return "\n".join(lines).rstrip() + "\n"


def _generate(everything_dir: Path) -> Dict[Path, str]:
    """Return a map of output path -> generated text for every target.

    Raises ``SystemExit`` if any gated enum has unclassified canonical members,
    forcing an explicit allow/deny decision (fail closed).
    """
    outputs: Dict[Path, str] = {}
    errors: List[str] = []
    for target in TARGETS:
        source_path = everything_dir / target.source_rel
        if not source_path.exists():
            raise SystemExit(f"Canonical source not found: {source_path}")
        source = source_path.read_text(encoding="utf-8")

        if target.source_kind == "python":
            canonical = _parse_python_enum(source, target.enum_class)
        elif target.source_kind == "typescript":
            canonical = _parse_typescript_enum(source, target.enum_class)
        else:
            raise SystemExit(f"Unknown source_kind: {target.source_kind}")

        unclassified = _classification_errors(target, canonical)
        if unclassified:
            errors.append(
                f"{target.enum_class}: unclassified canonical members "
                f"{sorted(unclassified)}. Add each to the `allowlist` "
                f"(customer-facing) or `denylist` (internal) for {target.enum_class} "
                f"in scripts/generate_models.py."
            )
            continue

        output_path = REPO_ROOT / target.output_rel
        existing = _existing_sdk_members(output_path, target.enum_class)
        members = _reconcile(
            canonical, existing, target.allowlist, target.denylist, target.expose_all
        )

        descriptions: Dict[str, str] = {}
        if target.descriptions_source_rel and target.descriptions_enum:
            descriptions_path = everything_dir / target.descriptions_source_rel
            if not descriptions_path.exists():
                raise SystemExit(f"Descriptions source not found: {descriptions_path}")
            descriptions = _parse_typescript_descriptions(
                descriptions_path.read_text(encoding="utf-8"), target.descriptions_enum
            )

        outputs[output_path] = _render(target, members, descriptions)

    if errors:
        raise SystemExit(
            "Enum classification failed (fail closed - new server values must be "
            "explicitly classified):\n  " + "\n  ".join(errors)
        )
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if files are stale.")
    parser.add_argument("--everything-dir", help="Path to the everything repo checkout.")
    args = parser.parse_args()

    everything_dir = _resolve_everything_dir(args.everything_dir)
    outputs = _generate(everything_dir)

    if args.check:
        stale = [
            path.relative_to(REPO_ROOT).as_posix()
            for path, text in outputs.items()
            if (path.read_text(encoding="utf-8") if path.exists() else None) != text
        ]
        if stale:
            print(
                f"Generated models are stale: {', '.join(sorted(stale))}. "
                f"Run `python scripts/generate_models.py` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print("Generated models are up to date.")
        return 0

    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(REPO_ROOT).as_posix()}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
