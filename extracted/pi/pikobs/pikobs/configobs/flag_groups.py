def is_radiance(family: str) -> bool:
    """A family on channels: its blacklist (bit 8) is left out of the shares."""
    try:
        import pikobs
        return str(pikobs.family(str(family).replace('.db', ''))[5]) \
            .strip().upper().startswith('CANAL')
    except Exception:
        return groups_for(family) in (_HYPERSPECTRAL, _MICROWAVE)


def reasons_for(family: str) -> List[Tuple]:
    return REASONS_RADIANCE if is_radiance(family) else REASONS_DEFAULT


def first_match(groups: Sequence, bits: Sequence[int]):
    """The first combination of the list the bits satisfy, else None."""
    return next((g for g in groups if matches(g, bits)), None)
