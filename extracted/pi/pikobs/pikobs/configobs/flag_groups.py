def groups_for(family: str) -> List[Tuple]:
    """Bit combinations to draw as pie charts for this family."""
    key = str(family).replace('.db', '')
    return FLAG_GROUPS.get(key, DEFAULT_GROUPS)


def group_title(group: Tuple) -> str:
    """The title a combination carries, else its entry in GROUP_TITLES."""
    return getattr(group, "title", None) or \
        GROUP_TITLES.get(tuple(group), f"Bits {tuple(group)}")


def bits_active(value: int) -> List[int]:
    """Positions of the bits set in value; [0] keeps its meaning for 0."""
    value = int(value)
    if value == 0:
        return []
    return [i for i in range(24) if value & (1 << i)]


def matches(group: Sequence, bits: Sequence[int]) -> bool:
    """Does this set of active bits satisfy the combination?

    The tuple is read as sets of conditions separated by ``'or'``; a
    ``'nX'`` entry means bit X must NOT be set, and applies to the whole
    combination.
    """
    excluded, sets, current = [], [], []
    for item in group:
        if isinstance(item, str) and item.startswith('n') and item != 'or':
            excluded.append(int(item[1:]))
        elif item == 'or':
            sets.append(current)
            current = []
        else:
            current.append(int(item))
    if current:
        sets.append(current)
    if any(b in bits for b in excluded):
        return False
    if not sets:                  # only exclusions: ("n12",) is "not assimilated"
        return True
    return any(all(b in bits for b in cond) for cond in sets if cond)


# ---- every observation once: assimilated or not, and why --------------------

class Titled(tuple):
    """A combination that carries its own title: a kind or a reason."""

    def __new__(cls, pattern, title):
        obj = super().__new__(cls, pattern)
        obj.title = title
        return obj


def _titled(pairs):
    return [Titled(pattern, title) for pattern, title in pairs]


