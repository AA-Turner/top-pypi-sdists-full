"""
PikObs Unified Testing Suite
===========================

This module provides a unified, automated framework for functional testing of 
PikObs data generation and analysis tools (e.g., "timeserie", "scatter", etc.).

Its primary goal is to ensure that changes to the codebase do not introduce
unexpected regressions in the output (files, databases, images).

Core Concept: Reference-Based Testing
--------------------------------------

The methodology is based on comparing the results generated by a current run 
("on-the-fly") against a set of pre-validated, stored results known as the 
"reference" or "golden" dataset.

- If the current output is identical to the reference, the test **PASSES**.
- If there are any differences, the test **FAILS**, alerting the developer.

Workflows
---------

There are two primary workflows for using this test suite: creating the initial
reference, and updating it during development.

**A. Bootstrap Workflow (First-Time Run)**

1.  **Run the Test**: Execute the test function pointing to a reference directory
    that does not yet exist.
    .. code-block:: python
       import pikobs
       pikobs.unittest_timeserie("/path/to/new/reference_dir")
2.  **Auto-Population**: The script runs the PikObs tool and, finding no reference,
    it automatically creates the directory and populates it with the new output.
3.  **Manual Verification**: The test **PASSES** with a warning. You **must** now
    manually inspect every file in the new reference directory to ensure it is
    100% correct. Once verified, commit these files to version control.

**B. Recommended Development Workflow (Updating an Existing Reference)**

This is the standard process when you intentionally change the code in a way
that affects the output.

1.  **Modify Your Code**: Make your changes to `pikobs.timeserie`, fix a bug, or
    add a new feature.

2.  **Run the Test Normally**: Run the test without any special flags.
    .. code-block:: python
       pikobs.unittest_timeserie("/path/to/existing/reference_dir")
    The test **is expected to FAIL**. This is good; it confirms your code
    change had an effect. The new, differing output is saved in the temporary
    `onthefly_*` directory.

3.  **Manually Verify the New Output**: Go into the `onthefly_*` directory.
    Inspect the generated files. Are they correct? Do they reflect the changes
    you intended? This is the most critical step.

4.  **Update the Reference**: If the new output is correct, run the test again,
    this time setting `update_reference=True`.
    .. code-block:: python
       pikobs.unittest_timeserie("/path/to/existing/reference_dir", update_reference=True)
    This will delete the old reference and replace it with your newly-verified
    output. The test will pass and issue a warning that the reference was updated.

5.  **Commit**: Commit both your code changes and the updated reference files
    to version control together. They are now the new "ground truth".

Usage via `python -c`
---------------------

.. code-block:: bash

   # Run a standard regression test
   python -c "import pikobs; pikobs.unittest_timeserie('/path/to/ref')"

   # Run a test and update the reference (Workflow Step 4)
   python -c "import pikobs; pikobs.unittest_timeserie('/path/to/ref', update_reference=True)"

.. warning::
   The validity of this testing system depends entirely on the **correctness
   of the reference files**. It is the user's responsibility to **manually verify**
   any new or updated reference data.

"""
