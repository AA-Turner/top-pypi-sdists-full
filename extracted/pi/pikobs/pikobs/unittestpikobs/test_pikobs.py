def call_pikobs_module(func_name, kwargs):
    """Executes a pikobs function using subprocess."""
    print(f"[*] Building command for pikobs.{func_name}...")
    arg_call = f"import pikobs; pikobs.{func_name}.arg_call()"
    command = ["python", "-c", arg_call]
    for k, v in kwargs.items():
        command.append(f"--{k}")
        command.extend(str(v).split())
    print(f"[*] Executing command in subprocess: {' '.join(command)}")
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"[!] Subprocess execution failed with return code {result.returncode}")
        raise RuntimeError(f"Execution failed:\n{result.stderr}")
    print(f"[*] Subprocess executed successfully.")
    return result.stdout, result.stderr

def files_identical(ref_file, gen_file):
    """Routes the comparison to the specific file type checker."""
    if ref_file.endswith('.db'):
        return sqlite_files_are_identical(ref_file, gen_file)
    if ref_file.lower().endswith(('.png', '.jpg', '.jpeg', '.tiff', '.bmp', '.gif')):
        return images_are_identical(ref_file, gen_file)
    with open(ref_file, 'rb') as f1, open(gen_file, 'rb') as f2:
        return f1.read() == f2.read()

def sqlite_files_are_identical(file1, file2):
    """Compares tables and row data of two SQLite databases."""
    print(f"    -> Comparing SQLite databases: {os.path.basename(file1)}")
    with sqlite3.connect(file1) as conn1, sqlite3.connect(file2) as conn2:
        cursor1, cursor2 = conn1.cursor(), conn2.cursor()
        cursor1.execute("SELECT name FROM sqlite_master WHERE type='table';")
        tables1 = set(row[0] for row in cursor1.fetchall())
        cursor2.execute("SELECT name FROM sqlite_master WHERE type='table';")
        tables2 = set(row[0] for row in cursor2.fetchall())
        if tables1 != tables2:
            print(f"    [!] Database tables mismatch in {os.path.basename(file1)}")
            return False
        for name in tables1:
            cursor1.execute(f"SELECT * FROM `{name}` ORDER BY 1;")
            rows1 = sorted(cursor1.fetchall())
            cursor2.execute(f"SELECT * FROM `{name}` ORDER BY 1;")
            rows2 = sorted(cursor2.fetchall())
            if rows1 != rows2:
                print(f"    [!] Data mismatch in table '{name}' of {os.path.basename(file1)}")
                return False
    return True

def images_are_identical(img1_path, img2_path):
    """Compares two images pixel by pixel."""
    print(f"    -> Comparing images: {os.path.basename(img1_path)}")
    img1 = Image.open(img1_path)
    img2 = Image.open(img2_path)
    if img1.size != img2.size or img1.mode != img2.mode:
        print(f"    [!] Image size or mode mismatch in {os.path.basename(img1_path)}")
        return False
    diff = ImageChops.difference(img1, img2)
    if diff.getbbox():
        print(f"    [!] Pixel content mismatch in image {os.path.basename(img1_path)}")
        return False
    return True

def files_exist_and_are_identical(reference_dir, generated_dir):
    """
    Checks if the file structure and content are identical between two directories.
    Fails if files are missing, extra, or have different content.
    """
    ref_files = set()
    for root, _, files in os.walk(reference_dir):
        for name in files:
            ref_files.add(os.path.relpath(os.path.join(root, name), reference_dir))

    gen_files = set()
    for root, _, files in os.walk(generated_dir):
        for name in files:
            gen_files.add(os.path.relpath(os.path.join(root, name), generated_dir))
            
    if ref_files != gen_files:
        print("[!] File structure mismatch detected.")
        missing_in_gen = ref_files - gen_files
        extra_in_gen = gen_files - ref_files
        
        if missing_in_gen:
            print(f"    - Missing files in output (expected but not found): {sorted(list(missing_in_gen))}")
        if extra_in_gen:
            print(f"    - Extra files in output (not present in reference): {sorted(list(extra_in_gen))}")
        return False

    for rel_path in sorted(list(ref_files)):
        ref_file_path = os.path.join(reference_dir, rel_path)
        gen_file_path = os.path.join(generated_dir, rel_path)
        if not files_identical(ref_file_path, gen_file_path):
            return False # The specific error is printed inside files_identical
            
    return True

class PikObsFileComparisonTest(unittest.TestCase):
    func_name = None      
    func_args = None      
    reference_dir = None  
    output_dir = None     
    update_reference = False

    def setUp(self):
        print("\n" + "="*50)
        print(f"[*] Setting up test for: {self.func_name}")
        if not all([self.func_name, self.func_args, self.reference_dir, self.output_dir]):
            self.skipTest("Test not correctly parameterized")
        if os.path.exists(self.output_dir):
            print(f"[*] Cleaning up previous working directory: {self.output_dir}")
            shutil.rmtree(self.output_dir)

    def test_pikobs_call_files_identical(self):
        try:
            # 1. Execute PikObs and generate temporary data
            print("[*] Starting PikObs execution...")
            call_pikobs_module(self.func_name, self.func_args)

            ref_dir = self.reference_dir
            out_dir = self.output_dir
            
            if not os.path.exists(out_dir) or not os.listdir(out_dir):
                self.fail("PikObs execution finished but produced no output files.")

            # --- CORRECTED AND STRICTER LOGIC ---
            
            # CASE 1: Initial creation (Bootstrap) if the reference directory does NOT exist.
            if not os.path.exists(ref_dir):
                print(f"[*] Reference directory not found. Populating for the first time: {ref_dir}")
                shutil.copytree(out_dir, ref_dir)
                warning_msg = (
                    f"\n[WARNING] New reference data has been created in: {ref_dir}\n"
                    "Please manually review the results to ensure they are correct before committing them."
                )
                warnings.warn(warning_msg)
                print(warning_msg)
                print("[*] Skipping comparison for this initial run. Test passes.")
                return # Test passes

            # CASE 2: Forced update if update_reference is True.
            if self.update_reference:
                print(f"[*] update_reference flag is set. Overwriting reference directory: {ref_dir}")
                shutil.rmtree(ref_dir)
                shutil.copytree(out_dir, ref_dir)
                warning_msg = (
                    f"\n[WARNING] Reference data has been updated in: {ref_dir}\n"
                    "Please manually review the results before committing them."
                )
                warnings.warn(warning_msg)
                print(warning_msg)
                print("[*] Skipping comparison. Test passes.")
                return # Test passes

            # CASE 3: Strict comparison in all other cases.
            print("[*] Reference directory exists. Starting strict file-by-file comparison...")
            self.assertTrue(
                files_exist_and_are_identical(ref_dir, out_dir),
                "FAIL: The generated files do not match the reference files. See details above."
            )
            print("[*] All files and their contents matched perfectly. Test PASSED.")
            
        except RuntimeError as e:
            print(f"[!] Test failed due to a runtime error during PikObs execution.")
            self.fail(f"Call to pikobs.{self.func_name} failed: {e}")

def run_pikobs_unittest(func_name, func_args, ref_dir, out_dir, update_reference=False):
    """Helper to configure and run the generic test suite."""
    print(f"[*] Initializing Test Runner for: {func_name}")
    print(f"    - Reference path: {ref_dir}")
    print(f"    - Work path (output): {out_dir}")
    if update_reference:
        print("    - UPDATE MODE: Reference will be overwritten.")
    
    PikObsFileComparisonTest.func_name = func_name
    PikObsFileComparisonTest.func_args = func_args
    PikObsFileComparisonTest.reference_dir = ref_dir
    PikObsFileComparisonTest.output_dir = out_dir
    PikObsFileComparisonTest.update_reference = update_reference
    
    suite = unittest.TestLoader().loadTestsFromTestCase(PikObsFileComparisonTest)
    runner = unittest.TextTestRunner(verbosity=2)
    runner.run(suite)

