"""
PikObs Unified Testing Suite
============================

This module provides a unified, automated framework for functional testing of 
PikObs tools. Its goal is to ensure that code changes do not introduce 
unexpected regressions in the output.

Core Concept: Reference-Based Testing
---------------------------------------
The system compares the output of a current run against a set of pre-validated
results (the "reference"). If they are identical, the test PASSES. If there are
any differences, it FAILS.

Workflows
---------

**A. Bootstrap Workflow (First-Time Run)**

1.  **Run**: Call the test function pointing to a path that does not exist.
    `pikobs.unittest_timeserie("/path/to/new/reference")`
2.  **Auto-Population**: The script creates the reference with the generated output.
3.  **Manual Verification**: You **must manually review** that the new reference
    files are correct before committing them to version control.

**B. Recommended Development Workflow (Updating an Existing Reference)**

1.  **Modify your code** in PikObs.
2.  **Run the normal test**: `pikobs.unittest_timeserie("/path/to/existing/ref")`.
    **The test is expected to FAIL**. This confirms your change had an effect.
3.  **Verify the new output**: Check the files in the temporary `onthefly_*`
    directory to ensure the new result is what you expected.
4.  **Update the Reference**: If the output is correct, run the test with
    `update_reference=True`. This replaces the old reference with the new one.
    `pikobs.unittest_timeserie("/path/to/existing/ref", update_reference=True)`
5.  **Commit**: Commit both your code changes and the updated reference files.

Extending the Test Suite (Adding New Tests)
-------------------------------------------

The test suite is designed to be an extensible list. To add a test for a new
tool (e.g., `pikobs.profile`), follow these steps:

**Step 1: Create the Test Function in `test_pikobs.py`**

Copy an existing function and adapt it. It must define the specific arguments
for the new tool and call the `run_pikobs_unittest` engine.

.. code-block:: python

   # In pikobs/unittest/test_pikobs.py

   def unittest_profile(reference_path, update_reference=False):
       \"\"\"Run the unified PikObs tests for profile functionality.\"\"\"
       print(f"\\n[*] --- Starting unittest_profile ---")
       ref_path_abs = os.path.abspath(reference_path)
       base_dir = os.path.dirname(ref_path_abs)
       work_path = os.path.join(base_dir, "onthefly_profile")

       # Arguments specific to the 'profile' tool
       func_args = {
           "path_experience_files": "...",
           "experience_name": "...",
           "pathwork": work_path,
           "station_id": "0-20000-0-12345",
           # ...other args...
       }
       
       # Call the test engine with the tool's name
       run_pikobs_unittest("profile", func_args, ref_path_abs, work_path, update_reference)

**Step 2: Expose the New Test Function**

Add the name of your new function to the `pikobs/__init__.py` file to make it
accessible from the main package.

.. code-block:: python

   # In pikobs/__init__.py
   from .unittest.test_pikobs import unittest_timeserie, unittest_scatter, unittest_profile # <-- Add here

List of Available Tests
-----------------------
- `unittest_timeserie`
- `unittest_scatter`
- ... (add new tests here as you create them)

Usage via `python -c`
---------------------
.. code-block:: bash

   # Run a standard regression test
   python -c "import pikobs; pikobs.unittest_timeserie('/path/to/ref')"

   # Update the reference after verifying a change
   python -c "import pikobs; pikobs.unittest_timeserie('/path/to/ref', update_reference=True)"
"""

