//! Binary to generate Python type stubs from Rust code using pyo3-stub-gen.
//!
//! Run with: `cargo run --bin stub_gen --features stub-gen`

use std::collections::BTreeSet;
use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};

use pyo3_stub_gen::Result;
use regex::Regex;

fn project_root() -> Result<PathBuf> {
    Ok(PathBuf::from(env!("CARGO_MANIFEST_DIR")))
}

fn generate_top_level_init_stub(stub_root: &Path) -> Result<()> {
    let runtime_init_path = stub_root.join("__init__.py");
    let runtime_init = fs::read_to_string(&runtime_init_path)?;
    let import_block_regex = Regex::new(r"from ferrox\._ferrox import \(\s*([\s\S]*?)\s*\)")?;
    let Some(import_capture) = import_block_regex.captures(&runtime_init) else {
        eprintln!(
            "warning: could not find import block in {}, skipping top-level __init__.pyi generation",
            runtime_init_path.display()
        );
        return Ok(());
    };
    let imported_names_block = import_capture.get(1).map_or("", |m| m.as_str());
    let mut from_ferrox: Vec<String> = imported_names_block
        .lines()
        .map(str::trim)
        .map(|line| line.trim_end_matches(','))
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(ToString::to_string)
        .collect();

    let assignment_regex = Regex::new(r"(?m)^(\w+) = (\w+)\.(\w+)$")?;
    let mut extra_lines: Vec<String> = Vec::new();
    for assignment_capture in assignment_regex.captures_iter(&runtime_init) {
        let (Some(target_match), Some(module_match), Some(attr_match)) = (
            assignment_capture.get(1),
            assignment_capture.get(2),
            assignment_capture.get(3),
        ) else {
            continue;
        };
        // Always emit the assignment form to match the runtime import path
        extra_lines.push(format!(
            "{} = {}.{}",
            target_match.as_str(),
            module_match.as_str(),
            attr_match.as_str()
        ));
    }

    let mut seen = BTreeSet::new();
    from_ferrox.retain(|name| seen.insert(name.clone()));

    // Collect single-line _ferrox imports (e.g. `from ferrox._ferrox import mp as _mp_native`)
    let ferrox_single_regex = Regex::new(r"(?m)^from ferrox\._ferrox import (\w+) as (\w+)$")?;
    let mut ferrox_alias_lines: Vec<String> = Vec::new();
    for cap in ferrox_single_regex.captures_iter(&runtime_init) {
        let (Some(original), Some(alias)) = (cap.get(1), cap.get(2)) else {
            continue;
        };
        ferrox_alias_lines.push(format!(
            "from ._ferrox import {} as {}",
            original.as_str(),
            alias.as_str()
        ));
    }

    // Collect non-_ferrox import lines (e.g. `from ferrox.mp import ...`)
    let other_import_regex = Regex::new(r"(?m)^from ferrox\.(\w+) import (.+)$")?;
    let mut other_import_lines: Vec<String> = Vec::new();
    for cap in other_import_regex.captures_iter(&runtime_init) {
        let (Some(module_match), Some(names_match)) = (cap.get(1), cap.get(2)) else {
            continue;
        };
        let module_name = module_match.as_str();
        if module_name == "_ferrox" {
            continue;
        }
        let qualified = names_match
            .as_str()
            .split(',')
            .map(str::trim)
            .map(|name| format!("{name} as {name}"))
            .collect::<Vec<_>>()
            .join(", ");
        other_import_lines.push(format!("from .{module_name} import {qualified}"));
    }

    let mut output_lines = vec![
        "# This file is automatically generated by pyo3_stub_gen".to_string(),
        "# ruff: noqa: I001".to_string(),
        String::new(),
    ];
    if !from_ferrox.is_empty() {
        let imports = from_ferrox
            .iter()
            .map(|name| format!("{name} as {name}"))
            .collect::<Vec<_>>()
            .join(", ");
        output_lines.push(format!("from ._ferrox import {imports}"));
    }
    output_lines.extend(ferrox_alias_lines);
    output_lines.extend(other_import_lines);
    output_lines.extend(extra_lines);
    output_lines.push(String::new());

    let output_path = stub_root.join("__init__.pyi");
    fs::write(&output_path, output_lines.join("\n"))?;
    println!("  Generated: {}", output_path.display());
    Ok(())
}

/// Add __version__ and typed submodule re-exports to _ferrox/__init__.pyi.
///
/// Inserts `from . import <sub> as <sub>` before the first class/function
/// definition so that type checkers follow the per-submodule stubs instead
/// of treating everything as untyped `ModuleType`.
fn append_ferrox_exports(stub_root: &Path) -> Result<()> {
    let ferrox_stub = stub_root.join("_ferrox").join("__init__.pyi");
    if !ferrox_stub.is_file() {
        return Ok(());
    }
    let mut content = fs::read_to_string(&ferrox_stub)?;

    if !content.contains("__version__") {
        content.push_str("\n__version__: str\n");
    }

    if !content.contains("from . import cell") {
        // Keep in sync with submodules.rs define_submodule! calls and lib.rs #[pymodule_export] uses
        let submodules = [
            "cell",
            "composition",
            "convex_hull",
            "coordination",
            "defects",
            "elastic",
            "io",
            "lattice",
            "md",
            "mp",
            "neighbors",
            "optimizers",
            "order_params",
            "oxidation",
            "potentials",
            "properties",
            "rdf",
            "species",
            "structure",
            "surfaces",
            "symmetry",
            "trajectory",
            "xrd",
        ];
        let mut block = String::from("\n");
        for sub in &submodules {
            writeln!(block, "from . import {sub} as {sub}").unwrap();
        }
        block.push('\n');
        // Insert before the first class or function definition to avoid E402
        if let Some(pos) = content
            .find("\n@final\n")
            .or_else(|| content.find("\ndef "))
        {
            content.insert_str(pos + 1, &block);
        } else {
            content.push_str(&block);
        }
    }

    fs::write(&ferrox_stub, content)?;
    println!("  Augmented: {}", ferrox_stub.display());
    Ok(())
}

fn main() -> Result<()> {
    let repo_root = project_root()?;
    let stub_root = repo_root.join("bindings").join("python").join("ferrox");

    let stub = ferrox::python::stub_info()?;
    stub.generate()?;
    append_ferrox_exports(&stub_root)?;
    generate_top_level_init_stub(&stub_root)?;
    Ok(())
}
