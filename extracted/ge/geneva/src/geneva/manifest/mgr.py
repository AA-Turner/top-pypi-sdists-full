import hashlib
import json
import logging
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Any, Optional

import attrs

if TYPE_CHECKING:
    from geneva.manifest.builder import (
        CondaManifestBuilder,
        PipManifestBuilder,
        SiteManifestBuilder,
    )
import pyarrow as pa

from geneva.state.manager import BaseManager
from geneva.utils import current_user, escape_sql_string, retry_lance

MANIFEST_TABLE_NAME = "geneva_manifests"

_LOG = logging.getLogger(__name__)


@attrs.define
class GenevaManifest:
    """A Geneva Manifest represents the files and dependencies used
    in the execution environment."""

    # metadata
    name: str = attrs.field()
    version: Optional[str] = attrs.field(default=None)

    # properties needed to init the cluster
    pip: list[str] = attrs.field(default=[])
    py_modules: list[str] = attrs.field(default=[])
    head_image: Optional[str] = attrs.field(default=None)
    worker_image: Optional[str] = attrs.field(default=None)

    # transient properties, only used during initial upload
    skip_site_packages: bool = attrs.field(default=True)
    delete_local_zips: bool = attrs.field(default=False)
    local_zip_output_dir: Optional[str] = attrs.field(default=None)

    # internal generated properties
    zips: list[list[str]] = attrs.field(default=[[]])
    checksum: Optional[str] = attrs.field(default=None)
    created_at: datetime = attrs.field(
        factory=lambda: datetime.now(timezone.utc),
        metadata={"pa_type": pa.timestamp("us", tz="UTC")},
    )
    created_by: str = attrs.field(factory=current_user)

    requirements_path: Optional[str] = attrs.field(default=None)
    # conda: stored as JSON string in Arrow (Lance doesn't support Map types)
    # Ray accepts complex structures like {"dependencies": [...], "channels": [...]}
    conda: dict[str, Any] = attrs.field(
        factory=dict,
        metadata={"pa_type": pa.string()},
    )
    conda_environment_path: Optional[str] = attrs.field(default=None)

    # Environment variables to set in Ray worker processes via runtime_env.
    # Stored as JSON string in Arrow (Lance doesn't support Map types).
    env_vars: dict[str, str] = attrs.field(
        factory=dict,
        metadata={"pa_type": pa.string()},
    )

    # Additional pip index URLs for Ray workers to install packages from.
    # These are merged with Geneva's default indexes (fury.io).
    pip_extra_index_urls: list[str] = attrs.field(factory=list)

    def __attrs_post_init__(self) -> None:
        self.checksum = self.compute_checksum()

    def compute_checksum(self) -> str:
        """Generate a stable checksum of the manifest, ignoring the checksum field.
        The zip file names include the checksum of the contents so this hash is
        comprehensive.
        """
        checksum_exclude_fields = {
            "name",  # excluding name since this may be autogenerated.
            "checksum",  # this is what remains unique
            "created_at",
            "created_by",
            "delete_local_zips",
            "local_zip_output_dir",
        }
        data = attrs.asdict(
            self,
            recurse=True,
            filter=lambda a, v: a.name not in checksum_exclude_fields,
        )
        payload = json.dumps(data, sort_keys=True, separators=(",", ":"), default=str)
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    # -------------------------------------------------------------------------
    # Factory Methods for Type-Safe Builders
    # -------------------------------------------------------------------------

    @staticmethod
    def create_pip(name: str) -> "PipManifestBuilder":
        """Create a pip-based manifest builder.

        Pin dependencies to exact versions: they are installed on the Ray
        workers, so ranged specifiers can resolve to versions that differ from
        the local environment.

        Examples
        --------
            manifest = (
                GenevaManifest.create_pip("my-manifest")
                .pip(["numpy==2.1.3"])
                .build()
            )
        """
        from geneva.manifest.builder import PipManifestBuilder

        return PipManifestBuilder.create(name)

    @staticmethod
    def create_conda(name: str) -> "CondaManifestBuilder":
        """Create a conda-based manifest builder.

        Pin dependencies to exact versions: they are installed on the Ray
        workers, so ranged specifiers can resolve to versions that differ from
        the local environment.

        Examples
        --------
            manifest = GenevaManifest.create_conda("my-manifest").conda({...}).build()
        """
        from geneva.manifest.builder import CondaManifestBuilder

        return CondaManifestBuilder.create(name)

    @staticmethod
    def create_site(name: str) -> "SiteManifestBuilder":
        """Create a site-packages manifest builder.

        Uploads local site-packages without external dependencies.
        upload_site_packages defaults to True.

        Examples
        --------
            manifest = GenevaManifest.create_site("my-manifest").build()
        """
        from geneva.manifest.builder import SiteManifestBuilder

        return SiteManifestBuilder.create(name)

    def as_dict(self) -> dict:
        return attrs.asdict(
            self,
            value_serializer=lambda obj, a, v: (
                v.value
                if isinstance(v, enum.Enum)
                else json.dumps(v)
                if isinstance(v, dict)
                else v
            ),
        )

    # Field names that are transient / runtime-only and must not appear
    # in the canonical JSON serialization that lives in column metadata.
    _JSON_EXCLUDE_FIELDS = frozenset(
        {
            "delete_local_zips",
            "local_zip_output_dir",
            "created_at",
            "created_by",
        }
    )

    def to_json(self) -> str:
        """Canonical JSON serialization of this manifest for column
        metadata storage. Excludes transient/runtime fields."""
        data = attrs.asdict(
            self,
            recurse=True,
            filter=lambda a, _v: a.name not in self._JSON_EXCLUDE_FIELDS,
        )
        return json.dumps(data, sort_keys=True, separators=(",", ":"), default=str)

    @classmethod
    def from_json(cls, payload: str) -> "GenevaManifest":
        """Reconstruct a GenevaManifest from a string produced by
        [`to_json`][geneva.manifest.mgr.GenevaManifest.to_json].
        Missing transient fields fall back to defaults."""
        data = json.loads(payload)
        return _make_manifest(data)


class ManifestConfigManager(BaseManager):
    def get_table_name(self) -> str:
        return MANIFEST_TABLE_NAME

    def get_model(self) -> Any:
        return GenevaManifest("dummy")

    @retry_lance
    def upsert(self, manifest: GenevaManifest) -> None:
        val = manifest.as_dict()
        self.delete(manifest.name)
        self.get_table().add([val])
        # # note: merge_insert with fails with schema errors - use delete+add for now
        # todo: fix schema error on merge_insert?

    @retry_lance
    def list(self, limit: int = 1000) -> list[GenevaManifest]:
        res = self.get_table(True).search().limit(limit).to_arrow().to_pylist()
        return [_make_manifest(manifest) for manifest in res]

    @retry_lance
    def load(self, name: str) -> GenevaManifest | None:
        res = (
            self.get_table(True)
            .search()
            .where(f"name = '{escape_sql_string(name)}'")
            .limit(1)
            .to_arrow()
            .to_pylist()
        )
        if not res:
            return None
        return _make_manifest(res[0])

    @retry_lance
    def delete(self, name: str) -> None:
        self.get_table().delete(f"name = '{escape_sql_string(name)}'")


def _make_manifest(args: dict) -> GenevaManifest:
    import cattrs

    # Shallow copy; conda is stored as JSON string in Arrow, restore as dict.
    args = dict(args)
    if "conda" in args:
        if isinstance(args["conda"], str):
            args["conda"] = json.loads(args["conda"])
        elif args["conda"] is None:
            args["conda"] = {}

    if "env_vars" in args:
        if isinstance(args["env_vars"], str):
            args["env_vars"] = json.loads(args["env_vars"])
        elif args["env_vars"] is None:
            args["env_vars"] = {}

    if "pip_extra_index_urls" in args and args["pip_extra_index_urls"] is None:
        args["pip_extra_index_urls"] = []

    converter = cattrs.Converter()
    converter.register_structure_hook(
        datetime,
        lambda ts, _: (
            datetime.fromisoformat(ts.replace("Z", "+00:00"))
            if isinstance(ts, str)
            else ts
        ),
    )
    return converter.structure(args, GenevaManifest)


def build_captured_manifest(
    conn: Any,
    name: str | None = None,
    *,
    skip_site_packages: bool = False,
) -> "GenevaManifest":
    """Eagerly zip + upload the local environment for ``conn`` and
    return a [`GenevaManifest`][GenevaManifest] ready to be passed to
    [`@udf`][geneva.udf].

    This is the implementation backing
    [`capture_local_environment`][Connection.capture_local_environment].
    It lives here (next to [`GenevaManifest`][GenevaManifest]) to keep the manifest
    construction logic in one place and to avoid an import cycle from
    ``geneva.db`` into the manifest package.

    Raises
    ------
        RuntimeError
            if ``conn`` cannot vend an Uploader (e.g. a
            ``db://`` connection without ``namespace_client_impl``
            configured). This is a configuration / environment error,
            not an unimplemented feature.
    """
    import uuid

    if name is None:
        name = f"capture-{uuid.uuid4().hex[:8]}"

    from geneva.packager.autodetect import upload_local_env

    try:
        uploader = _build_capture_uploader(conn)
    except (TypeError, ValueError) as e:
        raise RuntimeError(
            "Connection.capture_local_environment() requires a configured "
            "Uploader. For native (object-storage) connections, ensure the "
            "connection has a writable upload location. For db:// "
            "connections, configure namespace_client_impl so the namespace "
            "can vend upload credentials. Alternatively, use "
            "GenevaManifest.create_pip() with a pre-built image."
        ) from e

    # Build + return the manifest inside the same `with` block so the
    # uploader's context manager owns the zip file lifetime cleanly.
    with upload_local_env(
        uploader=uploader,
        skip_site_packages=skip_site_packages,
    ) as zips:
        manifest = GenevaManifest(
            name=name,
            skip_site_packages=skip_site_packages,
            zips=zips,
        )
        manifest.checksum = manifest.compute_checksum()
        return manifest


def _build_capture_uploader(conn: Any) -> Any:
    """Construct an Uploader scoped to ``conn``'s system manifest table.

    Mirrors the pattern in [`define_manifest`][Connection.define_manifest]: namespace
    connections use ``namespace_config`` + ``table_id``; native local
    connections use ``db_uri`` + ``table_id``; explicit ``upload_dir``
    overrides win when set.

    For namespace connections, the underlying ``Uploader`` resolves the
    upload location via ``namespace_client.describe_table()``. That call
    requires the manifest table to exist, so we proactively create it
    here (idempotent) before instantiating the Uploader.

    """
    from geneva.packager.uploader import Uploader

    if getattr(conn, "_upload_dir", None):
        return Uploader(upload_dir=conn._upload_dir)

    # Ensure the system manifest table exists so the Uploader can query its
    # location. Honor a pre-seeded ``conn._manifest_manager`` (and derive the
    # ``table_id`` from its actual namespace) so callers that installed a
    # manager against a non-default namespace -- e.g. to sidestep stale
    # ``__system`` state -- aren't silently bypassed here.
    mgr = conn._manifest_manager or ManifestConfigManager(conn)
    _ = mgr.get_table()

    table_id = mgr._namespace + [MANIFEST_TABLE_NAME]
    kwargs: dict[str, Any] = {}
    if conn._storage_options is not None:
        kwargs["storage_options"] = conn._storage_options
    return Uploader(
        namespace_config=conn._ns_config,
        table_id=table_id,
        **kwargs,
    )


def warn_if_manifest_not_applied(
    manifest: "GenevaManifest | None",
    *,
    target: str,
    udf_name: str,
    operation: str = "backfill",
) -> None:
    """Warn when a manifest will not shape the worker environment.

    Locally dispatched jobs (KubeRay, external Ray) build the worker
    environment once, when the cluster context is entered, so a manifest
    attached with ``@udf(manifest=...)`` — or with ``@udtf`` / ``@chunker``
    — afterwards has no effect on the running workers. Emits a warning
    naming what is in force instead. Stays silent when the active context
    already carries an equivalent manifest, or when there is no manifest.

    Parameters
    ----------
    manifest: GenevaManifest | None
        The manifest attached to the UDF, UDTF, or chunker being run.
    target: str
        What the job operates on, already labeled for the message
        (e.g. ``"column 'emb'"`` or ``"view 'chunks'"``).
    udf_name: str
        Name of the UDF, UDTF, or chunker carrying the manifest.
    operation: str
        Job kind naming the operation in the message. Default:
        ``"backfill"``.
    """
    if manifest is None:
        return

    from geneva._context import get_current_context

    active = getattr(get_current_context(), "manifest", None)
    if active is not None and active.compute_checksum() == manifest.compute_checksum():
        return

    in_force = (
        f"manifest '{active.name}'"
        if active is not None
        else "the environment the cluster was created with"
    )
    _LOG.warning(
        "The manifest attached to '%s' is not applied to this %s of %s. Workers "
        "run with %s. To apply it, create the cluster context with this manifest.",
        udf_name,
        operation,
        target,
        in_force,
    )
