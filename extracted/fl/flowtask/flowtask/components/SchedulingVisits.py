    def _get_ghost_employees_count(self, market_data):
        """Get the number of ghost employees for a market.
        Priority: 1. Column in dataframe, 2. kwarg parameter, . default value"""
        if self.ghost_employees_column in market_data.columns:
            # Get the first non-null value from the column
            ghost_count = market_data[self.ghost_employees_column].dropna().iloc[0]
            if pd.isna(ghost_count):
                return self.ghost_employees
            return int(ghost_count)
        return self.ghost_employees

    def _calculate_visit_time(self, start_time: time, elapsed_minutes: float) -> time:
        """Calculate the visit time by adding elapsed minutes to start time."""
        start_datetime = datetime.combine(date.today(), start_time)
        visit_datetime = start_datetime + timedelta(minutes=elapsed_minutes)
        return visit_datetime.time()

    def _format_time(self, time_obj: time) -> str:
        """Format time as HH:MM AM/PM."""
        return time_obj.strftime("%I:%M %p")

    def get_workdays(self, year: int, month: int, exception_dates: list = None):
        """Get all workdays (Monday to Friday) in a given month, excluding exception dates."""
        first_day = date(year, month, 1)
        last_day = date(year, month, calendar.monthrange(year, month)[1])
        workdays = pd.bdate_range(first_day, last_day)
        if exception_dates:
            # Convert exception_dates to datetime
            exception_dates = pd.to_datetime(exception_dates)
            workdays = workdays.difference(exception_dates)
        return workdays

    def _get_fdom(self, year, month):
        """Function to get the first Monday of a given month
        (which is Labor Day in the US)."""
        cal = calendar.Calendar()
        first_monday = None
        for day in cal.itermonthdays2(year, month):
            if day[0] != 0 and day[1] == 0:  # day[1] == 0 means Monday
                first_monday = day[0]
                break
        return datetime(year, month, first_monday)

    def get_distance(self, coord1, coord2):
        """Function to calculate distance
        between two points (latitude, longitude)."""
        return geodesic(coord1, coord2).miles

    def to_miles(self, distance) -> float:
        return distance * 0.621371  # Convert to miles

    def to_hours(self, minutes) -> float:
        return minutes / 60  # Convert to hours

    def get_labor_days(self, year: int = 2024, month: int = 9):
        """Function to get all workdays (Monday to Friday) in a given month."""
        # Get first Labor Day (first Monday) of the month
        labor_day = self._get_fdom(year, month)
        # Generate list of weekdays (excluding weekends) starting from Labor Day
        workdays = []
        current_day = labor_day
        while current_day.month == month:
            if current_day.weekday() < 5:  # Only Monday to Friday (weekday < 5)
                workdays.append(current_day)
            current_day += timedelta(days=1)
        return workdays

    @staticmethod
    def _stable_store_index(store_id: Any) -> int:
        """Deterministic, process-independent replacement for
        ``hash(store_id)``. Python's ``str`` hash is salted per-process
        (``PYTHONHASHSEED``) by default, which made the store-index-based
        day/week staggering in `get_scheduled_dates()` — and therefore the
        window `_pack_visits()` computes around it — non-reproducible
        across process restarts even with the same `random_seed`. Uses
        MD5 (not for security, purely for a stable, well-distributed
        digest) over the string form of `store_id`.
        """
        digest = hashlib.md5(str(store_id).encode("utf-8")).hexdigest()
        return int(digest, 16) % (10 ** 8)

    def _normalized_visit_frequency(self, cadence: str | None, visit_frequency: Any) -> str:
        """Mirror of the ``cadence`` -> ``visit_frequency`` normalization
        performed INSIDE `get_scheduled_dates()` (kept in sync
        intentionally — `get_scheduled_dates()` itself is out of scope to
        modify per FEAT-233's Codebase Contract). Used so the visit record
        stores the SAME effective cadence category that
        `get_scheduled_dates()` actually scheduled against, which
        `_pack_visits()` relies on to pick the ISO-week vs. monthly window.
        """
        frequency = visit_frequency
        if cadence:
            cadence = cadence.lower()
            if 'xweek' in cadence:
                frequency = 'weekly'
            elif 'xmonth' in cadence:
                frequency = 'monthly'
            elif 'xqtr' in cadence:
                frequency = 'monthly'  # quarterly folds into monthly, same as get_scheduled_dates
        if isinstance(frequency, str) and frequency.lower() == 'quarterly':
            frequency = 'monthly'
        return frequency

    def get_scheduled_dates(
        self,
        cadence: str,
        visit_rule: float,
        visit_frequency: Any,
        workdays: pd.DatetimeIndex,
        store_index: int
    ):
        """Given the visit_rule and visit_frequency,
        return a list of scheduled dates for the visits."""
        scheduled_dates = []

        if len(workdays) == 0:
            return scheduled_dates

        # Set visit_frequency and visit_rule based on cadence if provided
        if cadence:
            cadence = cadence.lower()
            if 'xweek' in cadence:
                num = int(cadence[0])
                visit_rule = num
                visit_frequency = 'weekly'
            elif 'xmonth' in cadence:
                num = int(cadence[0])
                visit_rule = num
                visit_frequency = 'monthly'
            elif 'xqtr' in cadence:
                num = int(cadence[0])
                visit_rule = num
                visit_frequency = 'quarterly'

        # If visit_frequency is numeric (e.g. pre-rename DataFrame where
        # the column still holds the visit *count* rather than the cadence
        # string), treat it as the visit rule and default to 'monthly'.
        if not isinstance(visit_frequency, str):
            visit_rule = visit_frequency
            visit_frequency = 'monthly'

        if visit_frequency.lower() == 'quarterly':
            # For simplicity, schedule as monthly with 1 visit per month
            visit_frequency = 'monthly'
            visit_rule = 1

        # Normalize visit_rule to a usable numeric form
        try:
            visit_rule_value = float(visit_rule)
        except (TypeError, ValueError):
            visit_rule_value = 0.0

        if math.isnan(visit_rule_value):
            visit_rule_value = 0.0

        visit_iterations = int(math.ceil(visit_rule_value)) if visit_rule_value > 0 else 0

        if visit_frequency.lower() == 'weekly':
            # FIXED: Proper indentation for weekly scheduling
            workdays_df = pd.DataFrame({'date': workdays})
            workdays_df['week'] = workdays_df['date'].dt.isocalendar().week
            weeks = sorted(workdays_df['week'].unique())

            for week in weeks:  # This loop was missing proper indentation
                week_days = workdays_df[workdays_df['week'] == week]['date'].sort_values().reset_index(drop=True)
                num_days = len(week_days)
                if num_days == 0:
                    continue

                # Ensure we don't exceed available days
                num_visits = min(visit_iterations, num_days)

                # Distribute visits evenly within the week
                for i in range(num_visits):
                    if i < num_days:
                        # Use store_index to stagger start days for different stores
                        day_index = (store_index + i) % num_days
                        scheduled_date = week_days[day_index]
                        scheduled_dates.append(scheduled_date)

        elif visit_frequency.lower() == 'monthly':
            # Improved monthly scheduling
            total_days = len(workdays)
            if visit_iterations == 0:
                visit_iterations = 1
                visit_rule_value = max(visit_rule_value, 1.0)
            if visit_rule_value > total_days:
                # If we need more visits than available days, schedule one per day
                scheduled_dates = list(workdays)
            else:
                # Distribute visits evenly across the month
                interval = total_days / max(visit_rule_value, 1.0)
                # Spread stores across the FULL width of each visit's slot,
                # not a fixed five-day head. With `visit_rule == 1` the loop
                # runs once, so `i * interval` is always 0 and a `% 5` offset
                # pinned every monthly store to the first five workdays —
                # front-loading the month and leaving the last week idle.
                # `slot_width` is the number of workdays that belong to one
                # visit, so consecutive stores fan out over the whole slot.
                slot_width = max(1, int(interval))
                for i in range(visit_iterations):
                    # Calculate target day index with an offset based on store
                    target_index = int(i * interval + (store_index % slot_width))
                    # Ensure we don't exceed array bounds
                    day_index = min(target_index, total_days - 1)
                    # Avoid duplicate dates
                    candidate_date = workdays[day_index]
                    if candidate_date not in scheduled_dates:
                        scheduled_dates.append(candidate_date)
                    else:
                        # Find next available date
                        for offset in range(1, total_days):
                            alt_index = (day_index + offset) % total_days
                            alt_date = workdays[alt_index]
                            if alt_date not in scheduled_dates:
                                scheduled_dates.append(alt_date)
                                break
        else:
            # Default fallback to monthly behavior
            total_days = len(workdays)
            visits_to_schedule = visit_iterations if visit_iterations > 0 else 1
            interval = total_days / max(visit_rule_value, 1.0)
            for i in range(visits_to_schedule):
                day_index = min(int(i * interval), total_days - 1)
                scheduled_dates.append(workdays[day_index])

        return sorted(scheduled_dates)

    def _market_monthly_visits(self, market_data: pd.DataFrame) -> float:
        """Total visits a market's stores require in the scheduled month.

        Weekly cadences are expanded by 4.3 (the average number of weeks
        in a month); every other cadence is taken as its `visit_rule`
        count per month.

        Args:
            market_data: The rows of one market.

        Returns:
            The market's monthly visit count. Null `visit_rule` /
            `visit_frequency` values fall back to the component defaults
            rather than raising.
        """
        total = 0.0
        for _, store in market_data.iterrows():
            visit_rule = store.get('visit_rule', self.visit_rule)
            if pd.isna(visit_rule):
                visit_rule = self.visit_rule
            frequency = store.get('visit_frequency', self.visit_frequency)
            if pd.isna(frequency):
                frequency = self.visit_frequency
            try:
                rule = float(visit_rule)
            except (TypeError, ValueError):
                rule = float(self.visit_rule)
            total += rule * (4.3 if str(frequency).lower() == 'weekly' else 1.0)
        return total

    def _employees_needed(self, monthly_visits: float) -> int:
        """Headcount required to absorb `monthly_visits` in one month.

        Args:
            monthly_visits: Visits the market must receive this month.

        Returns:
            `ceil(visits / (max_visits_per_day * workdays))`, never below
            1 for a market that has any work at all.

        Note:
            This counts visits only, not travel. A geographically wide
            market whose days are consumed by driving needs more people
            than this returns — see `max_distance` and the per-day
            `total_travel_time` in the output for the real picture.
        """
        if self._workdays_cache is None:
            self._workdays_cache = list(
                self.get_workdays(self.year, self.month, self._exception_dates)
            )
        capacity = self.max_visits_per_day * len(self._workdays_cache)
        if capacity <= 0:
            return 1
        return max(1, int(np.ceil(monthly_visits / capacity)))

    def _allocate_ghost_employees(
        self,
        demand: dict,
        visits: dict,
        budget: int | None,
    ) -> dict:
        """Share a fixed headcount across markets in proportion to work.

        Answers "given `budget` people and this much work, who gets
        whom?". Three regimes:

        1. **Uncapped or affordable** (`budget is None`, or total demand
           fits): every market gets exactly what it needs and any surplus
           headcount goes unused — hiring people a market cannot occupy
           is the imbalance this method exists to remove.
        2. **More markets than people**: the busiest `budget` markets get
           one each, the rest get zero, and every starved market is named
           in a warning. Their stores land in `exception_stores_df`, so
           the shortfall is visible rather than silent.
        3. **Over budget**: largest-remainder apportionment proportional
           to monthly visits, each market clamped to
           `[1, employees_needed]`. Headcount freed by a ceiling clamp is
           redistributed to markets that can still absorb it, so the
           budget is spent exactly.

        Ordering is fully deterministic (visits descending, then market
        name), so the same input always yields the same allocation.

        Args:
            demand: Market -> employees the market could occupy.
            visits: Market -> monthly visits, the proportionality weight.
            budget: Total headcount available, or None for uncapped.

        Returns:
            Market -> ghost employees to create.
        """
        if not demand:
            return {}

        need = {market: max(1, int(count)) for market, count in demand.items()}
        total_need = sum(need.values())

        def _weight(market) -> float:
            try:
                return max(0.0, float(visits.get(market, 0.0)))
            except (TypeError, ValueError):
                return 0.0

        # Busiest first; market name breaks ties so runs are reproducible.
        ordered = sorted(need, key=lambda market: (-_weight(market), str(market)))

        if budget is None or total_need <= budget:
            self._logger.info(
                "Ghost allocation: %d employees across %d markets "
                "(demand fits%s)",
                total_need, len(need),
                "" if budget is None else f", budget {budget}",
            )
            return need

        budget = max(0, int(budget))

        # Regime 2: cannot even give every market one person.
        if budget < len(need):
            allocation = {market: 0 for market in need}
            for market in ordered[:budget]:
                allocation[market] = 1
            starved = [market for market in ordered[budget:]]
            self._logger.warning(
                "Ghost allocation: %d markets but a ceiling of %d employees. "
                "%d market(s) will receive NO coverage and their stores will "
                "appear as exceptions: %s",
                len(need), budget, len(starved),
                ', '.join(str(market) for market in starved),
            )
            return allocation

        # Regime 3: proportional apportionment under the ceiling.
        total_weight = sum(_weight(market) for market in need)
        if total_weight <= 0:
            # No visit signal at all — fall back to an even spread rather
            # than dividing by zero.
            quotas = {market: budget / len(need) for market in need}
        else:
            quotas = {
                market: budget * _weight(market) / total_weight for market in need
            }

        remainders = {market: quotas[market] % 1 for market in need}
        allocation = {
            market: min(max(int(quotas[market]), 1), need[market])
            for market in need
        }

        # Fill: hand out headcount freed by the ceiling clamps, largest
        # fractional remainder first, one per market per round.
        while sum(allocation.values()) < budget:
            candidates = sorted(
                (m for m in ordered if allocation[m] < need[m]),
                key=lambda m: (-remainders[m], -_weight(m), str(m)),
            )
            if not candidates:
                break
            for market in candidates:
                if sum(allocation.values()) >= budget:
                    break
                allocation[market] += 1

        # Trim: the floor of 1 can push the total past the budget when
        # many small markets round up. Take back from the smallest
        # remainders first, never below one person per market.
        while sum(allocation.values()) > budget:
            candidates = sorted(
                (m for m in ordered if allocation[m] > 1),
                key=lambda m: (remainders[m], _weight(m), str(m)),
            )
            if not candidates:
                break
            for market in candidates:
                if sum(allocation.values()) <= budget:
                    break
                allocation[market] -= 1

        clamped = [m for m in need if allocation[m] < need[m]]
        self._logger.warning(
            "Ghost allocation: demand is %d employees but the ceiling is "
            "%d; allocated %d proportionally to workload. %d market(s) are "
            "staffed below their demand.",
            total_need, budget, sum(allocation.values()), len(clamped),
        )
        return allocation

    def _demand_ghost_allocation(self, df: pd.DataFrame | None = None) -> dict:
        """Size every market's ghost headcount from its own workload.

        Reads no `ghost_employees` column: the whole point of
        `ghost_allocation='demand'` is that the source dataframe does not
        get to declare a headcount it has no basis for.

        Args:
            df: Rows to size headcount from. Code-review fix (FEAT-241):
                the caller passes ``scheduling_source`` (normal-flow rows
                only, sub-cluster rows already peeled off) so demand
                sizing isn't inflated by workload the block scheduler —
                not the normal per-store ghost machinery this sizes for
                — actually ends up covering. Defaults to ``self.data``
                for any caller that predates that split.

        Returns:
            Market -> ghost employees to create, already reconciled
            against `max_employees`.
        """
        source = df if df is not None else self.data
        demand: dict = {}
        visits: dict = {}
        for market, market_data in source.groupby(self._market_name, sort=False):
            monthly_visits = self._market_monthly_visits(market_data)
            visits[market] = monthly_visits
            demand[market] = self._employees_needed(monthly_visits)
        return self._allocate_ghost_employees(demand, visits, self.max_employees)

    def analyze_market_capacity(self, df):
        """Analyze each market's capacity requirements using actual assigned employees."""
        market_analysis = {}
        total_employees_needed = 0

        self._logger.info("=== MARKET CAPACITY ANALYSIS ===")

        for market in df['market'].unique():
            market_data = df[df['market'] == market]
            store_count = len(market_data)

            # Calculate visits needed per month, and the headcount that
            # implies. Both extracted (FEAT-239) so the demand-driven ghost
            # allocator sizes markets from exactly the same formula this
            # analysis reports.
            total_visits = self._market_monthly_visits(market_data)
            employees_needed = self._employees_needed(total_visits)
            total_employees_needed += employees_needed

            # Count ACTUAL assigned employees for this market
            if 'associate_oid' in market_data.columns:
                # Count unique employees assigned to this market
                actual_employees = market_data['associate_oid'].nunique()
                # Filter out null/None values
                actual_employees = len(
                    [emp for emp in market_data['associate_oid'].unique() if emp is not None and pd.notna(emp)])
            else:
                # If no employees assigned yet, use the prediction method
                actual_employees = self._get_ghost_employees_count(market_data)

            market_analysis[market] = {
                'store_count': store_count,
                'total_monthly_visits': int(total_visits),
                'employees_needed': int(employees_needed),
                'current_employees': actual_employees
            }

            self._logger.info(f"Market: {market}")
            self._logger.info(f"  Stores: {store_count}, Visits needed: {int(total_visits)}")
            self._logger.info(f"  Employees needed: {int(employees_needed)}, Current: {actual_employees}")

            if employees_needed > actual_employees:
                self._logger.warning(f"  ⚠️  Market {market} is UNDER-STAFFED!")
            elif actual_employees == 0:
                self._logger.error(f"  ❌ Market {market} has NO EMPLOYEES assigned!")
            else:
                self._logger.info(f"  ✅ Market {market} is adequately staffed")

        self._logger.info(
            f"Total employees needed across all markets: {int(total_employees_needed)}"
        )
        return market_analysis

    async def start(self, **kwargs):
        if self.previous:
            self.data: pd.DataFrame = self.input
            if not isinstance(self.data, pd.DataFrame):
                raise ConfigError(
                    "Incompatible Pandas Dataframe", status=404
                )
        else:
            raise DataNotFound(
                "Data Not Found", status=404
            )
        await super().start(**kwargs)
        # Drop ignored markets (by `market_id`) before any scheduling work.
        if self.ignore_markets:
            if 'market_id' in self.data.columns:
                mask = self.data['market_id'].isin(self.ignore_markets)
                dropped = sorted(self.data.loc[mask, 'market_id'].unique().tolist())
                self._logger.notice(
                    f"ignore_markets: dropping {int(mask.sum())} stores from "
                    f"markets {dropped} (requested: {self.ignore_markets})"
                )
                self.data = self.data.loc[~mask].copy()
                if self.data.empty:
                    raise DataNotFound(
                        "All stores were removed by ignore_markets", status=404
                    )
            else:
                self._logger.warning(
                    "ignore_markets was set but the dataframe has no "
                    "'market_id' column; nothing was filtered."
                )
        # if dataframe doesn't have a store_position attribute
        if 'store_position' not in self.data.columns:
            # Create the store_position column
            self.data['store_position'] = self.data.apply(
                lambda row: (row['latitude'], row['longitude']),
                axis=1
            )
        # Exceptions Filename:
        self._exceptions_file = None
        if hasattr(self, 'exceptions_filename'):
            self._exceptions_file = Path(self.exceptions_filename).resolve()
        return True

