"""Check the built Python client against the released-surface record.

CI verifies every callable Python accessor in the built client against
``packages/codegen/released-operations.json``. This check runs in **both**
directions:

* every operation the Python client *covers* must resolve to a callable
  snake_case path on the client, and
* every callable accessor the client exposes must be one of those covered
  operations — no extra method may reach a release without appearing in the
  record.

"Covered" is doing real work, because the release candidate is ``tool_router``
only while the record holds all 104 operations. The coverage filter is
``python/surface-coverage.json``, generated by ``packages/codegen`` from the
same operation plan the resource classes are, so it is reviewable in a diff
rather than being a second hand-kept opinion. This script re-derives the
snake_case spelling from the record's camelCase locations independently of the
generator, so a naming bug has to occur twice, in two languages, to pass.

Introspecting the **built wheel** rather than ``src/`` is the point of ``--wheel``:
a packaging mistake — a resource module missing from the wheel, a subpackage
without its ``__init__.py`` — is invisible to a check that reads the source
tree, and is exactly the class of mistake a release candidate must not ship.

Usage::

    # against the current environment (fast; what pytest runs)
    uv run python scripts/check_surface_conformance.py

    # against a built artifact (what CI runs after `uv build`)
    uv run python scripts/check_surface_conformance.py --wheel dist/composio_client-2.0.0-py3-none-any.whl

    # internal: dump the surface of whatever `composio_client` is importable
    python scripts/check_surface_conformance.py --dump
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

from composio_client import ProjectAuth

_SCRIPTS = Path(__file__).resolve().parent
COVERAGE_PATH = _SCRIPTS.parent / "surface-coverage.json"
RELEASED_OPERATIONS_PATH = _SCRIPTS.parents[1] / "packages" / "codegen" / "released-operations.json"


def snake_case(camel: str) -> str:
    """The record's camelCase spelling as Python writes it.

    Deliberately a second implementation of the generator's rule rather than a
    lookup of its output: an initialism run is one word, and the last capital of
    a run starts the next word when a lowercase letter follows
    (``createDownloadURL`` -> ``create_download_url``, ``regenerateAPIKey`` ->
    ``regenerate_api_key``). A naive per-capital split gives
    ``create_download_u_r_l`` and would fail this check loudly.
    """
    boundary = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", camel)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", boundary).lower()


# ---------------------------------------------------------------------------
# The dump half: runs wherever `composio_client` is importable.
# ---------------------------------------------------------------------------


def _walk(resource: object, prefix: list[str], base: type) -> list[list[str]]:
    """Every public callable reachable from a resource, as accessor paths."""
    found: list[list[str]] = []
    for name in sorted(dir(resource)):
        if name.startswith("_"):
            continue
        value = getattr(resource, name)
        if isinstance(value, base):
            found.extend(_walk(value, [*prefix, name], base))
        elif callable(value):
            found.append([*prefix, name])
    return found


#: The one underscored client attribute that is a resource: the operations the
#: spec tags ``x-internal`` live under it, and the record lists them there.
INTERNAL_ACCESSOR = "_internal"


def _client_surface(client: object, base: type) -> list[list[str]]:
    found: list[list[str]] = []
    for name in sorted(dir(client)):
        if name.startswith("_") and name != INTERNAL_ACCESSOR:
            continue
        value = getattr(client, name)
        if isinstance(value, base):
            found.extend(_walk(value, [name], base))
    return found


def dump_surface() -> dict[str, Any]:
    """The accessor tree of the importable ``composio_client``, sync and async."""
    from composio_client import AsyncComposio, Composio  # noqa: PLC0415
    from composio_client.resources._base import (  # noqa: PLC0415
        AsyncAPIResource,
        SyncAPIResource,
    )

    # Never dispatches; the constructor only resolves options.
    api_key, base_url = "surface-conformance", "https://client.invalid"
    sync_client = Composio(auth=ProjectAuth(api_key), base_url=base_url)
    async_client = AsyncComposio(auth=ProjectAuth(api_key), base_url=base_url)
    try:
        return {
            "module": str(Path(sys.modules["composio_client"].__file__ or "?").parent),
            "sync": sorted(_client_surface(sync_client, SyncAPIResource)),
            "async": sorted(_client_surface(async_client, AsyncAPIResource)),
        }
    finally:
        sync_client.close()


# ---------------------------------------------------------------------------
# The comparison half: runs in the repository, against a dumped surface.
# ---------------------------------------------------------------------------


def check_surface(surface: dict[str, Any]) -> list[str]:
    """Compare a dumped surface against the coverage filter and the record."""
    coverage = json.loads(COVERAGE_PATH.read_text())
    released: dict[str, list[str]] = json.loads(RELEASED_OPERATIONS_PATH.read_text())
    problems: list[str] = []

    if not coverage["operations"]:
        problems.append("surface-coverage.json declares no operations")

    expected: set[tuple[str, ...]] = set()
    for entry in coverage["operations"]:
        key, location, accessor = entry["key"], entry["location"], entry["accessor"]
        # The coverage filter must be a *view* of the record, never a parallel
        # naming authority: a covered operation the record does not hold at the
        # same location is a coverage entry that has drifted.
        recorded = released.get(key)
        if recorded is None:
            problems.append(f"covered operation {key!r} is absent from released-operations.json")
        elif recorded != location:
            problems.append(
                f"covered operation {key!r} is recorded at {'.'.join(recorded)} "
                f"but coverage claims {'.'.join(location)}"
            )
        derived = [snake_case(segment) for segment in location]
        if derived != accessor:
            problems.append(
                f"covered operation {key!r}: the record's {'.'.join(location)} converts to "
                f"{'.'.join(derived)}, but coverage claims {'.'.join(accessor)}"
            )
        expected.add(tuple(accessor))

    for flavor in ("sync", "async"):
        actual = {tuple(path) for path in surface[flavor]}
        for missing in sorted(expected - actual):
            problems.append(f"{flavor}: covered operation has no callable at {'.'.join(missing)}")
        for extra in sorted(actual - expected):
            problems.append(f"{flavor}: {'.'.join(extra)} is callable but is not a covered operation")

    # The two clients are generated from one plan, so a divergence is a
    # generator or packaging fault rather than a surface decision.
    if sorted(surface["sync"]) != sorted(surface["async"]):
        problems.append("the sync and async clients expose different accessor trees")
    return problems


def surface_from_wheel(wheel: Path) -> dict[str, Any]:
    """Dump the surface of an installed wheel, in a throwaway environment."""
    completed = subprocess.run(  # noqa: S603
        [
            "uv",
            "run",
            "--isolated",
            "--no-project",
            "--refresh-package",
            "composio-client",
            "--with",
            str(wheel),
            "python",
            str(Path(__file__).resolve()),
            "--dump",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        raise SystemExit(f"surface conformance: could not introspect {wheel}\n{completed.stderr.strip()}")
    dumped: dict[str, Any] = json.loads(completed.stdout)
    return dumped


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dump", action="store_true", help="print the importable client's surface")
    parser.add_argument("--wheel", type=Path, help="introspect this built wheel instead")
    args = parser.parse_args(argv)

    if args.dump:
        json.dump(dump_surface(), sys.stdout)
        return 0

    surface = surface_from_wheel(args.wheel) if args.wheel else dump_surface()
    problems = check_surface(surface)
    if problems:
        print(f"surface conformance: {len(problems)} problem(s) against {surface['module']}")
        for problem in problems:
            print(f"  {problem}")
        return 1
    covered = len(json.loads(COVERAGE_PATH.read_text())["operations"])
    print(f"surface conformance: {covered} covered operation(s) callable in {surface['module']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
