"""Tests for ServiceNow Snowflake CREATE VIEW queries."""

from tests.helpers import assert_table_lineage_equal


def test_servicenow_snowflake_view_from_union_source():
    """Test Snowflake view with complex CTEs, UNIONs, and multiple JOINs."""
    assert_table_lineage_equal(
        """
create or replace view SRC_V_FACT_EVENT_OPEN_PIPELINE_ST(
    ACCOUNT_SYSID,
    ACCOUNT_CHANNEL_MANAGER_SYSID,
    ACCOUNT_NUMBER,
    OPPORTUNITY_TYPE,
    OPPORTUNITY_STAGE,
    LAND_EXPAND_RENEW_FLAG,
    OPPORTUNITY_NUMBER,
    OPPORTUNITY_LINE_ITEM_NUMBER,
    OPPORTUNITY_CLOSE_DT,
    OPPORTUNITY_CLOSE_QUARTER,
    OPPORTUNITY_CREATED_DT,
    OPPORTUNITY_CREATED_QUARTER,
    OPPORTUNITY_BU,
    OPPORTUNITY_TERRITORY_CC,
    OPPORTUNITY_TERRITORY_GEO,
    OPPORTUNITY_TERRITORY_AREA,
    REPORTING_TERRITORY_GEO,
    ACCOUNT_GRADE,
    CONTRACT_NUMBER,
    ACV,
    NET_NEW_ACV_USD,
    EVENT_CITY,
    EVENT_NAME,
    P0_EVENT_NAME,
    P1_EVENT_NAME,
    REGISTRANTS_COUNT,
    ATTENDEES_COUNT,
    P0_EVENT_REGISTRANTS_COUNT,
    P0_EVENT_ATTENDEES_COUNT,
    P1_EVENT_REGISTRANTS_COUNT,
    P1_EVENT_ATTENDEES_COUNT,
    ST_EXTRACT_DT,
    EVENT_REGISTERED_FLAG,
    EVENT_ATTENDED_FLAG
) as
WITH CTE_PREVIOUS_EVENT AS (
SELECT DISTINCT EVENT_NAME,PREVIOUS_EVENT_NAME FROM ODS_LS.MARKETING.MKT_KNOWLEDGE_EVENT_DATES
)

,CTE_EVENT_REGISTRATIONS AS (
SELECT DISTINCT
C.EVENT_NAME
,A.ACCOUNT_NUMBER
,Count (distinct case when  C.REGISTERED_FLAG='Y'  then C.EVENT_ATTENDEE_ID end) as  REGISTRANTS_COUNT
,Count (distinct case when  C.ATTENDED_FLAG='Y'  then C.EVENT_ATTENDEE_ID end) as  ATTENDEES_COUNT
FROM CDL_LS.MARKETING_RPT.V_FACT_EVENT_REGISTRATION A
LEFT OUTER JOIN CDL_LS.MARKETING_RPT.V_DIM_EVENT_LEAD_DETAIL C
ON A.EVENT_ATTENDEE_ID=C.EVENT_ATTENDEE_ID
LEFT OUTER JOIN CDL_LS.MARKETING_RPT.V_DIM_MARKETING_ACCOUNT D
ON A.ACCOUNT_NUMBER=D.ACCOUNT_NUMBER
WHERE 1=1
AND YEAR(A.EVENT_DT)>=2025
AND A.TEST_FLAG='N'
AND (C.REGISTERED_FLAG='Y' OR C.ATTENDED_FLAG='Y')
GROUP BY ALL

UNION ALL

SELECT
"EventName" EVENT_NAME
, "AccountNumber"  ACCOUNT_NUMBER
,Count (distinct case when  "Registration_Status" = 'Registered'  then "AttendeeID" end) as  REGISTRANTS_COUNT
,Count (distinct case when  "Registration_Status" = 'Attended'  then "AttendeeID" end) as  ATTENDEES_COUNT
from CDL_LS."MARKETING_ER"."KNOWLEDGE_REGISTRATION_EXT"
WHERE
"TestFlag" ='N'
and "Registration_Status" in ('Registered','Attended')
and "EventName" in ('K24','K23','WF24','WF23','SNSummit24','SNSummit23')
GROUP BY ALL
)

,BUSINESS_UNIT as (
SELECT
"ValueAtSource" "SourceBU",
CASE WHEN "ValueAtSource" = 'All BUs' THEN 'All BUs'
ELSE "ReportingValues"
END "ReportingBU"
FROM
ODS_LS.FLATFILESOURCE.MKT_DIMENSION_MAPPING_TABLE
WHERE
"CategoryType" = 'BusinessUnit'
AND "ActiveFlag" = 1
)

,CTE_BASE AS (
SELECT
ACCOUNT_SYSID
,ACCOUNT_CHANNEL_MANAGER_SYSID
,ACCOUNT_NUMBER
,OPPORTUNITY_TYPE
,OPPORTUNITY_STAGE
,LAND_EXPAND_RENEW_FLAG
,OPPORTUNITY_NUMBER
,OPPORTUNITY_LINE_ITEM_NUMBER
,OPPORTUNITY_CLOSE_DT
,OPPORTUNITY_CLOSE_QUARTER
,OPPORTUNITY_CREATED_DT
,OPPORTUNITY_CREATED_QUARTER
,OPPORTUNITY_BU
,OPPORTUNITY_TERRITORY_CC
,OPPORTUNITY_TERRITORY_GEO
,OPPORTUNITY_TERRITORY_AREA
,REPORTING_TERRITORY_GEO
,ACCOUNT_GRADE
,CONTRACT_NUMBER
,ACV
,NET_NEW_ACV_USD
,EVENT_CITY
,EVENT_NAME
,ST_EXTRACT_DT
FROM EDW_LS.MARKETING.FACT_PRE_EVENT_OPEN_PIPELINE_SNAPSHOT
)

,Reg_Attend AS (
SELECT
ACCOUNT_SYSID
,ACCOUNT_CHANNEL_MANAGER_SYSID
,ACCOUNT_NUMBER
,OPPORTUNITY_TYPE
,OPPORTUNITY_STAGE
,LAND_EXPAND_RENEW_FLAG
,OPPORTUNITY_NUMBER
,OPPORTUNITY_LINE_ITEM_NUMBER
,OPPORTUNITY_CLOSE_DT
,OPPORTUNITY_CLOSE_QUARTER
,OPPORTUNITY_CREATED_DT
,OPPORTUNITY_CREATED_QUARTER
,OPPORTUNITY_BU
,OPPORTUNITY_TERRITORY_CC
,OPPORTUNITY_TERRITORY_GEO
,OPPORTUNITY_TERRITORY_AREA
,REPORTING_TERRITORY_GEO
,ACCOUNT_GRADE
,CONTRACT_NUMBER
,ACV
,NET_NEW_ACV_USD
,EVENT_CITY
,EVENT_NAME
,ST_EXTRACT_DT
,'Y' EVENT_REGISTERED_FLAG
,'Y' EVENT_ATTENDED_FLAG
FROM CTE_BASE WHERE EVENT_CITY NOT LIKE '%Open Pipeline%'
)
,Reg_NotAttend as (
SELECT
 A.ACCOUNT_SYSID
,A.ACCOUNT_CHANNEL_MANAGER_SYSID
,A.ACCOUNT_NUMBER
,A.OPPORTUNITY_TYPE
,A.OPPORTUNITY_STAGE
,A.LAND_EXPAND_RENEW_FLAG
,A.OPPORTUNITY_NUMBER
,A.OPPORTUNITY_LINE_ITEM_NUMBER
,A.OPPORTUNITY_CLOSE_DT
,A.OPPORTUNITY_CLOSE_QUARTER
,A.OPPORTUNITY_CREATED_DT
,A.OPPORTUNITY_CREATED_QUARTER
,A.OPPORTUNITY_BU
,A.OPPORTUNITY_TERRITORY_CC
,A.OPPORTUNITY_TERRITORY_GEO
,A.OPPORTUNITY_TERRITORY_AREA
,A.REPORTING_TERRITORY_GEO
,A.ACCOUNT_GRADE
,A.CONTRACT_NUMBER
,A.ACV
,A.NET_NEW_ACV_USD
,A.EVENT_CITY
,A.EVENT_NAME
,A.ST_EXTRACT_DT
,'Y' EVENT_REGISTERED_FLAG
,'N' EVENT_ATTENDED_FLAG
FROM CTE_BASE A
INNER JOIN (SELECT DISTINCT
B.EVENT_NAME,
A.ACCOUNT_NUMBER
FROM CDL_LS.MARKETING_RPT.V_FACT_EVENT_REGISTRATION A
LEFT OUTER JOIN ODS_LS.MARKETING.MKT_KNOWLEDGE_EVENT_DATES B
ON A.CAMPAIGN_ID =B."CAMPAIGN_ID"
LEFT OUTER JOIN CDL_LS.MARKETING_RPT.V_DIM_EVENT_LEAD_DETAIL C
ON A.EVENT_ATTENDEE_ID=C.EVENT_ATTENDEE_ID
LEFT OUTER JOIN CDL_LS.MARKETING_RPT.V_DIM_MARKETING_ACCOUNT D
ON A.ACCOUNT_NUMBER=D.ACCOUNT_NUMBER
WHERE 1=1
AND A.TEST_FLAG='N'
AND C.REGISTERED_FLAG='Y'
AND A.ACCOUNT_NUMBER IS NOT NULL
) B
ON A."ACCOUNT_NUMBER"=B."ACCOUNT_NUMBER"
AND A.EVENT_NAME=B.EVENT_NAME
LEFT OUTER JOIN (SELECT DISTINCT "EVENT_NAME","ACCOUNT_NUMBER" FROM Reg_Attend) C
ON B."EVENT_NAME"=C."EVENT_NAME" AND A."ACCOUNT_NUMBER"=C."ACCOUNT_NUMBER"
WHERE A."EVENT_CITY" LIKE '%Open Pipeline%' and C."EVENT_NAME" IS NULL
)
,NotReg_NotAttend as (
SELECT
 A.ACCOUNT_SYSID
,A.ACCOUNT_CHANNEL_MANAGER_SYSID
,A.ACCOUNT_NUMBER
,A.OPPORTUNITY_TYPE
,A.OPPORTUNITY_STAGE
,A.LAND_EXPAND_RENEW_FLAG
,A.OPPORTUNITY_NUMBER
,A.OPPORTUNITY_LINE_ITEM_NUMBER
,A.OPPORTUNITY_CLOSE_DT
,A.OPPORTUNITY_CLOSE_QUARTER
,A.OPPORTUNITY_CREATED_DT
,A.OPPORTUNITY_CREATED_QUARTER
,A.OPPORTUNITY_BU
,A.OPPORTUNITY_TERRITORY_CC
,A.OPPORTUNITY_TERRITORY_GEO
,A.OPPORTUNITY_TERRITORY_AREA
,A.REPORTING_TERRITORY_GEO
,A.ACCOUNT_GRADE
,A.CONTRACT_NUMBER
,A.ACV
,A.NET_NEW_ACV_USD
,A.EVENT_CITY
,A.EVENT_NAME
,A.ST_EXTRACT_DT
,'N' EVENT_REGISTERED_FLAG
,'N' EVENT_ATTENDED_FLAG
FROM CTE_BASE A
LEFT OUTER JOIN (SELECT DISTINCT "EVENT_NAME","ACCOUNT_NUMBER" FROM EDW_LS.MARKETING_EM.SRC_V_DIM_EVENT_ACCOUNT_CREDITED WHERE 1=1 AND "REGISTERED_FLAG"='Y' AND  "ATTENDED_FLAG"='Y'
                 UNION
                 SELECT DISTINCT "EVENT_NAME","ACCOUNT_NUMBER" FROM Reg_NotAttend
                 UNION
                 SELECT DISTINCT "EVENT_NAME","ACCOUNT_NUMBER" FROM Reg_Attend
                 ) C
ON A."EVENT_NAME"=C."EVENT_NAME" AND A."ACCOUNT_NUMBER"=C."ACCOUNT_NUMBER"
WHERE A."EVENT_CITY" LIKE '%Open Pipeline%'
AND C."EVENT_NAME" IS NULL
)
,FINAL AS (select * from Reg_Attend
union all
select * from Reg_NotAttend
union all
select * from NotReg_NotAttend)

SELECT
 F.ACCOUNT_SYSID
,F.ACCOUNT_CHANNEL_MANAGER_SYSID
,F.ACCOUNT_NUMBER
,F.OPPORTUNITY_TYPE
,F.OPPORTUNITY_STAGE
,F.LAND_EXPAND_RENEW_FLAG
,F.OPPORTUNITY_NUMBER
,F.OPPORTUNITY_LINE_ITEM_NUMBER
,F.OPPORTUNITY_CLOSE_DT
,F.OPPORTUNITY_CLOSE_QUARTER
,F.OPPORTUNITY_CREATED_DT
,F.OPPORTUNITY_CREATED_QUARTER
,BU."ReportingBU" AS OPPORTUNITY_BU
,F.OPPORTUNITY_TERRITORY_CC
,F.OPPORTUNITY_TERRITORY_GEO
,F.OPPORTUNITY_TERRITORY_AREA
,F.REPORTING_TERRITORY_GEO
,F.ACCOUNT_GRADE
,F.CONTRACT_NUMBER
,F.ACV
,F.NET_NEW_ACV_USD
,F.EVENT_CITY
,F.EVENT_NAME
,P0.PREVIOUS_EVENT_NAME AS P0_EVENT_NAME
,P1.PREVIOUS_EVENT_NAME AS P1_EVENT_NAME
,CURRENT_EVENT_REG_ATT.REGISTRANTS_COUNT
,CASE WHEN F.EVENT_ATTENDED_FLAG='Y' THEN CURRENT_EVENT_REG_ATT.ATTENDEES_COUNT END ATTENDEES_COUNT
,P0_EVENT_REG_ATT.REGISTRANTS_COUNT AS P0_EVENT_REGISTRANTS_COUNT
,P0_EVENT_REG_ATT.ATTENDEES_COUNT AS P0_EVENT_ATTENDEES_COUNT
,P1_EVENT_REG_ATT.REGISTRANTS_COUNT AS P1_EVENT_REGISTRANTS_COUNT
,P1_EVENT_REG_ATT.ATTENDEES_COUNT AS P1_EVENT_ATTENDEES_COUNT
,F.ST_EXTRACT_DT
,F.EVENT_REGISTERED_FLAG
,F.EVENT_ATTENDED_FLAG
FROM FINAL F
LEFT OUTER JOIN BUSINESS_UNIT BU
                ON BU."SourceBU"= F.OPPORTUNITY_BU
LEFT OUTER JOIN CTE_PREVIOUS_EVENT P0
                ON F.EVENT_NAME= P0.EVENT_NAME
LEFT OUTER JOIN CTE_PREVIOUS_EVENT P1
                ON P0.PREVIOUS_EVENT_NAME=P1.EVENT_NAME
LEFT OUTER JOIN CTE_EVENT_REGISTRATIONS  CURRENT_EVENT_REG_ATT
                ON CURRENT_EVENT_REG_ATT.EVENT_NAME=F.EVENT_NAME
                AND CURRENT_EVENT_REG_ATT.ACCOUNT_NUMBER=F.ACCOUNT_NUMBER
LEFT OUTER JOIN CTE_EVENT_REGISTRATIONS  P0_EVENT_REG_ATT
                ON P0_EVENT_REG_ATT.EVENT_NAME=P0.PREVIOUS_EVENT_NAME
                AND P0_EVENT_REG_ATT.ACCOUNT_NUMBER=F.ACCOUNT_NUMBER
LEFT OUTER JOIN CTE_EVENT_REGISTRATIONS  P1_EVENT_REG_ATT
                ON P1_EVENT_REG_ATT.EVENT_NAME=P1.PREVIOUS_EVENT_NAME
                AND P1_EVENT_REG_ATT.ACCOUNT_NUMBER=F.ACCOUNT_NUMBER;""",
        {
            "cdl_ls.marketing_rpt.v_dim_event_lead_detail",
            "cdl_ls.marketing_rpt.v_fact_event_registration",
            "edw_ls.marketing_em.src_v_dim_event_account_credited",
            "cdl_ls.marketing_er.knowledge_registration_ext",
            "ods_ls.marketing.mkt_knowledge_event_dates",
            "cdl_ls.marketing_rpt.v_dim_marketing_account",
            "edw_ls.marketing.fact_pre_event_open_pipeline_snapshot",
            "ods_ls.flatfilesource.mkt_dimension_mapping_table",
        },
        {"src_v_fact_event_open_pipeline_st"},
        dialect="snowflake",
        test_sqlparse=False,
        skip_graph_check=True,
    )
