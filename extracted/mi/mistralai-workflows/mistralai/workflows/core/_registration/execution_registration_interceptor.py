from __future__ import annotations

import hashlib
from datetime import timedelta
from typing import Any

import structlog
import temporalio.client
import temporalio.common
import temporalio.worker
from temporalio import workflow

from mistralai.workflows.core._registration.registration_activity import (
    _register_execution,
)
from mistralai.workflows.core.temporal.context_handler_interceptor import (
    retrieve_context,
    workflow_context_var,
)
from mistralai.workflows.core.utils.contextvars import reset_contextvar, unwrap_contextual_result

logger = structlog.get_logger(__name__)


def _hash_token(raw_token: str) -> str:
    return hashlib.sha256(raw_token.encode("utf-8")).hexdigest()


class _ExecutionRegistrationWorkflowInboundInterceptor(temporalio.worker.WorkflowInboundInterceptor):
    async def execute_workflow(self, input: temporalio.worker.ExecuteWorkflowInput) -> Any:
        ctx = retrieve_context()
        if ctx is None:
            raise RuntimeError(
                "ExecutionRegistrationInterceptor requires a WorkflowContext. "
                "Ensure ContextHandlerInterceptor runs before this interceptor."
            )

        info = workflow.info()
        is_first_run = info.run_id == info.first_execution_run_id

        # Execution tokens are generated by abraxas for API-triggered executions.
        # For child workflows, continue-as-new, and scheduled workflows, the
        # interceptor generates them.  Reset runs replay the original payload
        # (with the stale token) so we must generate a fresh one to avoid
        # hash collisions.
        if ctx.execution_token is not None and is_first_run:
            raw_token = ctx.execution_token
        else:
            raw_token = str(workflow.uuid4())

        token_hash = _hash_token(raw_token)

        raw_result = await workflow.execute_local_activity(
            _register_execution,
            args=[
                info.workflow_id,
                info.run_id,
                info.workflow_type,
                info.task_queue,
                info.parent.workflow_id if info.parent else None,
                info.root.workflow_id if info.root else None,
                token_hash,
            ],
            start_to_close_timeout=timedelta(seconds=10),
            retry_policy=temporalio.common.RetryPolicy(maximum_attempts=3),
        )

        _, registered = unwrap_contextual_result(raw_result)

        # Retrocompatibility: a 404 means the API version doesn't expose the
        # /register endpoint yet — continue without setting the token.
        if not registered:
            logger.info(
                "Registration endpoint not available, continuing without it",
                workflow_id=info.workflow_id,
                run_id=info.run_id,
            )
            return await super().execute_workflow(input)

        updated_ctx = ctx.model_copy(update={"execution_token": raw_token})
        token = workflow_context_var.set(updated_ctx.model_dump_json())
        try:
            return await super().execute_workflow(input)
        finally:
            reset_contextvar(workflow_context_var, token)


class ExecutionRegistrationInterceptor(temporalio.client.Interceptor, temporalio.worker.Interceptor):
    def workflow_interceptor_class(
        self, input: temporalio.worker.WorkflowInterceptorClassInput
    ) -> type[temporalio.worker.WorkflowInboundInterceptor] | None:
        return _ExecutionRegistrationWorkflowInboundInterceptor
