"""Workflows (the `flows` collection) as api-chatty reads them: the port every store of their previews implements.

copilot_v2 (flows.letschatty.com) owns the document and writes it; api-chatty only READS it, so the port has no
write: whatever writes `flows` does it outside this port (docs/automatizacion/workflows.md of api-chatty, «Quién
escribe»). Not a catalog (ADR-010 of api-chatty): nothing is created, updated or deleted through it, nothing is
cached (a workflow edited in copilot has to show on the next read) and it is read by id whatever the company, because
the global workflow (`companyId` = 24 zeros, «Smart Follow Up») is every company's. That the list of a company also has the
global one is the use case's rule: the repository reads the companies it is given.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, List, Optional, Protocol, Set

from ...models.company.assets.flow import FlowPreview


@dataclass(frozen=True)
class GeneratedLink:
    """A link of a chain that copilot generated (`generado_por`), as the narrow reads project it: the id, and the
    stored `clave`, `hash`, `orden`, `cadena` and `cierre` AS THEY ARE (no coercion: the rules that read them look at
    their type, and copilot is who writes them). A field the read does not project, or the document does not have,
    is None (`main` read every one with `.get`, so a missing one and a null one were the same)."""

    id: str
    key: Any = None
    hash: Any = None
    order: Any = None
    chain: Any = None
    closing: Any = None


class WorkflowRepository(Protocol):
    async def by_id(self, workflow_id: str) -> FlowPreview:
        """The workflow with that id, deleted, hidden or generated ones included and whatever its company; the
        preview is built from the stored document as it is (`FlowPreview.default_create_instance_method`).
        Raises `NotFoundError` («No document found with id … in db collection … and db …») when it does not exist."""
        ...

    async def live_of_companies(self, company_ids: List[str], *, not_generated_by: str) -> List[FlowPreview]:
        """The workflows of those companies (read by `companyId`, the field copilot writes; which ones count, the global
        company included, is the use case's rule) that are not
        deleted (`deleted_at` null or missing) and were not generated by `not_generated_by` (`generado_por`), hidden
        ones included, in the order Mongo returns them. One stored document that cannot be built raises: the whole
        list fails."""
        ...

    async def selectable_among(self, company_ids: List[str], ids: List[str], *, not_generated_by: str) -> Set[str]:
        """Which of `ids` (valid ObjectId text) are workflows a picker offers: of those companies (`companyId`), not
        deleted (`deleted_at` null or missing), not hidden (`visible` anything but `false`) and not generated by
        `not_generated_by`. Only the ids are read (nothing is built), as the text of the stored `_id`."""
        ...


class GeneratedLinkReader(Protocol):
    """The narrow reads of the links copilot generated for the attention follow-up chains
    (`docs/atencion/cadenas-de-seguimiento.md` of api-chatty), on the same `flows`: a port of its own, so the chains
    depend only on what they read (`MongoGeneratedLinkReader`). Every one filters by the mark
    (`generado_por`, the partial filter of `idx_seguimientos_company_clave_visible_orden`), is projected and has a 5 s
    `maxTimeMS`; ids arrive already valid (the rule drops the others and reads nothing when none is left)."""

    async def visible_generated_of_company(self, company_id: str, *, generated_by: str, limit: int) -> List[GeneratedLink]:
        """The visible links generated for the company (`companyId` text), ordered by `clave` and `orden`, up to `limit`
        (cut after sorting), with `key`, `hash`, `order` and `chain`."""
        ...

    async def visible_generated_of_key(self, company_id: str, key: str, *, generated_by: str,
                                       limit: int) -> List[GeneratedLink]:
        """The visible links generated for one `clave` of the company, in Mongo's order, up to `limit`, with `key`,
        `hash`, `order` and `chain`."""
        ...

    async def generated_ids_among(self, company_id: str, ids: List[str], *, generated_by: str) -> Set[str]:
        """Which of these ids are links generated for the company, visible or retired. One query by `_id`."""
        ...

    async def follow_ups_among(self, ids: List[str], *, not_generated_by: str) -> Set[str]:
        """Which of these ids are follow-up workflows NOT generated by `not_generated_by`: `es_seguimiento: true` or
        titled «Smart Follow Up» (any case). Whatever the company: the «Smart Follow Up» is the global company's."""
        ...

    async def key_of_generated(self, company_id: str, workflow_id: str, *, generated_by: str) -> Optional[Any]:
        """The stored `clave` of a link generated for the company (visible or retired), or None when there is none."""
        ...

    async def generated_links_among(self, company_id: str, ids: List[str], *,
                                    generated_by: str) -> List[GeneratedLink]:
        """The links generated for the company among these ids, visible or retired, with `key`, `order` and
        `closing`. One query by `_id`."""
        ...

    async def generated_of_company(self, company_id: str, *, generated_by: str, limit: int) -> List[GeneratedLink]:
        """Every link generated for the company, visible or retired, in Mongo's order, up to `limit`, with `key`."""
        ...
