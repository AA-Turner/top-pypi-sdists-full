// Result of `dmd_parse`, `dmd_parse_lossless` or `dmd_unparse`. Must be freed with
// `dmd_parse_result_free`.
typedef struct DmdParseResult {
	// UTF-8 bytes of the call's output when `ok` -- the JSON AST for `dmd_parse`, the JSON tree for
	// `dmd_parse_lossless`, the markdown for `dmd_unparse` -- or of an error message otherwise. Not
	// NUL-terminated, and never null.
	uint8_t *data;
	// Length of `data` in bytes.
	size_t len;
	// Whether parsing succeeded.
	bool ok;
} DmdParseResult;

// The `fuel` argument to `dmd_parse` that selects the parser's own default budget. Zero is the
// sentinel because a C caller cannot spell "absent" and a budget of zero is not a request anyone
// can mean — it fails every parse that reaches the inline parser. Pass 1 for the smallest real
// budget.
#define DMD_FUEL_DEFAULT 0u

