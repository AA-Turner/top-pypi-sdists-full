# How often the background ticker emits a "still working" pulse during long,
# otherwise-silent stages (research / script / audio / each media render).
_TICK_INTERVAL_SECONDS = 3.0

# How often the DEDICATED heartbeat loop (`_heartbeat`, separate from the UI
# ticker) bumps the run row's ``last_heartbeat_at``. Clients that are NOT holding
# the live stream — a reloaded page, a phone back from background, the manage
# list, the reconcile endpoint — judge liveness from that column against a
# ~3-minute threshold. Stage commits alone leave it stale for the entire length
# of a video render or an ffmpeg compose, which made healthy runs read as
# "interrupted". 30s keeps the column fresh with ~6x margin. CAPS.
_DB_HEARTBEAT_INTERVAL_SECONDS = 30.0


async def run_heartbeat_loop(
    ckpt: object | None,
    running: dict[str, tuple[float, str]],
    *,
    interval: float = _DB_HEARTBEAT_INTERVAL_SECONDS,
) -> None:
    """Pulse ``last_heartbeat_at`` for as long as any stage is in flight.

    Module-level and dependency-light ON PURPOSE: this loop is the sole reason a
    long, silent stage still reads as ALIVE to every client that is not holding
    the stream, and the bug it replaced was invisible precisely because the logic
    was buried in a closure nobody could exercise. Now it can be driven directly.

    Two properties it must keep, both of which the old version lost:
      * It touches on its own clock, never as a side effect of emitting to the
        client. One wedged `on_event` must not stop the pulse.
      * It AWAITS the write instead of firing an unreferenced task, which the
        garbage collector was free to drop mid-flight.
    """
    touch = getattr(ckpt, "touch", None)
    if touch is None:
        return
    try:
        while True:
            await asyncio.sleep(interval)
            if running:
                await touch()
    except asyncio.CancelledError:
        pass


