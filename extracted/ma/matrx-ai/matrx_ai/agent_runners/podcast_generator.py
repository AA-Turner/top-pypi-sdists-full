def _usage_from_agent_result(result: AgentRunResult) -> dict[str, object] | None:
    """Extract an AiUsage-shape dict from an ``AgentRunResult``, or ``None``
    when the agent genuinely recorded no billed usage for this call."""
    agg = result.usage_aggregated
    if agg is None:
        return None
    total = agg.total
    if not total.total_tokens and not (total.total_cost or 0.0):
        return None
    models: dict[str, dict[str, object]] = {
        model_name: {
            "input_tokens": summary.input_tokens,
            "output_tokens": summary.output_tokens,
            "total_tokens": summary.total_tokens,
            "cost_usd": summary.cost or 0.0,
            "request_count": summary.request_count,
        }
        for model_name, summary in agg.by_model.items()
    }
    return AiUsage(
        input_tokens=total.input_tokens,
        output_tokens=total.output_tokens,
        total_tokens=total.total_tokens,
        cost_usd=total.total_cost or 0.0,
        models=models,
    ).model_dump()


def _to_stage(stage: str, result: AgentRunResult) -> StageResult:
    """Adapt a canonical ``AgentRunResult`` into the pipeline's ``StageResult``."""
    usage = _usage_from_agent_result(result)
    if not result.success:
        vcprint(f"[PodcastGenerator] {stage} failed: {result.error}", color="red")
        return StageResult(stage=stage, success=False, error=result.error, usage=usage)
    return StageResult(stage=stage, success=True, output=result.output, usage=usage)


def _aggregate_stage_usage(
    stage_results: list[StageResult], *, unsettled_only: bool = False
) -> dict[str, object] | None:
    """Sum every stage's ``usage`` (AiUsage shape) into one aggregate for the
    whole pipeline run — populated on BOTH the success and failure paths so a
    paid-but-failed run (e.g. script agent burned tokens, then audio failed)
    still settles its cost.

    ``unsettled_only=True`` is the BILLING aggregate (the settle-safe delta):
    it excludes stages replayed from a checkpoint (``usage_settled=True``),
    whose spend was already settled by the attempt that paid for it. The
    invariant (review #8): **a resumed run reports full usage but never
    settles the same stage twice.** Default (``False``) is the full REPORTING
    aggregate.

    Returns ``None`` (never a faked zero block) when no stage in the run
    tracked any usage at all — e.g. an early content-prep/gate failure before
    any billed call ran, or a pipeline where every stage that ran happens to
    be a non-agent media stage that doesn't track usage here.
    """
    stage_usages = [
        s.usage for s in stage_results if s.usage and not (unsettled_only and s.usage_settled)
    ]
    if not stage_usages:
        return None
    input_tokens = sum(int(u.get("input_tokens") or 0) for u in stage_usages)
    output_tokens = sum(int(u.get("output_tokens") or 0) for u in stage_usages)
    total_tokens = sum(int(u.get("total_tokens") or 0) for u in stage_usages)
    cost_usd = sum(float(u.get("cost_usd") or 0.0) for u in stage_usages)
    models: dict[str, dict[str, object]] = {}
    for usage in stage_usages:
        for model_name, model_usage in (usage.get("models") or {}).items():
            bucket = models.setdefault(
                model_name,
                {"input_tokens": 0, "output_tokens": 0, "total_tokens": 0, "cost_usd": 0.0},
            )
            bucket["input_tokens"] += int(model_usage.get("input_tokens") or 0)
            bucket["output_tokens"] += int(model_usage.get("output_tokens") or 0)
            bucket["total_tokens"] += int(model_usage.get("total_tokens") or 0)
            bucket["cost_usd"] += float(model_usage.get("cost_usd") or 0.0)
    return AiUsage(
        input_tokens=input_tokens,
        output_tokens=output_tokens,
        total_tokens=total_tokens,
        cost_usd=cost_usd,
        models=models,
    ).model_dump()


def _unsettled_cost(stage_results: list[StageResult]) -> float | None:
    """The dollars THIS attempt is responsible for settling onto the run row.

    The settle-safe delta (checkpoint-replayed stages excluded — the attempt that
    paid for them already settled them), so a resumed run adds only its own new
    spend. ``None`` when nothing billable ran, which leaves the row's existing
    total untouched rather than stamping a zero over it.

    Every terminal path passes this — a run that fails after burning a script
    agent and two video renders still owes its cost to the record. A generation
    that shows the user $0.00 for a dollar of real spend is a BILLING defect.
    """
    agg = _aggregate_stage_usage(stage_results, unsettled_only=True)
    if not agg:
        return None
    cost = float(agg.get("cost_usd") or 0.0)
    return cost or None


def _stage_from_payload(key: str, payload: dict[str, object]) -> StageResult:
    """Reconstruct a StageResult from a stage payload dict.

    ``usage`` IS restored (dropping it lost completed stages' spend from the
    resumed run's reporting aggregate — review #8).

    ``usage_settled`` answers ONE question: *did a previous attempt already pay
    for this stage?* It is therefore keyed strictly on the checkpointer's REPLAY
    marker — the payload came back from a stored checkpoint without running —
    and never on "the payload happens to carry usage."

    That distinction is the whole ballgame. This function runs on EVERY stage,
    fresh or replayed, so keying it on `isinstance(usage, dict)` marked stages
    that had *just executed on this attempt* as already-settled. Every stage of
    every fresh run was flagged paid-for, `unsettled_usage` aggregated to nothing,
    and the run settled $0.00 for real money. (Live proof 2026-08-11: run
    55850645 finished with per-stage costs of $0.036 / $0.0018 / $0.0156 and a
    `total_cost` of 0.)
    """
    usage = payload.get("usage")
    return StageResult(
        stage=str(payload.get("stage") or key),
        success=bool(payload.get("success", False)),
        output=str(payload.get("output") or ""),
        error=payload.get("error"),  # type: ignore[arg-type]
        note=payload.get("note"),  # type: ignore[arg-type]
        usage=usage if isinstance(usage, dict) else None,
        usage_settled=bool(payload.get(REPLAYED_KEY)),
    )


async def _checkpointed(
    ckpt: object | None,
    key: str,
    make: Callable[[], Awaitable[StageResult]],
) -> StageResult:
    """Run a StageResult-producing step through the checkpoint.

    On resume, a ``completed`` checkpoint short-circuits ``make`` entirely —
    that stage's expensive work (research, script, a paid image/video, audio)
    is never repeated. When there is no checkpointer, this is a transparent
    pass-through.
    """
    if ckpt is None:
        return await make()

    async def _fn() -> dict[str, object]:
        sr = await make()
        return sr.model_dump()

    payload = await ckpt.stage(key, _fn)  # type: ignore[attr-defined]
    return _stage_from_payload(key, payload)


async def _checkpointed_metadata(
    ckpt: object | None,
    key: str,
    make: Callable[[], Awaitable[tuple[StageResult, PodcastMetadata]]],
) -> tuple[StageResult, PodcastMetadata]:
    """Checkpoint variant for the metadata stage, which yields both a
    StageResult and the parsed ``PodcastMetadata`` (stored under ``metadata``)."""
    if ckpt is None:
        return await make()

    async def _fn() -> dict[str, object]:
        sr, meta = await make()
        data = sr.model_dump()
        data["metadata"] = meta.model_dump()
        return data

    payload = await ckpt.stage(key, _fn)  # type: ignore[attr-defined]
    meta = PodcastMetadata(**(payload.get("metadata") or {}))
    return _stage_from_payload(key, payload), meta


