async def _resolve_file_block(url: str) -> dict[str, object]:
    """Resolve a file URL into a fully-populated ``input_file`` block.

    The internal podcast pipeline calls agents directly via ``NamedAgent.run``
    and therefore NEVER passes through the AI Dream API boundary
    (``normalize_request_body``) that pre-fetches media bytes. Provider
    serializers (``DocumentContent.to_google`` etc.) refuse to fetch URLs —
    they require ``base64_data`` or a ``gs://`` uri — so a block carrying only
    a raw ``url`` is silently DROPPED and the extractor agent sees "no
    resources provided". Per the cloud-file media contract, code that
    constructs a media reference internally must resolve it itself. We resolve
    here to inline base64 so the bytes actually reach the model.
    """
    if not has_ext("get_cloud_file_manager"):
        # Standalone install — no cloud resolver. Degrade visibly: keep the
        # raw url so a provider that CAN fetch (e.g. Anthropic url documents)
        # still works, and so the gap is loud rather than silent.
        vcprint(
            f"[podcast] _resolve_file_block: no cloud FileManager injected; "
            f"passing raw url through unresolved: {url}",
            color="yellow",
        )
        return {"type": "input_file", "url": url}

    from matrx_files.cloud_sync.media_ref import MediaRef
    from matrx_utils.ctx import system_file_access

    fm = get_ext("get_cloud_file_manager")()
    ref = MediaRef(url=url)
    # Internal podcast pipeline resolving a server-side source ref — declare it
    # (in-request runs still authorize as the request user).
    with system_file_access("podcast-pipeline"):
        await fm.resolve_media_async(ref, needs_bytes=True)

    base64_data = getattr(ref, "base64_data", None)
    file_uri = getattr(ref, "file_uri", None)
    mime_type = getattr(ref, "mime_type", None)

    if base64_data:
        return {
            "type": "input_file",
            "base64_data": base64_data,
            "mime_type": mime_type,
        }
    if file_uri and str(file_uri).startswith("gs://"):
        return {"type": "input_file", "file_uri": file_uri, "mime_type": mime_type}

    resolver_error = getattr(ref, "resolver_error", None)
    vcprint(
        f"[podcast] _resolve_file_block: resolver returned no bytes for {url} "
        f"(error={resolver_error!r}); passing raw url through — the provider "
        "will likely drop it.",
        color="red",
    )
    return {"type": "input_file", "url": url, "mime_type": mime_type}


async def _build_extraction_user_input(
    request: PodcastRequest,
) -> list[dict[str, object]]:
    """
    Build the user_input content block list for the content extractor agent.

    Always starts with a text block (required to prevent silent executor failures),
    then appends one resolved input_file block per URL. URLs come from file_urls
    list; if that is empty, input_data is treated as a single file URL. Each file
    block is resolved to inline bytes (see ``_resolve_file_block``).
    """
    user_text = (
        request.input_data
        if request.input_data_type == InputDataType.PARTIAL_CONTENT
        else _EXTRACTION_DEFAULT_USER_TEXT
    )
    blocks: list[dict[str, object]] = [{"type": "input_text", "text": user_text}]

    # Only FILE_URL treats input_data as a file URL. PARTIAL_CONTENT's
    # input_data is raw text (already in the text block above) and must never
    # be sent through the file resolver.
    urls = list(request.file_urls)
    if not urls and request.input_data_type == InputDataType.FILE_URL and request.input_data:
        urls = [request.input_data]
    if urls:
        resolved = await asyncio.gather(*[_resolve_file_block(u) for u in urls])
        blocks.extend(resolved)

    return blocks


async def _prepare_content(request: PodcastRequest) -> StageResult:
    """
    Resolve raw input into clean content ready for script generation.
    See PODCAST_PIPELINE.md §2 for the full routing contract.

    - FULL_CONTENT:      pass through unchanged — already content (or a script)
    - PARTIAL_CONTENT:   pass through unchanged — rough notes / already-scraped /
                         already-transcribed TEXT. NEVER the file extractor: that
                         agent reads file BYTES, and forcing pasted text through
                         it (with its "extract everything" system prompt) is what
                         mangled notes into unusable content.
    - TOPIC:             Deep Web Research Agent turns a topic/keyword into content
    - FILE_URL:          extractor agent reads one or more file URLs via
                         multimodal user_input content blocks (the ONLY extractor use)
    """
    match request.input_data_type:
        case InputDataType.FULL_CONTENT | InputDataType.PARTIAL_CONTENT:
            return StageResult(
                stage="prepare_content",
                success=True,
                output=request.input_data,
            )

        case InputDataType.TOPIC:
            # The topic IS the user message. The bound researcher declares no
            # variables and its own prompt ends by asking for the topic, so the
            # topic block goes FIRST and any extra prep instruction follows it.
            user_input: list[dict[str, object]] = [
                {"type": "input_text", "text": request.input_data}
            ]
            if request.prep_user_message:
                user_input.append({"type": "input_text", "text": request.prep_user_message})
            result = await _run_mandated(
                _ResearchAgent,
                inputs=_ResearchAgent.Inputs(),
                user_input=user_input,
                label="Podcast Research",
            )
            return _to_stage("prepare_content_researcher", result)

        case InputDataType.FILE_URL:
            extraction_unit = request.extraction_unit or _EXTRACTION_DEFAULT_UNIT
            user_input_blocks = await _build_extraction_user_input(request)
            result = await _run_mandated(
                _ContentExtractorAgent,
                inputs=_ContentExtractorAgent.Inputs(extraction_unit=extraction_unit),
                user_input=user_input_blocks,
                label="Podcast Extraction",
            )
            return _to_stage("prepare_content_extractor", result)


