_SPEAKER_LINE_RE = None  # compiled lazily in _dialogue_speaker_lines


def _dialogue_speaker_lines(dialogue: str) -> list[tuple[str, str]]:
    """Parse `Name: text` turns from a dialogue block.

    Returns (name, text) per turn. A line that doesn't match the pattern is a
    continuation of the previous turn (scripts sometimes wrap long lines)."""
    import re

    global _SPEAKER_LINE_RE
    if _SPEAKER_LINE_RE is None:
        # ≤40 chars before the colon, no colon inside — same contract the
        # script agents are graded on.
        _SPEAKER_LINE_RE = re.compile(r"^\s*([^:\n]{1,40}?)\s*:\s*(.+)$")

    turns: list[tuple[str, str]] = []
    for raw_line in dialogue.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        m = _SPEAKER_LINE_RE.match(line)
        if m:
            turns.append((m.group(1).strip(), m.group(2).strip()))
        elif turns:
            turns.append((turns[-1][0], line))
    return turns


# THE GENDER CHAIN's lookup table lives in ``matrx_ai.config.name_gender`` — the
# TTS config layer resolves the same names when it adopts a script's speaker
# labels, and two tables would drift into disagreeing about who is male.
_normalize_gender = normalize_gender

# The default cast is authoritative for its own 20 names (it IS the pairing the
# pipeline suggests), layered over the broader table.
_GENDER_BY_NAME: dict[str, str] = {
    **COMMON_NAME_GENDERS,
    **{name.lower(): gender for name, gender in _DEFAULT_CAST},
}


def _gender_for_name(name: str, declared: str = "") -> str:
    """Resolve one speaker's gender against the podcast cast's own table
    (request-declared value wins; then the table; then "" for unknown)."""
    return gender_for_name(name, declared, _GENDER_BY_NAME)


def _default_cast(host_count: int, *, seed: str) -> list[tuple[str, str]]:
    """Draw ``host_count`` (name, gender) pairs from ``_DEFAULT_CAST`` with a
    seeded, gender-alternating rotation — so default casts vary per episode /
    preview instead of always leading with the same two names."""
    rng = random.Random(f"podcast-cast::{seed}")
    males = [(n, g) for n, g in _DEFAULT_CAST if g == "male"]
    females = [(n, g) for n, g in _DEFAULT_CAST if g == "female"]
    rng.shuffle(males)
    rng.shuffle(females)
    lead_female = rng.random() < 0.5
    out: list[tuple[str, str]] = []
    mi = fi = 0
    for i in range(host_count):
        want_female = (i % 2 == 0) == lead_female
        if want_female and fi < len(females):
            out.append(females[fi])
            fi += 1
        elif mi < len(males):
            out.append(males[mi])
            mi += 1
        elif fi < len(females):
            out.append(females[fi])
            fi += 1
        else:  # both exhausted (>20 hosts is impossible, but never crash)
            out.append(_DEFAULT_CAST[i % len(_DEFAULT_CAST)])
    return out


def _assign_dialogue_voices(
    names: list[str],
    explicit: dict[str, str],
    genders: dict[str, str],
    *,
    seed: str,
    provider: str = "elevenlabs",
) -> list[SpeakerSpec]:
    """Gender-aware voice assignment with per-episode rotation (both bands:
    ``elevenlabs`` for 3+ hosts, ``google`` for the 1–2 host Gemini path).

    * A speaker with an explicitly pinned voice keeps it (request / UI wins) — a
      loud, non-fatal warning fires if that voice's gender (when it's one of
      ours) disagrees with the declared gender.
    * Otherwise a voice is drawn from the gender-matched pool.
    * The pool order is shuffled deterministically from ``seed``, so the SAME
      episode always resolves to the SAME cast (resume-safe, since the audio
      stage recomputes this on every replay) while DIFFERENT episodes get
      different voices — the fix for "every podcast sounds the same".
    * Within one episode each speaker gets a DISTINCT voice until the matching
      pool is exhausted, then it wraps (so >10 same-gender speakers still work).
    """
    if provider == "google":
        by_gender, all_voices, gender_of = (
            _GOOGLE_BY_GENDER,
            _GOOGLE_ALL_VOICES,
            _GOOGLE_VOICE_GENDER,
        )
    else:
        by_gender, all_voices, gender_of = (
            _ELEVENLABS_BY_GENDER,
            _ELEVENLABS_ALL_VOICES,
            _ELEVENLABS_VOICE_GENDER,
        )
    rng = random.Random(f"podcast-voices::{provider}::{seed}")
    queues: dict[str, list[str]] = {
        "male": rng.sample(by_gender["male"], len(by_gender["male"])),
        "female": rng.sample(by_gender["female"], len(by_gender["female"])),
        "neutral": rng.sample(all_voices, len(all_voices)),
    }
    cursors: dict[str, int] = {"male": 0, "female": 0, "neutral": 0}
    used: set[str] = set(explicit.values())

    def _draw(gender: str) -> str:
        q = queues.get(gender) or queues["neutral"]
        # First pass: prefer an unused voice for within-episode distinctness.
        for _ in range(len(q)):
            vid = q[cursors[gender] % len(q)]
            cursors[gender] += 1
            if vid not in used:
                used.add(vid)
                return vid
        # Pool exhausted — allow reuse, just keep rotating.
        vid = q[cursors[gender] % len(q)]
        cursors[gender] += 1
        return vid

    resolved: list[SpeakerSpec] = []
    for name in names:
        g = _normalize_gender(genders.get(name))
        pinned = explicit.get(name)
        if pinned:
            known = gender_of.get(pinned)
            if known and g != "neutral" and known != g:
                vcprint(
                    f"[PodcastGenerator] Speaker '{name}' declared gender '{g}' but the "
                    f"explicitly-pinned voice {pinned} is '{known}'. Honoring the pinned "
                    "voice — fix the request/UI if this is wrong.",
                    color="yellow",
                )
            voice = pinned
        else:
            voice = _draw(g)
        resolved.append(SpeakerSpec(name=name, voice=voice, gender=genders.get(name, "")))
    return _enforce_distinct_voices(resolved, gender_of, queues)


def _enforce_distinct_voices(
    resolved: list[SpeakerSpec],
    gender_of: dict[str, str],
    queues: dict[str, list[str]],
) -> list[SpeakerSpec]:
    """THE INVARIANT: two speakers in one episode never share a voice.

    The pool draw already prefers unused voices, but EXPLICIT pins bypass it
    entirely — a request (or the studio's voice picker) that pins the same
    voice to two speakers produced a two-host episode rendered in ONE voice,
    with nothing anywhere saying so. Nobody listening can tell that from a
    model failure, which is exactly why it must be impossible by construction.

    A collision is REPAIRED, never raised (a live paid render must not die over
    a voice pick): the first speaker keeps the voice, each later collider is
    reassigned to an unused voice of ITS OWN declared gender, and the swap is
    logged loudly so the real source (usually a UI that let the user pick one
    voice twice) gets fixed.

    There is NO legitimate sharing case: ``_MAX_SPEAKER_COUNT`` (10) is the
    provider's own distinct-voice ceiling, so a renderable cast always fits.
    """
    seen: set[str] = set()
    for spec in resolved:
        if spec.voice not in seen:
            seen.add(spec.voice)
            continue
        wanted = _normalize_gender(spec.gender) or "neutral"
        pool = queues.get(wanted) or queues.get("neutral") or []
        replacement = next(
            (v for v in pool if v not in seen),
            # Every gender-matched voice is taken — take ANY unused voice
            # before tolerating a duplicate; a slight gender mismatch is far
            # less damaging than two speakers sharing one voice.
            next((v for v in (queues.get("neutral") or []) if v not in seen), ""),
        )
        if not replacement:
            vcprint(
                f"[PodcastGenerator] Speaker '{spec.name}' collides on voice "
                f"{spec.voice!r} and the voice pool is exhausted — the episode "
                "will have two speakers sharing a voice. Enable more voices in "
                "ai.voices.",
                color="red",
            )
            continue
        vcprint(
            f"[PodcastGenerator] DUPLICATE VOICE REPAIRED: speaker '{spec.name}' was "
            f"assigned {spec.voice!r}, already used by an earlier speaker in this "
            f"episode — reassigned to {replacement!r} "
            f"(declared gender={wanted!r}, actual={gender_of.get(replacement, 'unknown')!r}). "
            "Two speakers sharing one voice renders as a single-voice episode. "
            "If these voices were pinned by the request/UI, fix the picker.",
            color="yellow",
        )
        spec.voice = replacement
        seen.add(replacement)
    return resolved


def _verify_cast_genders(
    cast: list[SpeakerSpec],
    request: PodcastRequest,
    *,
    provider: str,
) -> list[SpeakerSpec]:
    """LAST LINE before the paid TTS call: no speaker may be voiced against
    their own gender (2026-08-20).

    ``_assign_dialogue_voices`` already draws gender-matched, so a mismatch here
    means something upstream overrode it — a stale voice pinned by an older
    client, a pool that wrapped under a large same-gender cast, or a catalog
    row whose gender changed since the pin was chosen. Those are exactly the
    cases that used to ship silently and land as "the co-host called a man
    Sarah".

    A voice the USER explicitly pinned in the cast editor is honored (their
    choice, loudly noted). Anything else is REPAIRED to a correct-gender voice
    rather than sent. Repair is deterministic — same run, same result, so a
    resumed run re-derives the identical cast."""
    gender_of = _GOOGLE_VOICE_GENDER if provider == "google" else _ELEVENLABS_VOICE_GENDER
    by_gender = _GOOGLE_BY_GENDER if provider == "google" else _ELEVENLABS_BY_GENDER
    user_pinned = {s.name for s in request.speakers if s.name.strip() and s.voice.strip()}
    taken = {s.voice for s in cast}

    for speaker in cast:
        want = _normalize_gender(speaker.gender)
        if want == "neutral":
            continue  # no claim to contradict
        actual = gender_of.get(speaker.voice)
        if actual is None or actual == want:
            continue
        if speaker.name in user_pinned:
            vcprint(
                f"[PodcastGenerator] Speaker '{speaker.name}' is {want} but the "
                f"user explicitly pinned a {actual} voice ({speaker.voice}). "
                "Honoring the explicit choice.",
                color="yellow",
            )
            continue
        pool = [v for v in by_gender.get(want, []) if v not in taken] or by_gender.get(want, [])
        if not pool:
            vcprint(
                f"[PodcastGenerator] GENDER MISMATCH for '{speaker.name}' ({want}) on "
                f"voice {speaker.voice} ({actual}) and NO {want} voice is available "
                "in the catalog to repair it. Sending as-is.",
                color="red",
            )
            continue
        replacement = pool[0]
        vcprint(
            f"[PodcastGenerator] GENDER MISMATCH REPAIRED: '{speaker.name}' is {want} "
            f"but was assigned {speaker.voice} ({actual}) — swapped to {replacement}. "
            "This is a bug upstream of voice assignment; the guard should never fire.",
            color="red",
        )
        taken.discard(speaker.voice)
        taken.add(replacement)
        speaker.voice = replacement
    return cast


async def preview_podcast_cast(
    host_count: int,
    *,
    seed: str,
) -> PodcastCastPreview:
    if not 1 <= host_count <= _MAX_SPEAKER_COUNT:
        raise ValueError(f"host_count must be between 1 and {_MAX_SPEAKER_COUNT}")

    await refresh_voice_pools()
    cast = _default_cast(host_count, seed=seed)
    names = [name for name, _gender in cast]
    genders = {name: gender for name, gender in cast}
    if host_count <= 2:
        speakers = _assign_dialogue_voices(names, {}, genders, seed=seed, provider="google")
        provider = PodcastAudioProvider.GOOGLE
    else:
        speakers = _assign_dialogue_voices(names, {}, genders, seed=seed)
        provider = PodcastAudioProvider.ELEVENLABS

    return PodcastCastPreview(
        host_count=host_count,
        provider=provider,
        speakers=speakers,
    )


def _effective_speakers(
    request: PodcastRequest, dialogue: str, script: str | None = None
) -> list[SpeakerSpec]:
    """Resolve the cast (names + voices) for the audio stage — names ALWAYS
    sourced from what the script actually says, so the config we hand TTS can
    never carry a name the transcript doesn't contain (PODCAST_PIPELINE.md §5).

    Name priority: request's named speakers → the agent's declared
    ``<speaker_settings>`` → the dialogue's own distinct labels. Voice priority:
    explicitly pinned (request / declared) → gender-matched pool draw.

    Both provider bands get GENDER-AWARE selection with per-episode rotation
    (3+ → ElevenLabs pool; 1–2 → Google pool) so unpinned default runs stop
    sounding identical episode after episode. The rotation seed folds in the
    dialogue itself, so it is stable across resume (the audio stage recomputes
    this on every replay from the same script) but different per episode — a
    show_id-only seed made every episode of one show, and every default-show
    run, resolve the same voices.

    GATE 2 guarantees these sources agree, so this is deterministic — never a
    guess the API has to repair."""
    names: list[str] = [s.name for s in request.speakers if s.name.strip()]
    voices: dict[str, str] = {
        s.name: s.voice for s in request.speakers if s.name.strip() and s.voice.strip()
    }
    genders: dict[str, str] = {
        s.name: s.gender for s in request.speakers if s.name.strip() and s.gender.strip()
    }

    declared = _parse_speaker_settings(script) if script else None
    if not names and declared:
        names = [s.name for s in declared]
    # Declared settings fill any gaps the request left (voice + gender), keyed by
    # name — the request still wins where it specified a value.
    if declared:
        for s in declared:
            if s.voice.strip():
                voices.setdefault(s.name, s.voice)
            if s.gender.strip():
                genders.setdefault(s.name, s.gender)

    if not names:
        names = _distinct_speakers(dialogue)
        if request.host_count:
            names = names[: request.host_count]

    # THE GENDER CHAIN (2026-08-20). Every speaker gets a gender BEFORE a voice
    # is drawn: request -> the agent's <speaker_settings> -> the name table.
    # Without this a derived cast carried no gender at all, every speaker
    # resolved "neutral", and the draw came from the MIXED pool — which is how a
    # host named Sarah ended up with a male voice while her co-host said her
    # name out loud. An unknown name still falls through to neutral, but it says
    # so, because a silent neutral is exactly what hid this for months.
    unknown: list[str] = []
    for name in names:
        resolved = _gender_for_name(name, genders.get(name, ""))
        if resolved:
            genders[name] = resolved
        else:
            unknown.append(name)
    if unknown:
        vcprint(
            f"[PodcastGenerator] No gender resolved for {unknown} — these voices are "
            "drawn from the full pool and MAY not match how the script refers to them. "
            "Add the name to _GENDER_BY_NAME, or have the script agent declare "
            "<speaker_settings> with a gender per speaker.",
            color="yellow",
        )

    # Resume-safe, per-episode seed: show_id alone collapses (the default show
    # is one shared UUID), so fold in the dialogue — identical within a run,
    # different across episodes.
    # (sha1, not hash() — hash() is per-process salted, which would re-cast a
    # resumed run in a new worker.)
    dialogue_digest = hashlib.sha1(dialogue.encode("utf-8")).hexdigest()[:16]
    episode_seed = f"{request.show_id}::{dialogue_digest}"

    # 3+ hosts → ElevenLabs: gender-aware + per-episode rotation.
    if request.host_count >= 3:
        return _assign_dialogue_voices(names, voices, genders, seed=episode_seed)

    # 1–2 hosts → Google: same gender-aware rotation, from the Gemini pool.
    return _assign_dialogue_voices(names, voices, genders, seed=episode_seed, provider="google")


def _dialogue_to_elevenlabs_turns(
    dialogue: str, speakers: list[SpeakerSpec]
) -> list[dict[str, str]]:
    """Convert `Name: text` turns into ElevenLabs dialogue inputs.

    Every script label MUST resolve to a voice — an unmapped speaker aborts
    BEFORE the paid TTS call (a silently dropped voice is worse than a loud
    failure)."""
    name_to_voice = {s.name: s.voice for s in speakers}
    turns: list[dict[str, str]] = []
    unmapped: set[str] = set()
    for name, text in _dialogue_speaker_lines(dialogue):
        voice = name_to_voice.get(name)
        if voice is None:
            unmapped.add(name)
            continue
        if turns and turns[-1]["voice_id"] == voice:
            # Merge consecutive turns of the same voice — fewer, larger
            # dialogue inputs batch better under the 4800-char limit.
            turns[-1]["text"] += " " + text
        else:
            turns.append({"text": text, "voice_id": voice})
    if unmapped:
        raise PodcastConfigError(
            f"Script speakers {sorted(unmapped)} have no voice mapping "
            f"(configured: {sorted(name_to_voice)}). The script agent drifted "
            "from the requested speaker names — regenerate or pass matching "
            "speakers[]."
        )
    if not turns:
        raise PodcastConfigError(
            "No `Speaker: line` turns found in the script dialogue — cannot "
            "build ElevenLabs dialogue audio."
        )
    # Pre-flight (before the paid call): ElevenLabs rejects a request carrying
    # more than _MAX_SPEAKER_COUNT distinct voice_ids. host_count is capped at
    # exactly that number, so this can only fire if someone raises the cap
    # without building multi-request render + stitch — in which case saying so
    # here beats a bare provider 400.
    distinct_voices = {t["voice_id"] for t in turns}
    if len(distinct_voices) > _MAX_SPEAKER_COUNT:
        raise PodcastConfigError(
            f"Dialogue would carry {len(distinct_voices)} distinct voices but "
            f"ElevenLabs text_to_dialogue allows at most {_MAX_SPEAKER_COUNT} "
            "per request — that provider cap is why host_count is capped there. "
            "Rendering a larger cast needs a multi-request render + stitch, "
            "which is deliberately not built."
        )
    return turns


def _audio_stage_result(result: AgentRunResult) -> StageResult:
    """Adapt the audio agent result — success WITHOUT an audio URL is a FAILURE.

    This conversion must happen HERE, before the checkpoint commits, not at the
    end of the pipeline: a TTS abort that the agent layer swallows (e.g. the
    2026-06-10 stall abort surfaced as success + empty output) would otherwise
    commit a 'completed' checkpoint with no audio — poisoning every resume,
    which would replay the empty result forever instead of re-running TTS.
    """
    stage = _to_stage("create_audio", result)
    if stage.success and not stage.output.strip():
        return StageResult(
            stage="create_audio",
            success=False,
            error=(
                "Audio stage produced no audio URL — TTS returned nothing "
                "(aborted render or a script with no narratable dialogue)."
            ),
        )
    return stage


def _apply_dictionary_pronunciations(text: str, dictionary: dict | None) -> str:
    """Rewrite spoken text using the dictionary's pronunciation respellings.

    Thin wrapper over the universal primitive `DictionaryConfig.apply_aliases`
    (see matrx_ai/config/dictionary_config.py) so the substitution logic lives in
    exactly one place. Used wherever a provider has no native pronunciation
    dictionary and we must bake the spoken form into the text itself.
    """
    from matrx_ai.config.dictionary_config import DictionaryConfig

    cfg = DictionaryConfig.coerce(dictionary)
    if cfg is None:
        return text
    return cfg.apply_aliases(text)


async def _create_audio(request: PodcastRequest, script: str) -> StageResult:
    # Defensive GATE 2 re-check: the orchestrator only reaches audio on a
    # GATE-2-valid script, but a resumed run could replay a checkpoint written
    # before the gate existed. A bad script fails the audio stage cleanly — it
    # never crashes the pipeline or reaches the (paid) TTS call.
    try:
        dialogue = _extract_dialogue(script)
    except ScriptValidationError as exc:
        return StageResult(
            stage="create_audio",
            success=False,
            error=f"Refusing TTS — script is invalid: {exc}",
        )
    n = request.host_count or _DEFAULT_SPEAKER_COUNT
    # Resolve the cast ONCE from the full (untruncated) dialogue + the script's
    # own declaration — so the voice config carries the EXACT names the
    # transcript uses. This is the gate at our layer: the translator/TTS never
    # receives a name the script doesn't contain. We do it correctly here; we
    # never ask the API to "fix" speaker names.
    cast = _effective_speakers(request, dialogue, script)
    # No speaker is ever voiced against their own gender (2026-08-20).
    cast = _verify_cast_genders(cast, request, provider="elevenlabs" if n >= 3 else "google")
    audio_content = (
        _truncate_dialogue_for_testing(dialogue, n)
        if request.truncate_audio_for_testing
        else dialogue
    )

    # 3+ speakers → ElevenLabs text_to_dialogue (Google multi-speaker caps at 2).
    if n >= 3:
        # ElevenLabs has no system-instruction channel — bake the dictionary's
        # pronunciations into the spoken text before building dialogue turns.
        audio_content = _apply_dictionary_pronunciations(audio_content, request.dictionary)
        try:
            turns = _dialogue_to_elevenlabs_turns(audio_content, cast)
        except PodcastConfigError as exc:
            # Caught BEFORE the paid TTS call — surface as a failed (resumable)
            # stage, never an unhandled pipeline crash.
            return StageResult(stage="create_audio", success=False, error=str(exc))
        result = await _run_mandated(
            _AudioDialogueAgent,
            inputs={"content": audio_content},
            config_overrides={"tts_voice": turns},
            label="Podcast Audio",
        )
        return _audio_stage_result(result)

    # 1–2 speakers → the proven Gemini TTS agents. The voice config is ALWAYS
    # built from the script's real speakers (``cast``) — never the audio agent's
    # pinned default names. That is what eliminates the "speaker name mismatch"
    # class of failure: the names we send always match the transcript labels.
    agent_cls = _select_audio_agent(request.podcast_type)
    if n == 1:
        voice = cast[0].voice if cast else _GEMINI_DEFAULT_VOICES[0]
        overrides: dict[str, object] = {"tts_voice": voice}
        # Single-voice TTS would read the `Name:` labels aloud — send only the
        # spoken text (labels exist for the parser contract, not the listener).
        spoken = [text for _name, text in _dialogue_speaker_lines(audio_content)]
        if spoken:
            audio_content = "\n\n".join(spoken)
    else:  # n == 2 → Google multi-speaker; names MUST match the transcript.
        # Gender rides along (THE GENDER CHAIN already resolved one per speaker).
        # TTSVoiceConfig needs it: when the script's labels drift from these
        # names it re-points each voice at a name of the SAME gender instead of
        # pairing positionally, which used to hand a male character a female
        # voice while the co-host said his name out loud.
        overrides = {
            "tts_voice": [
                {
                    "name": s.name,
                    "voice": s.voice,
                    "gender": _gender_for_name(s.name, s.gender),
                }
                for s in cast
            ]
        }

    # Gemini TTS receives the pronunciation directive via config.dictionary —
    # the Google translator folds the rendered system text into user content.
    if request.dictionary:
        overrides["dictionary"] = request.dictionary
    # Saved podcast audio is the HQ use case → request the high-quality Gemini
    # model tier (pro) for the 1–2 host path. Honored by GoogleChat.execute via
    # catalog offering's metadata.tts.quality_tiers.
    if request.tts_quality:
        overrides["tts_quality"] = request.tts_quality

    result = await _run_mandated(
        agent_cls,
        inputs=agent_cls.Inputs(
            content=audio_content,
            audio_style=_resolve_audio_style(request),
        ),
        config_overrides=overrides,
        label="Podcast Audio",
    )
    return _audio_stage_result(result)


