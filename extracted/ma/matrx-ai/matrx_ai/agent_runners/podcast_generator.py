async def _generate_metadata(prepared_content: str) -> tuple[StageResult, PodcastMetadata]:
    """
    Generate title, description, 5 image prompts, and 2 video prompts.

    Receives the same prepared_content passed to the script agent (not the
    finished script) so it can start immediately — concurrently with audio.
    The agent declares ``Output = PodcastMetadata``, so ``run_agent`` parses
    and validates the JSON via the canonical extractor (no hand-rolled regex).
    """
    result = await _run_mandated(
        _MetadataAgent,
        inputs=_MetadataAgent.Inputs(podcast_content=prepared_content),
        label="Podcast Metadata",
    )
    meta = result.parsed if isinstance(result.parsed, PodcastMetadata) else PodcastMetadata()

    stage = _to_stage("generate_metadata", result)
    if result.parse_error:
        vcprint(
            f"[PodcastGenerator] Metadata parse error — raw:\n{result.output[:300]}",
            color="yellow",
        )
        stage.error = f"metadata parse failed: {result.parse_error}"
    return stage, meta


