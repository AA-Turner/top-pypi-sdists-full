# (stage_key, human label) for the content-prep phase, keyed by input type.
# The stage_key matches the StageResult.stage the prep helper will emit so a UI
# can correlate the "started" event with its later "done" event.
_PREP_STAGE_INFO: dict[InputDataType, tuple[str, str]] = {
    InputDataType.FULL_CONTENT: ("prepare_content", "Preparing your content"),
    InputDataType.PARTIAL_CONTENT: ("prepare_content", "Preparing your content"),
    InputDataType.TOPIC: ("prepare_content_researcher", "Researching the topic on the web"),
    InputDataType.FILE_URL: ("prepare_content_extractor", "Extracting content from your file(s)"),
}


async def generate_podcast(
    request: PodcastRequest,
    on_event: PodcastEventCallback | None = None,
    *,
    run_id: str | None = None,
    user_id: str | None = None,
) -> PodcastGenerationResult:
    """
    Orchestrate the full podcast production pipeline.

    Resumability: every expensive stage (research, script, metadata, audio, and
    each individual paid image/video) is checkpointed to ``agent_run`` /
    ``agent_run_stage`` keyed to a run id. Pass ``run_id`` of a previously
    failed run to **resume** — completed stages replay from the checkpoint
    (instantly, free) and only the missing tail re-executes. With no DB the
    checkpointer degrades to a no-op and the pipeline runs exactly as before.
    ``user_id`` owns the run record.

    ``on_event`` (optional) is awaited with each :class:`PodcastEvent` the moment
    it lands, giving the caller a continuous, never-silent feed for streaming
    UIs: every stage's START and FINISH, the structured ``metadata`` the instant
    it parses (so the UI can show the title/description immediately), and each
    image/video ``asset`` as it lands (so slots fill in out-of-order while audio
    is still rendering). A callback failure is logged and never aborts the
    pipeline.

    Execution order is designed around two priorities:
      1. Audio is the critical path — nothing should block it.
      2. Everything else starts as early as possible to avoid waiting on audio.

    Concurrency strategy:
      Stage 1   — content prep (sequential, everything depends on this)
      Stage 1b  — post-prep optional transform (sequential)
      Stage 2+4 — script generation AND metadata generation fire concurrently.
                  Metadata uses the same prepared_content as the script agent,
                  so it starts immediately without waiting for the finished script.
      Stage 3   — audio starts as soon as the script is ready (critical path)
      Stage 5+6 — images and videos fire concurrently as soon as metadata resolves,
                  all while audio is still running

    Content prep and script are true blockers; any other stage failure is
    recorded in stage_results but does not halt the pipeline.
    """
    stamp_source_context(source_app="matrx-ai", source_feature="podcasts")
    # Load the ElevenLabs voice pool from the DB catalog (source of truth). Safe
    # no-op without a DB / when already loaded; keeps the built-in fallback on
    # failure. Done before any voice assignment in the audio stage.
    await refresh_voice_pools()
    stage_results: list[StageResult] = []

    # Progress denominator: prep + post_prep + script + metadata + audio, plus
    # one slot per image/video version. ``podcast_complete`` is the authoritative
    # 100% — step never overshoots total, and may finish below it if the metadata
    # agent returns fewer prompts than there are slots.
    # +1 for the final official-video composition stage.
    # Per-run media caps (0 → skip, 1 → single, None → full) are resolved once
    # here so the progress denominator, the metadata event, the slot
    # announcements, and generation all agree on the image/video count.
    eff_images = _effective_media_count(request.max_images, _TARGET_IMAGE_COUNT)
    eff_videos = _effective_media_count(request.max_videos, _TARGET_VIDEO_COUNT)
    # The feature image announces its own stage (`_start`), so it must be in the
    # denominator too — otherwise progress reports "step N+1 of N". This
    # condition MUST stay identical to the launch gate below.
    _wants_feature_image = request.include_feature_image and eff_images > 0
    total_steps = (
        6
        + eff_images
        + eff_videos
        + (1 if _wants_feature_image else 0)
        + (1 if request.target_audience.strip() else 0)
    )
    step = 0

    loop = asyncio.get_event_loop()
    pipeline_started_at = loop.time()
    # stage_key -> (started_at, label) for every stage currently in flight. The
    # ticker reads this to keep the UI moving during long, silent stages.
    running: dict[str, tuple[float, str]] = {}

    async def _emit(event: PodcastEvent) -> None:
        if on_event is None:
            return
        try:
            await on_event(event)
        except Exception as exc:
            vcprint(
                f"[PodcastGenerator] on_event callback failed ({event.kind}): {exc}",
                color="yellow",
            )

    async def _start(stage: str, label: str) -> None:
        nonlocal step
        step += 1
        running[stage] = (loop.time(), label)
        await _emit(
            PodcastEvent(
                kind=PodcastEventKind.STAGE_STARTED,
                stage=stage,
                label=label,
                step=step,
                total=total_steps,
            )
        )

    async def _record(stage: StageResult, label: str = "") -> None:
        """Append a stage result and stream its completion live."""
        stage_results.append(stage)
        running.pop(stage.stage, None)
        await _emit(
            PodcastEvent(
                kind=PodcastEventKind.STAGE_DONE,
                stage=stage.stage,
                label=label,
                success=stage.success,
                output=(stage.output[:500] if stage.output else ""),
                error=stage.error,
                step=step,
                total=total_steps,
            )
        )

    async def _ticker() -> None:
        """Emit a content-bearing 'still working' pulse every few seconds while
        any stage is in flight. This is what keeps the UI alive through research,
        script, and audio — long stages that otherwise stream nothing between
        their start and finish. Every Nth tick also bumps the run row's DB
        heartbeat (see _DB_HEARTBEAT_EVERY_TICKS) so clients NOT holding this
        stream — reloads, phones returning from background, the manage list —
        see the run as alive through multi-minute media renders."""
        tick_count = 0
        try:
            while True:
                await asyncio.sleep(_TICK_INTERVAL_SECONDS)
                if not running:
                    continue
                tick_count += 1
                # Surface the most-recently-started in-flight stage as the label.
                stage, (_started_at, label) = max(running.items(), key=lambda kv: kv[1][0])
                await _emit(
                    PodcastEvent(
                        kind=PodcastEventKind.TICK,
                        stage=stage,
                        label=label,
                        step=step,
                        total=total_steps,
                        elapsed_seconds=round(loop.time() - pipeline_started_at, 1),
                    )
                )
        except asyncio.CancelledError:
            pass

    async def _heartbeat() -> None:
        """Bump the run row's DB-visible clock while ANY stage is in flight.

        🚨 Deliberately its OWN loop, not a side effect of the UI ticker.

        It used to ride inside `_ticker`, which awaits `on_event` on every tick —
        so the DB pulse was downstream of the host's emit path and of a
        fire-and-forget `create_task` with no strong reference (an unreferenced
        task can be garbage-collected mid-flight). Either way, one wedged or slow
        emit stops the heartbeat, and every client that is NOT holding the stream
        judges liveness from that column: a healthy run reads as "stalled".

        That is not hypothetical. On run e505424c the heartbeat stopped at
        19:06:37 while `compose_official_video` ran to 19:25:11 — nineteen
        minutes of silence on a perfectly healthy run, which is exactly what put
        "interrupted / Re-run" in front of a user whose finished audio had been
        sitting there for eleven minutes. Re-running a finished podcast is the
        most expensive thing that screen can invite.

        So: separate task, strong reference, awaited write, no dependency on the
        stream. `touch()` swallows its own DB errors and never raises.
        """
        await run_heartbeat_loop(ckpt, running)

    async def _on_asset(kind: str, index: int, prompt: str, stage: StageResult) -> None:
        """Stream one image/video the moment it lands (also records the stage)."""
        stage_results.append(stage)
        running.pop(stage.stage, None)
        await _emit(
            PodcastEvent(
                kind=PodcastEventKind.ASSET,
                stage=stage.stage,
                asset_kind=kind,
                asset_index=index,
                asset_url=stage.output if stage.success else "",
                asset_prompt=prompt,
                success=stage.success,
                error=stage.error,
                note=stage.note,
                step=step,
                total=total_steps,
            )
        )

    vcprint(
        f"[PodcastGenerator] Starting pipeline — show_id={request.show_id} type={request.podcast_type}",
        color="cyan",
    )

    # PREFLIGHT — the durable run row is opened BEFORE a single paid call.
    #
    # It is not bookkeeping: it is the run's identity. Without it the client
    # never learns a run_id, the runs list (which reads agent_run) cannot show
    # the run, /podcast/resume has nothing to replay, and every stage checkpoint
    # is discarded — while the pipeline still spends minutes of script, TTS, and
    # image money. So it is also the cheapest possible proof that the database
    # accepts writes right now. ``require_durable=True`` turns the old silent
    # degrade into a clean refusal with nothing charged (2026-08 outage).
    # A resumed run replays its completed stages from the checkpoint for free.
    request_payload = request.model_dump(mode="json")
    if run_id:
        ckpt: object = await RunCheckpointer.resume(run_id=run_id, user_id=user_id)
    else:
        ckpt = await RunCheckpointer.start(
            kind="podcast",
            user_id=user_id,
            request=request_payload,
            require_durable=True,
        )

    # Belt and braces: the run id is what the client persists as its handle. An
    # empty one means the run is already lost — refuse rather than generate an
    # episode nobody can ever find again.
    opened_run_id = getattr(ckpt, "run_id", "") or ""
    if not opened_run_id:
        raise DurableRunUnavailable(
            "Cannot start a podcast run: no durable run id was assigned, so the "
            "run could not be found or resumed later. Nothing was charged."
        )

    await _emit(
        PodcastEvent(
            kind=PodcastEventKind.RUN,
            run_id=opened_run_id,
            step=0,
            total=total_steps,
        )
    )

    # The ticker runs for the WHOLE pipeline (research is one of the longest,
    # quietest stages) and is always cancelled in the finally.
    ticker_task = asyncio.create_task(_ticker())
    # Strong reference held for the whole run (see _heartbeat): an unreferenced
    # task can be garbage-collected, which is one of the ways the pulse died.
    heartbeat_task = asyncio.create_task(_heartbeat())
    # Declared OUT here (not where it is assigned, deep inside the try) so the
    # finally can always reach it. A task created inside a cancelled parent is
    # NOT auto-cancelled — without this, a client disconnect or a raising audio
    # stage would leave it detached, billing a gpt-image-2 render whose result
    # nothing ever reads.
    feature_image_task: asyncio.Task[tuple[StageResult, StageResult]] | None = None
    try:
        # --- Stage 1a: Prepare content (blocker — everything depends on this) ---
        prep_stage, prep_label = _PREP_STAGE_INFO[request.input_data_type]
        await _start(prep_stage, prep_label)
        prep_result = await _checkpointed(ckpt, prep_stage, lambda: _prepare_content(request))
        await _record(prep_result, label=prep_label)
        if not prep_result.success:
            await ckpt.fail(  # type: ignore[attr-defined]
                f"Content preparation failed: {prep_result.error}",
                total_cost=_unsettled_cost(stage_results),
            )
            return PodcastGenerationResult(
                show_id=request.show_id,
                success=False,
                stage_results=stage_results,
                error=f"Content preparation failed: {prep_result.error}",
                usage=_aggregate_stage_usage(stage_results),
                unsettled_usage=_aggregate_stage_usage(stage_results, unsettled_only=True),
            )
        prepared_content = prep_result.output

        # GATE 1 — content must be substantial enough to script from, UNLESS it
        # is already a finished script (a short finished script is legitimate).
        # Catches a thin scrape / empty research / degenerate file ("Dummy PDF")
        # HERE — before we pay a script agent to write nothing from nothing.
        if (
            not _has_dialogue_block(prepared_content)
            and len((prepared_content or "").strip()) < _MIN_CONTENT_CHARS
        ):
            chars = len((prepared_content or "").strip())
            gate_msg = (
                f"Content gate failed: only {chars} chars of usable content "
                f"(need ≥ {_MIN_CONTENT_CHARS}). The source produced too little "
                "to write a script from — try a richer source or a fuller paste."
            )
            gate_stage = StageResult(stage="content_gate", success=False, error=gate_msg)
            await _record(gate_stage, label="Checking the content")
            await ckpt.fail(gate_msg, total_cost=_unsettled_cost(stage_results))  # type: ignore[attr-defined]
            return PodcastGenerationResult(
                show_id=request.show_id,
                success=False,
                stage_results=stage_results,
                error=gate_msg,
                usage=_aggregate_stage_usage(stage_results),
                unsettled_usage=_aggregate_stage_usage(stage_results, unsettled_only=True),
            )

        # --- Stage 1a2: Audience adaptation (optional re-pitch, BEFORE post-prep
        # so translation — when chosen — stays the faithful last transform) ---
        if request.target_audience.strip():
            await _start("audience_adaptation", "Adapting the content for your audience")
            audience_result = await _checkpointed(
                ckpt,
                "audience_adaptation",
                lambda c=prepared_content: _apply_audience_adaptation(
                    c, request.target_audience, request.audience_guidance
                ),
            )
            await _record(audience_result, label="Adapting the content for your audience")
            if audience_result.success and audience_result.output:
                prepared_content = audience_result.output

        # --- Stage 1b: Post-preparation (optional transform) ---
        await _start("post_prep", "Post-processing the content")
        post_prep_result = await _checkpointed(
            ckpt,
            "post_prep",
            lambda: _apply_post_prep(
                prepared_content,
                request.post_prep_option,
                language=_derived_language(request),
            ),
        )
        await _record(post_prep_result, label="Post-processing the content")
        if post_prep_result.success and post_prep_result.output:
            prepared_content = post_prep_result.output

        # --- Stages 2/3/4/5/6: script, metadata, audio, images, videos ---
        # These overlap, and we react to each task the INSTANT it finishes —
        # never via a coupled gather. This is what makes the title show early:
        #   • metadata done  -> emit metadata (title/description) + launch media,
        #                        even while the slower script is still writing;
        #   • script done    -> launch audio (the critical path);
        # so the UI gets the title the moment metadata parses, not after the
        # script also finishes.
        vcprint("[PodcastGenerator] Launching script + metadata concurrently", color="cyan")
        await _start("create_script", "Writing the podcast script")
        await _start("generate_metadata", "Designing the title, description & visuals")
        script_task = asyncio.create_task(
            _checkpointed(
                ckpt, "create_script", lambda c=prepared_content: _create_script(request, c)
            )
        )
        metadata_task = asyncio.create_task(
            _checkpointed_metadata(
                ckpt, "generate_metadata", lambda c=prepared_content: _generate_metadata(c)
            )
        )

        script: str | None = None
        podcast_meta: PodcastMetadata | None = None
        audio_task: asyncio.Task | None = None
        media_tasks: list[asyncio.Task] = []
        image_descriptions: list[str] = []
        video_descriptions: list[str] = []
        script_failed_error: str | None = None

        pending: set[asyncio.Task] = {script_task, metadata_task}
        while pending:
            finished_set, pending = await asyncio.wait(pending, return_when=asyncio.FIRST_COMPLETED)
            for finished in finished_set:
                if finished is script_task:
                    script_result = finished.result()
                    await _record(script_result, label="Writing the podcast script")
                    if not script_result.success:
                        script_failed_error = script_result.error
                        continue
                    script = script_result.output
                    # Audio is the critical path — launch the instant the script lands.
                    await _start("create_audio", "Producing the audio (the longest step)")
                    audio_task = asyncio.create_task(
                        _checkpointed(
                            ckpt, "create_audio", lambda s=script: _create_audio(request, s)
                        )
                    )
                elif finished is metadata_task:
                    metadata_result, podcast_meta = finished.result()
                    await _record(
                        metadata_result, label="Designing the title, description & visuals"
                    )
                    # Apply the per-run media caps to the metadata itself, so the
                    # capped prompt lists are the SINGLE source of truth for the
                    # streamed metadata event (the UI's slot layout), the slot
                    # announcements, and generation. _pad_prompts trims to the
                    # effective count (0 → skip, 1 → a single asset) and pads when
                    # the agent returned fewer prompts than slots.
                    image_descriptions = _pad_prompts(podcast_meta.image_descriptions, eff_images)
                    video_descriptions = _pad_prompts(podcast_meta.video_descriptions, eff_videos)
                    podcast_meta.image_descriptions = image_descriptions
                    podcast_meta.video_descriptions = video_descriptions
                    # Stream the structured metadata THE INSTANT it parses —
                    # decoupled from the script — so the UI renders the title and
                    # lays out the media slots while everything else is still running.
                    await _emit(
                        PodcastEvent(
                            kind=PodcastEventKind.METADATA,
                            stage="generate_metadata",
                            metadata=podcast_meta,
                            step=step,
                            total=total_steps,
                        )
                    )
                    # Announce + launch media now (depends only on metadata). The
                    # slot count IS the capped prompt count — exactly what the
                    # metadata event told the UI to lay out.
                    image_targets = len(image_descriptions)
                    video_targets = len(video_descriptions)
                    for i in range(image_targets):
                        await _start(f"image_{i}", f"Generating image {i + 1} of {image_targets}")
                    for i in range(video_targets):
                        await _start(f"video_{i}", f"Generating video {i + 1} of {video_targets}")
                    if image_descriptions:
                        vcprint("[PodcastGenerator] Launching image generation", color="cyan")
                        media_tasks.append(
                            asyncio.create_task(
                                _generate_images(
                                    image_descriptions, eff_images, on_asset=_on_asset, ckpt=ckpt
                                )
                            )
                        )
                    if video_descriptions:
                        vcprint("[PodcastGenerator] Launching video generation", color="cyan")
                        media_tasks.append(
                            asyncio.create_task(
                                _generate_videos(
                                    video_descriptions, eff_videos, on_asset=_on_asset, ckpt=ckpt
                                )
                            )
                        )

        # Script is a hard blocker — if it failed, abort and cancel any media /
        # audio already in flight (launched off the metadata result).
        if script_failed_error is not None or script is None:
            for t in media_tasks:
                t.cancel()
            if audio_task is not None:
                audio_task.cancel()
            await ckpt.fail(  # type: ignore[attr-defined]
                f"Script generation failed: {script_failed_error}",
                total_cost=_unsettled_cost(stage_results),
            )
            return PodcastGenerationResult(
                show_id=request.show_id,
                success=False,
                title=(podcast_meta.title if podcast_meta else ""),
                description=(podcast_meta.description if podcast_meta else ""),
                stage_results=stage_results,
                error=f"Script generation failed: {script_failed_error}",
                usage=_aggregate_stage_usage(stage_results),
                unsettled_usage=_aggregate_stage_usage(stage_results, unsettled_only=True),
            )

        title = podcast_meta.title if podcast_meta else ""
        description = podcast_meta.description if podcast_meta else ""

        # --- Feature image (the transcript-derived sixth image) ---
        # Launched HERE, not with slots 0..4, because it reads the finished
        # script — the other slots launch off the metadata event, before a
        # script exists. Started now (rather than awaited now) so it overlaps
        # the audio critical path and adds no serial wall-clock. Its slot sits
        # AFTER the metadata-driven slots, so it can never renumber them.
        #
        # Slot is the COUNT OF ANNOUNCED MANDATES, not `eff_images`: when the
        # metadata agent returns no image descriptions at all, `_pad_prompts`
        # yields [] regardless of the target, so `eff_images` would leave a hole
        # (a lone card labelled "Image 6" with slots 0-4 never announced).
        feature_image_slot = len(image_descriptions)
        # Gated on the image budget too. `max_images=0` means "skip images" — a
        # deliberate fast/cheap mode — so it must skip this pair of agent calls
        # as well. It also keeps `image_urls` empty in that mode, which is what
        # stops the feature image from silently becoming the episode cover
        # (the cover is `image_urls[0]`).
        if _wants_feature_image:
            await _start(
                f"image_{feature_image_slot}",
                "Designing a feature image from the transcript",
            )
            feature_image_task = asyncio.create_task(
                _generate_feature_image(
                    script,
                    request.feature_image_style,
                    feature_image_slot,
                    on_asset=_on_asset,
                    ckpt=ckpt,
                )
            )

        # --- Await audio (critical path) ---
        audio_url = ""
        audio_error: str | None = None
        if audio_task is not None:
            audio_result = await audio_task
            # Audio is the critical path. An agent that reports success but
            # produced NO audio URL (e.g. Google TTS rejected a "script" that
            # has no speaker labels — what happens when the source had no real
            # narratable content) is NOT a success. Surface it honestly as a
            # failed stage instead of claiming a silent win; the episode can
            # still finish with its images/video, but the matrix must not lie.
            if audio_result.success and not audio_result.output:
                audio_result = StageResult(
                    stage=audio_result.stage,
                    success=False,
                    error=(
                        "Audio stage produced no audio URL — the script had no "
                        "narratable speaker dialogue (TTS returned nothing)."
                    ),
                )
            await _record(audio_result, label="Producing the audio (the longest step)")
            audio_url = audio_result.output if audio_result.success else ""
            if not audio_result.success:
                # Without audio there is no episode — the RUN is a failure
                # (fatal, resumable), even though the media that did render is
                # kept and replays free on resume. Claiming success here made
                # the client show a green "done" with no audio (2026-06-10).
                audio_error = audio_result.error or "Audio generation failed."

        # --- Collect media (already streamed live via ``_on_asset``; here we
        # only assemble the ordered URL lists for the final result). ---
        image_urls: list[str] = []
        video_urls: list[str] = []
        if media_tasks:
            # Defense in depth: per-asset failures are already soft (see
            # _generate_image / _generate_video), so these batches don't raise.
            # But media is BEST-EFFORT relative to the audio critical path —
            # `return_exceptions=True` guarantees that even an unexpected error
            # assembling a batch can never abort a run that already produced
            # audio; it just yields no URLs for that batch.
            media_results = await asyncio.gather(*media_tasks, return_exceptions=True)
            idx = 0
            if image_descriptions:
                res = media_results[idx]
                image_results: list[StageResult] = res if isinstance(res, list) else []
                if not isinstance(res, list):
                    vcprint(
                        f"[PodcastGenerator] image batch errored (non-fatal): {res!r}",
                        color="yellow",
                    )
                # `_is_media_url` here too, not just in `_attempt`: a RESUMED
                # run replays checkpointed stages via `_stage_from_payload`
                # WITHOUT re-running `_attempt`, so a stage persisted as
                # success-with-non-URL (e.g. a pre-guard run, or the still-open
                # concurrent-contaminant class) would otherwise flow straight
                # into image_urls and be eligible for image_urls[0] — the cover.
                image_urls = [
                    r.output for r in image_results if r.success and _is_media_url(r.output)
                ]
                idx += 1
            if video_descriptions:
                res = media_results[idx]
                video_results: list[StageResult] = res if isinstance(res, list) else []
                if not isinstance(res, list):
                    vcprint(
                        f"[PodcastGenerator] video batch errored (non-fatal): {res!r}",
                        color="yellow",
                    )
                video_urls = [
                    r.output for r in video_results if r.success and _is_media_url(r.output)
                ]

        # Feature image lands LAST in image_urls. Deliberate: the episode cover
        # is `image_urls[0]` (services/podcast/generation.py) and the official
        # video reads the list in order — appending leaves both untouched, so a
        # run behaves exactly as before plus one extra image at the end.
        if feature_image_task is not None:
            try:
                feature_prompt_stage, feature_image_stage = await feature_image_task
                # Record the prompt step for usage accounting (the image step is
                # already recorded by ``_on_asset``).
                stage_results.append(feature_prompt_stage)
                # URL-guard the resume path here too (the checkpointed
                # `image_{slot}` stage bypasses `_run_image`'s guard on replay).
                if feature_image_stage.success and _is_media_url(feature_image_stage.output):
                    image_urls.append(feature_image_stage.output)
            except asyncio.CancelledError:
                raise
            except Exception as exc:  # noqa: BLE001
                # Belt and braces — _generate_feature_image already soft-fails
                # internally, so reaching here means something truly unexpected.
                # It must never take down a run that already produced audio.
                vcprint(
                    f"[PodcastGenerator] feature image task errored (non-fatal): {exc!r}",
                    color="yellow",
                )

        # --- Stage 7: Compose the official slideshow video ---
        # Stitch the generated clips + stills into one crossfaded, share-ready
        # video. Best-effort — a failure here never fails the episode (audio +
        # individual assets already exist), it just leaves official_video_url
        # empty and records the reason.
        official_video_url = ""
        official_video_error = ""
        if (image_urls or video_urls) and (len(image_urls) + len(video_urls) >= 2):
            await _start("compose_official_video", "Composing your official video")
            compose_result = await _checkpointed(
                ckpt,
                "compose_official_video",
                lambda: _compose_official_video(video_urls, image_urls, title),
            )
            await _record(compose_result, label="Composing your official video")
            if compose_result.success and compose_result.output:
                official_video_url = compose_result.output
                vcprint(
                    f"[PodcastGenerator] Official video composed — {official_video_url}",
                    color="green",
                )
                await _emit(
                    PodcastEvent(
                        kind=PodcastEventKind.OFFICIAL_VIDEO,
                        stage="compose_official_video",
                        asset_kind="video",
                        asset_url=official_video_url,
                        success=True,
                        step=step,
                        total=total_steps,
                    )
                )
            else:
                official_video_error = compose_result.error or "official video composition failed"
                vcprint(
                    f"[PodcastGenerator] Official video FAILED — {official_video_error} "
                    f"(images={len(image_urls)}, videos={len(video_urls)})",
                    color="red",
                )
        else:
            official_video_error = (
                f"not enough media to compose an official video "
                f"(images={len(image_urls)}, videos={len(video_urls)}; need >= 2)"
            )
            vcprint(
                f"[PodcastGenerator] Official video skipped — {official_video_error}",
                color="yellow",
            )

        vcprint(
            f"[PodcastGenerator] Pipeline complete — show_id={request.show_id}",
            color="green",
        )

        # Resolve the cast that voiced the episode (names from the request or
        # the script's own labels; voices from the request or the default
        # palette). Best-effort metadata — never blocks the result.
        try:
            resolved_speakers = _effective_speakers(request, _extract_dialogue(script), script)
        except Exception:  # noqa: BLE001
            resolved_speakers = list(request.speakers)

        result = PodcastGenerationResult(
            show_id=request.show_id,
            success=audio_error is None,
            script=script,
            audio_url=audio_url,
            title=title,
            description=description,
            image_urls=image_urls,
            video_urls=video_urls,
            official_video_url=official_video_url,
            official_video_error=official_video_error,
            host_count=request.host_count,
            speakers=resolved_speakers,
            stage_results=stage_results,
            error=(f"Audio generation failed: {audio_error}" if audio_error else None),
            usage=_aggregate_stage_usage(stage_results),
            unsettled_usage=_aggregate_stage_usage(stage_results, unsettled_only=True),
        )
        if audio_error is None:
            await ckpt.finish(  # type: ignore[attr-defined]
                result.model_dump(mode="json"),
                total_cost=_unsettled_cost(stage_results),
            )
        else:
            # Failed-but-resumable: the checkpointed media replays free; only
            # the audio tail re-runs on /resume.
            await ckpt.fail(  # type: ignore[attr-defined]
                f"Audio generation failed: {audio_error}",
                total_cost=_unsettled_cost(stage_results),
            )
        return result
    except asyncio.CancelledError as exc:
        # Client disconnect / shutdown — leave the run resumable (don't mark it
        # failed) so it can be picked up again from its last good stage.
        #
        # Reconciliation remains the sole owner of terminal status/cost so a
        # cancelled pass cannot double-count. The cancellation itself is still
        # captured immediately for human review before it is re-raised.
        from matrx_connect.streaming.error_capture import capture_error

        await capture_error(
            exc,
            kind="podcast_run_cancelled",
            user_id=user_id,
            route="agent_runner/podcast",
            error_type="CancelledError",
            payload={
                "run_id": opened_run_id,
                "show_id": request.show_id,
                "completed_stages": [item.stage for item in stage_results],
            },
            context={"unsettled_cost": _unsettled_cost(stage_results)},
        )
        raise
    except Exception as exc:
        # Any unexpected error marks the run failed (with the reason) so it's
        # both surfaced and resumable rather than stuck in 'processing'.
        await ckpt.fail(  # type: ignore[attr-defined]
            f"{type(exc).__name__}: {exc}",
            total_cost=_unsettled_cost(stage_results),
        )
        raise
    finally:
        ticker_task.cancel()
        heartbeat_task.cancel()
        # Same discipline the script-failure path already applies to
        # media_tasks/audio_task: never leave a paid generation running for a
        # run that is no longer collecting results.
        if feature_image_task is not None and not feature_image_task.done():
            feature_image_task.cancel()
