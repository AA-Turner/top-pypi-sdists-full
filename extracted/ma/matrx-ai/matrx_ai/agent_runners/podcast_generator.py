async def _apply_audience_adaptation(
    content: str, target_audience: str, guidance: str
) -> StageResult:
    """Optional content → content re-pitch for a target audience.

    Runs BEFORE ``_apply_post_prep`` (adapt in the source language, then let a
    translation option be the faithful last transform). SOFT stage by the same
    contract as post-prep: any failure — including a degenerate too-short
    output — keeps the original content and never kills the run.
    """
    stage = "audience_adaptation"
    if not target_audience.strip():
        return StageResult(stage=stage, success=True, output=content)
    try:
        result = await _run_mandated(
            _AudienceAdapterAgent,
            inputs=_AudienceAdapterAgent.Inputs(
                prepared_content=content,
                target_audience=target_audience.strip(),
                adaptation_guidance=guidance.strip(),
            ),
            label="Podcast Audience Adaptation",
        )
    except Exception as exc:  # noqa: BLE001 — soft stage: record + keep original content
        vcprint(f"[PodcastGenerator] {stage} failed: {exc}", color="red")
        return StageResult(stage=stage, success=False, error=str(exc))

    stage_result = _to_stage(stage, result)
    output = (stage_result.output or "").strip()
    # Same degenerate-output guard as post-prep: a re-pitch that returns a
    # fraction of the substance must not replace real content.
    floor = min(_MIN_CONTENT_CHARS, max(1, len(content.strip()) // 2))
    if stage_result.success and len(output) < floor:
        vcprint(
            f"[PodcastGenerator] {stage} returned only {len(output)} chars "
            f"(< {floor}) — keeping the original content.",
            color="yellow",
        )
        return StageResult(
            stage=stage,
            success=False,
            error=(
                f"audience adaptation returned too little content ({len(output)} chars) — "
                "using original content"
            ),
            usage=stage_result.usage,
        )
    return stage_result


async def _apply_post_prep(content: str, option: PostPrepOption, *, language: str) -> StageResult:
    """Optional content → content transform between preparation and script.

    Each option runs its own mandated agent (mandate key ``podcast.post_prep_*``).
    SOFT stage by contract (PODCAST_PIPELINE.md §7): any failure returns a
    failed StageResult and the pipeline keeps the original content — post-prep
    must never kill a run. An empty/short transform result is treated as a
    failure rather than replacing real content with a degenerate body.

    ``language`` is the run's derived script language — the translation
    option's target (the decision recorded in the translation spec).
    """
    if option == PostPrepOption.NONE:
        return StageResult(stage="post_prep", success=True, output=content)

    stage = f"post_prep_{option}"
    try:
        match option:
            case PostPrepOption.TRANSLATION:
                result = await _run_mandated(
                    _PostPrepTranslationAgent,
                    inputs=_PostPrepTranslationAgent.Inputs(
                        content=content, target_language=language
                    ),
                    label="Podcast Post-Prep Translation",
                )
            case PostPrepOption.SUMMARIZATION:
                result = await _run_mandated(
                    _PostPrepSummarizationAgent,
                    inputs=_PostPrepSummarizationAgent.Inputs(content=content),
                    label="Podcast Post-Prep Summarization",
                )
            case PostPrepOption.EXPANSION:
                result = await _run_mandated(
                    _PostPrepExpansionAgent,
                    inputs=_PostPrepExpansionAgent.Inputs(content=content),
                    label="Podcast Post-Prep Expansion",
                )
            case PostPrepOption.FACT_CHECKING:
                result = await _run_mandated(
                    _PostPrepFactCheckingAgent,
                    inputs=_PostPrepFactCheckingAgent.Inputs(content=content),
                    label="Podcast Post-Prep Fact Check",
                )
            case _:
                return StageResult(
                    stage=stage,
                    success=False,
                    error=f"unknown post-prep option '{option}' — using original content",
                )
    except Exception as exc:  # noqa: BLE001 — soft stage: record + keep original content
        vcprint(f"[PodcastGenerator] {stage} failed: {exc}", color="red")
        return StageResult(stage=stage, success=False, error=str(exc))

    stage_result = _to_stage(stage, result)
    output = (stage_result.output or "").strip()
    # Degenerate-output guard: a "successful" transform that returns a fraction
    # of the expected substance must not replace real content. The floor scales
    # with the input so a legitimately short full_content body (GATE-1-exempt)
    # is never rejected for being short; summarization is allowed to shrink,
    # so its floor is the smaller of the gate minimum and half the input.
    floor = min(_MIN_CONTENT_CHARS, max(1, len(content.strip()) // 2))
    if stage_result.success and len(output) < floor:
        vcprint(
            f"[PodcastGenerator] {stage} returned only {len(output)} chars "
            f"(< {floor}) — keeping the original content.",
            color="yellow",
        )
        return StageResult(
            stage=stage,
            success=False,
            error=(
                f"transform returned too little content ({len(output)} chars) — "
                "using original content"
            ),
            usage=stage_result.usage,
        )
    return stage_result


