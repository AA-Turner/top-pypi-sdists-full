def _is_legacy_script_request(request: PodcastRequest) -> bool:
    """The original fixed two-host pipeline — keep the proven pinned agents.

    Anything beyond it (host count, custom format/theme/names) routes to the
    host-count-aware agents."""
    if request.host_count != 2 or request.theme or request.speakers:
        return False
    if request.podcast_type == PodcastType.PERSIAN:
        return not request.format and not request.language
    if request.language and _derived_language(request).lower() != "english":
        return False
    return request.format in ("", "educational", "news")


def _speaker_names_json(request: PodcastRequest) -> str:
    """Names handed to the script agent. Request-named speakers win verbatim
    (GATE 2 enforces they all speak). When the request names NOBODY, suggest a
    fresh rotated draw from the default cast instead of sending "[]" — an LLM
    left to invent a cast invents the SAME names run after run (the "every
    podcast has the same hosts" collapse), while a suggested cast varies per
    run. Suggestions are not gate-enforced: the agent may adapt them (e.g. for
    language/theme fit) and GATE 2 only checks count + declared consistency."""
    import json

    pairs: list[tuple[str, str]] = [
        (s.name, _gender_for_name(s.name, s.gender)) for s in request.speakers if s.name.strip()
    ]
    if not pairs and request.host_count >= 2:
        pairs = _default_cast(request.host_count, seed=uuid.uuid4().hex)
    if not pairs:
        return "[]"
    # Name AND gender (2026-08-20). The pipeline voices each host by gender, so
    # the writer must know it too — otherwise the script says "he" about the
    # host we render with a female voice, or invents a cast whose names read the
    # opposite way. Objects rather than bare strings so the two halves can never
    # drift apart again; a name we cannot resolve carries an empty gender rather
    # than a guess.
    return json.dumps([{"name": n, "gender": g} for n, g in pairs])


def _canonical_script(script: str) -> str:
    """Reduce a GATE-2-validated script to its canonical persisted form.

    The agent's raw output may carry reasoning prose, stray tags, or commentary
    around the real blocks. Only two parts are the script: the validated
    ``<podcast_dialogue>`` block and the optional ``<speaker_settings>``
    declaration. Everything else is dropped HERE, at the gate, so every
    downstream consumer — the checkpoint, the audio stage, ``pc_episodes.script``,
    and every agent that later reads the episode (blog, show notes, chapters,
    title optimizer) — sees the same clean script and can never inherit
    reasoning text. Idempotent: canonicalizing a canonical script is a no-op."""
    dialogue = _extract_dialogue(script)
    parts = [f"<podcast_dialogue>\n{dialogue}\n</podcast_dialogue>"]
    m = _SPEAKER_SETTINGS_RE.search(script or "")
    if m and m.group(1).strip():
        parts.append(f"<speaker_settings>{m.group(1).strip()}</speaker_settings>")
    return "\n\n".join(parts)


def _validated_script_stage(result: AgentRunResult, request: PodcastRequest) -> StageResult:
    """GATE 2 wrapper for a script-agent result.

    A script agent that "succeeds" but returns prose/thinking, an empty block, or
    a cast-violating script is converted to a FAILED ``create_script`` stage — so
    the orchestrator never launches audio on it. On pass, the stage output is the
    CANONICAL script (dialogue block + optional speaker_settings — never the
    agent's raw output; see ``_canonical_script``). The failure is resumable
    (the script stage re-runs).

    🚨 The script agent's USAGE rides through EVERY path here. The agent has
    already been paid for by the time this wrapper sees its result — a GATE-2
    rejection does not refund those tokens. Returning a bare ``StageResult``
    without ``usage=`` is what made ``create_script`` — the most expensive
    agent in the pipeline — record ZERO cost on every podcast run (found by
    S6's per-arm cost audit across the 5 most recent live runs; the third
    billing-undercount incident in this file)."""
    usage = _usage_from_agent_result(result)
    if not result.success:
        # Pass the agent's own failure through as a failed stage. (This used to
        # recurse into itself with identical args — a guaranteed RecursionError
        # on any failed script agent run.)
        return _to_stage("create_script", result)
    try:
        _validate_script(result.output, request)
    except ScriptValidationError as exc:
        vcprint(
            f"[PodcastGenerator] create_script REJECTED by GATE 2: {exc}",
            color="red",
        )
        return StageResult(
            stage="create_script",
            success=False,
            error=f"Script failed validation: {exc}",
            usage=usage,
        )
    return StageResult(
        stage="create_script",
        success=True,
        output=_canonical_script(result.output),
        usage=usage,
    )


async def _create_script(request: PodcastRequest, prepared_content: str) -> StageResult:
    # "Script → straight to recording": if the prepared content is ALREADY a
    # finished script (contains a <podcast_dialogue> block), skip generation
    # entirely and validate it directly. A user who pastes a complete script
    # (or a prior stage that produced one) does not get re-written. GATE 2 still
    # applies — a pasted script whose cast doesn't match the request fails here,
    # not silently at the audio stage.
    if _has_dialogue_block(prepared_content):
        try:
            _validate_script(prepared_content, request)
        except ScriptValidationError as exc:
            return StageResult(
                stage="create_script",
                success=False,
                error=f"Provided script failed validation: {exc}",
            )
        vcprint(
            "[PodcastGenerator] Input is already a valid script — skipping "
            "generation, going straight to audio.",
            color="cyan",
        )
        return StageResult(
            stage="create_script", success=True, output=_canonical_script(prepared_content)
        )

    if _is_legacy_script_request(request):
        match request.podcast_type:
            case PodcastType.NEWS:
                legacy_cls = _NewsScriptAgent
            case PodcastType.PERSIAN:
                legacy_cls = _PersianScriptAgent
            case _:
                legacy_cls = _EducationalScriptAgent
        if request.format == "news":
            legacy_cls = _NewsScriptAgent
        result = await _run_mandated(
            legacy_cls,
            inputs=legacy_cls.Inputs(podcast_topic_or_content=prepared_content),
            label="Podcast Script",
        )
        return _validated_script_stage(result, request)

    n = request.host_count
    if n == 1:
        solo_name = request.speakers[0].name if request.speakers else ""
        result = await _run_mandated(
            _SoloScriptAgent,
            inputs={
                "prepared_content": prepared_content,
                "format": _derived_format(request),
                "theme": request.theme,
                "language": _derived_language(request),
                "speaker_name": solo_name,
            },
            label="Podcast Script",
        )
        return _validated_script_stage(result, request)

    if n >= 5:
        result = await _run_mandated(
            _RoundtableScriptAgent,
            inputs={
                "prepared_content": prepared_content,
                "num_speakers": str(n),
                "format": _derived_format(request),
                "theme": request.theme,
                "language": _derived_language(request),
                # BLANK ON PURPOSE (2026-08-23): no persona data (role/stance)
                # exists anywhere on PodcastRequest — only name/voice/gender,
                # which already travel in speaker_names. Blank is the agent's
                # documented "fall back to speaker_names" path; the previous
                # hardcoded "[]" fabricated a value nothing ever fills (and the
                # durable-workflow twin podcast_w3_script maps no personas at
                # all, so the two call sites now agree). If the request ever
                # grows real personas, fill this from them — never a constant.
                "speaker_personas": "",
                "speaker_names": _speaker_names_json(request),
            },
            label="Podcast Script",
        )
        return _validated_script_stage(result, request)

    # 2–4 hosts off the legacy path → the built multihost agent.
    result = await _run_mandated(
        _MultihostScriptAgent,
        inputs=_MultihostScriptAgent.Inputs(
            prepared_content=prepared_content,
            num_speakers=str(n),
            format=_derived_format(request),
            theme=request.theme,
            language=_derived_language(request),
            speaker_names=_speaker_names_json(request),
        ),
        label="Podcast Script",
    )
    return _validated_script_stage(result, request)


