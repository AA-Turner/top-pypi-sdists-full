def resolve_feature_image_style(value: str | None) -> tuple[FeatureImageStyle, str]:
    """Map a wire token to ``(style, prompt_text)``.

    Unknown/missing tokens fall back to the default rather than raising — a
    stale client must never be able to fail a whole podcast run over a label.
    """
    try:
        style = FeatureImageStyle(value) if value else DEFAULT_FEATURE_IMAGE_STYLE
    except ValueError:
        vcprint(
            f"[PodcastGenerator] unknown feature_image_style={value!r} — "
            f"falling back to {DEFAULT_FEATURE_IMAGE_STYLE.value}",
            color="yellow",
        )
        style = DEFAULT_FEATURE_IMAGE_STYLE
    return style, FEATURE_IMAGE_STYLE_PROMPTS[style]


