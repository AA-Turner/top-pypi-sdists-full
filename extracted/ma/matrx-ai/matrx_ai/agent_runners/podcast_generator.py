_DIALOGUE_BLOCK_RE = re.compile(r"<podcast_dialogue>(.*?)</podcast_dialogue>", re.DOTALL)


def _has_dialogue_block(text: str) -> bool:
    """True if ``text`` already contains a non-empty <podcast_dialogue> block.

    Non-raising probe (the counterpart to the strict ``_extract_dialogue``). Used
    to decide two things WITHOUT generating: (1) is the prepared content already a
    finished script → skip script generation; (2) is it script-shaped → exempt
    from the content-length gate."""
    return any(m.strip() for m in _DIALOGUE_BLOCK_RE.findall(text or ""))


# Optional, authoritative speaker declaration the script agent MAY append after
# the dialogue block. When present it is the source of truth for the cast (and,
# if the agent declared genders, the gender-matched voice assignment) — so the
# pipeline never GUESSES the speakers. See PODCAST_PIPELINE.md §4.1. The agent
# contract (name + gender; the server picks the voice and rotates the pool):
#   <speaker_settings>{"speakers":[{"name":"Alex","gender":"male"}, …]}</speaker_settings>
# (gender + voice both optional). Absent → fall back to the dialogue's own labels.
_SPEAKER_SETTINGS_RE = re.compile(r"<speaker_settings>(.*?)</speaker_settings>", re.DOTALL)


def _parse_speaker_settings(script: str) -> list[SpeakerSpec] | None:
    """Parse the optional ``<speaker_settings>`` JSON the agent may declare.

    Returns the declared speakers (name + optional gender + optional voice), or
    None when absent / unparseable (the pipeline then derives the cast from the
    dialogue labels — never a crash). Accepts both ``["Alex","Sarah"]`` and
    ``[{"name":"Alex","gender":"male","voice":"orus"}]`` forms. ``gender`` is the
    field the script agents should declare (name + gender, no voice) so the
    server owns gender-matched voice selection."""
    import json

    m = _SPEAKER_SETTINGS_RE.search(script or "")
    if not m:
        return None
    raw = m.group(1).strip()
    # The agent may wrap it in a ```json fence — tolerate it.
    raw = re.sub(r"^```(?:json)?|```$", "", raw, flags=re.MULTILINE).strip()
    try:
        data = json.loads(raw)
    except (ValueError, TypeError):
        return None
    items = data.get("speakers") if isinstance(data, dict) else data
    if not isinstance(items, list) or not items:
        return None
    out: list[SpeakerSpec] = []
    for it in items:
        if isinstance(it, str) and it.strip():
            out.append(SpeakerSpec(name=it.strip(), voice=""))
        elif isinstance(it, dict) and str(it.get("name", "")).strip():
            out.append(
                SpeakerSpec(
                    name=str(it["name"]).strip(),
                    voice=str(it.get("voice", "") or "").strip(),
                    gender=str(it.get("gender", "") or "").strip(),
                )
            )
    return out or None


def _extract_dialogue(script: str) -> str:
    """GATE 2 enforcement point — return the validated dialogue block, or RAISE.

    The hard rule: a script is ONLY the text inside a
    ``<podcast_dialogue>…</podcast_dialogue>`` block. If the agent returned prose,
    thinking, or a malformed/empty block, that is NOT a script and must never be
    forwarded to the TTS stage. The old behaviour — ``return script`` on no match
    — is exactly what leaked raw reasoning text into Google TTS; it is gone.

    Takes the LONGEST block found (the real script is substantial; a stray tag a
    model writes inside its own reasoning is short or empty), so a model that
    "thinks out loud" about the dialogue tag before emitting the real one is
    handled correctly.

    Raises :class:`ScriptValidationError` — callers convert it to a failed stage.
    """
    blocks = [m.strip() for m in _DIALOGUE_BLOCK_RE.findall(script or "")]
    blocks = [b for b in blocks if b]
    if not blocks:
        raise ScriptValidationError(
            "Script has no usable <podcast_dialogue>…</podcast_dialogue> block — "
            "the agent returned prose/thinking, not a script. Refusing to send to "
            "the audio stage."
        )
    return max(blocks, key=len)


def _distinct_speakers(dialogue: str) -> list[str]:
    """Distinct speaker labels in first-appearance order."""
    distinct: list[str] = []
    for name, _text in _dialogue_speaker_lines(dialogue):
        if name not in distinct:
            distinct.append(name)
    return distinct


def _validate_script(script: str, request: PodcastRequest) -> str:
    """Full GATE 2. Returns the validated dialogue block, or RAISES.

    The contract is EXACT — what the UI promised, the script must deliver, and
    that is what reaches TTS (PODCAST_PIPELINE.md §3/§4). No "close enough", no
    downstream name-fixing:
      1. a usable ``<podcast_dialogue>`` block with ≥1 ``Name: line`` turn,
      2. **exactly** ``host_count`` distinct speakers — 14 means 14, not 13,
      3. every request-named speaker actually speaks (case-sensitive),
      4. if the agent declared ``<speaker_settings>``, its names match the
         dialogue's actual labels exactly (an agent that lies about its own
         script is rejected, not trusted).
    """
    dialogue = _extract_dialogue(script)
    turns = _dialogue_speaker_lines(dialogue)
    if not turns:
        raise ScriptValidationError(
            "The <podcast_dialogue> block has no 'Name: line' speaker turns."
        )
    distinct = _distinct_speakers(dialogue)
    n = request.host_count or _DEFAULT_SPEAKER_COUNT

    # (2) EXACT cast size. The UI asked for n hosts; the script must have n.
    if len(distinct) != n:
        raise ScriptValidationError(
            f"Script has {len(distinct)} distinct speakers {distinct} but the "
            f"request requires exactly {n}. The script agent must produce exactly "
            f"{n} speakers — re-run (the agent prompt must enforce the count)."
        )

    # (3) Every requested speaker name must actually speak.
    named = [s.name for s in request.speakers if s.name.strip()]
    if named:
        missing = [nm for nm in named if nm not in distinct]
        if missing:
            raise ScriptValidationError(
                f"Requested speaker(s) {missing} never speak in the script "
                f"(the script's speakers are {distinct}). Names are case-sensitive."
            )

    # (4) Declared <speaker_settings> must agree with the actual dialogue labels.
    declared = _parse_speaker_settings(script)
    if declared is not None:
        declared_names = [s.name for s in declared]
        if set(declared_names) != set(distinct):
            raise ScriptValidationError(
                f"<speaker_settings> declares {declared_names} but the dialogue's "
                f"actual speakers are {distinct}. The agent's declaration must "
                f"match its own script exactly."
            )
    return dialogue


def _truncate_dialogue_for_testing(dialogue: str, speakers: int = _DEFAULT_SPEAKER_COUNT) -> str:
    """
    For testing: given an ALREADY-EXTRACTED dialogue block (GATE 2 has run, so
    the input is the validated ``Name: line`` text — NOT a full script with
    tags), keep the FIRST turn of each distinct speaker, in first-appearance
    order, up to ``speakers`` of them.

    One line per host is the whole point of test mode — but it must be one line
    per *distinct* host, not merely the first N lines. A script that opens with
    two turns from the same host would otherwise drop the other host entirely,
    leaving the multi-speaker TTS contract a speaker short — a configured
    speaker missing from the transcript is a hard validation failure (this is
    half of why non-English test runs were failing). Reusing the same
    ``Name: text`` parser the audio stage uses keeps every configured voice
    represented and is script-agnostic (handles non-Latin labels too). Falls
    back to the first 300 chars of the dialogue when no turns are found.
    """
    kept: list[str] = []
    seen: set[str] = set()
    for name, text in _dialogue_speaker_lines(dialogue):
        if name in seen:
            continue
        seen.add(name)
        kept.append(f"{name}: {text}")
        if len(kept) >= speakers:
            break

    if kept:
        vcprint(
            f"[PodcastGenerator] Script truncated to {len(kept)} speaker "
            f"turn(s) (one per host) for testing",
            color="yellow",
        )
        return "\n\n".join(kept)

    return dialogue[:300]


