# Set once refresh_voice_pools() has successfully loaded the DB catalog, so a
# long-lived worker process refreshes at most once (the catalog is near-static;
# a process restart re-reads it).
_voice_pools_loaded = False


async def refresh_voice_pools(*, force: bool = False) -> None:
    """Load the ElevenLabs voice pool from ``ai.voices`` (the source of truth).

    Replaces the in-memory pool with enabled DB rows; on no-DB / empty-table /
    error it keeps the built-in fallback. Runs at most once per process unless
    ``force`` is passed. Never raises — voice selection must never be blocked by
    a catalog read.
    """
    global _ELEVENLABS_VOICE_POOL, _GOOGLE_VOICE_POOL, _voice_pools_loaded
    if _voice_pools_loaded and not force:
        return

    async def _load(provider: str) -> list[tuple[str, str, str]]:
        try:
            from matrx_ai.db.voice_catalog import load_enabled_voices

            rows = await load_enabled_voices(provider)
        except Exception:  # noqa: BLE001 — degrade to fallback
            rows = []
        return [
            (
                r["provider_voice_id"],
                _normalize_gender(r.get("gender")),
                r.get("name") or r["provider_voice_id"],
            )
            for r in rows
            if r.get("provider_voice_id")
        ]

    for provider, rebuild in (
        ("elevenlabs", _rebuild_elevenlabs_derived),
        ("google", _rebuild_google_derived),
    ):
        pool = await _load(provider)
        # Need at least one male AND one female to do gender-matched casting; if
        # the DB can't satisfy that, keep the curated fallback rather than degrade.
        has_m = any(g == "male" for _, g, _ in pool)
        has_f = any(g == "female" for _, g, _ in pool)
        if pool and has_m and has_f:
            if provider == "elevenlabs":
                _ELEVENLABS_VOICE_POOL = pool
            else:
                _GOOGLE_VOICE_POOL = pool
            rebuild()
            vcprint(
                f"[PodcastGenerator] Loaded {len(pool)} {provider} voices from the DB catalog.",
                color="green",
            )
        else:
            vcprint(
                f"[PodcastGenerator] DB voice catalog unavailable/insufficient for "
                f"{provider} — using the built-in fallback pool.",
                color="yellow",
            )
    _voice_pools_loaded = True


