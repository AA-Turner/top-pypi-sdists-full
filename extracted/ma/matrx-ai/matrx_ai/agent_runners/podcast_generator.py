AssetCallback = Callable[[str, int, str, "StageResult"], Awaitable[None]]


# ---------------------------------------------------------------------------
# BORN-PUBLIC MEDIA — why every media stage here runs inside
# ``public_media_scope()``.
#
# A podcast episode is PUBLISHED — an anonymous reader loads its cover, its
# videos, and its audio from a public page and from social-share previews. So
# every asset this pipeline generates must be born PUBLIC, carrying a permanent
# ``cdn.matrxserver.com`` URL, at the moment it is persisted.
#
# The default for `ai_images` / `ai_video` is `personal` (privacy: a chat image
# must not be world-readable), which mints an EXPIRING signed S3 URL. That URL
# is what a stage checkpoint records, what the ASSET stream event carries, and
# what the client then writes into `podcast.pc_studio_runs.image_urls` /
# `video_urls`. Flipping the files public afterwards did NOT undo any of that:
# the flip MOVES the S3 object to the public bucket, so every already-emitted
# signed URL is DEAD immediately — not merely expiring in a week.
#
# Persisting public up front removes the whole class: there is never a
# non-durable URL to emit, checkpoint, persist, or heal. Audio is already born
# public via ``BORN_PUBLIC_FEATURES``; the composed official video passes
# ``visibility="public"`` explicitly.
# ---------------------------------------------------------------------------


_MEDIA_FILE_ID_RE = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", re.IGNORECASE
)


def _is_media_url(output: str | None) -> bool:
    """An image/video agent's output MUST be a durable URL or a ``file_id``.

    Guaranteed safety net against the concurrency class fixed above: if a
    sibling agent's streamed text ever contaminates a media slot's captured
    output, that output is prose, not a media handle. Treating a non-handle
    "success" as a failure turns silent corruption (garbage rendered as a cover)
    into a clean, retryable failed card — and, because the episode cover is
    ``image_urls[0]``, keeps corruption from ever becoming the published cover.

    A bare ``file_id`` is accepted because that is the canonical internal handle
    (media_config THE OUTPUT RULE): a media block flattened to text hands back an
    identity, never an expiring link. Inside ``public_media_scope()`` these
    agents get a durable CDN URL and this branch never fires; when it does, the
    persist boundary (``make_url_durable``) mints the public URL from the id
    before it reaches a column the anonymous episode page reads.
    """
    if not output:
        return False
    candidate = output.strip()
    if candidate.lower().startswith(("http://", "https://")):
        return True
    return bool(_MEDIA_FILE_ID_RE.match(candidate))


async def _run_asset_with_fallback(
    stage_key: str,
    agents: list[type[NamedAgent]],
    index: int,
    make_inputs: Callable[[type[NamedAgent]], BaseModel],
    *,
    conversation_label: str | None = None,
) -> StageResult:
    """Run one image/video slot with a one-shot model fallback.

    A single asset is NON-CRITICAL. Provider rejections (Together.ai / Black
    Forest Labs content moderation routinely false-flags benign AI-written
    creative concepts other models render fine) and transient errors must
    degrade, never abort a pipeline that already spent a dozen expensive
    calls. Before settling on a failed slot, retry ONCE with the next pinned
    agent version (a different model/style) — most moderation false-positives
    and transient provider errors clear on a different model. A fallback
    success carries a `note` so the UI can show a small informational chip;
    a double failure returns the primary error (fallback error appended).
    """

    run_label = conversation_label or stage_key

    async def _attempt(agent: type[NamedAgent], label: str) -> tuple[StageResult, str | None]:
        try:
            result = await _run_mandated(
                agent,
                inputs=make_inputs(agent),
                label=label,
                # Media slots emit their own typed ASSET event. Their provider
                # stream must never share the parent text accumulator with
                # sibling slots in this concurrent fan-out.
                suppress_stream=True,
            )
        except asyncio.CancelledError:
            raise
        except Exception as exc:  # noqa: BLE001
            return (
                StageResult(stage=stage_key, success=False, error=str(exc)),
                f"{type(exc).__name__}: {exc}",
            )
        stage = _to_stage(stage_key, result)
        # A "successful" render whose output isn't a URL is not a success — it
        # is corrupted output (see _is_media_url). Downgrade to a failure so the
        # one-shot fallback model is tried, and a persistent bad output settles
        # as a clean failed card instead of a garbage URL.
        if stage.success and not _is_media_url(stage.output):
            bad = (stage.output or "")[:80]
            err = f"agent returned a non-URL output (not a rendered asset): {bad!r}"
            vcprint(f"[PodcastGenerator] {stage_key} {err}", color="yellow")
            return StageResult(stage=stage_key, success=False, error=err), err
        return stage, (stage.error if not stage.success else None)

    primary = agents[index % len(agents)]
    stage, primary_error = await _attempt(primary, run_label)
    if stage.success or len(agents) < 2:
        return stage

    fallback = agents[(index + 1) % len(agents)]
    vcprint(
        f"[PodcastGenerator] {stage_key} failed on {primary.name} "
        f"({primary_error}) — retrying once with {fallback.name}",
        color="yellow",
    )
    retry, retry_error = await _attempt(fallback, run_label)
    if retry.success:
        retry.note = "The first model declined this one — rendered with a backup model."
        return retry

    vcprint(
        f"[PodcastGenerator] {stage_key} failed on both models (non-fatal, "
        f"continuing): primary={primary_error} fallback={retry_error}",
        color="yellow",
    )
    return StageResult(
        stage=stage_key,
        success=False,
        error=f"{primary_error} (fallback model also failed: {retry_error})",
    )


async def _generate_image(
    prompt: str,
    index: int,
    on_asset: AssetCallback | None = None,
    ckpt: object | None = None,
) -> StageResult:
    async def _run() -> StageResult:
        # Soft-failure contract: any failure returns success=False — ckpt.stage
        # commits a resumable failed checkpoint, the pipeline carries on, and
        # the frontend shows a quiet "Couldn't render — Retry" card.
        return await _run_asset_with_fallback(
            f"image_{index}",
            _IMAGE_AGENTS,
            index,
            lambda agent: agent.Inputs(image_description=prompt),
            conversation_label=f"Podcast Image {index + 1}",
        )

    # Per-asset checkpoint: a resumed run reuses an already-rendered (paid-for)
    # image instead of regenerating it.
    stage = await _checkpointed(ckpt, f"image_{index}", _run)
    # Stream this image the moment it finishes — don't wait for the whole batch.
    if on_asset is not None:
        await on_asset("image", index, prompt, stage)
    return stage


def _pad_prompts(descriptions: list[str], target: int) -> list[str]:
    """Trim to ``target`` prompts, or pad by repeating the last one."""
    prompts = descriptions[:target]
    while prompts and len(prompts) < target:
        prompts.append(prompts[-1])
    return prompts


def _effective_media_count(cap: int | None, maximum: int) -> int:
    """Resolve a per-run media cap to a concrete slot count.

    ``None`` → the full ``maximum`` (one asset per pinned agent version). A value
    clamps into ``[0, maximum]`` — ``0`` skips the media type, ``1`` renders a
    single asset. This is what lets a test run trade the expensive full media
    fan-out for a fast, cheap check without touching the audio/script path.
    """
    if cap is None:
        return maximum
    return max(0, min(cap, maximum))


async def _generate_images(
    image_descriptions: list[str],
    target: int = _TARGET_IMAGE_COUNT,
    on_asset: AssetCallback | None = None,
    ckpt: object | None = None,
) -> list[StageResult]:
    """Generate ``target`` images fully in parallel through the image agent."""
    await _warn_if_image_agents_are_not_diverse()
    prompts = _pad_prompts(image_descriptions, target)
    if not prompts:
        return []

    # Each call runs in its own Task so its child-context fork is isolated.
    # Results return in slot order (gather), but each Task streams its asset as
    # soon as it lands via ``on_asset`` so the UI fills in images out-of-order.
    #
    # BORN PUBLIC (see the BORN-PUBLIC MEDIA note): the Tasks are created INSIDE the
    # scope, so each inherits it and persists its image straight to the public
    # bucket with a durable CDN URL.
    with public_media_scope():
        tasks = [
            asyncio.create_task(_generate_image(prompt, i, on_asset, ckpt))
            for i, prompt in enumerate(prompts)
        ]
        return list(await asyncio.gather(*tasks))


async def _generate_feature_image(
    transcript: str,
    style_value: str | None,
    slot: int,
    on_asset: AssetCallback | None = None,
    ckpt: object | None = None,
) -> tuple[StageResult, StageResult]:
    """Render the transcript-derived feature image (two-step agent chain).

    Step 1 turns the FULL transcript plus a style instruction into a long,
    detailed image prompt; step 2 renders it. Returns ``(prompt_stage,
    image_stage)`` — the caller records ``prompt_stage`` (``image_stage`` is
    already recorded by ``on_asset``), mirroring ``_generate_metadata``'s
    tuple shape.

    Each step is its OWN checkpoint. That keeps the prompt's ``output`` (the
    generated prompt text) available on resume without widening the shared
    ``StageResult`` model, stops a resume from re-paying for the prompt agent,
    and — because the prompt step is a real ``StageResult`` — lets its token
    usage flow into the run's usage aggregate instead of being discarded. The
    image step is keyed ``image_{slot}`` to match the per-asset catalog
    convention (``{kind}_{slot}``) so it lands in the images grid like any
    other slot.

    NON-CRITICAL, exactly like the other image Mandates: every failure path returns
    ``success=False`` so the run continues and the UI shows a quiet failed card.
    Runs AFTER the script (it needs the transcript), unlike slots 0..4 which
    launch off the metadata agent before the script exists.
    """
    stage_key = f"image_{slot}"
    prompt_key = "feature_image_prompt"
    style, style_prompt = resolve_feature_image_style(style_value)

    async def _run_prompt() -> StageResult:
        try:
            result = await _run_mandated(
                _ImagePromptAgent,
                inputs=_ImagePromptAgent.Inputs(
                    intent_or_content=transcript,
                    style=style_prompt,
                ),
                label="Podcast Feature Image Prompt",
                # ISOLATE this concurrent side-quest agent's stream. A
                # child-agent fork ALIASES the parent's emitter
                # (context/app_context.py fork_for_child_agent), and the
                # executor rebuilds a stage's output from that emitter's shared
                # turn-text accumulator on the error/truncate/cancel paths — so
                # a concurrent agent's streamed tokens can land in another
                # slot's captured output. This agent is the first LONG TEXT
                # streamer to run concurrently with the image agents; its prompt
                # interleaved into a concurrent image Mandate (proven: a metadata
                # image's stored output was a verbatim window of THIS prompt).
                # suppress_stream gives it its OWN SilentEmitter, so its tokens
                # never enter the shared accumulator the image agents read. The
                # sink is the emitter, NOT request_id, so independent_request is
                # deliberately NOT set — it wouldn't help and would orphan this
                # agent's cost from the run's CX lineage (SUBAGENTS.md H4). Its
                # structured result still returns via AgentRunResult.
                suppress_stream=True,
            )
        except asyncio.CancelledError:
            raise
        except Exception as exc:  # noqa: BLE001
            return StageResult(
                stage=prompt_key,
                success=False,
                error=f"{type(exc).__name__}: {exc}",
            )
        return _to_stage(prompt_key, result)

    prompt_stage = await _checkpointed(ckpt, prompt_key, _run_prompt)
    image_prompt = (prompt_stage.output or "").strip()
    if not prompt_stage.success or not image_prompt:
        reason = prompt_stage.error or "the prompt agent returned nothing"
        failed = StageResult(
            stage=stage_key,
            success=False,
            error=f"feature image prompt failed: {reason}",
        )
        if on_asset is not None:
            await on_asset("image", slot, "", failed)
        vcprint(
            f"[PodcastGenerator] feature image prompt failed (non-fatal): {reason}",
            color="yellow",
        )
        return prompt_stage, failed

    async def _run_image() -> StageResult:
        # BORN PUBLIC (see the BORN-PUBLIC MEDIA note) — the feature image is the episode
        # cover candidate an anonymous reader loads.
        try:
            with public_media_scope():
                result = await _run_mandated(
                    _FeatureImageAgent,
                    inputs=_FeatureImageAgent.Inputs(image_description=image_prompt),
                    label="Podcast Feature Image",
                    # Same emitter isolation as the prompt agent above (it forks
                    # with the shared emitter and runs concurrently with the other
                    # media slots). request_id is not the sink, so no
                    # independent_request here either.
                    suppress_stream=True,
                )
        except asyncio.CancelledError:
            raise
        except Exception as exc:  # noqa: BLE001
            return StageResult(
                stage=stage_key,
                success=False,
                error=f"feature image render failed: {type(exc).__name__}: {exc}",
            )
        stage = _to_stage(stage_key, result)
        # Same URL guard as the metadata slots: a non-URL "success" is corrupted
        # output, not a rendered image — settle it as a clean failure.
        if stage.success and not _is_media_url(stage.output):
            bad = (stage.output or "")[:80]
            return StageResult(
                stage=stage_key,
                success=False,
                error=f"feature image render returned a non-URL output: {bad!r}",
            )
        return stage

    image_stage = await _checkpointed(ckpt, stage_key, _run_image)
    if on_asset is not None:
        # The generated prompt (not the raw transcript) is what rendered this.
        await on_asset("image", slot, image_prompt, image_stage)
    vcprint(
        f"[PodcastGenerator] feature image (style={style.value}) "
        f"{'ok' if image_stage.success else 'failed (non-fatal): ' + str(image_stage.error)}",
        color="cyan" if image_stage.success else "yellow",
    )
    return prompt_stage, image_stage


