async def _generate_videos(
    video_descriptions: list[str],
    target: int = _TARGET_VIDEO_COUNT,
    on_asset: AssetCallback | None = None,
    ckpt: object | None = None,
) -> list[StageResult]:
    """
    Generate ``target`` videos via the video agent.

    Videos are staggered slightly (not fired simultaneously) to avoid DB
    connection-pool pressure — each video job long-polls the provider and
    creates rows on both start and finish.
    """
    prompts = _pad_prompts(video_descriptions, target)
    if not prompts:
        return []

    # BORN PUBLIC (see the BORN-PUBLIC MEDIA note).
    results: list[StageResult] = []
    with public_media_scope():
        for i, prompt in enumerate(prompts):
            if i > 0:
                await asyncio.sleep(2)  # brief stagger to avoid simultaneous DB writes
            results.append(await _generate_video(prompt, i, on_asset, ckpt))
    return results


# ---------------------------------------------------------------------------
# Stage 7 — Official video composition
#
# Stitch the generated videos + images into a single crossfaded slideshow via
# the matrx-utils video-composition primitive. Square images are centered over
# a blurred fill so everything shares the wide 16:9 canvas. This is the
# episode's primary, share-ready video.
# ---------------------------------------------------------------------------

# On-screen seconds per still image in the composed video, and the crossfade
# length between segments. Tuned so 5 images + 2 short clips land at ~20-30s.
_OFFICIAL_VIDEO_IMAGE_SECONDS = 3.5
_OFFICIAL_VIDEO_CROSSFADE = 0.8
_OFFICIAL_VIDEO_WIDTH = 1280
_OFFICIAL_VIDEO_HEIGHT = 720


def _official_video_order(video_urls: list[str], image_urls: list[str]) -> list[tuple[str, str]]:
    """Interleave clips and stills into a pleasing sequence.

    Opens on a video, then alternates two images per video so the motion is
    spaced out: ``v0, i0, i1, v1, i2, i3, i4 …``. Any leftover media is
    appended in order. Returns a list of ``(kind, url)`` pairs.
    """
    vids = list(video_urls)
    imgs = list(image_urls)
    order: list[tuple[str, str]] = []
    if vids:
        order.append(("video", vids.pop(0)))
    while imgs or vids:
        for _ in range(2):
            if imgs:
                order.append(("image", imgs.pop(0)))
        if vids:
            order.append(("video", vids.pop(0)))
    return order


async def _read_media_handle_bytes(fm, handle: str) -> bytes:
    """Resolve ONE media handle to bytes through the canonical media funnel.

    A media handle here is whatever a stage recorded (see ``_is_media_url``):
    a bare ``file_id`` — the canonical internal identity — or any URL WE
    issued for it (public CDN, signed S3, share link). Both become a
    ``MediaRef`` and go through ``FileManager.resolve_media_async``, which
    resolves identity FIRST (``cld_files`` row → S3 read) and knows every URL
    dialect we mint, including ``cdn.matrxserver.com``.

    NEVER call ``fm.read_url_async`` here. That is the raw storage reader: it
    parses an S3 URL into bucket+key and rejects anything else, so a public
    CDN URL — the exact durable form a published episode's media carries —
    dies with "Cannot determine storage backend from HTTPS URL". Every
    episode whose media went public failed official-video composition for
    that reason (fixed 2026-08-17).
    """
    from matrx_files import MediaRef
    from matrx_utils.ctx import system_file_access

    candidate = (handle or "").strip()
    ref = (
        MediaRef(file_id=candidate)
        if _MEDIA_FILE_ID_RE.match(candidate)
        else MediaRef(url=candidate)
    )
    # Internal pipeline reading media it just generated — declare it so a
    # background (no-request-context) run authorizes; an in-request run still
    # authorizes as the request user.
    with system_file_access("podcast-official-video"):
        await fm.resolve_media_async(ref, needs_bytes=True)

    if ref.resolver_error:
        raise RuntimeError(f"could not resolve {candidate}: {ref.resolver_error}")
    if not ref.base64_data:
        raise RuntimeError(f"resolved {candidate} but got no bytes back")
    return base64.b64decode(ref.base64_data)


async def _compose_official_video(
    video_urls: list[str], image_urls: list[str], title: str
) -> StageResult:
    """Download the generated media, compose one crossfaded slideshow MP4,
    upload it via the canonical media pipeline, and return its URL.

    Requires the host-injected cloud FileManager (``get_cloud_file_manager``)
    so it can resolve the generated media handles and write the result. A
    standalone matrx-ai install without that injection point cleanly reports
    the stage as skipped rather than raising.
    """
    from matrx_files import SlideSegment, compose_slideshow_async

    order = _official_video_order(video_urls, image_urls)
    # Need at least two segments to make a "video" worth the name.
    if len(order) < 2:
        return StageResult(
            stage="compose_official_video",
            success=False,
            error="not enough media to compose an official video",
        )
    if not has_ext("get_cloud_file_manager"):
        return StageResult(
            stage="compose_official_video",
            success=False,
            error="cloud file manager not configured — cannot read/write media",
        )

    fm = get_ext("get_cloud_file_manager")()

    # Resolve every source to bytes concurrently, by identity (see
    # _read_media_handle_bytes) — never by raw storage-URL parsing.
    try:
        blobs = await asyncio.gather(*[_read_media_handle_bytes(fm, handle) for _, handle in order])
    except Exception as exc:
        return StageResult(
            stage="compose_official_video",
            success=False,
            error=f"failed to download source media: {exc}",
        )

    segments = [
        SlideSegment(
            data=blob,
            kind=kind,  # type: ignore[arg-type]
            duration=_OFFICIAL_VIDEO_IMAGE_SECONDS if kind == "image" else None,
        )
        for (kind, _url), blob in zip(order, blobs)
    ]

    try:
        mp4_bytes = await compose_slideshow_async(
            segments,
            width=_OFFICIAL_VIDEO_WIDTH,
            height=_OFFICIAL_VIDEO_HEIGHT,
            image_duration=_OFFICIAL_VIDEO_IMAGE_SECONDS,
            crossfade=_OFFICIAL_VIDEO_CROSSFADE,
        )
    except Exception as exc:
        return StageResult(
            stage="compose_official_video",
            success=False,
            error=f"video composition failed: {exc}",
        )

    # Persist through the canonical AI-media pipeline (ai_video folder, public
    # so the episode page renders it without signed-URL expiry).
    from matrx_ai.media.media_persistence import save_media_envelope_async

    try:
        envelope = await save_media_envelope_async(
            mp4_bytes,
            "video/mp4",
            visibility="public",
            prompt=(title or "podcast official video"),
            feature="ai_video",
            extra_metadata={"source": "podcast_official_video"},
        )
    except Exception as exc:
        return StageResult(
            stage="compose_official_video",
            success=False,
            error=f"failed to persist composed video: {exc}",
        )

    url = envelope.url or envelope.cdn_url or envelope.storage_uri
    return StageResult(stage="compose_official_video", success=True, output=url or "")


