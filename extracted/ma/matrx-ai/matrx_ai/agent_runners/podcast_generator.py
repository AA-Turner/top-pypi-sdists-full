"""
Podcast Generator — Agent Orchestration Pipeline

Orchestrates the full podcast production workflow on top of the canonical
``NamedAgent`` stack (THE ONE — see ``matrx_ai/agents/named.py``). Every LLM /
media call is a declarative ``NamedAgent`` subclass pinned to a committed
``agx_version`` (``is_version=True``) so admin-UI edits can never silently
drift the contract out from under this code. Each call runs through
``NamedAgent.run`` -> ``run_agent`` -> ``child_agent_context`` for the standard
context fork + lifecycle events + reservation isolation.

Pipeline stages:
    1. Prepare Content   — extract (files) / research (topic) / pass-through (content)
    2. Create Script     — produce structured podcast script
    3. Create Audio      — convert script to TTS audio (critical path)
    4. Generate Metadata — title, description, image/video prompts (concurrent with script)
    5. Generate Images   — N images, all via the image agent (parallel, concurrent with audio)
    6. Generate Videos   — N videos, via the video agent (concurrent with audio)

Topic flow (the "great episode from a single keyword" path):
    Topic -> Deep Web Research Agent -> research output becomes the content base
    -> Script Writer -> Script -> Audio. The research output is the same
    ``prepared_content`` the metadata generator consumes, so metadata fires
    concurrently with the script.

Concurrency design:
    - Stages 2 (script) and 4 (metadata) fire concurrently — both take prepared_content.
    - Stage 3 (audio) starts immediately when the script is ready.
    - Stages 5 (images) and 6 (videos) fire as Tasks the moment metadata resolves,
      running fully concurrently with audio (the slowest step).
    - Everything is gathered at the end, so audio is never blocked by media generation.

Media persistence: image / audio / video agents route through the unified AI
pipeline, which persists generated bytes to ``cld_files`` and returns a resolved
URL as the agent's output. Nothing here touches a raw provider key.

DB persistence (pc_episodes) is intentionally NOT done here — this module lives
in the standalone ``matrx-ai`` package and must not import ``aidream/db``. The
aidream router persists the returned ``PodcastGenerationResult``.
"""

