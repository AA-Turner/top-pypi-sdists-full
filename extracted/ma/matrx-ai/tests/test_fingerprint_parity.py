"""Fingerprint parity — Python vs the TypeScript source of truth.

Every vector in ``tests/fixtures/fingerprint_vectors.json`` was generated by
running the FE implementation (matrx-frontend
``features/content-ir/core/fingerprint.ts``); the fixture must stay
byte-identical with its frontend twin
(``features/content-ir/__tests__/fingerprint-vectors.json``). This suite is
the HARD GATE for emitting ``metadata.__ir`` envelopes: a single mismatch
means the FE silently re-parses every server-built envelope.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TypedDict

import pytest

from matrx_ai.processing.blocks.fingerprint import Fingerprinter, fingerprint_text

_FIXTURE_PATH = Path(__file__).parent / "fixtures" / "fingerprint_vectors.json"


class _Vector(TypedDict):
    name: str
    input: str
    fingerprint: str


def _load_vectors() -> list[_Vector]:
    with _FIXTURE_PATH.open(encoding="utf-8") as f:
        data = json.load(f)
    vectors: list[_Vector] = data["vectors"]
    assert len(vectors) >= 16, "vector fixture unexpectedly small — regenerate from TS"
    return vectors


_VECTORS = _load_vectors()


def test_trap_classes_present() -> None:
    names = {v["name"] for v in _VECTORS}
    for required in (
        "empty",
        "emoji_single",
        "astral_clef",
        "lone_high_surrogate",
        "lone_low_surrogate",
        "large_kind_region_10kb",
    ):
        assert required in names


@pytest.mark.parametrize("vector", _VECTORS, ids=[v["name"] for v in _VECTORS])
def test_fingerprint_matches_ts(vector: _Vector) -> None:
    assert fingerprint_text(vector["input"]) == vector["fingerprint"]


@pytest.mark.parametrize("vector", _VECTORS, ids=[v["name"] for v in _VECTORS])
def test_incremental_matches_one_shot(vector: _Vector) -> None:
    # 3-code-point chunks deliberately split surrogate pairs on astral inputs;
    # the incremental form must be boundary-independent, like the TS twin.
    hasher = Fingerprinter()
    source = vector["input"]
    for i in range(0, len(source), 3):
        hasher.push(source[i : i + 3])
    assert hasher.current() == vector["fingerprint"]


def test_utf16_length_not_code_points() -> None:
    # "😀" is 1 Python code point but MUST count as 2 UTF-16 units, like JS
    # String.prototype.length — the length prefix is part of the wire format.
    assert fingerprint_text("\U0001f600").startswith("2-")
