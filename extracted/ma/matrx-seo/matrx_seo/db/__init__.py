"""Database binding for the matrx-seo vertical.

**There is ONE database (Matrx Main).** Hosted or standalone, this package
connects to the same Postgres every other Matrx service uses, through the
SAME env var names aidream uses (``SUPABASE_MATRIX_*``). There is no
second candidate and no fallback chain — inventing one
would send the next person hunting for a second database that does not exist.

The package ships the CANONICAL ``seo.*`` model classes
(:mod:`matrx_seo.db.models_seo`, generated by the host's ``db/generate.py``,
``_database="matrx_seo"`` — a matrx-orm *config name*, NOT a database). What
that name points at is decided exactly once:

* **Hosted (inside aidream)** — ``configure_db(db_config_name=...)`` aliases
  ``matrx_seo`` onto the host's already-registered pool. One physical pool.
* **Standalone (the vertical's own service)** — :func:`bootstrap_db` registers
  a pool from the same ``SUPABASE_MATRIX_*`` env vars, then
  :func:`assert_service_role` **requires the connected role to be ``svc_seo``**.
  Only the CREDENTIALS differ per deployment: the SEO service sets
  ``SUPABASE_MATRIX_USER=svc_seo`` + its password, so it lives inside the
  granted boundary (``db/grants.yaml``). Same names, same database, a role
  scoped to what this service may touch.
"""

from __future__ import annotations

from matrx_orm import PLATFORM_DB_ENV_PREFIX, register_platform_db

PACKAGE_DB_NAME = "matrx_seo"
# The ONE database's env prefix, owned by matrx_orm.platform_db and re-exported
# here for readability. ONE connection, required; never a second candidate.
DB_ENV_PREFIX = PLATFORM_DB_ENV_PREFIX
SERVICE_ROLE_NAME = "svc_seo"

_models_registered = False


def _register_models() -> None:
    global _models_registered
    if not _models_registered:
        from matrx_seo.db import models_seo  # noqa: F401  (registers on import)

        _models_registered = True


def configure_db(db_config_name: str) -> None:
    """Hosted entry — alias :data:`PACKAGE_DB_NAME` onto the host's pool."""
    from matrx_orm import is_database_registered, register_database_alias

    if not is_database_registered(db_config_name):
        raise RuntimeError(
            f"matrx-seo configure_db: db config {db_config_name!r} is not registered — "
            "register the host database with matrx-orm first"
        )
    if not is_database_registered(PACKAGE_DB_NAME):
        register_database_alias(PACKAGE_DB_NAME, db_config_name)
    _register_models()


def bootstrap_db() -> None:
    """Standalone entry — register the pool from the ONE database's env vars.

    Same ``SUPABASE_MATRIX_*`` names as every other service, through the ONE
    platform resolver (``matrx_orm.register_platform_db``); this
    deployment's USER/PASSWORD are svc_seo's (enforced by
    :func:`assert_service_role`)."""
    register_platform_db(
        PACKAGE_DB_NAME,
        additional_schemas=[],
        package="matrx-seo",
    )
    _register_models()


async def assert_service_role(*, allow_local_dev: bool = False) -> str:
    """Standalone boot gate: the pool MUST be svc_seo. Crash loudly otherwise —
    a vertical running on broad credentials is the fake-package failure mode."""
    from matrx_orm.core.async_db_manager import AsyncDatabaseManager

    identity = await AsyncDatabaseManager.connection_identity(PACKAGE_DB_NAME)
    current = identity.current_user
    if current != SERVICE_ROLE_NAME:
        if allow_local_dev:
            return current
        raise RuntimeError(
            f"matrx-seo standalone MUST connect as {SERVICE_ROLE_NAME!r} (the granted "
            f"boundary in db/grants.yaml) — got {current!r}. Set "
            f"{DB_ENV_PREFIX}_USER={SERVICE_ROLE_NAME} + its password on THIS "
            "deployment; do NOT hand this service a broad platform role."
        )
    return current
