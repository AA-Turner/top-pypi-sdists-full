"""The doors of an Action — where the ONE declaration can be run from.

An Action is declared once (``declare_action``) and every door is an adapter
generated from that declaration, never a second declaration:

- ``step``      — a workflow node (generated here, by matrx-graph).
- ``tool``      — an agent tool (generated by ``matrx_ai.tools.action_door``).
- ``directive`` — the ``action`` class of the Kind Directives grammar
  (generated by the host's directive door).
- ``mcp``       — the ``product_action`` MCP tool (run in-process, as the caller).
- ``api``       — ``POST /actions/{name}/run`` (the host's HTTP door). Open on EVERY
  runnable Action by construction; never declared.

The names each door is reached by are DERIVED from the Action's dotted name by
the two functions below, so no door can carry a second, hand-typed name.
"""

from __future__ import annotations

from typing import Any, Literal

ActionDoor = Literal["step", "tool", "directive", "mcp", "api"]
DOORS: frozenset[str] = frozenset({"step", "tool", "directive", "mcp", "api"})

#: The HTTP path of an Action's api door (the host mounts it; matrx-graph only names it).
API_PATH = "/actions/{name}/run"


def api_path_for(action_name: str) -> str:
    """The api door of an Action: ``POST /actions/<dotted name>/run``."""
    return API_PATH.format(name=action_name)


def tool_name_for(action_name: str) -> str:
    """The agent tool name of an Action: dots become underscores.

    Provider tool names allow ``[A-Za-z0-9_-]`` only, so ``workspace.create_task``
    is offered to a model as ``workspace_create_task``.
    """
    return action_name.replace(".", "_")


def directive_noun_for(action_name: str) -> str:
    """The directive noun of an Action: its LAST dotted segment.

    ``workspace.create_task`` → ``create_task`` → slug
    ``directive_v1_action_create_task``. The namespace before the last dot never
    reaches the slug, so content an agent already emits keeps resolving; two
    Actions whose last segments collide are refused when the door opens.
    """
    return action_name.rsplit(".", 1)[-1]


def directive_noun_of(spec: Any) -> str | None:
    """The directive noun EVERY runnable Action is reached by (Arman, 2026-10-29: every
    Action has a directive, by construction — not opt-in).

    - An Action that declared the ``directive`` door keeps its last-segment noun
      (content agents already emit keeps resolving).
    - Every other runnable Action gets ``tool_name_for(name)`` — the whole dotted name,
      dots → underscores — so a newly reachable noun can never collide or move when
      another Action is added.
    - A record write carries its own create/update/delete slug (``directive_slug``) and
      has no ``action``-class noun; a step-only ``register_node`` (no work function, the
      ``code`` engine) has no directive. Both return None.
    - An ``admin_only`` Action gets a directive only when it declared the door itself.
    """
    if spec.directive_slug:
        return None
    if spec.engine == "code" and spec.work is None:
        return None
    # A generated Action (workflow / agent row) gets the whole-name noun like every other
    # Action; the host's directive door resolves its slug lazily at decode time, as the caller.
    if getattr(spec, "admin_only", False) and "directive" not in spec.doors:
        # An admin-only Action is never opened automatically: any agent's answer can
        # carry a directive, and admin SQL must not become one by construction.
        return None
    if "directive" in spec.doors:
        return directive_noun_for(spec.name)
    return tool_name_for(spec.name)


def validate_doors(name: str, doors: frozenset[str] | set[str] | tuple[str, ...]) -> frozenset[str]:
    out = frozenset(doors)
    unknown = sorted(out - DOORS)
    if unknown:
        raise ValueError(
            f"Action {name!r} names unknown door(s) {unknown}; the doors are {sorted(DOORS)}."
        )
    if not out:
        raise ValueError(f"Action {name!r} declares no door — it could never be run.")
    return out


__all__ = ["API_PATH", "DOORS", "api_path_for", "ActionDoor", "directive_noun_for", "directive_noun_of", "tool_name_for", "validate_doors"]
