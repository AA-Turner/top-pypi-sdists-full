# File: matrx_files/db/models_platform.py
"""Hand-maintained models for the CANONICAL platform-schema tables this
package reads/writes. NOT generated by ``db/generate.py`` (the package's
codegen scope is the ``files`` + ``iam`` schemas) — keep in sync with
``platform.share_links`` (see ai-matrx ``migrations/share_links_canonical_system.sql``).

Share links live in ``platform.share_links`` — the ONE share-link system for
every resource type. The legacy ``files.share_links`` lane is retired
(table deprecated, ``consume_share_link`` dropped).
"""

from enum import Enum
from typing import ClassVar

from matrx_orm import (
    BooleanField,
    DateTimeField,
    EnumField,
    ForeignKey,
    IntegerField,
    JSONBField,
    Model,
    TextField,
    UUIDField,
    model_registry,
)


class SharePermissionLevel(str, Enum):
    ADMIN = "admin"
    EDITOR = "editor"
    VIEWER = "viewer"


class PlatformShareLinks(Model):
    id = UUIDField(primary_key=True, null=False)
    resource_type = TextField(null=False)
    resource_id = UUIDField(null=False)
    token = TextField(null=False, unique=True)
    permission_level = EnumField(enum_class=SharePermissionLevel, null=False, default="viewer")
    created_by = ForeignKey(to_model="Users", to_column="id", to_schema="auth", null=False)
    organization_id = UUIDField()
    label = TextField()
    expires_at = DateTimeField()
    max_uses = IntegerField()
    use_count = IntegerField(null=False, default=0)
    is_active = BooleanField(null=False, default=True)
    created_at = DateTimeField(null=False)
    last_used_at = DateTimeField()
    metadata = JSONBField(null=False, default={})
    _inverse_foreign_keys: ClassVar[dict[str, dict[str, str]]] = {}
    _database = "matrx_files"
    _table_name = "share_links"
    _db_schema = "platform"


__all__ = ["PlatformShareLinks", "SharePermissionLevel"]


model_registry.register_all([PlatformShareLinks], skip_existing=True)
