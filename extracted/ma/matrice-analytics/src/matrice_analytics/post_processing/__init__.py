"""
Post-processing utilities for Matrice SDK.

This module provides a unified, clean interface for post-processing model outputs
with support for various use cases like people counting, customer service analysis,
and more.

Key Features:
- Unified PostProcessor class for all processing needs
- Built-in use case processors for common scenarios
- Flexible configuration management with JSON/YAML support
- Comprehensive validation and error handling
- Processing statistics and insights
- Zone-based analysis and tracking

Quick Start:
    from matrice_analytics.post_processing import PostProcessor

    # Simple processing
    processor = PostProcessor()
    result = processor.process_simple(
        raw_results, "people_counting",
        confidence_threshold=0.5
    )

    # With configuration file
    result = processor.process_from_file(raw_results, "config.json")

    # Get available use cases
    usecases = processor.list_available_usecases()

Import cost
-----------
Every public name below is resolved **lazily**, via the PEP 562 module-level
``__getattr__`` -- the same treatment ``matrice_analytics/__init__.py`` already
had.  This module used to import ~122 use-case modules, construct 119 instances
and run 123 ``registry.register_use_case`` calls at import time, so *any* touch
of the package executed 3,525 modules in ~49 s on the deployment image, pulling in
torch, cv2, scipy, pandas and onnxruntime.  Every ``spawn``-ed inference worker
paid that independently, and paid it again on each supervisor respawn.

Nothing about the public surface changes: ``from matrice_analytics.post_processing
import PostProcessor``, ``import *`` and attribute access all still work, and each
one performs exactly the import that used to happen at package-import time -- but
only the single leaf module that actually defines the name.  The registry is
likewise served from a static catalogue (``core/_usecase_table.py``) and loads a
use-case module only when something asks for that use case.

``_lazy_exports.py``, ``_typing_surface.py`` and ``core/_usecase_table.py`` are
generated; run ``python scripts/gen_post_processing_lazy.py --write`` after adding
or renaming a public name or a use case.
"""

