def __getattr__(name: str) -> Any:
    """Resolve a public name on first access (PEP 562).

    Keeps the whole legacy surface importable from this package while making the
    import itself cost one module instead of the entire use-case catalogue.
    """
    if name in LAZY_SUBMODULES:
        value: Any = importlib.import_module(f"{__name__}.{name}")
    else:
        # The eager block re-exported the whole `.usecases` surface, so a name that
        # is importable from there has always been importable from here too -- even
        # the ~10 that never made it into __all__.  Keep that true.
        module = LAZY_EXPORTS.get(name) or _USECASE_EXPORTS.get(name)
        if module is not None:
            value = getattr(importlib.import_module(module), name)
        else:
            alias = LAZY_ALIASES.get(name) or _USECASE_ALIASES.get(name)
            if alias is None:
                raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
            alias_module, _, real = alias.partition(":")
            value = getattr(importlib.import_module(alias_module), real)

    # Cache so subsequent lookups skip __getattr__ entirely.
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    return sorted(
        set(globals())
        | set(__all__)
        | set(LAZY_SUBMODULES)
        | set(LAZY_EXPORTS)
        | set(LAZY_ALIASES)
        | set(_USECASE_EXPORTS)
        | set(_USECASE_ALIASES)
    )


