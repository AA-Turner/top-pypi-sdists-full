    def _hazard_alert_settings_map(self, config: HazardZoneEntryConfig) -> Dict[str, Any]:
        if not config.alert_config:
            return {"Default": "JSON"}
        types_ = getattr(config.alert_config, "alert_type", ["Default"])
        values = getattr(config.alert_config, "alert_value", ["JSON"])
        if not isinstance(types_, (list, tuple)):
            types_ = [types_]
        if not isinstance(values, (list, tuple)):
            values = [values]
        return {str(t): v for t, v in zip(types_, values)}

    def _finalize_matrice_alert_hazard(
        self,
        alert: Dict[str, Any],
        frame_id: str,
        config: HazardZoneEntryConfig,
        *,
        force_emit: bool = False,
    ) -> Dict[str, Any]:
        """pipe_gas_leak_detection-style: status, frames, duration, emit."""
        try:
            cur_int = int(frame_id)
        except (TypeError, ValueError):
            cur_int = int(self._total_frame_counter)
        alert["status"] = "active"
        alert["start_frame"] = cur_int
        alert["current_frame"] = cur_int
        alert["duration_frames"] = 0
        if force_emit:
            alert["emit"] = True
            return alert
        cooldown = 0
        if config.alert_config:
            cooldown = int(getattr(config.alert_config, "alert_cooldown", 0) or 0)
        emit_allowed = True
        if cooldown > 0 and time.time() - self._last_matrice_alert_emit_time < cooldown:
            emit_allowed = False
        alert["emit"] = emit_allowed
        if emit_allowed:
            self._last_matrice_alert_emit_time = time.time()
        return alert

    def _check_alerts(
        self,
        counting_summary: Dict,
        _zone_analysis: Dict,
        config: HazardZoneEntryConfig,
        frame_id: str,
    ) -> List[Dict]:
        """Check for alert conditions and generate alerts."""
        _ = (_zone_analysis,)

        def get_trend(data, lookback=900, threshold=0.6):
            """
            Determine if the trend is ascending or descending based on actual value progression.
            Now works with values 0,1,2,3 (not just binary).
            """
            window = data[-lookback:] if len(data) >= lookback else data
            if len(window) < 2:
                return True  # not enough data to determine trend
            increasing = 0
            total = 0
            for i in range(1, len(window)):
                if window[i] >= window[i - 1]:
                    increasing += 1
                total += 1
            ratio = increasing / total if total else 0.0
            if ratio >= threshold:
                return True
            elif ratio <= (1 - threshold):
                return False
            return None

        alerts: List[Dict[str, Any]] = []

        if config.alert_config:
            settings_map = self._hazard_alert_settings_map(config)
            alert_type_str = self._hazard_primary_alert_type(config)
        else:
            settings_map = {"Default": "JSON"}
            alert_type_str = "Default"

        min_inside = float(max(1, int(getattr(config, "min_inside_frames", 3))))

        self._frame_hazard_entry_events = []
        for det in counting_summary.get("detections", []) or []:
            evt = det.get("_hazard_entry_event") if isinstance(det, dict) else None
            if not evt:
                continue
            self._frame_hazard_entry_events.append(dict(evt))
            self._zone_alerted_tracks.setdefault(evt["zone_name"], set()).add(evt["track_id"])
            det.pop("_hazard_entry_event", None)

        # Persistent critical alerts while confirmed at_risk person(s) are inside a hazard zone.
        at_risk_by_zone: Dict[str, List[Any]] = {}
        for det in counting_summary.get("detections", []) or []:
            if not isinstance(det, dict) or det.get("category") != "at_risk":
                continue
            zone_name = det.get("_hazard_zone")
            if not zone_name:
                continue
            track_id = det.get("track_id")
            bucket = at_risk_by_zone.setdefault(str(zone_name), [])
            if track_id is not None and track_id not in bucket:
                bucket.append(track_id)

        for zone_name, track_ids in at_risk_by_zone.items():
            alert = self.create_alert_object(
                alert_type=alert_type_str,
                alert_id=f"hazard_zone_entry_{zone_name}",
                incident_category=str(self.CASE_TYPE or "hazard_zone_entry"),
                threshold_value=min_inside,
                ascending=True,
                settings=settings_map,
            )
            alert["hazard_zone"] = zone_name
            alert["at_risk_count"] = len(track_ids)
            alert["at_risk_track_ids"] = list(track_ids)
            if track_ids:
                alert["track_id"] = track_ids[0]
            alert["event_type"] = "hazard_zone_entry"
            alert["risk_label"] = "at_risk"
            alert["security_label"] = "at_risk"
            alert["severity_level"] = "critical"
            self._finalize_matrice_alert_hazard(alert, frame_id, config, force_emit=True)
            alerts.append(alert)

        total_people = counting_summary.get("total_objects", 0)

        if not config.alert_config:
            return alerts

        # Count threshold alerts
        if hasattr(config.alert_config, "count_thresholds") and config.alert_config.count_thresholds:
            for category, threshold in config.alert_config.count_thresholds.items():
                thr = float(threshold)
                if category == "all" and total_people >= threshold:
                    tr = get_trend(self._ascending_alert_list, lookback=900, threshold=0.8)
                    asc = True if tr is None else bool(tr)
                    alert = self.create_alert_object(
                        alert_type=alert_type_str,
                        alert_id=f"alert_{category}_{frame_id}",
                        incident_category=str(self.CASE_TYPE or "hazard_zone_entry"),
                        threshold_value=thr,
                        ascending=asc,
                        settings=settings_map,
                    )
                    alerts.append(self._finalize_matrice_alert_hazard(alert, frame_id, config))
                elif category in counting_summary.get("categories", {}):
                    count = counting_summary["categories"][category]

                    if count >= threshold:
                        tr = get_trend(
                            self._ascending_alert_list,
                            lookback=900,
                            threshold=0.8,
                        )
                        asc = True if tr is None else bool(tr)
                        alert = self.create_alert_object(
                            alert_type=alert_type_str,
                            alert_id=f"alert_{category}_{frame_id}",
                            incident_category=str(self.CASE_TYPE or "hazard_zone_entry"),
                            threshold_value=thr,
                            ascending=asc,
                            settings=settings_map,
                        )
                        alerts.append(self._finalize_matrice_alert_hazard(alert, frame_id, config))

        return alerts

