# resolves at runtime.
"""
Use case implementations for post-processing.

This module contains all available use case processors for different
post-processing scenarios.

Import cost
-----------
Every name below is resolved **lazily**, via the PEP 562 module-level
``__getattr__``.  This barrel used to import all 133 leaf modules at import time,
so touching one use case loaded the entire catalogue -- ~1,975 modules and roughly
49 s on the deployment image, paid again by every ``spawn``-ed inference worker.

``_lazy_exports.py`` is generated; run
``python scripts/gen_post_processing_lazy.py --write`` after adding or renaming a
public name.
"""

from __future__ import annotations

import importlib
from typing import TYPE_CHECKING, Any

from ._lazy_exports import LAZY_ALIASES, LAZY_EXPORTS, LAZY_SUBMODULES

# Static re-exports, so type checkers and IDEs still see the full surface while the
# runtime resolves it lazily.  Never executed -- __getattr__ below does the real work.
if TYPE_CHECKING:  # pragma: no cover
    # --- BEGIN generated by scripts/gen_post_processing_lazy.py ---
    from ._typing_surface import *  # noqa: F401,F403
    # --- END generated ---


def _resolve(name: str) -> Any:
    """Import and return the object a lazy map entry points at, or None."""
    module = LAZY_EXPORTS.get(name)
    if module is not None:
        return getattr(importlib.import_module(module), name)
    alias = LAZY_ALIASES.get(name)
    if alias is not None:
        module, _, real = alias.partition(":")
        return getattr(importlib.import_module(module), real)
    return None


def __getattr__(name: str) -> Any:
    """Resolve a use-case name on first access (PEP 562)."""
    if name in LAZY_SUBMODULES:
        value: Any = importlib.import_module(f"{__name__}.{name}")
    else:
        value = _resolve(name)
        if value is None:
            raise AttributeError(f"module {__name__!r} has no attribute {name!r}")

    globals()[name] = value
    return value


def __dir__() -> list[str]:
    return sorted(
        set(globals()) | set(__all__) | set(LAZY_SUBMODULES) | set(LAZY_EXPORTS) | set(LAZY_ALIASES)
    )


