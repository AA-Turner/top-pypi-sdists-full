def _read_json_input(
    json_str: str | None,
    input_file: str | None,
) -> dict:
    """Read JSON from a positional arg, --input file, or STDIN (in that priority)."""
    if json_str is not None:
        return json.loads(json_str)
    if input_file is not None:
        return json.loads(Path(input_file).read_text())
    if not sys.stdin.isatty():
        return json.loads(sys.stdin.read())
    exit_with_error(
        "No JSON input provided. Pass it as a positional argument, "
        "via --input <file>, or pipe to STDIN."
    )
    raise SystemExit(1)  # unreachable, but satisfies type checker


