def _load_json_file(file_path: Path) -> dict | None:
    """Load a JSON file and return its contents.

    Returns None if the file doesn't exist or contains invalid JSON.
    """
    if not file_path.exists():
        return None
    try:
        return json.loads(file_path.read_text())
    except json.JSONDecodeError as e:
        print_error(f"Failed to parse JSON in file: {file_path}\nError: {e}")
        return None


def _run_connector_command(
    connector_image: str,
    command: Command,
    output_dir: Path,
    target_or_control: TargetOrControl,
    config_path: Path | None = None,
    catalog_path: Path | None = None,
    state_path: Path | None = None,
    proxy_url: str | None = None,
    enable_debug_logs: bool = False,
) -> tuple[dict, ComparableOutputs]:
    """Run a connector command and return its results and its declared objects.

    The dict is a flattened view of `ExecutionResult`: counts, exit status and
    artifact paths, which is all the reports need. What a comparison needs
    instead -- the spec, the discovered catalog -- travels beside it as
    `ComparableOutputs` rather than growing a dict that several consumers read.
    The `ExecutionResult` itself is still dropped here: it holds every parsed
    message, and a comparison keeps both sides alive at once.

    Args:
        connector_image: Full connector image name with tag.
        command: The Airbyte command to run.
        output_dir: Directory to store output files.
        target_or_control: Whether this is target or control version.
        config_path: Path to connector config JSON file.
        catalog_path: Path to configured catalog JSON file.
        state_path: Path to state JSON file.
        proxy_url: Optional HTTP proxy URL for traffic capture.
        enable_debug_logs: If `True`, pass `LOG_LEVEL=DEBUG` to the connector container.

    Returns:
        The flattened results, and the objects the connector declared.
    """
    connector = ConnectorUnderTest.from_image_name(connector_image, target_or_control)

    config = _load_json_file(config_path) if config_path else None
    state = _load_json_file(state_path) if state_path else None

    configured_catalog = None
    if catalog_path and catalog_path.exists():
        catalog_json = catalog_path.read_text()
        configured_catalog = ConfiguredAirbyteCatalog.parse_raw(catalog_json)

    # Pass log level as an environment variable to the connector container
    container_env: dict[str, str] = {}
    if enable_debug_logs:
        container_env["LOG_LEVEL"] = "DEBUG"

    execution_inputs = ExecutionInputs(
        connector_under_test=connector,
        command=command,
        output_dir=output_dir,
        config=config,
        configured_catalog=configured_catalog,
        state=state,
        environment_variables=container_env or None,
    )

    runner = ConnectorRunner(execution_inputs, proxy_url=proxy_url)
    result = runner.run()

    result.save_artifacts(output_dir)

    result_dict: dict[str, object] = {
        "connector": connector_image,
        "command": command.value,
        "success": result.success,
        "exit_code": result.exit_code,
        "stdout_file": str(result.stdout_file_path),
        "stderr_file": str(result.stderr_file_path),
        "message_counts": {
            k.value: v for k, v in result.get_message_count_per_type().items()
        },
        "record_counts_per_stream": result.get_record_count_per_stream(),
    }

    # For CHECK, include the parsed connectionStatus from the Airbyte protocol.
    # The CDK exits 0 regardless of check outcome; the real pass/fail signal
    # lives in the CONNECTION_STATUS message (status=SUCCEEDED or FAILED).
    if command == Command.CHECK:
        conn_status = result.get_connection_status()
        if conn_status is not None:
            result_dict["connection_status"] = conn_status.status.value
            result_dict["connection_status_message"] = conn_status.message or ""
        else:
            result_dict["connection_status"] = None
            result_dict["connection_status_message"] = ""

    return result_dict, ComparableOutputs.from_execution_result(result)


def _annotate_run_verdict(command: str, result: dict[str, Any]) -> dict[str, Any]:
    """Copy a run result with `success` as the verdict, exit status kept separately.

    `ExecutionResult.success` is the container exit status, which for `check` says
    nothing about whether the connector could connect -- the CDK exits 0 even when a
    check fails. Any payload read as the verdict must therefore not expose the exit
    status under `success`, at any nesting level. The raw value stays available as
    `exited_cleanly`; for every command but `check` the two are equal.

    Returns a copy: callers pass the unannotated originals to the report generator,
    which reads `success` as the exit status.
    """
    return {
        **result,
        "success": command_result_succeeded(command, result),
        "exited_cleanly": result["success"],
    }


# The checks the declared-output comparisons contribute, named for the row a
# reviewer reads in the report and in the step summary.
_SPEC_CHECK = "Spec compatibility"
_CATALOG_SCHEMA_CHECK = "Catalog schema"

# How many individual changes a check's one-line summary names before it says
# how many more there are. The full list is in the report and in the run's JSON
# payload, and the comparators order their findings worst-first, so the ones
# named here are the ones worth naming.
_MAX_LISTED_CHANGES = 3

# How many changes the JSON payload lists per comparison. Same reason as
# `_MAX_DIFF_PAYLOAD_CHARS`: the payload is written to `GITHUB_OUTPUT`, and a
# reordered `oneOf` on a wide spec produces hundreds of sentences.
_MAX_PAYLOAD_CHANGES = 100

# How many per-stream entries it lists. A wide source has thousands of streams,
# and one line each is enough to exceed the same output budget without a single
# diff being attached.
_MAX_PAYLOAD_STREAMS = 100

# How much of a comparison's detail the run's JSON payload carries. That payload
# is written to `GITHUB_OUTPUT`, which is size-limited, and a wide connector's
# catalog diff has no natural bound -- so the payload keeps as many stream diffs
# as fit and says how many it dropped. The catalogs themselves are saved
# artifacts, which is where an unbounded diff belongs.
_MAX_DIFF_PAYLOAD_CHARS = 50_000


def _compare_declared_outputs(
    *,
    command: str,
    outcome: ComparisonOutcome,
    control_outputs: ComparableOutputs,
    target_outputs: ComparableOutputs,
) -> tuple[tuple[CheckResult, ...], tuple[DiffBlock, ...], dict[str, Any]]:
    """Compare what the two versions declared, for the commands that declare it.

    This is the content check for `spec` and `discover`: without it their
    verdict is the exit code, and a connector that drops a config field or
    changes a stream's schema exits 0 all the way to a release. `check` reports
    its own status and `read` is compared on its records, so neither has a
    declared object to diff here.

    Only runs when both commands succeeded. A failed run has nothing to compare,
    and reporting "no spec to compare" beside the command failure that caused it
    would state the same problem twice, in weaker terms the second time.

    A comparator that raises is left to propagate. Both comparators normalise
    what they are given, so the only ways here are a programming error in a
    future caller or a schema nested past the recursion limit -- and the
    workflow already has the right vocabulary for both: a step that dies is an
    `internal_failure`, reported as infrastructure rather than as a regression,
    with the connector's artifacts uploaded either way. Catching it here would
    only let a tooling bug read as "the new version broke its spec".

    Args:
        command: The Airbyte command that was run.
        outcome: The already-evaluated command outcome.
        control_outputs: What the control version declared.
        target_outputs: What the target version declared.

    Returns:
        The checks to fold into the verdict, the diff blocks that show what they
        found, and the comparison detail for the run's JSON payload -- all empty
        when there was nothing to compare.
    """
    if not outcome.success:
        return (), (), {}

    if command == "spec":
        return _spec_comparison(control_outputs.spec, target_outputs.spec)

    if command == "discover":
        return _catalog_comparison(control_outputs.catalog, target_outputs.catalog)

    return (), (), {}


def _spec_comparison(
    control_spec: Any, target_spec: Any
) -> tuple[tuple[CheckResult, ...], tuple[DiffBlock, ...], dict[str, Any]]:
    """Run the spec comparison and shape it for every surface."""
    result = compare_specs(control_spec, target_spec)

    check = CheckResult(
        name=_SPEC_CHECK,
        passed=result.passed,
        summary=_change_summary(
            result.message,
            # A passing spec check still says what was added: an additive change
            # is the thing a reviewer most wants to see confirmed.
            result.errors if result.errors else result.warnings,
        ),
        details=tuple(result.errors),
    )
    # The incompatible changes are the check's `details`, which the report renders
    # under the check row and the step summary lists -- a block would repeat them.
    # The compatible ones have nowhere else to go, and a reviewer asking "what
    # else moved?" is asking about exactly those.
    blocks = tuple(
        block
        for block in (
            _change_block("Spec — compatible changes", result.warnings, "add"),
        )
        if block is not None
    )

    return (check,), blocks, {"spec": _spec_detail(result)}


def _catalog_comparison(
    control_catalog: Any, target_catalog: Any
) -> tuple[tuple[CheckResult, ...], tuple[DiffBlock, ...], dict[str, Any]]:
    """Run the discovered-catalog comparison and shape it for every surface."""
    result = compare_catalog_schemas(control_catalog, target_catalog)

    check = CheckResult(
        name=_CATALOG_SCHEMA_CHECK,
        passed=result.passed,
        # A catalog that only grew -- new streams, new fields, nothing removed
        # or retyped -- is reported and does not gate the release. Connectors
        # add streams constantly, and a check that goes red on every one of them
        # is a check people learn to click past.
        severity="diagnostic" if result.additive_only else "strict",
        summary=_change_summary(result.message, result.errors),
        details=tuple(result.errors),
    )

    # The findings themselves are the check's `details`, which the report renders
    # under the check row: a stream that is missing or new has no schema diff, so
    # that list is the only place it appears.
    blocks: list[DiffBlock] = []

    # One block per changed stream, in catalog order -- only a *changed*
    # stream has a diff, so there is no severity left to sort by here -- and
    # within the same budget the payload uses: a report that inlines every schema
    # of a 200-stream source is not a report anyone reads. What the budget drops
    # is named rather than skipped.
    budget = _MAX_DIFF_PAYLOAD_CHARS
    dropped: list[str] = []
    for name in result.failed_streams:
        stream = result.stream_results[name]
        if not stream.schema_diff:
            continue

        payload = json.dumps(stream.schema_diff, indent=2, sort_keys=True)
        if len(payload) > budget:
            dropped.append(name)
            continue

        budget -= len(payload)
        blocks.append(build_json_block(f"Schema diff — {name}", payload))

    if dropped:
        blocks.append(
            build_diff_block(
                "Schema diffs omitted for size",
                [
                    DiffLine(
                        kind="meta",
                        text=(
                            "These streams changed, and their diffs were too large "
                            "for this report. Both discovered catalogs are in the "
                            "artifact, under airbyte_messages/catalog.jsonl."
                        ),
                    ),
                    *(DiffLine(kind="del", text=name) for name in dropped),
                ],
                language="text",
            )
        )

    return (check,), tuple(blocks), {"catalog_schema": _catalog_schema_detail(result)}


def _change_block(title: str, changes: list[str], kind: str) -> DiffBlock | None:
    """One diff block listing a comparison's findings, or `None` if there are none."""
    if not changes:
        return None

    return build_diff_block(
        title,
        [DiffLine(kind=kind, text=change) for change in changes],
        language="text",
    )


def _change_summary(message: str, changes: list[str]) -> str:
    """One line: what the comparison concluded, and the first few reasons."""
    if not changes:
        return message

    listed = "; ".join(changes[:_MAX_LISTED_CHANGES])
    remaining = len(changes) - _MAX_LISTED_CHANGES
    if remaining > 0:
        listed = f"{listed}; and {remaining} more"

    return f"{message}: {listed}"


def _bounded_changes(changes: list[str]) -> list[str]:
    """A change list the JSON payload can carry, saying what it left out."""
    if len(changes) <= _MAX_PAYLOAD_CHANGES:
        return changes

    dropped = len(changes) - _MAX_PAYLOAD_CHANGES

    return [
        *changes[:_MAX_PAYLOAD_CHANGES],
        f"... and {dropped} more, in the report and the console output",
    ]


def _spec_detail(result: ComparisonResult) -> dict[str, Any]:
    """The spec comparison, for the run's JSON payload."""
    return {
        "passed": result.passed,
        "message": result.message,
        "breaking_changes": _bounded_changes(result.errors),
        "compatible_changes": _bounded_changes(result.warnings),
    }


def _catalog_schema_detail(result: ComparisonResult) -> dict[str, Any]:
    """The catalog comparison, for the run's JSON payload.

    Every stream that changed is named with its verdict -- so the payload says
    what moved, not just that something did -- while the diffs themselves are
    kept only while they fit in `_MAX_DIFF_PAYLOAD_CHARS`, and the number of
    entries is capped in turn: a thousand-stream source would otherwise put a
    thousand of them into `GITHUB_OUTPUT`. Both bounds say what they dropped,
    on the console and in the payload: a bound nobody mentions reads as "there
    was nothing more to see".
    """
    streams: dict[str, Any] = {}
    omitted: list[str] = []
    budget = _MAX_DIFF_PAYLOAD_CHARS

    # Non-passing first, so the cap falls on the streams with nothing to say.
    ordered = sorted(result.stream_results.items(), key=lambda item: item[1].passed)
    kept, dropped_entries = (
        ordered[:_MAX_PAYLOAD_STREAMS],
        ordered[_MAX_PAYLOAD_STREAMS:],
    )

    for name, stream in kept:
        entry: dict[str, Any] = {"passed": stream.passed, "message": stream.message}
        streams[name] = entry

        if not stream.schema_diff:
            continue

        rendered = len(json.dumps(stream.schema_diff, separators=(",", ":")))
        if rendered > budget:
            omitted.append(name)
            entry["diff_omitted"] = "Too large for this payload; diff the catalogs"
            continue

        budget -= rendered
        entry["diff"] = stream.schema_diff

    if omitted:
        print_warning(
            f"Comparison detail for {len(omitted)} streams was too large for the "
            f"run's JSON output ({', '.join(omitted)}); their diffs are omitted "
            "there. Both discovered catalogs are in the saved artifacts."
        )

    if dropped_entries:
        print_warning(
            f"The run's JSON output lists {_MAX_PAYLOAD_STREAMS} of "
            f"{len(ordered)} streams, changed ones first. The report and the "
            "saved catalogs carry them all."
        )

    detail: dict[str, Any] = {
        "passed": result.passed,
        # Why a `passed: false` did not fail the run: everything found was an
        # addition, which is reported as a warning rather than a regression.
        "additive_only": result.additive_only,
        "message": result.message,
        "changed_streams": _bounded_changes(result.failed_streams),
        "streams": streams,
    }
    if omitted:
        detail["streams_with_omitted_diffs"] = omitted
    if dropped_entries:
        detail["streams_omitted"] = len(dropped_entries)

    return detail


def _build_connector_image_from_source(
    connector_name: str,
    repo_root: Path | None = None,
    tag: str = "dev",
) -> str | None:
    """Build a connector image from source code.

    Args:
        connector_name: Name of the connector (e.g., 'source-pokeapi').
        repo_root: Optional path to the airbyte repo root. If not provided,
            will attempt to auto-detect from current directory.
        tag: Tag to apply to the built image (default: 'dev').

    Returns:
        The full image name with tag if successful, None if build fails.
    """
    if not verify_docker_installation():
        print_error("Docker is not installed or not running")
        return None

    try:
        connector_directory = find_connector_root_from_name(connector_name)
    except FileNotFoundError:
        if repo_root:
            connector_directory = repo_root / CONNECTORS_SUBDIR / connector_name
            if not connector_directory.exists():
                print_error(f"Connector directory not found: {connector_directory}")
                return None
        else:
            print_error(
                f"Could not find connector '{connector_name}'. "
                "Try providing --repo-root to specify the airbyte repo location."
            )
            return None

    metadata_file_path = connector_directory / "metadata.yaml"
    if not metadata_file_path.exists():
        print_error(f"metadata.yaml not found at {metadata_file_path}")
        return None

    metadata = MetadataFile.from_file(metadata_file_path)
    print_success(f"Building image for connector: {connector_name}")

    built_image = build_connector_image(
        connector_name=connector_name,
        connector_directory=connector_directory,
        metadata=metadata,
        tag=tag,
        no_verify=False,
    )
    print_success(f"Successfully built image: {built_image}")
    return built_image


def _fetch_control_image_from_metadata(connector_name: str) -> str | None:
    """Fetch the current released connector image from metadata.yaml on main branch.

    This fetches the connector's metadata.yaml from the airbyte monorepo's master branch
    and extracts the dockerRepository and dockerImageTag to construct the control image.

    Args:
        connector_name: The connector name (e.g., 'source-github').

    Returns:
        The full connector image with tag (e.g., 'airbyte/source-github:1.0.0'),
        or None if the metadata could not be fetched or parsed.
    """
    metadata_url = (
        f"https://raw.githubusercontent.com/airbytehq/airbyte/master/"
        f"airbyte-integrations/connectors/{connector_name}/metadata.yaml"
    )
    response = requests.get(metadata_url, timeout=30)
    if not response.ok:
        print_error(
            f"Failed to fetch metadata for {connector_name}: "
            f"HTTP {response.status_code} from {metadata_url}"
        )
        return None

    metadata = yaml.safe_load(response.text)
    if not isinstance(metadata, dict):
        print_error(f"Invalid metadata format for {connector_name}: expected dict")
        return None

    data = metadata.get("data", {})
    docker_repository = data.get("dockerRepository")
    docker_image_tag = data.get("dockerImageTag")

    if not docker_repository or not docker_image_tag:
        print_error(
            f"Could not find dockerRepository/dockerImageTag in metadata for {connector_name}"
        )
        return None

    return f"{docker_repository}:{docker_image_tag}"


def _run_with_optional_http_metrics(
    connector_image: str,
    command: Command,
    output_dir: Path,
    target_or_control: TargetOrControl,
    enable_http_metrics: bool,
    config_path: Path | None,
    catalog_path: Path | None,
    state_path: Path | None,
    enable_debug_logs: bool = False,
) -> tuple[dict, ComparableOutputs]:
    """Run a connector command with optional HTTP metrics capture.

    When enable_http_metrics is True, starts mitmproxy to capture HTTP traffic.
    If mitmproxy fails to start, falls back to running without metrics.

    Args:
        connector_image: Full connector image name with tag.
        command: The Airbyte command to run.
        output_dir: Directory to store output files.
        target_or_control: Whether this is target or control version.
        enable_http_metrics: Whether to capture HTTP metrics via mitmproxy.
        config_path: Path to connector config JSON file.
        catalog_path: Path to configured catalog JSON file.
        state_path: Path to state JSON file.
        enable_debug_logs: If `True`, pass `LOG_LEVEL=DEBUG` to the connector container.

    Returns:
        What `_run_connector_command` returns, with `http_metrics` added to the
        results dict when they were captured.
    """
    if not enable_http_metrics:
        return _run_connector_command(
            connector_image=connector_image,
            command=command,
            output_dir=output_dir,
            target_or_control=target_or_control,
            config_path=config_path,
            catalog_path=catalog_path,
            state_path=state_path,
            enable_debug_logs=enable_debug_logs,
        )

    with MitmproxyManager.start(output_dir) as session:
        if session is None:
            print_error("Mitmproxy unavailable, running without HTTP metrics")
            return _run_connector_command(
                connector_image=connector_image,
                command=command,
                output_dir=output_dir,
                target_or_control=target_or_control,
                config_path=config_path,
                catalog_path=catalog_path,
                state_path=state_path,
                enable_debug_logs=enable_debug_logs,
            )

        print_success(f"Started mitmproxy on {session.proxy_url}")
        result, comparable = _run_connector_command(
            connector_image=connector_image,
            command=command,
            output_dir=output_dir,
            target_or_control=target_or_control,
            config_path=config_path,
            catalog_path=catalog_path,
            state_path=state_path,
            proxy_url=session.proxy_url,
            enable_debug_logs=enable_debug_logs,
        )

        http_metrics = parse_http_dump(session.dump_file_path)
        result["http_metrics"] = {
            "flow_count": http_metrics.flow_count,
            "duplicate_flow_count": http_metrics.duplicate_flow_count,
            # Carried into the report because it is the number that tells a
            # reviewer whether a record difference is a real regression or
            # upstream drift. Today it is a duplicate-URL heuristic; it only
            # becomes exact once HTTP replay lands.
            "cache_hits_count": http_metrics.cache_hits_count,
            "cache_hit_ratio": http_metrics.cache_hit_ratio,
        }
        print_success(
            f"Captured {http_metrics.flow_count} HTTP flows "
            f"({http_metrics.duplicate_flow_count} duplicates)"
        )
        return result, comparable


def _compare_read_records(
    target_result: dict,
    control_result: dict,
    catalog_file: Path | None,
) -> tuple[RecordComparisonSummary | None, str | None]:
    """Run record-level comparisons between control and target read outputs.

    Uses primary keys from the configured catalog (source-defined primary
    keys come from the discovered catalog) to compare record counts, PK
    presence, PK integrity, and field values. Streams without a primary key
    fall back to a directional record count comparison.

    Each run's stdout is first split into per-stream record files (a single
    streaming pass), and the comparison then loads one stream at a time, so
    memory stays bounded by the largest stream instead of the full output
    of both runs. The per-stream files land next to each run's stdout and
    double as debugging artifacts. Within one stream, both sides are
    materialized as parsed messages plus dict copies plus PK indexes --
    measured at roughly 13 bytes resident per byte of record JSON, so a
    single stream of ~500 MB of records is the practical ceiling on a
    standard 7 GB runner. Start here when debugging an OOM.

    Returns:
        `(summary, skip_reason)`. The summary is None when the comparison
        cannot run at all -- then `skip_reason` says why, so the caller can
        surface a diagnostic check instead of letting the run read as a pass
        that compared records. An unexpected error during the comparison
        itself returns a FAILED summary instead of raising: by this point
        both (expensive, live-API) runs have completed, and a comparison bug
        must fail the verdict, not destroy the run's outputs and reports.
    """
    if catalog_file is None or not catalog_file.exists():
        reason = "no configured catalog available"
        print_warning(f"Skipping record-level comparison: {reason}")
        return None, reason

    try:
        configured_catalog = ConfiguredAirbyteCatalog.model_validate_json(
            catalog_file.read_text()
        )
    except Exception as exc:
        reason = f"configured catalog could not be parsed ({exc})"
        print_warning(f"Skipping record-level comparison: {reason}")
        return None, reason

    try:
        primary_keys = get_primary_keys_per_stream(configured_catalog)
        # A stream name that repeats across namespaces merges two streams in
        # this name-keyed pipeline; those names degraded to count-only above,
        # and the reader must hear why from the summary, not just stdout.
        collision_warnings = [
            f"Stream name {name!r} appears in more than one namespace; the "
            "record comparison keys streams by name, so its records are "
            "compared by count only"
            for name in duplicate_stream_names(configured_catalog)
        ]
        control_record_files = split_records_per_stream(
            Path(control_result["stdout_file"])
        )
        target_record_files = split_records_per_stream(
            Path(target_result["stdout_file"])
        )

        summary = run_record_comparisons_from_files(
            control_record_files=control_record_files,
            target_record_files=target_record_files,
            primary_keys_per_stream=primary_keys,
        )
        summary.warnings[:0] = collision_warnings
    except Exception as exc:
        summary = RecordComparisonSummary(
            passed=False,
            errored=True,
            count_comparison=ComparisonResult(
                passed=False, message="Record comparison errored"
            ),
            errors=[f"Record comparison errored: {exc!r}"],
        )

    if summary.passed:
        print_success("Record comparison passed (counts, PKs, field values)")
    else:
        print_error("Record comparison failed:")
        for error in summary.errors[:20]:
            print_error(f"  - {error}")
    for warning in summary.warnings[:20]:
        print_warning(warning)

    return summary, None


@connector_app.command(name="regression-test")
def regression_test(
    skip_compare: Annotated[
        bool,
        Parameter(
            help="If True, skip comparison and run single-version tests only. "
            "If False (default), run comparison tests (target vs control)."
        ),
    ] = False,
    skip_record_comparison: Annotated[
        bool,
        Parameter(
            help="If True, skip the record-level comparison for read commands "
            "(counts, PK presence, PK integrity, field values) and gate the "
            "verdict on command outcomes only. Escape hatch for sources whose "
            "data legitimately changes between the two live runs (rolling "
            "windows, feeds that age out records) until HTTP request caching "
            "makes strict comparison reliable."
        ),
    ] = False,
    test_image: Annotated[
        str | None,
        Parameter(
            help="Test connector image with tag (e.g., airbyte/source-github:1.0.0). "
            "This is the image under test - in comparison mode, it's compared against control_image."
        ),
    ] = None,
    control_image: Annotated[
        str | None,
        Parameter(
            help="Control connector image (baseline version) with tag (e.g., airbyte/source-github:1.0.0). "
            "Ignored if `skip_compare=True`."
        ),
    ] = None,
    connector_name: Annotated[
        str | None,
        Parameter(
            help="Connector name to build image from source (e.g., 'source-pokeapi'). "
            "If provided, builds the image locally with tag 'dev'. "
            "For comparison tests (default), this builds the target image. "
            "For single-version tests (skip_compare=True), this builds the test image."
        ),
    ] = None,
    repo_root: Annotated[
        str | None,
        Parameter(
            help="Path to the airbyte repo root. Required if connector_name is provided "
            "and the repo cannot be auto-detected."
        ),
    ] = None,
    command: Annotated[
        Literal["spec", "check", "discover", "read"],
        Parameter(help="The Airbyte command to run."),
    ] = "check",
    connection_id: Annotated[
        str | None,
        Parameter(
            help="Airbyte Cloud connection ID to fetch config/catalog from. "
            "Mutually exclusive with config-path/catalog-path. "
            "If provided, test_image/control_image can be auto-detected."
        ),
    ] = None,
    config_path: Annotated[
        str | None,
        Parameter(help="Path to the connector config JSON file."),
    ] = None,
    catalog_path: Annotated[
        str | None,
        Parameter(help="Path to the configured catalog JSON file (required for read)."),
    ] = None,
    state_path: Annotated[
        str | None,
        Parameter(help="Path to the state JSON file (optional for read)."),
    ] = None,
    output_dir: Annotated[
        str,
        Parameter(help="Directory to store test artifacts."),
    ] = "/tmp/regression_test_artifacts",
    enable_http_metrics: Annotated[
        bool,
        Parameter(
            help="Capture HTTP traffic metrics via mitmproxy (experimental). "
            "Requires mitmdump to be installed. Only used in comparison mode."
        ),
    ] = False,
    selected_streams: Annotated[
        str | None,
        Parameter(
            help="Comma-separated list of stream names to include in the read. "
            "Only these streams will be included in the configured catalog. "
            "This is useful to limit data volume by testing only specific streams."
        ),
    ] = None,
    enable_debug_logs: Annotated[
        bool,
        Parameter(
            help="Enable debug-level logging for regression test output. "
            "Also passed as `LOG_LEVEL=DEBUG` to the connector Docker container."
        ),
    ] = False,
    with_state: Annotated[
        bool | None,
        Parameter(
            negative="--no-state",
            help="Fetch and pass the connection's current state to the read command, "
            "producing a warm read instead of a cold read. Defaults to `True` when "
            "`--connection-id` is provided, `False` otherwise. Has no effect unless "
            "the command is `read`. Ignored when `--state-path` is explicitly provided.",
        ),
    ] = None,
) -> None:
    """Run regression tests on connectors.

    This command supports two modes:

    Comparison mode (skip_compare=False, default):
        Runs the specified Airbyte protocol command against both the target (new)
        and control (baseline) connector versions, then compares the results.
        This helps identify regressions between versions.

    Single-version mode (skip_compare=True):
        Runs the specified Airbyte protocol command against a single connector
        and validates the output. No comparison is performed.

    Results are written to the output directory and to GitHub Actions outputs
    if running in CI.

    You can provide the test image in three ways:
    1. --test-image: Use a pre-built image from Docker registry
    2. --connector-name: Build the image locally from source code
    3. --connection-id: Auto-detect from an Airbyte Cloud connection

    You can provide config/catalog either via file paths OR via a connection_id
    that fetches them from Airbyte Cloud.
    """
    # Configure debug logging for the regression test harness when requested
    if enable_debug_logs:
        logging.basicConfig(
            level=logging.DEBUG,
            format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
            force=True,
        )

    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    cmd = Command(command)

    config_file: Path | None = None
    catalog_file: Path | None = None
    state_file = Path(state_path) if state_path else None

    selected_stream_names: set[str] = (
        {s.strip() for s in selected_streams.split(",") if s.strip()}
        if selected_streams
        else set()
    )

    # Resolve the test image (used in both single-version and comparison modes)
    resolved_test_image: str | None = test_image
    resolved_control_image: str | None = control_image

    # Validate conflicting parameters
    # Single-version mode: reject comparison-specific parameters
    if skip_compare and control_image:
        write_github_output("success", False)
        write_github_output(
            "error", "Cannot specify control_image with skip_compare=True"
        )
        exit_with_error(
            "Cannot specify --control-image with --skip-compare. "
            "Control image is only used in comparison mode."
        )

    # If connector_name is provided, build the image from source
    if connector_name:
        if resolved_test_image:
            write_github_output("success", False)
            write_github_output(
                "error", "Cannot specify both test_image and connector_name"
            )
            exit_with_error("Cannot specify both --test-image and --connector-name")

        repo_root_path = Path(repo_root) if repo_root else None
        built_image = _build_connector_image_from_source(
            connector_name=connector_name,
            repo_root=repo_root_path,
            tag="dev",
        )
        if not built_image:
            write_github_output("success", False)
            write_github_output("error", f"Failed to build image for {connector_name}")
            exit_with_error(f"Failed to build image for {connector_name}")
        resolved_test_image = built_image

    if connection_id:
        if config_path or catalog_path:
            write_github_output("success", False)
            write_github_output(
                "error", "Cannot specify both connection_id and file paths"
            )
            exit_with_error(
                "Cannot specify both connection_id and config_path/catalog_path"
            )

        print_success(f"Fetching config/catalog from connection: {connection_id}")
        connection_data = fetch_connection_data(connection_id)

        # Check if we should retrieve unmasked secrets
        if should_use_secret_retriever():
            print_success(
                "USE_CONNECTION_SECRET_RETRIEVER enabled - enriching config with unmasked secrets..."
            )
            try:
                connection_data = enrich_config_with_secrets(
                    connection_data,
                    retrieval_reason="Regression test with USE_CONNECTION_SECRET_RETRIEVER=true",
                )
                print_success("Successfully retrieved unmasked secrets from database")
            except SecretRetrievalError as e:
                write_github_output("success", False)
                write_github_output("error", str(e))
                exit_with_error(
                    f"{e}\n\n"
                    f"This connection cannot be used for regression testing. "
                    f"Please use a connection from a non-EU workspace, or use GSM-based "
                    f"integration test credentials instead (by omitting --connection-id)."
                )

        # Fill in stream schemas: the minimal catalog from the public API has
        # empty json_schema values, which silently yields zero records for
        # connectors that derive request fields from the catalog schema.
        # Only the read command consumes the catalog, so spec/check/discover
        # skip the extra Cloud API round trip.
        enrichment_state: list[dict[str, Any]] | None = None
        enrichment_state_fetched = False
        if cmd.needs_catalog():
            merged_count = 0
            try:
                enrichment = enrich_catalog_schemas_from_cloud(connection_data)
                connection_data = enrichment.connection_data
                merged_count = enrichment.merged_count
                enrichment_state = enrichment.state
                enrichment_state_fetched = True
            except Exception as exc:
                print_error(f"Failed to fetch stream schemas from Cloud API: {exc}")
            missing_schemas = streams_missing_schemas(connection_data.catalog)
            if selected_stream_names:
                missing_schemas = [
                    s for s in missing_schemas if s in selected_stream_names
                ]
            if missing_schemas and should_use_secret_retriever():
                try:
                    connection_data, db_merged_count = (
                        enrich_catalog_schemas_from_platform_db(
                            connection_data,
                            retrieval_reason="Regression test catalog schema enrichment",
                        )
                    )
                    merged_count += db_merged_count
                except Exception as exc:
                    print_error(f"Failed to merge stored stream schemas: {exc}")
                missing_schemas = streams_missing_schemas(connection_data.catalog)
                if selected_stream_names:
                    missing_schemas = [
                        s for s in missing_schemas if s in selected_stream_names
                    ]
            total_streams = len(connection_data.catalog.get("streams", []))
            checked_streams = (
                f"{len(missing_schemas)} of {len(selected_stream_names)} "
                "selected stream(s)"
                if selected_stream_names
                else f"{len(missing_schemas)} of {total_streams} stream(s)"
            )
            if not total_streams:
                error_msg = (
                    "No configured streams found in the connection catalog. "
                    "A read with zero streams would produce zero records on "
                    "both versions, so failing instead of producing a false pass."
                )
                write_github_output("success", False)
                write_github_output("error", error_msg)
                exit_with_error(error_msg)
            if missing_schemas:
                error_msg = (
                    f"Stream schemas missing for {checked_streams}: "
                    f"{', '.join(missing_schemas)}. "
                    "Connectors that derive request fields from the catalog "
                    "schema would silently return zero records, so failing "
                    "instead of producing a false pass."
                )
                write_github_output("success", False)
                write_github_output("error", error_msg)
                exit_with_error(error_msg)
            print_success(
                f"Stream schemas ready: merged {merged_count} of {total_streams} "
                "stream(s)"
                + (
                    f"; checked {len(selected_stream_names)} selected stream(s)"
                    if selected_stream_names
                    else ""
                )
            )

        # Resolve with_state default: True when connection_id is provided
        resolved_with_state = with_state if with_state is not None else True

        if not (resolved_with_state and not state_file and command == "read"):
            connection_data.state = None
        elif enrichment_state_fetched:
            connection_data.state = enrichment_state
            if connection_data.state:
                print_success(
                    f"Using state fetched during schema enrichment "
                    f"({len(connection_data.state)} stream(s))"
                )
            else:
                print_success("No state available for this connection (initial sync)")
        else:
            print_success("Fetching connection state for warm read...")
            try:
                connection_data.state = fetch_connection_state(connection_data)
                if connection_data.state:
                    print_success(
                        f"Fetched state with {len(connection_data.state)} stream(s)"
                    )
                else:
                    connection_data.state = None
                    print_success(
                        "No state available for this connection (initial sync)"
                    )
            except Exception as exc:
                print_error(f"Failed to fetch connection state: {exc}")
                print_success("Falling back to cold read (no state)")

        config_file, catalog_file, state_file_from_conn = save_connection_data_to_files(
            connection_data, output_path / "connection_data"
        )

        if state_file_from_conn and not state_file:
            state_file = state_file_from_conn

        print_success(
            f"Fetched config for source: {connection_data.source_name} "
            f"with {len(connection_data.stream_names)} streams"
        )

        # Auto-detect test/control image from connection if not provided
        if not resolved_test_image and connection_data.connector_image:
            resolved_test_image = connection_data.connector_image
            print_success(f"Auto-detected test image: {resolved_test_image}")

        if (
            not skip_compare
            and not resolved_control_image
            and connection_data.connector_image
        ):
            resolved_control_image = connection_data.connector_image
            print_success(f"Auto-detected control image: {resolved_control_image}")
    elif config_path:
        config_file = Path(config_path)
        catalog_file = Path(catalog_path) if catalog_path else None
    elif connector_name:
        # Fallback: fetch integration test secrets from GSM using PyAirbyte API
        print_success(
            f"No connection_id or config_path provided. "
            f"Attempting to fetch integration test config from GSM for {connector_name}..."
        )
        gsm_config = get_first_config_from_secrets(connector_name)
        if gsm_config:
            # Write config to a temp file (not in output_path to avoid artifact upload)
            gsm_config_dir = Path(
                tempfile.mkdtemp(prefix=f"gsm-config-{connector_name}-")
            )
            gsm_config_dir.chmod(0o700)
            gsm_config_file = gsm_config_dir / "config.json"
            gsm_config_file.write_text(json.dumps(gsm_config, indent=2))
            gsm_config_file.chmod(0o600)
            config_file = gsm_config_file
            # Use catalog_path if provided (e.g., generated from discover output)
            catalog_file = Path(catalog_path) if catalog_path else None
            print_success(
                f"Fetched integration test config from GSM for {connector_name}"
            )
        else:
            print_error(
                f"Failed to fetch integration test config from GSM for {connector_name}."
            )
            config_file = None
            # Use catalog_path if provided (e.g., generated from discover output)
            catalog_file = Path(catalog_path) if catalog_path else None
    else:
        config_file = None
        catalog_file = Path(catalog_path) if catalog_path else None

    # Auto-detect control_image from metadata.yaml if connector_name is provided (comparison mode only)
    if not skip_compare and not resolved_control_image and connector_name:
        resolved_control_image = _fetch_control_image_from_metadata(connector_name)
        if resolved_control_image:
            print_success(
                f"Auto-detected control image from metadata.yaml: {resolved_control_image}"
            )

    # Validate that we have the required images
    if not resolved_test_image:
        write_github_output("success", False)
        write_github_output("error", "No test image specified")
        exit_with_error(
            "You must provide one of the following: a test_image, a connector_name "
            "to build the image from source, or a connection_id to auto-detect the image."
        )

    if not skip_compare and not resolved_control_image:
        write_github_output("success", False)
        write_github_output("error", "No control image specified")
        exit_with_error(
            "You must provide one of the following: a control_image, a connection_id "
            "for a connection that has an associated connector image, or a connector_name "
            "to auto-detect the control image from the airbyte repo's metadata.yaml."
        )

    # Pull images if they weren't just built locally
    # If connector_name was provided, we just built the test image locally
    if not connector_name and not ensure_image_available(resolved_test_image):
        write_github_output("success", False)
        write_github_output("error", f"Failed to pull image: {resolved_test_image}")
        exit_with_error(f"Failed to pull test image: {resolved_test_image}")

    if (
        not skip_compare
        and resolved_control_image
        and not ensure_image_available(resolved_control_image)
    ):
        write_github_output("success", False)
        write_github_output("error", f"Failed to pull image: {resolved_control_image}")
        exit_with_error(
            f"Failed to pull control connector image: {resolved_control_image}"
        )

    # Apply selected_streams filter to catalog if requested
    if selected_stream_names and catalog_file:
        print_success(
            f"Filtering catalog to {len(selected_stream_names)} selected streams: "
            f"{', '.join(sorted(selected_stream_names))}"
        )
        filter_configured_catalog_file(catalog_file, selected_stream_names)

    # Upgrade READ → READ_WITH_STATE when a state file is available
    if cmd == Command.READ and state_file:
        cmd = Command.READ_WITH_STATE
        print_success("State available — using read-with-state (warm read)")

    # Track telemetry for the regression test
    # Extract version from image tag (e.g., "airbyte/source-github:1.0.0" -> "1.0.0")
    target_version = (
        resolved_test_image.rsplit(":", 1)[-1]
        if ":" in resolved_test_image
        else "unknown"
    )
    control_version = None
    if resolved_control_image and ":" in resolved_control_image:
        control_version = resolved_control_image.rsplit(":", 1)[-1]

    # Get tester identity from environment (GitHub Actions sets GITHUB_ACTOR)
    tester = os.getenv("GITHUB_ACTOR") or os.getenv("USER")

    track_regression_test(
        user_id=tester,
        connector_image=resolved_test_image,
        command=command,
        target_version=target_version,
        control_version=control_version,
        additional_properties={
            "connection_id": connection_id,
            "skip_compare": skip_compare,
            "with_state": cmd == Command.READ_WITH_STATE,
        },
    )

    # Execute the appropriate mode
    if skip_compare:
        # Single-version mode: run only the connector image. There is no control
        # to compare its spec or catalog against, so the declared objects go
        # unread here.
        result, _ = _run_connector_command(
            connector_image=resolved_test_image,
            command=cmd,
            output_dir=output_path,
            target_or_control=TargetOrControl.TARGET,
            config_path=config_file,
            catalog_path=catalog_file,
            state_path=state_file,
            enable_debug_logs=enable_debug_logs,
        )

        # Same per-version rule as comparison mode: for CHECK the exit code alone
        # is not the verdict, connectionStatus is.
        annotated_result = _annotate_run_verdict(command, result)
        single_success = bool(annotated_result["success"])

        print_json(annotated_result)

        single_outputs: dict[str, object] = {
            "success": single_success,
            "connector": resolved_test_image,
            "command": command,
            "exit_code": result["exit_code"],
        }
        if command == "check":
            # Named to match the comparison-mode output the workflow summary reads.
            single_outputs["target_connection_status"] = result.get("connection_status")

        write_github_outputs(single_outputs)

        # Generate report.md with detailed metrics
        report_path = generate_single_version_report(
            connector_image=resolved_test_image,
            command=command,
            result=result,
            output_dir=output_path,
        )
        print_success(f"Generated report: {report_path}")

        # The detailed surface is report.html in the uploaded artifact; the step
        # summary gets the concise block instead of the whole report. Both are
        # built from the unannotated result: the model derives the verdict itself.
        report_model = build_single_version_report_model(
            connector_image=resolved_test_image,
            command=command,
            result=result,
            configured_streams=_configured_stream_names(cmd, catalog_file),
            connection_objects=_collect_connection_objects(
                catalog_file, state_file, output_path / "airbyte_messages"
            ),
        )
        html_report_path = write_html_report(report_model, output_path)
        print_success(f"Generated HTML report: {html_report_path}")

        # Write the concise summary to GITHUB_STEP_SUMMARY (if env var exists)
        write_github_summary(render_inline_summary(report_model))

        if single_success:
            print_success(
                f"Single-version regression test passed for {resolved_test_image}"
            )
        elif command == "check" and result["success"]:
            print_error(
                f"Single-version regression test failed for {resolved_test_image}: "
                f"connectionStatus {result.get('connection_status') or 'missing'} "
                "(the connector itself exited 0)."
            )
        else:
            print_error(
                f"Single-version regression test failed for {resolved_test_image}"
            )
    else:
        # Comparison mode: run both control and target images. The control
        # version runs FIRST on purpose: the record comparison is
        # directional (extra records in the target are allowed, missing
        # ones fail), so data created upstream between the two live runs
        # must land in the target output — where it is tolerated — rather
        # than in the control output, where it would read as records
        # missing from the target and fail the comparison. Accepted side
        # effect (applies to every command, not just read): a hanging or
        # timing-out control run means the target never runs, so such a
        # run says nothing about the version under test.
        target_output = output_path / "target"
        control_output = output_path / "control"

        control_result, control_outputs = _run_with_optional_http_metrics(
            connector_image=resolved_control_image,  # type: ignore[arg-type]
            command=cmd,
            output_dir=control_output,
            target_or_control=TargetOrControl.CONTROL,
            enable_http_metrics=enable_http_metrics,
            config_path=config_file,
            catalog_path=catalog_file,
            state_path=state_file,
            enable_debug_logs=enable_debug_logs,
        )

        target_result, target_outputs = _run_with_optional_http_metrics(
            connector_image=resolved_test_image,
            command=cmd,
            output_dir=target_output,
            target_or_control=TargetOrControl.TARGET,
            enable_http_metrics=enable_http_metrics,
            config_path=config_file,
            catalog_path=catalog_file,
            state_path=state_file,
            enable_debug_logs=enable_debug_logs,
        )

        outcome = evaluate_comparison_outcome(command, target_result, control_result)

        # Record-level comparison for READ commands (counts, PK presence,
        # PK integrity, field values). Only meaningful when both runs
        # succeeded; a comparison failure is a regression and fails the
        # verdict even though both containers exited cleanly. `outcome`
        # itself stays the pure exit-status/connectionStatus layer — the
        # folded verdict lives in `success`/`regression_detected` below.
        record_comparison: RecordComparisonSummary | None = None
        # A skipped comparison must be visible on the report surfaces, not
        # only on stdout: without this row the run reads as a pass that
        # compared records. Diagnostic, because the skip is not a regression.
        record_comparison_skipped: CheckResult | None = None
        if (
            cmd in (Command.READ, Command.READ_WITH_STATE)
            and outcome.both_succeeded
            and not skip_record_comparison
        ):
            record_comparison, skip_reason = _compare_read_records(
                target_result=target_result,
                control_result=control_result,
                catalog_file=catalog_file,
            )
            if record_comparison is None and skip_reason is not None:
                record_comparison_skipped = CheckResult(
                    name="Record comparison",
                    passed=False,
                    severity="diagnostic",
                    summary=f"Skipped — {skip_reason}; records were not compared",
                )
        elif skip_record_comparison and cmd in (Command.READ, Command.READ_WITH_STATE):
            print_warning(
                "Record-level comparison skipped (--skip-record-comparison); "
                "the verdict gates on command outcomes only."
            )
            record_comparison_skipped = CheckResult(
                name="Record comparison",
                passed=False,
                severity="diagnostic",
                summary="Skipped (--skip-record-comparison); records were not compared",
            )
        record_comparison_failed = (
            record_comparison is not None and not record_comparison.passed
        )
        # An errored comparison fails the run (fail closed) but as
        # INCONCLUSIVE, like both_failed: a comparator crash must not tell a
        # connector developer their change caused a regression.
        comparison_errored = record_comparison is not None and record_comparison.errored

        # Spec/catalog-schema comparison of what the two versions declared
        # about themselves; a failed check here is a regression as much as
        # a dropped record.
        (
            comparison_checks,
            comparison_diff_blocks,
            comparison_detail,
        ) = _compare_declared_outputs(
            command=command,
            outcome=outcome,
            control_outputs=control_outputs,
            target_outputs=target_outputs,
        )
        failed_comparisons = failed_checks(comparison_checks)

        success = (
            outcome.success and not record_comparison_failed and not failed_comparisons
        )
        regression_detected = (
            outcome.regression_detected
            or (record_comparison_failed and not comparison_errored)
            or bool(failed_comparisons)
        )

        # Annotate copies of each side, never the originals: `generate_regression_report`
        # below reads `result["success"]` as the exit status, so handing it a dict whose
        # `success` is the verdict would corrupt the report's per-version wording.
        combined_result = {
            "target": _annotate_run_verdict(command, target_result),
            "control": _annotate_run_verdict(command, control_result),
            "both_succeeded": outcome.both_succeeded,
            "regression_detected": regression_detected,
            # The authoritative verdict, so consumers of this payload (stdout and
            # the `regression_report` output) never have to re-derive it from
            # `regression_detected` -- which is false for an inconclusive run.
            "success": success,
            "both_failed": outcome.both_failed,
        }
        if record_comparison is not None:
            combined_result["record_comparison"] = record_comparison.to_dict()
        if comparison_detail:
            combined_result["comparison"] = comparison_detail

        print_json(combined_result)

        gh_outputs: dict[str, object] = {
            "success": success,
            "target_image": resolved_test_image,
            "control_image": resolved_control_image,
            "command": command,
            "target_exit_code": target_result["exit_code"],
            "control_exit_code": control_result["exit_code"],
            "regression_detected": regression_detected,
            "both_failed": outcome.both_failed,
        }

        if command == "check":
            gh_outputs["target_connection_status"] = target_result.get(
                "connection_status"
            )
            gh_outputs["control_connection_status"] = control_result.get(
                "connection_status"
            )

        if record_comparison is not None:
            gh_outputs["record_comparison_passed"] = record_comparison.passed

        write_github_outputs(gh_outputs)

        write_json_output("regression_report", combined_result)

        report_path = generate_regression_report(
            target_image=resolved_test_image,
            control_image=resolved_control_image,  # type: ignore[arg-type]
            command=command,
            target_result=target_result,
            control_result=control_result,
            output_dir=output_path,
            record_comparison=(
                record_comparison.to_dict() if record_comparison is not None else None
            ),
            # Without these the markdown report would announce "no regression"
            # over the same run the HTML report and the CLI call a failure --
            # and, for a warning, would show no finding at all where the other
            # two surfaces show one.
            comparison_findings=[
                (check.status, f"{check.name}: {check.summary}")
                for check in comparison_checks
                if check.status in {"fail", "warn"}
            ],
        )
        print_success(f"Generated regression report: {report_path}")

        # Same rule as `generate_regression_report` above: the model reads
        # `result["success"]` as the exit status and derives the per-version
        # verdict itself, so it gets the unannotated originals. `outcome` is
        # passed through so the run is evaluated exactly once.
        report_model = build_comparison_report_model(
            target_image=resolved_test_image,
            control_image=resolved_control_image,  # type: ignore[arg-type]
            command=command,
            target_result=target_result,
            control_result=control_result,
            outcome=outcome,
            record_comparison=record_comparison,
            extra_checks=(
                *comparison_checks,
                *([record_comparison_skipped] if record_comparison_skipped else []),
            ),
            extra_diff_blocks=comparison_diff_blocks,
            configured_streams=_configured_stream_names(cmd, catalog_file),
            connection_objects=_collect_connection_objects(
                catalog_file, state_file, target_output / "airbyte_messages"
            ),
        )
        html_report_path = write_html_report(report_model, output_path)
        print_success(f"Generated regression HTML report: {html_report_path}")

        # Write the concise summary to GITHUB_STEP_SUMMARY (if env var exists)
        write_github_summary(render_inline_summary(report_model))

        if failed_comparisons:
            # Only reachable when both commands ran cleanly -- a comparison is
            # skipped otherwise -- so this says what the exit codes could not.
            print_error(
                f"Regression detected between {resolved_test_image} and "
                f"{resolved_control_image}: "
                + "; ".join(
                    f"{check.name.lower()} — {check.summary}"
                    for check in failed_comparisons
                )
            )
        elif outcome.check_improvement:
            print_success(
                f"Regression test passed for {resolved_test_image} vs "
                f"{resolved_control_image}: target connectionStatus SUCCEEDED "
                "while control FAILED (improvement)."
            )
        elif outcome.both_succeeded and comparison_errored:
            print_error(
                f"Record comparison errored for {resolved_test_image} vs "
                f"{resolved_control_image}. Test failed/inconclusive; this "
                "is a tooling failure, not evidence of a regression."
            )
        elif outcome.both_succeeded and record_comparison_failed:
            print_error(
                f"Regression detected between {resolved_test_image} and "
                f"{resolved_control_image}: both versions ran, but the "
                "record comparison failed."
            )
        elif outcome.both_succeeded:
            print_success(
                f"Regression test passed for {resolved_test_image} vs {resolved_control_image}"
            )
        elif outcome.regression_detected:
            print_error(
                f"Regression detected between {resolved_test_image} and {resolved_control_image}"
            )
        elif outcome.both_failed:
            print_error(
                f"Both versions failed for {resolved_test_image} vs {resolved_control_image}. "
                "Test failed/inconclusive; cannot rule out a regression."
            )
        else:
            print_error(
                f"Control {resolved_control_image} failed while target "
                f"{resolved_test_image} succeeded. Test failed/inconclusive; "
                "nothing to compare the target against."
            )


def _configured_stream_names(
    command: Command, catalog_file: Path | None
) -> tuple[str, ...]:
    """Every stream the run was configured to read.

    The report's per-stream tables are keyed on emitted records, so a stream
    that returned nothing has no entry and would be missing from the report
    entirely. Reading the configured catalog is what lets it be shown as zero.

    Only for commands that read records. `--connection-id` fetches a catalog for
    every command, and handing it to `spec`, `check` or `discover` would give
    them an all-zero stream table and a coverage warning saying no stream
    returned anything -- true, meaningless, and enough noise to train a reviewer
    to ignore the warning on the one command where it means something.
    """
    if command not in (Command.READ, Command.READ_WITH_STATE):
        return ()

    if catalog_file is None or not catalog_file.exists():
        return ()

    try:
        catalog = ConfiguredAirbyteCatalog.parse_raw(catalog_file.read_text())
    except Exception as exc:
        print_warning(f"Could not read the configured catalog for the report: {exc}")
        return ()

    return tuple(
        sorted(
            configured.stream.name
            for configured in catalog.streams
            if configured.stream
        )
    )


def _collect_connection_objects(
    catalog_file: Path | None,
    state_file: Path | None,
    messages_dir: Path | None,
) -> tuple[DiffBlock, ...]:
    """Gather the objects the run was given or discovered, for the report.

    The connector config is deliberately absent: it is the one object that
    carries secrets, and the report is an artifact anyone with repo access can
    download.

    Args:
        catalog_file: The configured catalog handed to the run.
        state_file: The state handed to the run, for a warm read.
        messages_dir: The target side's `airbyte_messages` directory, which
            holds the catalog the connector discovered.

    Returns:
        One JSON block per object that exists, in the order a reader wants them.
    """
    sources: list[tuple[str, Path | None]] = [
        ("Configured catalog (input)", catalog_file),
        ("State (input)", state_file),
        (
            "Discovered catalog (from the target)",
            (messages_dir / "catalog.jsonl") if messages_dir else None,
        ),
    ]

    blocks: list[DiffBlock] = []
    for title, path in sources:
        if path is None or not path.is_file():
            continue

        try:
            payload = path.read_text()
        except OSError:
            continue

        if payload.strip():
            blocks.append(build_json_block(title, payload))

    return tuple(blocks)


# The order commands are presented in, matching how a sync runs them. Anything
# else found under the artifacts directory follows, sorted.
_REPORT_COMMAND_ORDER = ("spec", "check", "discover", "read")


@connector_app.command(name="consolidate-regression-reports")
def consolidate_regression_reports(
    artifacts_dir: Annotated[
        str,
        Parameter(
            help="Directory holding one subdirectory per command, each with the "
            "`report.html` that `regression-test --output-dir` wrote."
        ),
    ],
    output_path: Annotated[
        str | None,
        Parameter(
            name=["--output"],
            help="Where to write the consolidated report. "
            "Defaults to `report.html` in `--artifacts-dir`.",
        ),
    ] = None,
) -> None:
    """Fold one run's per-command regression reports into a single page.

    The regression test runs the CLI once per Airbyte command, so each command
    writes its own report into its own artifact. This produces the run-level
    view -- a verdict table across commands plus every report inlined -- so a
    reviewer downloads one file instead of four.

    Never fails the run: a command whose report is missing or unreadable is
    skipped, because this is a reporting convenience and the per-command
    artifacts remain the source of truth.
    """
    artifacts_path = Path(artifacts_dir)
    ordered = [artifacts_path / command for command in _REPORT_COMMAND_ORDER]
    extra = sorted(
        path
        for path in artifacts_path.glob("*")
        if path.is_dir() and path not in ordered
    )
    report_paths = [
        directory / HTML_REPORT_FILENAME for directory in [*ordered, *extra]
    ]

    consolidated = consolidate_reports(report_paths)
    if consolidated is None:
        print_warning(
            f"No per-command reports found under {artifacts_path}; "
            "nothing to consolidate."
        )
        return

    destination = Path(output_path) if output_path else artifacts_path / "report.html"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(consolidated)
    print_success(f"Consolidated regression report: {destination}")


