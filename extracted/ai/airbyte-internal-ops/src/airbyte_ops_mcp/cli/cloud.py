_OverrideLevel = Literal["actor", "workspace", "organization"]
_TierFilter = Literal["TIER_0", "TIER_1", "TIER_2", "UNKNOWN", "ALL"]


def _resolve_cli_cloud_auth() -> ResolvedCloudAuth:
    """Resolve Airbyte Cloud auth from environment variables for CLI use.

    Mirrors the priority order the MCP server uses:

    1. `AIRBYTE_CLOUD_BEARER_TOKEN`
    2. `AIRBYTE_CLOUD_CLIENT_ID` + `AIRBYTE_CLOUD_CLIENT_SECRET`

    Raises a CLI error via `exit_with_error` if no usable credentials are present.
    """
    bearer_token = os.environ.get("AIRBYTE_CLOUD_BEARER_TOKEN")
    if bearer_token:
        return ResolvedCloudAuth(bearer_token=bearer_token)

    client_id = os.environ.get("AIRBYTE_CLOUD_CLIENT_ID")
    client_secret = os.environ.get("AIRBYTE_CLOUD_CLIENT_SECRET")
    if client_id and client_secret:
        return ResolvedCloudAuth(client_id=client_id, client_secret=client_secret)

    exit_with_error(
        "Missing Airbyte Cloud credentials. Set AIRBYTE_CLOUD_BEARER_TOKEN, or "
        "both AIRBYTE_CLOUD_CLIENT_ID and AIRBYTE_CLOUD_CLIENT_SECRET."
    )


def _validate_override_scope_args(
    *,
    override_level: _OverrideLevel,
    workspace_id: str | None,
    organization_id: str | None,
    connector_id: str | None,
    connector_type: Literal["source", "destination"] | None,
    actor_definition_id: str | None,
) -> None:
    """Validate scope-specific arguments for `set/clear-version-override`.

    Calls `exit_with_error` (which terminates the process) if the supplied
    arguments are inconsistent with the requested `override_level`.
    """
    if override_level == "actor":
        missing = [
            name
            for name, value in (
                ("--workspace-id", workspace_id),
                ("--connector-id", connector_id),
                ("--connector-type", connector_type),
            )
            if not value
        ]
        if missing:
            exit_with_error(
                "Override level 'actor' requires " + ", ".join(missing) + "."
            )
        if actor_definition_id is not None:
            exit_with_error(
                "Override level 'actor' must not be combined with "
                "--actor-definition-id."
            )
        if organization_id is not None:
            exit_with_error(
                "Override level 'actor' must not be combined with --organization-id."
            )
        return

    if override_level == "workspace":
        missing = [
            name
            for name, value in (
                ("--workspace-id", workspace_id),
                ("--actor-definition-id", actor_definition_id),
            )
            if not value
        ]
        if missing:
            exit_with_error(
                "Override level 'workspace' requires " + ", ".join(missing) + "."
            )
        if connector_id is not None or connector_type is not None:
            exit_with_error(
                "Override level 'workspace' must not be combined with "
                "--connector-id or --connector-type."
            )
        if organization_id is not None:
            exit_with_error(
                "Override level 'workspace' must not be combined with "
                "--organization-id."
            )
        return

    # override_level == "organization"
    missing = [
        name
        for name, value in (
            ("--organization-id", organization_id),
            ("--actor-definition-id", actor_definition_id),
        )
        if not value
    ]
    if missing:
        exit_with_error(
            "Override level 'organization' requires " + ", ".join(missing) + "."
        )
    if connector_id is not None or connector_type is not None:
        exit_with_error(
            "Override level 'organization' must not be combined with "
            "--connector-id or --connector-type."
        )
    if workspace_id is not None:
        exit_with_error(
            "Override level 'organization' must not be combined with --workspace-id."
        )


def _dispatch_version_override(
    *,
    override_level: _OverrideLevel,
    workspace_id: str | None,
    organization_id: str | None,
    connector_id: str | None,
    connector_type: Literal["source", "destination"] | None,
    actor_definition_id: str | None,
    version: str | None,
    unset: bool,
    reason: str | None,
    reason_url: str | None,
    issue_url: str,
    approval_comment_url: str,
    ai_agent_session_url: str | None,
    customer_tier_filter: _TierFilter,
) -> None:
    """Route a version-override request through the normalized core helper.

    Resolves `--actor-definition-id` to its canonical name and connector type
    via the cloud registry for `workspace`/`organization` scopes. Prints the
    operation result as JSON.
    """
    _validate_override_scope_args(
        override_level=override_level,
        workspace_id=workspace_id,
        organization_id=organization_id,
        connector_id=connector_id,
        connector_type=connector_type,
        actor_definition_id=actor_definition_id,
    )

    auth = _resolve_cli_cloud_auth()

    if override_level == "actor":
        assert workspace_id is not None
        assert connector_id is not None
        assert connector_type is not None
        assert organization_id is None
        try:
            ws_resolution = resolve_workspace(workspace_id)
            if not ws_resolution.organization_id:
                exit_with_error("Could not resolve organization for workspace.")
            result = set_cloud_version_override(
                auth=auth,
                target=VersionOverrideTarget(
                    scope="actor",
                    organization_id=ws_resolution.organization_id,
                    workspace_id=workspace_id,
                    actor_id=connector_id,
                    connector_type=connector_type,
                ),
                approval_comment_url=approval_comment_url,
                version=version,
                unset=unset,
                override_reason=reason,
                override_reason_reference_url=reason_url,
                issue_url=issue_url,
                ai_agent_session_url=ai_agent_session_url,
                customer_tier_filter=customer_tier_filter,
            )
        except (PyAirbyteInputError, CloudAuthError) as e:
            exit_with_error(str(e))
        _print_override_result(result.success, result.message)
        print_json(result.model_dump())
        return

    try:
        assert actor_definition_id is not None
        canonical_name, resolved_connector_type = (
            resolve_definition_id_to_canonical_info(actor_definition_id)
        )
    except (PyAirbyteInputError, requests.RequestException) as e:
        exit_with_error(f"Failed to resolve --actor-definition-id: {e}")
    typed_connector_type: Literal["source", "destination"] = (
        "source" if resolved_connector_type == "source" else "destination"
    )

    if override_level == "workspace":
        assert workspace_id is not None
        try:
            ws_resolution = resolve_workspace(workspace_id)
            if not ws_resolution.organization_id:
                exit_with_error("Could not resolve organization for workspace.")
            target = VersionOverrideTarget(
                scope="workspace",
                organization_id=ws_resolution.organization_id,
                workspace_id=workspace_id,
                connector_name=canonical_name,
                connector_type=typed_connector_type,
            )
        except PyAirbyteInputError as e:
            exit_with_error(str(e))
    else:
        assert organization_id is not None
        target = VersionOverrideTarget(
            scope="organization",
            organization_id=organization_id,
            connector_name=canonical_name,
            connector_type=typed_connector_type,
        )

    try:
        result = set_cloud_version_override(
            auth=auth,
            target=target,
            approval_comment_url=approval_comment_url,
            version=version,
            unset=unset,
            override_reason=reason,
            override_reason_reference_url=reason_url,
            issue_url=issue_url,
            ai_agent_session_url=ai_agent_session_url,
            customer_tier_filter=customer_tier_filter,
        )
    except (PyAirbyteInputError, CloudAuthError) as e:
        exit_with_error(str(e))
    _print_override_result(result.success, result.message)
    print_json(result.model_dump())


def _print_override_result(success: bool, message: str) -> None:
    """Emit an override-operation status message via the shared CLI helpers."""
    if success:
        print_success(message)
    else:
        print_error(message)


