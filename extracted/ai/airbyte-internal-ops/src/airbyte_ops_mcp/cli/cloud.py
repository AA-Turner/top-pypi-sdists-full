def _load_json_file(file_path: Path) -> dict | None:
    """Load a JSON file and return its contents.

    Returns None if the file doesn't exist or contains invalid JSON.
    """
    if not file_path.exists():
        return None
    try:
        return json.loads(file_path.read_text())
    except json.JSONDecodeError as e:
        print_error(f"Failed to parse JSON in file: {file_path}\nError: {e}")
        return None


def _parse_extra_env(pairs: list[str] | None) -> dict[str, str]:
    """Parse repeatable KEY=VALUE arguments for connector container env."""
    parsed: dict[str, str] = {}
    for item in pairs or []:
        if "=" not in item:
            exit_with_error(f"Invalid --extra-env value (expected KEY=VALUE): {item}")
        key, value = item.split("=", 1)
        key = key.strip()
        if not key:
            exit_with_error(f"Invalid --extra-env value (expected KEY=VALUE): {item}")
        parsed[key] = value
    return parsed


def _run_connector_command(
    connector_image: str,
    command: Command,
    output_dir: Path,
    target_or_control: TargetOrControl,
    config_path: Path | None = None,
    catalog_path: Path | None = None,
    state_path: Path | None = None,
    proxy_url: str | None = None,
    ca_cert_path: Path | None = None,
    enable_debug_logs: bool = False,
    extra_env: dict[str, str] | None = None,
) -> tuple[dict, ComparableOutputs]:
    """Run a connector command and return its results and its declared objects.

    The dict is a flattened view of `ExecutionResult`: counts, exit status and
    artifact paths, which is all the reports need. What a comparison needs
    instead -- the spec, the discovered catalog -- travels beside it as
    `ComparableOutputs` rather than growing a dict that several consumers read.
    The `ExecutionResult` itself is still dropped here: it holds every parsed
    message, and a comparison keeps both sides alive at once.

    Args:
        connector_image: Full connector image name with tag.
        command: The Airbyte command to run.
        output_dir: Directory to store output files.
        target_or_control: Whether this is target or control version.
        config_path: Path to connector config JSON file.
        catalog_path: Path to configured catalog JSON file.
        state_path: Path to state JSON file.
        proxy_url: Optional HTTP proxy URL for traffic capture.
        ca_cert_path: Path to the proxy's CA certificate, so the container trusts
            it. Without it every HTTPS request through the proxy fails TLS
            verification and the capture comes back near-empty.
        enable_debug_logs: If `True`, pass `LOG_LEVEL=DEBUG` to the connector container.
        extra_env: Additional environment variables for the connector container.

    Returns:
        The flattened results, and the objects the connector declared.
    """
    connector = ConnectorUnderTest.from_image_name(connector_image, target_or_control)

    config = _load_json_file(config_path) if config_path else None
    state = _load_json_file(state_path) if state_path else None

    configured_catalog = None
    if catalog_path and catalog_path.exists():
        catalog_json = catalog_path.read_text()
        configured_catalog = ConfiguredAirbyteCatalog.parse_raw(catalog_json)

    # Pass log level as an environment variable to the connector container
    container_env: dict[str, str] = {}
    if enable_debug_logs:
        container_env["LOG_LEVEL"] = "DEBUG"
    container_env.update(extra_env or {})

    execution_inputs = ExecutionInputs(
        connector_under_test=connector,
        command=command,
        output_dir=output_dir,
        config=config,
        configured_catalog=configured_catalog,
        state=state,
        environment_variables=container_env or None,
    )

    runner = ConnectorRunner(
        execution_inputs, proxy_url=proxy_url, ca_cert_path=ca_cert_path
    )
    result = runner.run()

    result.save_artifacts(output_dir)

    result_dict: dict[str, object] = {
        "connector": connector_image,
        "command": command.value,
        "success": result.success,
        "exit_code": result.exit_code,
        "stdout_file": str(result.stdout_file_path),
        "stderr_file": str(result.stderr_file_path),
        "message_counts": {
            k.value: v for k, v in result.get_message_count_per_type().items()
        },
        "record_counts_per_stream": result.get_record_count_per_stream(),
    }

    # For CHECK, include the parsed connectionStatus from the Airbyte protocol.
    # The CDK exits 0 regardless of check outcome; the real pass/fail signal
    # lives in the CONNECTION_STATUS message (status=SUCCEEDED or FAILED).
    if command == Command.CHECK:
        conn_status = result.get_connection_status()
        if conn_status is not None:
            result_dict["connection_status"] = conn_status.status.value
            result_dict["connection_status_message"] = conn_status.message or ""
        else:
            result_dict["connection_status"] = None
            result_dict["connection_status_message"] = ""

    return result_dict, ComparableOutputs.from_execution_result(result)


def _annotate_run_verdict(command: str, result: dict[str, Any]) -> dict[str, Any]:
    """Copy a run result with `success` as the verdict, exit status kept separately.

    `ExecutionResult.success` is the container exit status, which for `check` says
    nothing about whether the connector could connect -- the CDK exits 0 even when a
    check fails. Any payload read as the verdict must therefore not expose the exit
    status under `success`, at any nesting level. The raw value stays available as
    `exited_cleanly`; for every command but `check` the two are equal.

    Returns a copy: callers pass the unannotated originals to the report generator,
    which reads `success` as the exit status.
    """
    return {
        **result,
        "success": command_result_succeeded(command, result),
        "exited_cleanly": result["success"],
    }


# The checks the output comparisons contribute, named for the row a reviewer
# reads in the report and in the step summary.
_SPEC_CHECK = "Spec compatibility"
_CATALOG_SCHEMA_CHECK = "Catalog schema"
_FINAL_STATE_CHECK = "Final state per stream"

# How many individual changes a check's one-line summary names before it says
# how many more there are. The full list is in the report and in the run's JSON
# payload, and the comparators order their findings worst-first, so the ones
# named here are the ones worth naming.
_MAX_LISTED_CHANGES = 3

# How many changes the JSON payload lists per comparison. Same reason as
# `_MAX_DIFF_PAYLOAD_CHARS`: the payload is written to `GITHUB_OUTPUT`, and a
# reordered `oneOf` on a wide spec produces hundreds of sentences.
_MAX_PAYLOAD_CHANGES = 100

# How many per-stream entries it lists. A wide source has thousands of streams,
# and one line each is enough to exceed the same output budget without a single
# diff being attached.
_MAX_PAYLOAD_STREAMS = 100

# How much of a comparison's detail the run's JSON payload carries. That payload
# is written to `GITHUB_OUTPUT`, which is size-limited, and a wide connector's
# catalog diff has no natural bound -- so the payload keeps as many stream diffs
# as fit and says how many it dropped. The catalogs themselves are saved
# artifacts, which is where an unbounded diff belongs.
_MAX_DIFF_PAYLOAD_CHARS = 50_000


def _compare_outputs(
    *,
    command: str,
    outcome: ComparisonOutcome,
    control_outputs: ComparableOutputs,
    target_outputs: ComparableOutputs,
) -> tuple[tuple[CheckResult, ...], tuple[DiffBlock, ...], dict[str, Any]]:
    """Compare what the two versions produced, for the commands that produce it.

    This is the content check for `spec`, `discover` and `read`: without it their
    verdict is the exit code, and a connector that drops a config field, changes
    a stream's schema or corrupts the state the next sync resumes from exits 0
    all the way to a release. `check` reports its own status, so it is the one
    command with nothing to diff here.

    Only runs when both commands succeeded. A failed run has nothing to compare,
    and reporting "no spec to compare" beside the command failure that caused it
    would state the same problem twice, in weaker terms the second time.

    A comparator that raises is left to propagate. The comparators normalise what
    they are given, so the only ways here are a programming error in a future
    caller or a schema nested past the recursion limit -- and the workflow
    already has the right vocabulary for both: a step that dies is an
    `internal_failure`, reported as infrastructure rather than as a regression,
    with the connector's artifacts uploaded either way. Catching it here would
    only let a tooling bug read as "the new version broke its spec".

    Args:
        command: The Airbyte command that was run, as the CLI names it. This is
            always `"read"` for a read, including one given a state file: the
            `READ` -> `READ_WITH_STATE` upgrade only changes the `Command` the
            container is run with.
        outcome: The already-evaluated command outcome.
        control_outputs: What the control version produced.
        target_outputs: What the target version produced.

    Returns:
        The checks to fold into the verdict, the diff blocks that show what they
        found, and the comparison detail for the run's JSON payload -- all empty
        when there was nothing to compare.
    """
    if not outcome.success:
        return (), (), {}

    if command == "spec":
        return _spec_comparison(control_outputs.spec, target_outputs.spec)

    if command == "discover":
        return _catalog_comparison(control_outputs.catalog, target_outputs.catalog)

    if command == "read":
        return _final_state_comparison(
            control_outputs.final_states, target_outputs.final_states
        )

    return (), (), {}


def _spec_comparison(
    control_spec: Any, target_spec: Any
) -> tuple[tuple[CheckResult, ...], tuple[DiffBlock, ...], dict[str, Any]]:
    """Run the spec comparison and shape it for every surface."""
    result = compare_specs(control_spec, target_spec)

    check = CheckResult(
        name=_SPEC_CHECK,
        passed=result.passed,
        summary=_change_summary(
            result.message,
            # A passing spec check still says what was added: an additive change
            # is the thing a reviewer most wants to see confirmed.
            result.errors if result.errors else result.warnings,
        ),
        details=tuple(result.errors),
    )
    # The incompatible changes are the check's `details`, which the report renders
    # under the check row and the step summary lists -- a block would repeat them.
    # The compatible ones have nowhere else to go, and a reviewer asking "what
    # else moved?" is asking about exactly those.
    blocks = tuple(
        block
        for block in (
            _change_block("Spec — compatible changes", result.warnings, "add"),
        )
        if block is not None
    )

    return (check,), blocks, {"spec": _spec_detail(result)}


def _catalog_comparison(
    control_catalog: Any, target_catalog: Any
) -> tuple[tuple[CheckResult, ...], tuple[DiffBlock, ...], dict[str, Any]]:
    """Run the discovered-catalog comparison and shape it for every surface."""
    result = compare_catalog_schemas(control_catalog, target_catalog)

    check = CheckResult(
        name=_CATALOG_SCHEMA_CHECK,
        passed=result.passed,
        # A catalog that only grew -- new streams, new fields, nothing removed
        # or retyped -- is reported and does not gate the release. Connectors
        # add streams constantly, and a check that goes red on every one of them
        # is a check people learn to click past.
        severity="diagnostic" if result.additive_only else "strict",
        summary=_change_summary(result.message, result.errors),
        details=tuple(result.errors),
    )

    # The findings themselves are the check's `details`, which the report renders
    # under the check row: a stream that is missing or new has no schema diff, so
    # that list is the only place it appears.
    blocks = _stream_diff_blocks(
        result,
        block_title="Schema diff",
        omission_title="Schema diffs omitted for size",
        artifact_hint=(
            "Both discovered catalogs are in the artifact, under "
            "airbyte_messages/catalog.jsonl."
        ),
    )

    return (check,), blocks, {"catalog_schema": _catalog_schema_detail(result)}


def _final_state_comparison(
    control_states: dict[tuple[str | None, str], Any] | None,
    target_states: dict[tuple[str | None, str], Any] | None,
) -> tuple[tuple[CheckResult, ...], tuple[DiffBlock, ...], dict[str, Any]]:
    """Run the final-state comparison and shape it for every surface."""
    result = compare_final_states(control_states, target_states)

    # Structural findings first, then the value-only ones: the check lists
    # everything it found, and the summary quotes the front of that list.
    findings = [*result.errors, *result.warnings]

    check = CheckResult(
        name=_FINAL_STATE_CHECK,
        passed=result.passed,
        # Two ways a non-passing state check does not gate. A cursor that only
        # advanced: until HTTP replay lands, the two versions call the live API
        # in separate runs and a timestamp cursor moves between them on its own.
        # And a read with no state on either side, where there was nothing to
        # compare rather than something wrong.
        severity=(
            "diagnostic" if result.value_only or result.inconclusive else "strict"
        ),
        summary=_change_summary(result.message, findings),
        details=tuple(findings),
    )

    blocks = _stream_diff_blocks(
        result,
        block_title="Final state diff",
        omission_title="Final state diffs omitted for size",
        artifact_hint=(
            "Both versions' state messages are in the artifact, under "
            "airbyte_messages/state.jsonl."
        ),
    )

    return (check,), blocks, {"final_state": _final_state_detail(result)}


def _stream_diff_blocks(
    result: ComparisonResult,
    *,
    block_title: str,
    omission_title: str,
    artifact_hint: str,
) -> tuple[DiffBlock, ...]:
    """One block per changed stream, within the report's diff budget.

    In comparison order -- only a *changed* stream has a diff, so there is no
    severity left to sort by here -- and within the same budget the payload uses:
    a report that inlines every schema of a 200-stream source is not a report
    anyone reads. What the budget drops is named rather than skipped, since a
    block that is simply absent reads as "there was nothing to see".
    """
    blocks: list[DiffBlock] = []
    budget = _MAX_DIFF_PAYLOAD_CHARS
    dropped: list[str] = []

    for name in result.failed_streams:
        stream = result.stream_results[name]
        if not stream.schema_diff:
            continue

        payload = json.dumps(stream.schema_diff, indent=2, sort_keys=True)
        if len(payload) > budget:
            dropped.append(name)
            continue

        budget -= len(payload)
        blocks.append(build_json_block(f"{block_title} — {name}", payload))

    if dropped:
        blocks.append(
            build_diff_block(
                omission_title,
                [
                    DiffLine(
                        kind="meta",
                        text=(
                            "These streams changed, and their diffs were too "
                            f"large for this report. {artifact_hint}"
                        ),
                    ),
                    *(DiffLine(kind="del", text=name) for name in dropped),
                ],
                language="text",
            )
        )

    return tuple(blocks)


def _change_block(title: str, changes: list[str], kind: str) -> DiffBlock | None:
    """One diff block listing a comparison's findings, or `None` if there are none."""
    if not changes:
        return None

    return build_diff_block(
        title,
        [DiffLine(kind=kind, text=change) for change in changes],
        language="text",
    )


def _change_summary(message: str, changes: list[str]) -> str:
    """One line: what the comparison concluded, and the first few reasons."""
    if not changes:
        return message

    listed = "; ".join(changes[:_MAX_LISTED_CHANGES])
    remaining = len(changes) - _MAX_LISTED_CHANGES
    if remaining > 0:
        listed = f"{listed}; and {remaining} more"

    return f"{message}: {listed}"


def _bounded_changes(changes: list[str]) -> list[str]:
    """A change list the JSON payload can carry, saying what it left out."""
    if len(changes) <= _MAX_PAYLOAD_CHANGES:
        return changes

    dropped = len(changes) - _MAX_PAYLOAD_CHANGES

    return [
        *changes[:_MAX_PAYLOAD_CHANGES],
        f"... and {dropped} more, in the report and the console output",
    ]


def _spec_detail(result: ComparisonResult) -> dict[str, Any]:
    """The spec comparison, for the run's JSON payload."""
    return {
        "passed": result.passed,
        "message": result.message,
        "breaking_changes": _bounded_changes(result.errors),
        "compatible_changes": _bounded_changes(result.warnings),
    }


def _catalog_schema_detail(result: ComparisonResult) -> dict[str, Any]:
    """The catalog comparison, for the run's JSON payload."""
    streams, omitted, dropped = _bounded_stream_diffs(
        result,
        omission_note="Too large for this payload; diff the catalogs",
        artifact_hint="Both discovered catalogs are in the saved artifacts.",
    )

    detail: dict[str, Any] = {
        "passed": result.passed,
        # Why a `passed: false` did not fail the run: everything found was an
        # addition, which is reported as a warning rather than a regression.
        "additive_only": result.additive_only,
        "message": result.message,
        "changed_streams": _bounded_changes(result.failed_streams),
        "streams": streams,
    }
    if omitted:
        detail["streams_with_omitted_diffs"] = omitted
    if dropped:
        detail["streams_omitted"] = dropped

    return detail


def _final_state_detail(result: ComparisonResult) -> dict[str, Any]:
    """The final-state comparison, for the run's JSON payload."""
    streams, omitted, dropped = _bounded_stream_diffs(
        result,
        omission_note="Too large for this payload; diff the state messages",
        artifact_hint="Both versions' state messages are in the saved artifacts.",
    )

    detail: dict[str, Any] = {
        "passed": result.passed,
        # The two reasons a `passed: false` did not fail the run, kept apart so
        # the payload never says "every state that moved moved in value only"
        # about a read where nothing moved because nothing was compared.
        "value_only": result.value_only,
        "inconclusive": result.inconclusive,
        "message": result.message,
        "changed_streams": _bounded_changes(result.failed_streams),
        "streams": streams,
    }
    if omitted:
        detail["streams_with_omitted_diffs"] = omitted
    if dropped:
        detail["streams_omitted"] = dropped

    return detail


def _bounded_stream_diffs(
    result: ComparisonResult,
    *,
    omission_note: str,
    artifact_hint: str,
) -> tuple[dict[str, Any], list[str], int]:
    """A comparison's per-stream verdicts and diffs, sized for the JSON payload.

    Every stream that changed is named with its verdict -- so the payload says
    what moved, not just that something did -- while the diffs themselves are
    kept only while they fit in `_MAX_DIFF_PAYLOAD_CHARS`, and the number of
    entries is capped in turn: a thousand-stream source would otherwise put a
    thousand of them into `GITHUB_OUTPUT`. Both bounds say what they dropped,
    on the console and in the payload: a bound nobody mentions reads as "there
    was nothing more to see".
    """
    streams: dict[str, Any] = {}
    omitted: list[str] = []
    budget = _MAX_DIFF_PAYLOAD_CHARS

    # Non-passing first, so the cap falls on the streams with nothing to say.
    ordered = sorted(result.stream_results.items(), key=lambda item: item[1].passed)
    kept, dropped_entries = (
        ordered[:_MAX_PAYLOAD_STREAMS],
        ordered[_MAX_PAYLOAD_STREAMS:],
    )

    for name, stream in kept:
        entry: dict[str, Any] = {"passed": stream.passed, "message": stream.message}
        streams[name] = entry

        if not stream.schema_diff:
            continue

        rendered = len(json.dumps(stream.schema_diff, separators=(",", ":")))
        if rendered > budget:
            omitted.append(name)
            entry["diff_omitted"] = omission_note
            continue

        budget -= rendered
        entry["diff"] = stream.schema_diff

    if omitted:
        print_warning(
            f"Comparison detail for {len(omitted)} streams was too large for the "
            f"run's JSON output ({', '.join(omitted)}); their diffs are omitted "
            f"there. {artifact_hint}"
        )

    if dropped_entries:
        print_warning(
            f"The run's JSON output lists {_MAX_PAYLOAD_STREAMS} of "
            f"{len(ordered)} streams, changed ones first. The report carries "
            f"them all. {artifact_hint}"
        )

    return streams, omitted, len(dropped_entries)


def _build_connector_image_from_source(
    connector_name: str,
    repo_root: Path | None = None,
    tag: str = "dev",
    *,
    prefer_repo_root: bool = False,
) -> str | None:
    """Build a connector image from source code.

    Args:
        connector_name: Name of the connector (e.g., 'source-pokeapi').
        repo_root: Optional path to the airbyte repo root. If not provided,
            will attempt to auto-detect from current directory.
        tag: Tag to apply to the built image (default: 'dev').
        prefer_repo_root: Use `repo_root` even when auto-discovery would find
            a connector directory. Reproduction cases set it: auto-discovery
            searches from the working directory and can pick up a different
            airbyte checkout on the machine, silently building the wrong source.

    Returns:
        The full image name with tag if successful, None if build fails.
    """
    if not verify_docker_installation():
        print_error("Docker is not installed or not running")
        return None

    connector_directory: Path | None = None
    if not (prefer_repo_root and repo_root):
        with suppress(FileNotFoundError):
            connector_directory = find_connector_root_from_name(connector_name)
    if connector_directory is None:
        if repo_root:
            connector_directory = repo_root / CONNECTORS_SUBDIR / connector_name
            if not connector_directory.exists():
                print_error(f"Connector directory not found: {connector_directory}")
                return None
        else:
            print_error(
                f"Could not find connector '{connector_name}'. "
                "Try providing --repo-root to specify the airbyte repo location."
            )
            return None
    metadata_file_path = connector_directory / "metadata.yaml"
    if not metadata_file_path.exists():
        print_error(f"metadata.yaml not found at {metadata_file_path}")
        return None

    metadata = MetadataFile.from_file(metadata_file_path)
    print_success(f"Building image for connector: {connector_name}")

    built_image = build_connector_image(
        connector_name=connector_name,
        connector_directory=connector_directory,
        metadata=metadata,
        tag=tag,
        no_verify=False,
    )
    print_success(f"Successfully built image: {built_image}")
    return built_image


def _fetch_control_image_from_metadata(connector_name: str) -> str | None:
    """Fetch the current released connector image from metadata.yaml on main branch.

    This fetches the connector's metadata.yaml from the airbyte monorepo's master branch
    and extracts the dockerRepository and dockerImageTag to construct the control image.

    Args:
        connector_name: The connector name (e.g., 'source-github').

    Returns:
        The full connector image with tag (e.g., 'airbyte/source-github:1.0.0'),
        or None if the metadata could not be fetched or parsed.
    """
    metadata_url = (
        f"https://raw.githubusercontent.com/airbytehq/airbyte/master/"
        f"airbyte-integrations/connectors/{connector_name}/metadata.yaml"
    )
    response = requests.get(metadata_url, timeout=30)
    if not response.ok:
        print_error(
            f"Failed to fetch metadata for {connector_name}: "
            f"HTTP {response.status_code} from {metadata_url}"
        )
        return None

    metadata = yaml.safe_load(response.text)
    if not isinstance(metadata, dict):
        print_error(f"Invalid metadata format for {connector_name}: expected dict")
        return None

    data = metadata.get("data", {})
    docker_repository = data.get("dockerRepository")
    docker_image_tag = data.get("dockerImageTag")

    if not docker_repository or not docker_image_tag:
        print_error(
            f"Could not find dockerRepository/dockerImageTag in metadata for {connector_name}"
        )
        return None

    return f"{docker_repository}:{docker_image_tag}"


def _run_with_optional_http_metrics(
    connector_image: str,
    command: Command,
    output_dir: Path,
    target_or_control: TargetOrControl,
    enable_http_metrics: bool,
    config_path: Path | None,
    catalog_path: Path | None,
    state_path: Path | None,
    enable_debug_logs: bool = False,
    extra_env: dict[str, str] | None = None,
    replay_expected: bool = False,
    replay_from: Path | None = None,
    replay_options: ReplayOptions | None = None,
    stream_large_bodies: str = DEFAULT_STREAM_LARGE_BODIES,
) -> tuple[dict, ComparableOutputs]:
    """Run a connector command with optional HTTP metrics capture.

    When enable_http_metrics is True, starts mitmproxy to capture HTTP traffic.
    If mitmproxy fails to start, falls back to running without metrics.

    Args:
        connector_image: Full connector image name with tag.
        command: The Airbyte command to run.
        output_dir: Directory to store output files.
        target_or_control: Whether this is target or control version.
        enable_http_metrics: Whether to capture HTTP metrics via mitmproxy.
        config_path: Path to connector config JSON file.
        catalog_path: Path to configured catalog JSON file.
        state_path: Path to state JSON file.
        enable_debug_logs: If `True`, pass `LOG_LEVEL=DEBUG` to the connector container.
        extra_env: Additional environment variables for the connector container.
        replay_expected: Whether this run was *meant* to replay. Separate from
            `replay_from`, which is only non-None once a recording actually
            exists -- when the proxy is unavailable there is no recording to
            point at, and that is exactly the case that has to be reported.
        replay_from: A previous run's HTTP dump to serve responses from, so this
            run sees the same upstream data the recorded one did. Requires
            `enable_http_metrics`; ignored without it.
        replay_options: Replay tuning; defaults apply when omitted.
        stream_large_bodies: Body-size threshold above which mitmproxy streams
            rather than records a body.

    Returns:
        What `_run_connector_command` returns, with `http_metrics` added to the
        results dict when they were captured -- plus `http_dump_file`, the dump
        this run recorded, which is what a subsequent run replays from.
    """
    if not enable_http_metrics:
        return _run_connector_command(
            connector_image=connector_image,
            command=command,
            output_dir=output_dir,
            target_or_control=target_or_control,
            config_path=config_path,
            catalog_path=catalog_path,
            state_path=state_path,
            enable_debug_logs=enable_debug_logs,
            extra_env=extra_env,
        )

    # The manager rather than `MitmproxyManager.start`: the reason a startup
    # failed and the fact that a shutdown had to be killed are only reachable
    # through it -- there is no session to carry the first, and the second is
    # not known until the session is gone.
    manager = MitmproxyManager(
        output_dir,
        replay_from=replay_from,
        replay_options=replay_options,
        stream_large_bodies=stream_large_bodies,
    )
    with manager.running() as session:
        if session is None:
            startup_failure = (
                manager.startup_failure_reason or "mitmproxy is unavailable"
            )
            print_error(
                f"Mitmproxy unavailable ({startup_failure}), "
                "running without HTTP metrics"
            )
            result, comparable = _run_connector_command(
                connector_image=connector_image,
                command=command,
                output_dir=output_dir,
                target_or_control=target_or_control,
                config_path=config_path,
                catalog_path=catalog_path,
                state_path=state_path,
                enable_debug_logs=enable_debug_logs,
                extra_env=extra_env,
            )
            if replay_expected:
                # The one skip path that produces no session, and so reported
                # nothing at all: no metrics, no reason, an ordinary green
                # comparison against live data. Keyed on `replay_expected` and
                # not on `replay_from`: when mitmdump is missing the *control*
                # run records no dump either, so there is nothing to point at
                # and the condition that looks natural here is never true in
                # the failure it defends against.
                #
                # The precise reason, not a fixed "mitmproxy is unavailable":
                # `wait_for_proxy_listener` distinguishes a proxy that died on
                # startup and a corpus that took longer than its ceiling to
                # load, and those point at a code fix where the hardcoded
                # string tells a reader to install mitmproxy.
                result["http_metrics"] = {
                    "replay_skipped_reason": (
                        f"{startup_failure}, so nothing could be replayed"
                    )
                }
            return result, comparable

        if session.replay_source:
            print_success(
                f"Started mitmproxy on {session.proxy_url} "
                f"(replaying {session.replay_source}, "
                f"{session.unreplayable_flow_count} flow(s) not replayable)"
            )
        else:
            print_success(f"Started mitmproxy on {session.proxy_url}")
            if session.replay_skipped_reason:
                print_warning(
                    f"HTTP replay unavailable ({session.replay_skipped_reason}); "
                    "this run hits the live API, so it cannot be compared against "
                    "identical upstream data"
                )

        result, comparable = _run_connector_command(
            connector_image=connector_image,
            command=command,
            output_dir=output_dir,
            target_or_control=target_or_control,
            config_path=config_path,
            catalog_path=catalog_path,
            state_path=state_path,
            proxy_url=session.proxy_url,
            ca_cert_path=session.ca_cert_path,
            enable_debug_logs=enable_debug_logs,
            extra_env=extra_env,
        )

        # The path, not the metrics: this is what the next run replays from.
        result["http_dump_file"] = str(session.dump_file_path)

        # Everything the metrics are built from, carried out of the block. The
        # dump itself cannot be read here: mitmproxy's `save` addon writes each
        # flow through a block-buffered file and only flushes and closes it in
        # `done()`, holding in-flight flows until shutdown -- so parsing inside
        # the `with` misses the buffered tail, and `live_flow_count` is the
        # feature's acceptance criterion, not a rough count.
        dump_file_path = session.dump_file_path
        replay_source = session.replay_source
        replay_skipped_reason = session.replay_skipped_reason
        unreplayable_flow_count = session.unreplayable_flow_count

    http_metrics = parse_http_dump(dump_file_path, replay_source)
    metrics_payload: dict[str, object] = {
        "flow_count": http_metrics.flow_count,
        "duplicate_flow_count": http_metrics.duplicate_flow_count,
        # Carried into the report because it is the number that tells a
        # reviewer whether a record difference is a real regression or
        # upstream drift. Today it is a duplicate-URL heuristic; it only
        # becomes exact once HTTP replay lands.
        "cache_hits_count": http_metrics.cache_hits_count,
        "cache_hit_ratio": http_metrics.cache_hit_ratio,
        # On a replaying target run, `live_flow_count` is the acceptance
        # criterion for replay -- so it belongs in the report rather than
        # only in the raw dump.
        "replayed_flow_count": http_metrics.replayed_flow_count,
        "live_flow_count": http_metrics.live_flow_count,
        "replay_hit_ratio": http_metrics.replay_hit_ratio,
    }
    if replay_from is not None:
        # Keyed on replay having been *asked* for, not on a corpus having
        # survived: when every recorded flow is unreplayable there is no
        # corpus, and that is exactly the run whose dropped count matters.
        # Poor replay coverage is usually this, and the fix is a bigger
        # `--http-replay-max-body`.
        metrics_payload["unreplayable_flow_count"] = unreplayable_flow_count
    if replay_source:
        metrics_payload["replay_source"] = str(replay_source)
        # Only on a replaying run, where a live request is a request the corpus
        # could not answer and so the one thing that explains a coverage
        # shortfall. On a recording run every request is live, so the same list
        # would be a request log, which is not a surface to widen for no
        # diagnostic gain. Query-parameter values are masked either way -- these
        # URLs reach the step summary, the workflow log and `report.html`, and
        # plenty of APIs put credentials in the query string; see `redact_url`.
        live_urls = http_metrics.top_live_urls()
        if live_urls:
            metrics_payload["live_urls"] = live_urls
            metrics_payload["live_unique_url_count"] = len(http_metrics.live_url_counts)
    if manager.metrics_incomplete_reason:
        # Read after the block, not inside it: a killed shutdown is only known
        # once `_stop` has run. Recorded because every count below is then a
        # lower bound -- and short in the direction that makes a run look closer
        # to the replay acceptance criterion than it was.
        metrics_payload["metrics_incomplete"] = manager.metrics_incomplete_reason
    skipped_reason = replay_skipped_reason
    if replay_expected and replay_source is None and not skipped_reason:
        # The proxy came up but there was no recording to replay -- the
        # control run captured nothing. Same outcome as any other skip, so
        # it has to read the same way rather than as a clean replayed run.
        skipped_reason = "the control run recorded no HTTP dump to replay from"
    if skipped_reason:
        metrics_payload["replay_skipped_reason"] = skipped_reason
    result["http_metrics"] = metrics_payload

    print_success(
        f"Captured {http_metrics.flow_count} HTTP flows "
        f"({http_metrics.duplicate_flow_count} duplicates)"
    )
    if replay_source:
        print_success(
            f"Replayed {http_metrics.replayed_flow_count} of "
            f"{http_metrics.flow_count} request(s) "
            f"({http_metrics.replay_hit_ratio}); "
            f"{http_metrics.live_flow_count} went live"
        )
    return result, comparable


def _discard_oversized_http_dumps(*results: dict, max_bytes: int) -> None:
    """Drop recorded dumps too large to keep, and say so in the report.

    "Too large to keep" is about the runner's disk, not the artifact upload:
    dumps are excluded from every upload step regardless of size.

    Deleting is not silent: the size that was discarded lands in the run's
    `http_metrics`, so a reader looking for the dump learns why it is not there
    instead of finding a dangling path.
    """
    for result in results:
        dump_file = result.get("http_dump_file")
        if not dump_file:
            continue

        discarded = discard_oversized_dump(Path(dump_file), max_bytes)
        if discarded is None:
            continue

        result.pop("http_dump_file", None)
        metrics = result.get("http_metrics")
        if isinstance(metrics, dict):
            metrics["discarded_dump_mb"] = round(discarded / 1024 / 1024)
        print_warning(
            f"Discarded {dump_file}: {discarded / 1024 / 1024:.0f} MB exceeds the "
            "retention cap, and a dump this large is what fills the runner's disk. "
            "Dumps are never uploaded as artifacts; raise "
            "--http-replay-max-dump-size-mb to keep it for a local run"
        )


def _compare_read_records(
    target_result: dict,
    control_result: dict,
    catalog_file: Path | None,
) -> tuple[RecordComparisonSummary | None, str | None]:
    """Run record-level comparisons between control and target read outputs.

    Uses primary keys from the configured catalog (source-defined primary
    keys come from the discovered catalog) to compare record counts, PK
    presence, PK integrity, and field values. Streams without a primary key
    fall back to a directional record count comparison.

    Each run's stdout is first split into per-stream record files (a single
    streaming pass), and the comparison then loads one stream at a time, so
    memory stays bounded by the largest stream instead of the full output
    of both runs. The per-stream files land next to each run's stdout and
    double as debugging artifacts. Within one stream, both sides are
    materialized as parsed messages plus dict copies plus PK indexes --
    measured at roughly 13 bytes resident per byte of record JSON, so a
    single stream of ~500 MB of records is the practical ceiling on a
    standard 7 GB runner. Start here when debugging an OOM.

    Returns:
        `(summary, skip_reason)`. The summary is None when the comparison
        cannot run at all -- then `skip_reason` says why, so the caller can
        surface a diagnostic check instead of letting the run read as a pass
        that compared records. An unexpected error during the comparison
        itself returns a FAILED summary instead of raising: by this point
        both (expensive, live-API) runs have completed, and a comparison bug
        must fail the verdict, not destroy the run's outputs and reports.
    """
    if catalog_file is None or not catalog_file.exists():
        reason = "no configured catalog available"
        print_warning(f"Skipping record-level comparison: {reason}")
        return None, reason

    try:
        configured_catalog = ConfiguredAirbyteCatalog.model_validate_json(
            catalog_file.read_text()
        )
    except Exception as exc:
        reason = f"configured catalog could not be parsed ({exc})"
        print_warning(f"Skipping record-level comparison: {reason}")
        return None, reason

    try:
        primary_keys = get_primary_keys_per_stream(configured_catalog)
        # A stream name that repeats across namespaces merges two streams in
        # this name-keyed pipeline; those names degraded to count-only above,
        # and the reader must hear why from the summary, not just stdout.
        collision_warnings = [
            f"Stream name {name!r} appears in more than one namespace; the "
            "record comparison keys streams by name, so its records are "
            "compared by count only"
            for name in duplicate_stream_names(configured_catalog)
        ]
        control_record_files = split_records_per_stream(
            Path(control_result["stdout_file"])
        )
        target_record_files = split_records_per_stream(
            Path(target_result["stdout_file"])
        )

        summary = run_record_comparisons_from_files(
            control_record_files=control_record_files,
            target_record_files=target_record_files,
            primary_keys_per_stream=primary_keys,
        )
        summary.warnings[:0] = collision_warnings
    except Exception as exc:
        summary = RecordComparisonSummary(
            passed=False,
            errored=True,
            count_comparison=ComparisonResult(
                passed=False, message="Record comparison errored"
            ),
            errors=[f"Record comparison errored: {exc!r}"],
        )

    if summary.passed:
        print_success("Record comparison passed (counts, PKs, field values)")
    else:
        print_error("Record comparison failed:")
        for error in summary.errors[:20]:
            print_error(f"  - {error}")
    for warning in summary.warnings[:20]:
        print_warning(warning)

    return summary, None


