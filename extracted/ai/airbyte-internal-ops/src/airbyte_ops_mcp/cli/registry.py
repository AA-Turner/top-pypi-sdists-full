@store_app.command(name="compile")
def compile_cmd(
    store: Annotated[
        str,
        Parameter(
            help="Store target (e.g. 'coral:dev', 'coral:prod', 'coral:dev/prefix').",
        ),
    ],
    *,
    output_store: Annotated[
        str | None,
        Parameter(
            help="Write compiled artifacts to `<registry>:local:<path>`; omit the path to allocate a temporary directory.",
        ),
    ] = None,
    connector_name: Annotated[
        tuple[str, ...] | None,
        Parameter(
            help="Only compile these connectors (can be repeated).",
        ),
    ] = None,
    dry_run: Annotated[
        bool,
        Parameter(help="Show what would be done without writing."),
    ] = False,
    with_secrets_mask: Annotated[
        bool,
        Parameter(
            help=(
                "Also regenerate specs_secrets_mask.yaml by scanning all "
                "connector specs for airbyte_secret properties."
            ),
        ),
    ] = False,
    with_legacy_migration: Annotated[
        str | None,
        Parameter(
            help=(
                "Run a one-time legacy migration step during compile. "
                "Currently supported: 'v1' — delete cloud.json / oss.json "
                "files for connectors whose registryOverrides.cloud.enabled "
                "or registryOverrides.oss.enabled is false. This cleans up "
                "artifacts produced by the legacy pipeline that did not "
                "respect the enabled flag."
            ),
        ),
    ] = None,
    with_metrics: Annotated[
        bool,
        Parameter(
            help=(
                "Inject latest connector quality metrics from the analytics "
                "JSONL export into generated.metrics."
            ),
            negative="--no-metrics",
        ),
    ] = True,
    force: Annotated[
        bool,
        Parameter(
            help=(
                "Force resync of latest/ directories even if version markers are current. "
                "Useful when metadata changes without a version bump."
            ),
        ),
    ] = False,
    with_full_restate: Annotated[
        bool,
        Parameter(
            help=(
                "Re-derive every version's release attribution from metadata.yaml. "
                "Expensive for all connectors (~33.5k reads). Without "
                "--release-attribution-index, historical blocks unavailable "
                "from metadata.yaml are discarded."
            ),
            negative="--no-full-restate",
        ),
    ] = False,
    release_attribution_index: Annotated[
        Path | None,
        Parameter(
            help=(
                "Seed missing release blocks from a Phase 1 attribution index "
                "without rewriting historical metadata.yaml files."
            ),
        ),
    ] = None,
) -> None:
    """Compile the registry: sync latest/ dirs, write global and per-connector indexes.

    Scans all version directories in the target store, determines the latest GA
    semver per connector (excluding yanked and pre-release versions), ensures
    each `latest/` directory matches the computed latest, and writes:

    * `registries/v0/cloud_registry.json` -- global cloud registry index
    * `registries/v0/oss_registry.json`   -- global OSS registry index
    * `metadata/airbyte/<connector>/versions.json` -- per-connector version index

    With `--with-secrets-mask`, also regenerates:

    * `registries/v0/specs_secrets_mask.yaml` -- properties marked as secrets

    With `--with-legacy-migration=v1`, deletes `cloud.json` / `oss.json`
    files for connectors whose `registryOverrides.cloud.enabled` or
    `registryOverrides.oss.enabled` is `false`.

    By default, injects connector quality metrics from the latest analytics
    JSONL export into `generated.metrics`. Use `--no-metrics` for offline
    scenarios.

    With `--force`, resyncs all latest/ directories even if the version marker
    matches the computed latest version.

    With `--with-full-restate`, re-reads every version's metadata.yaml to
    re-derive release attribution. This is an expensive operation at roughly
    33.5k reads for the full registry.

    With `--release-attribution-index`, seeds historical `release` blocks
    directly into versions.json from a Phase 1 Git backfill index.

    Uses efficient glob patterns for scanning (no file downloads during discovery).

    Requires GCS_CREDENTIALS environment variable to be set.

    Examples:
        airbyte-ops registry store compile --store coral:dev --dry-run

        airbyte-ops registry store compile --store coral:dev/aj-test100 \\
            --connector-name source-faker --connector-name destination-bigquery

        airbyte-ops registry store compile --store coral:prod --with-secrets-mask

        airbyte-ops registry store compile --store coral:dev \\
            --with-legacy-migration v1
    """
    registry = _resolve_store(store)
    parsed_output_store = (
        RegistryStore.parse(output_store) if output_store is not None else None
    )
    if parsed_output_store is not None and parsed_output_store.env != "local":
        exit_with_error(
            "--output-store must use `<registry>:local:<path>`; an empty path allocates a temporary directory."
        )

    result = registry.compile(
        output_store=parsed_output_store,
        connector_name=list(connector_name) if connector_name else None,
        dry_run=dry_run,
        with_secrets_mask=with_secrets_mask,
        with_legacy_migration=with_legacy_migration,
        with_metrics=with_metrics,
        force=force,
        with_full_restate=with_full_restate,
        release_attribution_index=release_attribution_index,
    )

    print_json(
        {
            "status": result.status,
            "target": result.target,
            "connectors_scanned": result.connectors_scanned,
            "versions_found": result.versions_found,
            "yanked_versions": result.yanked_versions,
            "latest_updated": result.latest_updated,
            "latest_already_current": result.latest_already_current,
            "cloud_registry_entries": result.cloud_registry_entries,
            "oss_registry_entries": result.oss_registry_entries,
            "composite_registry_entries": result.composite_registry_entries,
            "metrics_connector_count": result.metrics_connector_count,
            "metrics_registry_entries": result.metrics_registry_entries,
            "metrics_source": result.metrics_source,
            "metrics_error": result.metrics_error,
            "version_indexes_written": result.version_indexes_written,
            "version_indexes_skipped": result.version_indexes_skipped,
            "specs_secrets_mask_properties": result.specs_secrets_mask_properties,
            "errors": result.errors,
            "dry_run": result.dry_run,
        }
    )

    if result.status == "success" or result.status == "dry-run":
        print_success(result.summary())
    else:
        exit_with_error(
            f"Compile completed with {len(result.errors)} error(s): "
            + "; ".join(result.errors),
            code=1,
        )


