@connector_app.command(name="list")
def list_connectors_cmd(
    store: Annotated[
        str,
        Parameter(
            help="Store target (e.g. 'coral:dev', 'coral:prod').",
        ),
    ],
    *,
    certified_only: Annotated[
        bool,
        Parameter(help="Include only certified connectors."),
    ] = False,
    support_level: Annotated[
        SupportLevel | None,
        Parameter(
            help=(
                "Exact support level to match "
                "(e.g. `certified`, `community`, `archived`)."
            )
        ),
    ] = None,
    min_support_level: Annotated[
        SupportLevel | None,
        Parameter(
            help=(
                "Minimum support level (inclusive). "
                "Levels from lowest to highest: `archived`, `community`, `certified`."
            )
        ),
    ] = None,
    connector_type: Annotated[
        ConnectorType | None,
        Parameter(help="Filter by connector type: `source` or `destination`."),
    ] = None,
    language: Annotated[
        ConnectorLanguage | None,
        Parameter(
            help=(
                "Filter by implementation language "
                "(e.g. `python`, `java`, `manifest-only`)."
            )
        ),
    ] = None,
    format: Annotated[
        Literal["json", "text"],
        Parameter(
            help="Output format: 'json' for JSON array, 'text' for newline-separated."
        ),
    ] = "json",
) -> None:
    """List connectors in the registry.

    When filters are applied, reads the compiled `cloud_registry.json` index
    for fast lookups. Without filters, falls back to scanning individual
    metadata blobs (captures all connectors including OSS-only).

    Requires GCS_CREDENTIALS environment variable to be set.
    """
    registry = _resolve_store(store)

    # `--certified-only` is sugar for `--support-level certified`.
    effective_support_level = support_level
    if certified_only:
        if support_level and support_level != SupportLevel.CERTIFIED:
            exit_with_error(
                "`--certified-only` conflicts with `--support-level "
                f"{support_level}`. Use one or the other.",
                code=1,
            )
        effective_support_level = SupportLevel.CERTIFIED

    try:
        connectors = registry.list_connectors(
            support_level=effective_support_level,
            min_support_level=min_support_level,
            connector_type=connector_type,
            language=language,
        )
    except Exception as e:
        exit_with_error(f"Error listing connectors: {e}", code=1)

    if format == "json":
        print_json({"connectors": connectors, "count": len(connectors)})
    else:
        for connector in connectors:
            print(connector)


