@store_app.command(name="delete-dev-latest")
def delete_dev_latest_cmd(
    store: Annotated[
        str,
        Parameter(
            help="Store target (must begin with 'coral:dev').",
        ),
    ],
    *,
    connector_name: Annotated[
        tuple[str, ...] | None,
        Parameter(
            help="Only delete latest/ for these connectors (can be repeated).",
        ),
    ] = None,
    dry_run: Annotated[
        bool,
        Parameter(help="Show what would be done without deleting."),
    ] = False,
) -> None:
    """Delete all latest/ directories from a dev registry store.

    Discovers every connector that has a `latest/` directory and
    deletes each one in parallel using a thread pool.

    This is useful before a full re-compile to prove that latest/
    directories can be correctly regenerated from versioned data.

    Only dev stores are allowed (store must begin with 'coral:dev').

    Requires GCS_CREDENTIALS environment variable to be set.

    Examples:
        airbyte-ops registry store delete-dev-latest --store coral:dev --dry-run

        airbyte-ops registry store delete-dev-latest --store coral:dev/aj-test100

        airbyte-ops registry store delete-dev-latest --store coral:dev \\
            --connector-name source-faker --connector-name destination-bigquery
    """
    if not store.startswith("coral:dev"):
        exit_with_error(
            "delete-dev-latest only supports dev stores "
            f"(store must begin with 'coral:dev', got '{store}').",
            code=1,
        )

    registry = _resolve_store(store)

    result = registry.delete_dev_latest(
        connector_name=list(connector_name) if connector_name else None,
        dry_run=dry_run,
    )

    print_json(
        {
            "status": result.status,
            "target": result.target,
            "connectors_found": result.connectors_found,
            "latest_dirs_deleted": result.latest_dirs_deleted,
            "errors": result.errors,
            "dry_run": result.dry_run,
        }
    )

    if result.status in ("success", "dry-run"):
        print_success(result.summary())
    else:
        exit_with_error(
            f"Delete completed with {len(result.errors)} error(s): "
            + "; ".join(result.errors[:5]),
            code=1,
        )


