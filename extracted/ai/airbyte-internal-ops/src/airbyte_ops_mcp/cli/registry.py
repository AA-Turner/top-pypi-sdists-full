@store_app.command(name="compare")
def compare_cmd(
    store: Annotated[
        str,
        Parameter(
            help="Store target being evaluated (e.g. 'coral:dev/20260306-mirror-compile').",
        ),
    ],
    reference_store: Annotated[
        str,
        Parameter(
            help="Known-good reference store to compare against.",
        ),
    ],
    *,
    connector_name: Annotated[
        tuple[str, ...] | None,
        Parameter(
            help="Only compare these connectors (can be repeated).",
        ),
    ] = None,
    with_artifacts: Annotated[
        bool,
        Parameter(
            help="Compare per-connector artifact files "
            "(metadata.yaml, cloud.json, oss.json, spec.json).",
            negative="--no-artifacts",
        ),
    ] = True,
    with_indexes: Annotated[
        bool,
        Parameter(
            help="Compare global registry index files "
            "(cloud_registry.json, oss_registry.json, composite_registry.json).",
            negative="--no-indexes",
        ),
    ] = True,
    assert_stable: Annotated[
        bool,
        Parameter(help="Make the exit code reflect registry safety assertions only."),
    ] = False,
    with_volatile_fields: Annotated[
        bool,
        Parameter(help="Include default volatile-field differences."),
    ] = False,
    html_report: Annotated[
        Path | None,
        Parameter(help="Write a self-contained HTML report to this path."),
    ] = None,
    text_report: Annotated[
        Path | None,
        Parameter(help="Write a plain-text diff report to this path."),
    ] = None,
) -> None:
    """Compare a store against a reference store and report differences.

    Evaluates the `--store` target against `--reference-store` and reports
    per-connector artifact diffs and global index diffs.

    Requires GCS_CREDENTIALS environment variable to be set.

    Examples:
        airbyte-ops registry store compare --store coral:dev/20260306-mirror \\
            --reference-store coral:prod

        airbyte-ops registry store compare --store coral:dev/my-test \\
            --connector-name source-faker --no-indexes

        airbyte-ops registry store compare --store coral:dev/my-test \\
            --no-artifacts
    """
    store_target = resolve_registry_store(store=store)
    ref_target = resolve_registry_store(store=reference_store)
    either_side_local = store_target.env == "local" or ref_target.env == "local"

    result = compare_stores(
        store=store_target,
        reference=ref_target,
        connector_name=list(connector_name) if connector_name else None,
        with_artifacts=(with_artifacts and not either_side_local),
        with_indexes=with_indexes,
        tolerated_paths=(() if with_volatile_fields else DEFAULT_TOLERATED_PATHS),
    )

    print_json(result.to_dict())
    if text_report is not None:
        write_text_report(result, str(text_report))
    if html_report is not None:
        write_html_report(result, str(html_report))

    if assert_stable and (
        result.connectors_only_in_store
        or result.connectors_only_in_reference
        or result.connectors_latest_forward
        or result.connectors_latest_backward
    ):
        exit_with_error("Registry safety assertions failed.", code=1)

    if result.status == "match":
        print_success(result.summary())
    elif result.status == "differences-found":
        error_console.print(f"[yellow]{result.summary()}[/yellow]")

        # Print a concise per-connector diff summary
        for diff in result.connector_diffs:
            if diff.status in ("only_in_store", "only_in_reference"):
                error_console.print(f"  {diff.connector}: {diff.status}")
            else:
                for ad in diff.artifact_diffs:
                    error_console.print(
                        f"  {diff.connector}/{ad.file}: {ad.status}"
                        + (f" ({ad.details})" if ad.details else "")
                    )

        for idx_diff in result.index_diffs:
            if idx_diff.status != "match":
                error_console.print(
                    f"  [index] {idx_diff.file}: {idx_diff.status}"
                    + (
                        f" (store={idx_diff.entry_count_store},"
                        f" ref={idx_diff.entry_count_reference})"
                        if idx_diff.entry_count_store or idx_diff.entry_count_reference
                        else ""
                    )
                )

        if not assert_stable:
            sys.exit(1)
    else:
        exit_with_error(
            f"Compare completed with {len(result.errors)} error(s): "
            + "; ".join(result.errors[:5]),
            code=1,
        )
