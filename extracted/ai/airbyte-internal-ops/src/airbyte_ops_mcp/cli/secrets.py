"""CLI commands for connector integration-test secrets.

Commands:
    airbyte-ops secrets fetch   - Download connector secrets from GSM into `./secrets/`
    airbyte-ops secrets list    - List connector secrets visible in GSM
    airbyte-ops secrets ci-mask - Emit GitHub Actions `::add-mask::` lines

These commands operate on the connector integration-test secrets stored in
Google Secret Manager (project `dataline-integration-testing` by default).
They are intended to replace the `airbyte-cdk secrets` group in a subsequent
phase; the CDK commands remain functional until that migration lands.

> **Note:** `airbyte-ops devin secret-*` is a different subsystem for
> Devin-internal 1Password on-demand secrets and is unrelated to this group.

## CLI reference

The commands below are regenerated by `poe docs-generate` via cyclopts's
programmatic docs API; see `docs/generate_cli.py`.

.. include:: ../../../docs/generated/cli/secrets.md
   :start-line: 2
"""

from __future__ import annotations

__all__: list[str] = []

from typing import Annotated

from airbyte_cdk.utils.connector_paths import resolve_connector_name_and_directory
from cyclopts import Parameter
from rich.console import Console
from rich.table import Table

from airbyte_ops_mcp.cli._base import App, app
from airbyte_ops_mcp.connector_secrets import (
    DEFAULT_GCP_PROJECT_ID,
    ConnectorSecretWithNoValidVersionsError,
    extract_gcp_secret_name,
    fetch_secret_handles,
    get_gcp_secret_url,
    get_gsm_secrets_client,
    get_secret_filepath,
    get_secrets_dir,
    write_secret_file,
)
from airbyte_ops_mcp.connector_secrets.ci_masks import (
    is_running_in_ci,
    print_ci_secrets_masks,
)

error_console = Console(stderr=True)

secrets_app = App(
    name="secrets", help="Manage connector integration-test secrets in GSM."
)
app.command(secrets_app)

_CONNECTOR_HELP = (
    "Connector name (e.g. 'source-pokeapi') or path to a connector directory. "
    "If omitted, the current working directory is used and must be a connector "
    "directory."
)
_GCP_PROJECT_ID_HELP = (
    "GCP project ID for retrieving integration-test credentials. Defaults to "
    "the `GCP_PROJECT_ID` environment variable, or 'dataline-integration-testing' "
    "when unset."
)


@secrets_app.command(name="fetch")
def fetch(
    connector: Annotated[str | None, Parameter(help=_CONNECTOR_HELP)] = None,
    *,
    gcp_project_id: Annotated[
        str, Parameter(help=_GCP_PROJECT_ID_HELP)
    ] = DEFAULT_GCP_PROJECT_ID,
    print_ci_secrets_masks_flag: Annotated[
        bool | None,
        Parameter(
            name=["--print-ci-secrets-masks"],
            negative=["--no-print-ci-secrets-masks"],
            help=(
                "Emit GitHub Actions `::add-mask::` lines for fetched secrets. "
                "Ignored outside CI (requires the `CI` env var). Defaults to "
                "auto-detection from `CI`."
            ),
        ),
    ] = None,
) -> None:
    """Fetch connector secrets from GSM into the connector's `secrets/` directory.

    Equivalent to the old `airbyte-cdk secrets fetch`. Runs in three steps:

    1. Resolve the connector (from `[CONNECTOR]`, or the cwd).
    2. List GSM secrets labeled `connector=<name>` in `--gcp-project-id`.
    3. Write each secret's latest enabled version to `secrets/<filename>.json`
       (mode `0o600`). The filename comes from the secret's `filename` label,
       or defaults to `config.json`.

    When `--print-ci-secrets-masks` is set (or auto-detected in CI), emits
    GitHub Actions masking commands after writing.
    """
    error_console.print("Fetching secrets...")

    client = get_gsm_secrets_client()
    connector_name, connector_directory = resolve_connector_name_and_directory(
        connector
    )
    secrets_dir = get_secrets_dir(
        connector_directory=connector_directory,
        ensure_exists=True,
    )
    secrets = fetch_secret_handles(
        connector_name=connector_name,
        gcp_project_id=gcp_project_id,
        client=client,
    )

    secret_count = 0
    exceptions: list[ConnectorSecretWithNoValidVersionsError] = []

    for secret in secrets:
        secret_file_path = get_secret_filepath(secrets_dir=secrets_dir, secret=secret)
        try:
            write_secret_file(
                secret=secret,
                client=client,
                file_path=secret_file_path,
                connector_name=connector_name,
                gcp_project_id=gcp_project_id,
            )
        except ConnectorSecretWithNoValidVersionsError as err:
            exceptions.append(err)
            error_console.print(
                f"Failed to retrieve secret '{err.secret_name}': No enabled version found"
            )
            continue

        error_console.print(f"Secret written to: {secret_file_path.absolute()!s}")
        secret_count += 1

    if secret_count == 0 and not exceptions:
        error_console.print(f"No secrets found for connector: '{connector_name}'")

    if exceptions:
        error_console.print(
            f"[red]Failed to retrieve {len(exceptions)} secret(s)[/red]"
        )
        if secret_count == 0:
            raise exceptions[0]

    emit_masks = print_ci_secrets_masks_flag
    if emit_masks is None:
        emit_masks = is_running_in_ci()

    if emit_masks:
        print_ci_secrets_masks(
            secrets_dir=secrets_dir,
            strict_ci_env_check=True,
        )


@secrets_app.command(name="list")
def list_(
    connector: Annotated[str | None, Parameter(help=_CONNECTOR_HELP)] = None,
    *,
    gcp_project_id: Annotated[
        str, Parameter(help=_GCP_PROJECT_ID_HELP)
    ] = DEFAULT_GCP_PROJECT_ID,
) -> None:
    """List connector secrets visible in GSM without downloading any values.

    Prints a Rich table with the secret name (linked to its GCP console page),
    labels, and creation time. Only metadata is read — no secret payloads are
    fetched.
    """
    error_console.print("Scanning secrets...")

    if connector and "/" not in connector and "\\" not in connector:
        connector_name = connector
    else:
        connector_name, _ = resolve_connector_name_and_directory(connector)

    secrets = fetch_secret_handles(
        connector_name=connector_name,
        gcp_project_id=gcp_project_id,
    )
    if not secrets:
        error_console.print(f"No secrets found for connector: '{connector_name}'")
        return

    console = Console()
    console.print(
        f"[green]Secrets for connector '{connector_name}' in project "
        f"'{gcp_project_id}':[/green]"
    )
    table = Table(title=f"'{connector_name}' Secrets")
    table.add_column("Name", justify="left", style="cyan", overflow="fold")
    table.add_column("Labels", justify="left", style="magenta", overflow="fold")
    table.add_column("Created", justify="left", style="blue", overflow="fold")
    for secret in secrets:
        secret_name = extract_gcp_secret_name(secret.name)
        secret_url = get_gcp_secret_url(secret_name, gcp_project_id)
        table.add_row(
            f"[link={secret_url}]{secret_name}[/link]",
            "\n".join(f"{k}={v}" for k, v in secret.labels.items()),
            str(secret.create_time),
        )
    console.print(table)


@secrets_app.command(name="ci-mask")
def ci_mask(
    connector: Annotated[str | None, Parameter(help=_CONNECTOR_HELP)] = None,
) -> None:
    """Emit GitHub Actions `::add-mask::` lines for a connector's fetched secrets.

    Reads every `*.json` file in the connector's local `secrets/` directory and
    prints a mask command for each secret-valued property (matched against the
    canonical
    [`specs_secrets_mask.yaml`](https://connectors.airbyte.com/files/registries/v0/specs_secrets_mask.yaml)
    list). Intended to run inside a GitHub Actions job; refuses to emit output
    when `CI` is unset to prevent accidentally printing secret values locally.

    This subcommand is equivalent to running `airbyte-ops secrets fetch
    --print-ci-secrets-masks` without re-downloading secrets.
    """
    _, connector_directory = resolve_connector_name_and_directory(connector)
    secrets_dir = get_secrets_dir(
        connector_directory=connector_directory,
        ensure_exists=False,
    )
    if not secrets_dir.is_dir():
        error_console.print(
            f"No secrets directory found at {secrets_dir!s}; nothing to mask."
        )
        return

    print_ci_secrets_masks(
        secrets_dir=secrets_dir,
        strict_ci_env_check=True,
    )
