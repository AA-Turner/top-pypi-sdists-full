    /// `cargo test --release -p scai-state-core bench_index_apply_cost -- --ignored --nocapture`
    /// (`SCAI_BENCH_N` sets the document count, default 10k; `SCAI_BENCH_PAD`
    /// adds that many bytes to each document). WAL sizes above
    /// [`WAL_TRUNCATE_BYTES`] read 0: `apply` truncated the WAL.
    #[test]
    #[ignore = "benchmark; run explicitly"]
    fn bench_index_apply_cost() {
        let n: usize = std::env::var("SCAI_BENCH_N")
            .ok()
            .and_then(|v| v.parse().ok())
            .unwrap_or(10_000);
        let pad: usize = std::env::var("SCAI_BENCH_PAD")
            .ok()
            .and_then(|v| v.parse().ok())
            .unwrap_or(0);
        let ids: Vec<String> = (0..n)
            .map(|i| format!("SCHEMA_{}/TABLE/T_{i}.{i:032x}", i % 50))
            .collect();
        // `values` = generation whose indexed values differ from gen 0's.
        let generation = |g: usize, values: bool| -> Vec<String> {
            ids.iter()
                .enumerate()
                .map(|(i, id)| {
                    let mut doc = realistic_doc(id, i, g);
                    doc["pad"] = json!("p".repeat(pad));
                    if values {
                        doc["planning"]["wave"] = json!((i + 1) % 12);
                    }
                    doc.to_string()
                })
                .collect()
        };
        let (gen0, gen1, gen2) = (
            generation(0, false),
            generation(1, false),
            generation(2, true),
        );
        assert!(
            derive(&ids[0], &gen0[0]).regular && derive(&ids[0], &gen2[0]).regular,
            "realistic docs are regular"
        );
        println!(
            "{n} docs, avg {} bytes",
            gen0.iter().map(String::len).sum::<usize>() / n
        );
        fn batch<'a>(ids: &'a [String], docs: &'a [String], f: u64) -> IndexChanges<'a> {
            IndexChanges {
                upserts: ids
                    .iter()
                    .zip(docs)
                    .map(|(id, doc)| row(id, doc, fp(f)))
                    .collect(),
                ..Default::default()
            }
        }
        let wal_size = |db: &Path| {
            let mut wal = db.as_os_str().to_owned();
            wal.push("-wal");
            std::fs::metadata(&wal).map(|m| m.len()).unwrap_or(0)
        };
        for plain in [true, false] {
            let steps = [
                "insert",
                "doc changed",
                "doc + values changed",
                "identical, same fp",
                "identical, new fp",
            ];
            let mut best = [Duration::MAX; 5];
            let mut wal = [0u64; 5];
            for _ in 0..3 {
                let (_dir, db, storage) = new_db();
                if plain {
                    let conn = raw_conn(&db);
                    let names: Vec<String> = conn
                        .prepare("SELECT name FROM sqlite_schema WHERE type = 'index' AND name LIKE 'ix_%'")
                        .unwrap()
                        .query_map([], |r| r.get(0))
                        .unwrap()
                        .collect::<rusqlite::Result<_>>()
                        .unwrap();
                    for name in names {
                        conn.execute(&format!("DROP INDEX {name}"), []).unwrap();
                    }
                }
                for (step, batch) in [
                    batch(&ids, &gen0, 1),
                    batch(&ids, &gen1, 1),
                    batch(&ids, &gen2, 1),
                    batch(&ids, &gen2, 1),
                    batch(&ids, &gen2, 2),
                ]
                .iter()
                .enumerate()
                {
                    storage
                        .with_conn("bench", |c| {
                            c.query_row("PRAGMA wal_checkpoint(TRUNCATE)", [], |_| Ok(()))
                        })
                        .unwrap();
                    let start = std::time::Instant::now();
                    storage.apply(batch).unwrap();
                    best[step] = best[step].min(start.elapsed());
                    wal[step] = wal_size(&db);
                }
            }
            println!(
                "{}:",
                if plain {
                    "no value or fingerprint indexes"
                } else {
                    "index schema"
                }
            );
            for (step, label) in steps.iter().enumerate() {
                println!(
                    "  {label:>20}: {:>8.1?} ({:>5.1} µs/doc), WAL {:>6.1} MiB",
                    best[step],
                    best[step].as_secs_f64() * 1e6 / n as f64,
                    wal[step] as f64 / 1048576.0
                );
            }
        }
        let start = std::time::Instant::now();
        let derived: Vec<Derived> = ids
            .iter()
            .zip(&gen0)
            .map(|(id, doc)| derive(id, doc))
            .collect();
        println!(
            "{:>40}: {:.1} µs/doc (serial)",
            "derive",
            start.elapsed().as_secs_f64() * 1e6 / derived.len() as f64
        );

        // Read side.
        let (_dir, db, storage) = new_db();
        storage.apply(&batch(&ids, &gen0, 1)).unwrap();
        let time = |label: &str, f: &mut dyn FnMut() -> usize| {
            let mut best = Duration::MAX;
            let mut rows = 0;
            for _ in 0..5 {
                let start = std::time::Instant::now();
                rows = f();
                best = best.min(start.elapsed());
            }
            println!("{label:>40}: {rows} rows in {best:.1?}");
        };
        time("fingerprints()", &mut || {
            storage.fingerprints().unwrap().len()
        });
        // The same read with the fingerprint after `doc` (overflow walks).
        raw_conn(&db)
            .execute_batch(
                "CREATE TABLE doc_first (id TEXT PRIMARY KEY NOT NULL, doc TEXT NOT NULL, \
                 fp_size INTEGER NOT NULL, fp_mtime_ns INTEGER NOT NULL, fp_file_id INTEGER NOT NULL); \
                 INSERT INTO doc_first SELECT id, doc, fp_size, fp_mtime_ns, fp_file_id FROM code_units;",
            )
            .unwrap();
        time("fingerprints, doc-first layout", &mut || {
            storage
                .with_conn("bench", |c| {
                    c.prepare("SELECT id, fp_size, fp_mtime_ns, fp_file_id FROM doc_first")?
                        .query_map([], |r| {
                            let fp = (r.get::<_, i64>(1)?, r.get::<_, i64>(2)?, r.get(3)?);
                            Ok((r.get::<_, String>(0)?, fp))
                        })?
                        .collect::<rusqlite::Result<HashMap<String, (i64, i64, i64)>>>()
                        .map(|m| m.len())
                })
                .unwrap()
        });
        time("file_ids()", &mut || storage.file_ids().unwrap().len());
        time("ids()", &mut || storage.ids().unwrap().len());
        let start = std::time::Instant::now();
        for i in 0..1000 {
            storage
                .apply(&IndexChanges {
                    dir_mtime_ns: Some(i),
                    dir_recorded_ns: Some(i),
                    ..Default::default()
                })
                .unwrap();
        }
        println!(
            "{:>40}: {:.1?} each",
            "meta-only apply",
            start.elapsed() / 1000
        );
        time("full keyset scan", &mut || {
            let mut rows = 0;
            storage
                .for_each_chunk(super::super::SCAN_CHUNK, |ids, _| {
                    rows += ids.len();
                    Ok(())
                })
                .unwrap();
            rows
        });
        for (label, p) in [
            (
                "load_candidates wave = 3 (~1/12)",
                Prefilter::In(IndexedField::Wave, vec![IndexValue::Integer(3)]),
            ),
            (
                "load_candidates in scope, not missing",
                Prefilter::And(vec![
                    Prefilter::In(IndexedField::InScope, vec![IndexValue::Integer(1)]),
                    Prefilter::In(IndexedField::IsMissing, vec![IndexValue::Integer(0)]),
                ]),
            ),
            (
                "load_candidates 100 ids",
                Prefilter::In(
                    IndexedField::Id,
                    ids.iter()
                        .step_by((n / 100).max(1))
                        .map(|s| tx(s))
                        .collect(),
                ),
            ),
        ] {
            time(label, &mut || {
                storage
                    .load_candidates(&p, |_, _| ())
                    .unwrap()
                    .map_or(0, |v| v.len())
            });
        }
    }
