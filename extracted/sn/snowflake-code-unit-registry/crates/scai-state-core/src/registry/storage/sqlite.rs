/// Stem of this library's index files: `v{INDEX_FORMAT_VERSION}-{hash}`,
/// where `hash` (8 hex digits) covers what derived values depend on besides
/// this crate's code — the embedded code unit schema and
/// `CURRENT_SCHEMA_VERSION`. The database is `{stem}.db`, its lock
/// `{stem}.db.lock`.
pub(super) fn index_stem() -> &'static str {
    static STEM: OnceLock<String> = OnceLock::new();
    STEM.get_or_init(|| {
        stem_for(
            INDEX_FORMAT_VERSION,
            CODE_UNIT_SCHEMA,
            CURRENT_SCHEMA_VERSION,
        )
    })
}

fn stem_for(format: i64, schema: &str, schema_version: i64) -> String {
    let mut bytes = schema.as_bytes().to_vec();
    bytes.push(0);
    bytes.extend_from_slice(&schema_version.to_le_bytes());
    let hash = xxhash_rust::xxh3::xxh3_64(&bytes);
    format!("v{format}-{:08x}", hash >> 32)
}

/// The database of this library's index in `index_dir`.
pub(super) fn db_path(index_dir: &Path) -> PathBuf {
    index_dir.join(format!("{}.db", index_stem()))
}

/// Delete, best effort, the files in `index_dir` of indexes other than this
/// library's — `v*.db` with its `-wal`, `-shm` and `.lock` — once none of an
/// index's files was modified for [`STALE_INDEX_AGE`] before `now`, and
/// any `*.db.corrupt-*` file of that age. An index whose lock another
/// opener holds is left alone. Never touches this library's live files.
fn remove_stale_files(index_dir: &Path, now: SystemTime) {
    let Ok(entries) = std::fs::read_dir(index_dir) else {
        return;
    };
    let stale = |modified: Option<SystemTime>| {
        modified.is_some_and(|m| now.duration_since(m).is_ok_and(|age| age > STALE_INDEX_AGE))
    };
    let ours = index_stem();
    // Stem → (its files, newest mtime; `None` if any is unknown).
    let mut groups: HashMap<String, (Vec<PathBuf>, Option<SystemTime>)> = HashMap::new();
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let Some((stem, suffix)) = name.split_once(".db") else {
            continue;
        };
        if !stem.starts_with('v') {
            continue;
        }
        let modified = entry.metadata().and_then(|m| m.modified()).ok();
        if suffix.starts_with(".corrupt-") {
            if stale(modified) {
                let _ = std::fs::remove_file(entry.path());
            }
            continue;
        }
        if stem == ours || !["", "-wal", "-shm", ".lock"].contains(&suffix) {
            continue;
        }
        let group = groups
            .entry(stem.to_string())
            .or_insert_with(|| (Vec::new(), Some(SystemTime::UNIX_EPOCH)));
        group.0.push(entry.path());
        group.1 = match (group.1, modified) {
            (Some(a), Some(b)) => Some(a.max(b)),
            _ => None,
        };
    }
    for (stem, (files, newest)) in groups {
        if !stale(newest) {
            continue;
        }
        // An opener of that index holds its lock shared while connecting.
        let lock = OpenOptions::new()
            .write(true)
            .open(index_dir.join(format!("{stem}.db.lock")))
            .ok();
        if lock
            .as_ref()
            .is_some_and(|file| FileExt::try_lock_exclusive(file).is_err())
        {
            continue;
        }
        // The database first: without it the others are inert.
        let mut files = files;
        files.sort_by_key(|path| path.extension().is_none_or(|e| e != "db"));
        for file in files {
            let _ = std::fs::remove_file(file);
        }
    }
}

/// Whether the database holds exactly this build's schema: its format version
/// and, for every object, the very statement this build would execute.
/// Objects of other names (a test's trigger, say) are ignored.
fn schema_is_current(conn: &Connection) -> rusqlite::Result<bool> {
    let version: i64 = conn.pragma_query_value(None, "user_version", |row| row.get(0))?;
    if version != INDEX_FORMAT_VERSION {
        return Ok(false);
    }
    let mut stmt = conn.prepare_cached("SELECT sql FROM sqlite_schema WHERE name = ?1")?;
    for (name, sql) in schema_objects() {
        let stored: Option<Option<String>> =
            stmt.query_row([&name], |row| row.get(0)).optional()?;
        if stored.flatten().as_deref() != Some(sql.as_str()) {
            return Ok(false);
        }
    }
    Ok(true)
}

/// Inside `tx` (`BEGIN IMMEDIATE`): drop every schema object, then create
/// the current schema with its meta row and format version. Dropping a
/// whole table frees its pages without visiting rows.
fn rebuild_schema(tx: &Connection) -> rusqlite::Result<()> {
    let mut objects: Vec<(String, String)> = tx
        .prepare(
            "SELECT type, name FROM sqlite_schema \
             WHERE type IN ('table', 'view', 'trigger') AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\'",
        )?
        .query_map([], |row| Ok((row.get(0)?, row.get(1)?)))?
        .collect::<rusqlite::Result<_>>()?;
    // Views and triggers first; a table takes its indexes and triggers along.
    objects.sort_by_key(|(kind, _)| kind == "table");
    for (kind, name) in objects {
        tx.execute(
            &format!(
                "DROP {} IF EXISTS \"{}\"",
                kind.to_ascii_uppercase(),
                name.replace('"', "\"\"")
            ),
            [],
        )?;
    }
    for (_, sql) in schema_objects() {
        tx.execute(&sql, [])?;
    }
    tx.execute("INSERT INTO meta (singleton) VALUES (1)", [])?;
    tx.pragma_update(None, "user_version", INDEX_FORMAT_VERSION)
}

/// Empty an oversized WAL (see "WAL growth" in the module docs). Best effort:
/// the batch has committed, so failures here are ignored.
fn trim_wal(conn: &Connection, db: &Path) {
    let mut wal = db.as_os_str().to_owned();
    wal.push("-wal");
    let size = std::fs::metadata(&wal).map(|m| m.len()).unwrap_or(0);
    if size <= WAL_TRUNCATE_BYTES {
        return;
    }
    if conn.busy_timeout(WAL_TRUNCATE_WAIT).is_ok() {
        // One row: (busy, log frames, checkpointed frames); busy = 1 when
        // readers did not drain in time — the next batch retries.
        let _ = conn.query_row("PRAGMA wal_checkpoint(TRUNCATE)", [], |_| Ok(()));
    }
    let _ = conn.busy_timeout(BUSY_TIMEOUT);
}

/// Wall-clock nanoseconds since the Unix epoch (0 before it).
fn now_ns() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |d| i64::try_from(d.as_nanos()).unwrap_or(i64::MAX))
}

