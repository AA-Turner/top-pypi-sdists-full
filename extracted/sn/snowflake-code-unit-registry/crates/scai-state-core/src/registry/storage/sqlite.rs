    #[test]
    fn distribute_expands_and_over_or() {
        use IndexedField::*;
        let leaf = |f: IndexedField, v: &str| Prefilter::In(f, vec![tx(v)]);
        let (a, b, c, d) = (
            leaf(Kind, "a"),
            leaf(Kind, "b"),
            leaf(Kind, "c"),
            leaf(Kind, "d"),
        );
        // a AND (b OR c) AND (d)  →  (a AND b AND d) OR (a AND c AND d)
        let p = Prefilter::And(vec![
            a.clone(),
            Prefilter::Or(vec![b.clone(), c.clone()]),
            Prefilter::And(vec![d.clone()]),
        ]);
        assert_eq!(
            distribute(&p),
            Prefilter::Or(vec![
                Prefilter::And(vec![a.clone(), b.clone(), d.clone()]),
                Prefilter::And(vec![a.clone(), c.clone(), d.clone()]),
            ])
        );
        // Nested ORs flatten; an empty OR operand makes the AND false.
        assert_eq!(
            distribute(&Prefilter::Or(vec![
                a.clone(),
                Prefilter::Or(vec![b.clone()])
            ])),
            Prefilter::Or(vec![a.clone(), b.clone()])
        );
        assert_eq!(
            render(&distribute(&Prefilter::And(vec![
                a.clone(),
                Prefilter::Or(vec![])
            ]))),
            Rendered::Const(false)
        );
        // Too many branches: left as is (apart from flattening).
        let wide = Prefilter::Or((0..5).map(|i| leaf(Wave, &i.to_string())).collect());
        let p = Prefilter::And(vec![wide.clone(), wide.clone()]);
        assert_eq!(distribute(&p), p);
        // The truth value never changes.
        let (_dir, _db, storage) = new_db();
        for (id, kind, name) in [
            ("1", "script", "x"),
            ("2", "etl", "y"),
            ("3", "script", "y"),
        ] {
            put(
                &storage,
                id,
                &json!({ "kind": kind, "source": { "name": name } }),
            );
        }
        let p = Prefilter::And(vec![
            Prefilter::Or(vec![leaf(Kind, "script"), leaf(Kind, "etl")]),
            Prefilter::Or(vec![
                leaf(SourceName, "y"),
                Prefilter::IsNull {
                    field: Wave,
                    negated: true,
                },
            ]),
        ]);
        assert_eq!(matching(&storage, &p), matching(&storage, &distribute(&p)));
        assert_eq!(matching(&storage, &p), ["2", "3"]);
    }

