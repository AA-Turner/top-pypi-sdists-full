/// Index format version: the database file name starts with
/// `v{INDEX_FORMAT_VERSION}-` (see [`index_stem`]) and the database records
/// it in `PRAGMA user_version`. Bump it whenever the schema changes —
/// including any change to [`IndexedField`] — or the way values are derived
/// ([`derive`]), so that libraries of different formats use different files
/// instead of resetting or misreading each other's.
