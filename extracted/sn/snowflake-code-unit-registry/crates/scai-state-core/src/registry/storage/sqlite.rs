/// How long the files of another index (another library version, an older
/// format) must have gone unmodified before [`SqliteIndex::open`] deletes
/// them. Any index in use is modified far more often: every sweep (at least
/// every 30 s of reads) commits to its WAL.
const STALE_INDEX_AGE: Duration = Duration::from_secs(7 * 24 * 60 * 60);

/// How long a connection waits on a locked database before failing.
const BUSY_TIMEOUT: Duration = Duration::from_secs(10);

/// Size the WAL file is truncated back to when it rewinds (bytes).
const JOURNAL_SIZE_LIMIT: i64 = 64 * 1024 * 1024;

/// WAL file size (bytes) above which a committing writer empties the WAL
/// with a `TRUNCATE` checkpoint (see "WAL growth" in the module docs).
const WAL_TRUNCATE_BYTES: u64 = 32 * 1024 * 1024;

/// Longest a `TRUNCATE` checkpoint waits for in-flight readers.
const WAL_TRUNCATE_WAIT: Duration = Duration::from_millis(100);

/// Page cache (KiB) a connection uses while it applies a batch; the
/// connection's own `cache_size` is restored afterwards, which frees the
