    #[test]
    fn for_each_chunk_visits_each_row_once_in_rowid_order() {
        for (rows, chunk) in [(0, 3), (1, 1), (6, 3), (7, 3), (5, 10), (4, 0)] {
            let (_dir, _db, storage) = new_db();
            for i in (0..rows).rev() {
                put(&storage, &format!("id{i}"), &json!({ "n": i }));
            }
            let mut seen = Vec::new();
            let mut sizes = Vec::new();
            storage
                .for_each_chunk(chunk, |ids, texts| {
                    assert_eq!(ids.len(), texts.len());
                    sizes.push(ids.len());
                    for (id, text) in ids.iter().zip(texts) {
                        let doc = text.unwrap().expect("scan texts are always present");
                        assert_eq!(read_one(&storage, id).as_deref(), Some(doc.as_str()));
                        seen.push(id.clone());
                    }
                    Ok(())
                })
                .unwrap();
            assert_eq!(
                seen,
                rowid_order(&storage),
                "rows = {rows}, chunk = {chunk}"
            );
            assert!(sizes.iter().all(|&s| s <= chunk.max(1)), "{sizes:?}");
        }
    }

    #[test]
    fn for_each_chunk_tolerates_writes_from_the_callback() {
        let (_dir, _db, storage) = new_db();
        for i in 0..10 {
            put(&storage, &format!("id{i}"), &json!({ "gen": 0 }));
        }
        let before = rowid_order(&storage);
        let mut seen: Vec<String> = Vec::new();
        let mut pages = 0;
        storage
            .for_each_chunk(3, |ids, _| {
                pages += 1;
                seen.extend(ids.iter().cloned());
                // Rewrite every row — visited and not yet visited alike, like
                // a migration — and delete the last one before its page.
                let doc = json!({ "gen": pages }).to_string();
                let upserts = before
                    .iter()
                    .filter(|id| *id != "id9")
                    .map(|id| row(id, &doc, fp(pages)))
                    .collect();
                let deletes = if pages == 1 { vec!["id9"] } else { vec![] };
                storage
                    .apply(&IndexChanges {
                        upserts,
                        deletes,
                        ..Default::default()
                    })
                    .unwrap();
                Ok(())
            })
            .unwrap();
        // Each surviving row exactly once, in the original rowid order; the
        // last page boundary falls exactly at the end (3 full pages).
        assert_eq!(seen, before[..9]);
        assert_eq!(pages, 3);
        assert_eq!(rowid_order(&storage), before[..9], "upserts keep rowids");
    }

