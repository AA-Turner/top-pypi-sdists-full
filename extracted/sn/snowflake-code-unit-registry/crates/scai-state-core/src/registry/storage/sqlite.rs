    /// Overwrite `len` bytes of the (closed) database `db` at `offset`.
    fn clobber(db: &Path, offset: u64, len: usize) {
        use std::io::{Seek, SeekFrom, Write};
        let mut file = OpenOptions::new().write(true).open(db).unwrap();
        file.seek(SeekFrom::Start(offset)).unwrap();
        file.write_all(&vec![0xA5; len]).unwrap();
    }

    fn corrupt_files(dir: &Path) -> usize {
        file_names(dir)
            .iter()
            .filter(|n| n.contains(".corrupt-"))
            .count()
    }

