/// What [`lookup`] found stored for an upsert.
#[derive(Debug)]
enum Stored {
    Absent,
    /// The stored `doc` is byte-identical to the upsert's.
    Identical,
    /// Another document, with these [`derived_values`].
    Changed(Vec<SqlValue>),
}

/// Step 1 of an upsert batch (see "Derived columns" in the module docs):
/// what is stored for each of `upserts`, from one snapshot.
fn lookup(conn: &mut Connection, upserts: &[IndexRow<'_>]) -> rusqlite::Result<Vec<Stored>> {
    let tx = conn.transaction_with_behavior(TransactionBehavior::Deferred)?;
    let found = {
        let mut stmt = tx.prepare_cached(&put_sql().lookup)?;
        let columns = derived_columns().len();
        upserts
            .iter()
            .map(|row| {
                let doc: &str = &row.doc;
                stmt.query_row(params![row.id, doc], |r| {
                    if r.get::<_, bool>(0)? {
                        return Ok(Stored::Identical);
                    }
                    (1..=columns)
                        .map(|i| r.get::<_, SqlValue>(i))
                        .collect::<rusqlite::Result<_>>()
                        .map(Stored::Changed)
                })
                .optional()
                .map(|stored| stored.unwrap_or(Stored::Absent))
            })
            .collect::<rusqlite::Result<Vec<_>>>()?
    };
    // Read-only: ending the snapshot with a rollback is equivalent.
    tx.finish()?;
    Ok(found)
}

/// Step 2: an upsert ready to write.
#[derive(Debug)]
enum Prepared {
    /// Byte-identical to the stored row: update the fingerprint only.
    Identical,
    /// New or changed, with its [`derived_values`]; `unchanged_values` when
    /// they equal the stored row's.
    Derived {
        values: Vec<SqlValue>,
        unchanged_values: bool,
    },
}

impl Prepared {
    fn new(row: &IndexRow<'_>, stored: Stored) -> Self {
        if matches!(stored, Stored::Identical) {
            return Self::Identical;
        }
        let values = derived_values(&derive(row.id, &row.doc));
        let unchanged_values = matches!(&stored, Stored::Changed(old) if *old == values);
        Self::Derived {
            values,
            unchanged_values,
        }
    }
}

/// Step 3: apply `changes` (with `prepared` for its upserts, in order) in
/// one `BEGIN IMMEDIATE` transaction. `Ok(Err(message))` means a row's
/// statement failed and the transaction was rolled back.
fn apply_changes(
    conn: &mut Connection,
    changes: &IndexChanges<'_>,
    prepared: &[Prepared],
    now: i64,
    path: &Path,
) -> rusqlite::Result<std::result::Result<(), String>> {
    let tx = conn.transaction_with_behavior(TransactionBehavior::Immediate)?;
    {
        let row_failed = |id: &str, e: rusqlite::Error| {
            format!(
                "index row for '{id}' failed: {}",
                sqlite_message(path, "write", &e)
            )
        };
        if !changes.deletes.is_empty() {
            let mut delete = tx.prepare_cached(SQL_DELETE)?;
            for &id in &changes.deletes {
                if let Err(e) = delete.execute(params![id]) {
                    return Ok(Err(row_failed(id, e)));
                }
            }
        }
        if !changes.upserts.is_empty() {
            let mut put = PutStatements::new(&tx)?;
            for (row, prepared) in changes.upserts.iter().zip(prepared) {
                if let Err(e) = put.put(row, prepared, now) {
                    return Ok(Err(row_failed(row.id, e)));
                }
            }
        }
        tx.prepare_cached(SQL_COMMIT_META)?.execute(params![
            changes.dir_mtime_ns,
            changes.dir_recorded_ns,
            changes.swept_at_ns
        ])?;
    }
    tx.commit()?;
    Ok(Ok(()))
}

/// The statements behind [`PutStatements::put`], prepared once per batch.
struct PutStatements<'conn> {
    fingerprint: rusqlite::CachedStatement<'conn>,
    update_doc: rusqlite::CachedStatement<'conn>,
    upsert: rusqlite::CachedStatement<'conn>,
}

impl<'conn> PutStatements<'conn> {
    fn new(conn: &'conn Connection) -> rusqlite::Result<Self> {
        let sql = put_sql();
        Ok(Self {
            fingerprint: conn.prepare_cached(SQL_UPDATE_FINGERPRINT)?,
            update_doc: conn.prepare_cached(&sql.update_doc)?,
            upsert: conn.prepare_cached(&sql.upsert)?,
        })
    }

    /// Store `row` with `recorded_ns = now`, keeping an existing row's
    /// rowid, as cheaply as `prepared` allows:
    ///
    /// - byte-identical document: update only the fingerprint columns. No
    ///   index but the fingerprint index depends on them, and since the
    ///   record keeps its size SQLite overwrites just the changed bytes of
    ///   the row's first page, leaving overflow pages alone;
    /// - changed document with unchanged derived values: update fingerprint
    ///   and `doc`, again maintaining no value index;
    /// - otherwise: insert, or replace every column.
    ///
    /// The first two re-check, in their `WHERE` clause, what [`lookup`] saw;
    /// when that no longer holds they change nothing and the full upsert
    /// runs instead (deriving inline for a formerly identical row), so the
    /// row ends up right whatever committed in between.
    fn put(&mut self, row: &IndexRow<'_>, prepared: &Prepared, now: i64) -> rusqlite::Result<()> {
        let fp = row.fingerprint;
        let (size, mtime, file_id) = (to_sql_u64(fp.size), fp.mtime_ns, to_sql_u64(fp.file_id));
        let doc: &str = &row.doc;
        let inline;
        let (values, unchanged_values) = match prepared {
            Prepared::Identical => {
                let updated = self
                    .fingerprint
                    .execute(params![row.id, size, mtime, file_id, now, doc])?;
                if updated == 1 {
                    return Ok(());
                }
                inline = derived_values(&derive(row.id, doc));
                (&inline, false)
            }
            Prepared::Derived {
                values,
                unchanged_values,
            } => (values, *unchanged_values),
        };
        let fixed: [&dyn ToSql; 6] = [&row.id, &size, &mtime, &file_id, &now, &doc];
        let params = || {
            fixed
                .iter()
                .copied()
                .chain(values.iter().map(|v| v as &dyn ToSql))
                .collect::<Vec<_>>()
        };
        if unchanged_values && self.update_doc.execute(params().as_slice())? == 1 {
            return Ok(());
        }
        self.upsert.execute(params().as_slice())?;
        Ok(())
    }
}

