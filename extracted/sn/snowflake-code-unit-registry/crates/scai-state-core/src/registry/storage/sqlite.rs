    fn open_removes_other_index_files_only_once_stale() {
        let dir = tempfile::tempdir().unwrap();
        let index_dir = dir.path().join(".index");
        std::fs::create_dir_all(&index_dir).unwrap();
        let old = STALE_INDEX_AGE + Duration::from_secs(3600);
        let recent = STALE_INDEX_AGE - Duration::from_secs(3600);
        let files: &[(&str, Duration)] = &[
            // An old format, untouched for over a week: removed.
            ("v2.db", old),
            ("v2.db-wal", old),
            ("v2.db-shm", old),
            ("v2.db.lock", old),
            // Another schema hash, stale: removed.
            ("v3-00000000.db", old),
            // Another library version whose WAL is still written: kept whole.
            ("v3-11111111.db", old),
            ("v3-11111111.db-wal", recent),
            ("v3-11111111.db.lock", old),
            // Recently used: kept.
            ("v3-22222222.db", recent),
            // Corrupt-aside files: removed once stale, ours included.
            ("v2.db.corrupt-1", old),
            ("v3-33333333.db.corrupt-2", recent),
            // Not index files: never touched.
            ("notes.txt", old),
            ("x.db", old),
        ];
        for (name, age) in files {
            let path = index_dir.join(name);
            std::fs::write(&path, "x").unwrap();
            age_file(&path, *age);
        }
        let ours_aside = format!("{}.corrupt-3", db_name());
        std::fs::write(index_dir.join(&ours_aside), "x").unwrap();
        age_file(&index_dir.join(&ours_aside), old);

        let index = SqliteIndex::open(&index_dir).unwrap();
        put(&index, "a", &json!({}));
        let mut want: Vec<String> = [
            ".gitignore",
            "notes.txt",
            "v3-11111111.db",
            "v3-11111111.db-wal",
            "v3-11111111.db.lock",
            "v3-22222222.db",
            "v3-33333333.db.corrupt-2",
            "x.db",
        ]
        .map(String::from)
        .to_vec();
        want.extend([
            db_name(),
            format!("{}-shm", db_name()),
            format!("{}-wal", db_name()),
        ]);
        want.push(format!("{}.lock", db_name()));
        want.sort();
        assert_eq!(file_names(&index_dir), want);

        // Our own files are never removed, however old they look.
        drop(index);
        for name in [db_name(), format!("{}.lock", db_name())] {
            age_file(&index_dir.join(name), old);
        }
        let index = SqliteIndex::open(&index_dir).unwrap();
        assert_eq!(index.ids().unwrap(), ["a"]);

        // A stale index whose lock another opener holds is left alone.
        for name in ["v3-44444444.db", "v3-44444444.db.lock"] {
            std::fs::write(index_dir.join(name), "x").unwrap();
            age_file(&index_dir.join(name), old);
        }
        let held = File::open(index_dir.join("v3-44444444.db.lock")).unwrap();
        FileExt::lock_shared(&held).unwrap();
        drop(SqliteIndex::open(&index_dir).unwrap());
        assert!(index_dir.join("v3-44444444.db").exists());
        drop(held);
        drop(SqliteIndex::open(&index_dir).unwrap());
        assert!(!index_dir.join("v3-44444444.db").exists());
        assert!(!index_dir.join("v3-44444444.db.lock").exists());
    }

