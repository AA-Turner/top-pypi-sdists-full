// ── Prefilter rendering ──────────────────────────────────────────────────

/// A parameterized SQL condition (anonymous `?` placeholders, in order).
#[derive(Debug, Clone, PartialEq)]
struct SqlCond {
    sql: String,
    params: Vec<SqlValue>,
}

/// A rendered [`Prefilter`]: constant-folded, so that a `Sql` condition
/// never contains a constant branch (a constant `OR` branch defeats the
/// multi-index OR plan).
#[derive(Debug, Clone, PartialEq)]
enum Rendered {
    Const(bool),
    Sql(SqlCond),
}

fn bind(value: &IndexValue) -> SqlValue {
    match value {
        IndexValue::Text(s) => SqlValue::Text(s.clone()),
        IndexValue::Integer(i) => SqlValue::Integer(*i),
    }
}

/// `values` as a JSON array for `json_each`, which yields TEXT for strings
/// and INTEGER for integers — the types they would bind as.
fn json_array(values: &[IndexValue]) -> String {
    let mut out = String::from("[");
    for (i, value) in values.iter().enumerate() {
        if i > 0 {
            out.push(',');
        }
        match value {
            IndexValue::Text(s) => {
                out.push_str(&serde_json::to_string(s).expect("string serializes"))
            }
            IndexValue::Integer(n) => out.push_str(&n.to_string()),
        }
    }
    out.push(']');
    out
}

/// Most `Or` branches an `And` may be expanded into by [`distribute`].
const MAX_DISTRIBUTED_BRANCHES: usize = 16;

/// Rewrite an `And` with `Or` operands into an `Or` of `And`s (when that
/// yields at most [`MAX_DISTRIBUTED_BRANCHES`] branches), e.g.
/// `a AND (b OR c)` → `(a AND b) OR (a AND c)`. Same truth value; but SQLite
/// only runs an OR as a multi-index OR when it is a top-level OR term, and
/// otherwise serves `inScope AND NOT isMissing AND (canonicalName = X OR
/// (schema = S AND name = N))` through the barely selective boolean index.
fn distribute(prefilter: &Prefilter) -> Prefilter {
    match prefilter {
        Prefilter::And(parts) => {
            let mut flat = Vec::with_capacity(parts.len());
            for part in parts.iter().map(distribute) {
                match part {
                    Prefilter::And(inner) => flat.extend(inner),
                    other => flat.push(other),
                }
            }
            let branches = flat.iter().try_fold(1usize, |n, part| match part {
                Prefilter::Or(alternatives) => n.checked_mul(alternatives.len()),
                _ => Some(n),
            });
            let has_or = flat.iter().any(|p| matches!(p, Prefilter::Or(_)));
            if !has_or || branches.is_none_or(|n| n > MAX_DISTRIBUTED_BRANCHES) {
                return Prefilter::And(flat);
            }
            let mut conjunctions: Vec<Vec<Prefilter>> = vec![Vec::new()];
            for part in flat {
                conjunctions = match part {
                    Prefilter::Or(alternatives) => conjunctions
                        .iter()
                        .flat_map(|prefix| {
                            alternatives.iter().map(move |alternative| {
                                let mut conjunction = prefix.clone();
                                conjunction.push(alternative.clone());
                                conjunction
                            })
                        })
                        .collect(),
                    other => {
                        for conjunction in &mut conjunctions {
                            conjunction.push(other.clone());
                        }
                        conjunctions
                    }
                };
            }
            Prefilter::Or(conjunctions.into_iter().map(Prefilter::And).collect())
        }
        Prefilter::Or(parts) => {
            let mut flat = Vec::with_capacity(parts.len());
            for part in parts.iter().map(distribute) {
                match part {
                    Prefilter::Or(inner) => flat.extend(inner),
                    other => flat.push(other),
                }
            }
            Prefilter::Or(flat)
        }
        leaf => leaf.clone(),
    }
}

fn render(prefilter: &Prefilter) -> Rendered {
    match (prefilter, render_term(prefilter)) {
        // A boolean column has two values, but without statistics SQLite
        // assumes an equality on any index matches ~10 rows. Left alone, it
        // then prefers the (in_scope, is_missing, …) index over a selective
        // OR on other columns and re-checks that OR on nearly every row.
        (Prefilter::In(field, _) | Prefilter::Range { field, .. }, Rendered::Sql(cond))
            if field.kind() == FieldKind::Bool =>
        {
            Rendered::Sql(SqlCond {
                sql: format!("likelihood({}, {TWO_VALUED})", cond.sql),
                params: cond.params,
            })
        }
        (_, rendered) => rendered,
    }
}

fn render_term(prefilter: &Prefilter) -> Rendered {
    match prefilter {
        Prefilter::And(parts) => combine(parts, "AND", true),
        Prefilter::Or(parts) => combine(parts, "OR", false),
        Prefilter::In(_, values) if values.is_empty() => Rendered::Const(false),
        Prefilter::In(field, values) => {
            let column = field.column();
            if let [value] = values.as_slice() {
                return sql(format!("{column} = ?"), vec![bind(value)]);
            }
            if values.len() > INLINE_IN_MAX {
                return sql(
                    format!("{column} IN (SELECT value FROM json_each(?))"),
                    vec![SqlValue::Text(json_array(values))],
                );
            }
            let marks = vec!["?"; values.len()].join(", ");
            sql(
                format!("{column} IN ({marks})"),
                values.iter().map(bind).collect(),
            )
        }
        Prefilter::Range { field, low, high } => {
            let column = field.column();
            let term = |bound: &Bound, strict: &str, inclusive: &str| {
                let op = if bound.inclusive { inclusive } else { strict };
                (format!("{column} {op} ?"), bind(&bound.value))
            };
            let terms: Vec<(String, SqlValue)> = low
                .iter()
                .map(|b| term(b, ">", ">="))
                .chain(high.iter().map(|b| term(b, "<", "<=")))
                .collect();
            if terms.is_empty() {
                // No bound, no constraint: conservatively true (even for NULL).
                return Rendered::Const(true);
            }
            let (sqls, params): (Vec<String>, Vec<SqlValue>) = terms.into_iter().unzip();
            sql(format!("({})", sqls.join(" AND ")), params)
        }
        Prefilter::IsNull { field, negated } => {
            if field.is_storage_key() {
                // The key is never NULL.
                return Rendered::Const(*negated);
            }
            let column = field.column();
            if !negated {
                return sql(format!("{column} IS NULL"), Vec::new());
            }
            // `IS NOT NULL` is not index-searchable; an open-ended range is.
            // Exact for these columns: a TEXT column only ever holds text
            // (every text is >= ''), a numeric one only numbers (every number
            // is >= -inf; a REAL keeps its type under INTEGER affinity).
            let floor = match field.kind() {
                FieldKind::Text => SqlValue::Text(String::new()),
                FieldKind::Integer | FieldKind::Bool => SqlValue::Real(f64::NEG_INFINITY),
            };
            sql(format!("{column} >= ?"), vec![floor])
        }
    }
}

fn sql(sql: String, params: Vec<SqlValue>) -> Rendered {
    Rendered::Sql(SqlCond { sql, params })
}

/// Fold `parts` under `op`, whose identity is `identity` (`AND`: true,
/// `OR`: false); the opposite constant absorbs everything.
fn combine(parts: &[Prefilter], op: &str, identity: bool) -> Rendered {
    let mut conds = Vec::new();
    for part in parts {
        match render(part) {
            Rendered::Const(c) if c == identity => {}
            Rendered::Const(absorbing) => return Rendered::Const(absorbing),
            Rendered::Sql(cond) => conds.push(cond),
        }
    }
    match conds.len() {
        0 => Rendered::Const(identity),
        1 => Rendered::Sql(conds.pop().expect("one condition")),
        _ => Rendered::Sql(join_balanced(conds, op)),
    }
}

/// Join with `op` as a balanced tree of parentheses, so a long list stays
/// far below SQLite's expression depth limit (1000).
fn join_balanced(mut conds: Vec<SqlCond>, op: &str) -> SqlCond {
    if conds.len() == 1 {
        return conds.pop().expect("one condition");
    }
    let right = conds.split_off(conds.len() / 2);
    let (left, right) = (join_balanced(conds, op), join_balanced(right, op));
    let mut params = left.params;
    params.extend(right.params);
    SqlCond {
        sql: format!("({} {op} {})", left.sql, right.sql),
        params,
    }
}

/// The rowid query for candidates: `prefilter` (`None` = false) or any
/// document the prefilter cannot vouch for, i.e. an irregular one.
///
/// The irregular term carries `likelihood(…, 0.001)`: irregular rows are
/// rare in practice, and the planner has no statistics. The hint changes
/// estimates only, never results or index usability.
fn candidate_query(prefilter: Option<SqlCond>) -> SqlCond {
    let mut sql = String::from("SELECT rowid FROM code_units WHERE ");
    let mut params = Vec::new();
    if let Some(pre) = prefilter {
        write!(sql, "{} OR ", pre.sql).expect("write to String");
        params = pre.params;
    }
    write!(sql, "likelihood({REGULAR_COLUMN} = 0, {RARE})").expect("write to String");
    SqlCond { sql, params }
}

/// `EXPLAIN QUERY PLAN` detail lines for `query`.
fn query_plan(conn: &Connection, query: &SqlCond) -> rusqlite::Result<Vec<String>> {
    conn.prepare(&format!("EXPLAIN QUERY PLAN {}", query.sql))?
        .query_map(params_from_iter(&query.params), |row| {
            row.get::<_, String>(3)
        })?
        .collect()
}

/// Whether the plan for `query` visits every row: a `SCAN` of the table, or
/// of a whole (covering) index. Every acceptable step is a `SEARCH`.
fn plan_scans_table(conn: &Connection, query: &SqlCond) -> rusqlite::Result<bool> {
    Ok(query_plan(conn, query)?
        .iter()
        .any(|detail| detail.starts_with("SCAN code_units")))
}

/// `(id, doc)` of each of `rowids` still present, in one read transaction.
fn read_by_rowid(conn: &mut Connection, rowids: &[i64]) -> rusqlite::Result<Vec<(String, String)>> {
    let tx = conn.transaction_with_behavior(TransactionBehavior::Deferred)?;
    let rows = {
        let mut stmt = tx.prepare_cached(SQL_READ_ROWID)?;
        let mut rows = Vec::with_capacity(rowids.len());
        for &rowid in rowids {
            let row = stmt
                .query_row(params![rowid], |row| Ok((row.get(0)?, row.get(1)?)))
                .optional()?;
            rows.extend(row);
        }
        rows
    };
    tx.finish()?;
    Ok(rows)
}

