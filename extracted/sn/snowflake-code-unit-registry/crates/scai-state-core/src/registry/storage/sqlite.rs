//! SQLite index of the registry files: `registry/.index/v{N}-{hash}.db`.
//!
//! The JSON files `registry/{id}.json` are the record. This database is a
//! git-ignored cache of them, kept current by the sync engine (see "Storage:
//! JSON Files + SQLite Index" in `registry/README.md`), that makes whole-
//! registry and filtered reads cheap. Deleting it is always safe: the next
//! read rebuilds it from the files. This module only stores rows and answers
//! queries; deciding *when* the index is trusted, sweeping, and locking are
//! the sync engine's job.
//!
//! # Schema
//!
//! The database file is named after the index format version
//! [`INDEX_FORMAT_VERSION`] (also recorded in `PRAGMA user_version`) plus a
//! hash of what the derived values depend on — the embedded
//! `code-unit.schema.json` and `CURRENT_SCHEMA_VERSION` — e.g. `v3-1a2b3c4d.db`
//! (see [`index_stem`]). Two library versions that would derive different
//! values (a newer one accepting a new enum variant, say) therefore never
//! share rows. The DDL is generated by [`schema_objects`] from
//! [`IndexedField::ALL`] (the single source of truth for which fields are
//! mirrored), roughly:
//!
//! ```sql
//! CREATE TABLE code_units (
//!     id          TEXT PRIMARY KEY NOT NULL,  -- the file stem
//!     fp_size     INTEGER NOT NULL,           -- fingerprint of the file `doc`
//!     fp_mtime_ns INTEGER NOT NULL,           --   was read from (u64 values
//!     fp_file_id  INTEGER NOT NULL,           --   stored bit-for-bit as i64)
//!     recorded_ns INTEGER NOT NULL,           -- wall clock when the row was written
//!     regular     INTEGER NOT NULL,           -- 1 / 0, see `index::derive`
//!     -- one plain column per non-key IndexedField, written by the library:
//!     kind TEXT, source_object_type TEXT, ..., wave INTEGER, in_scope INTEGER, ...,
//!     doc         TEXT NOT NULL               -- the file's text, verbatim
//! );
//! CREATE TABLE meta (                         -- exactly one row
//!     singleton INTEGER PRIMARY KEY NOT NULL CHECK (singleton = 1),
//!     dir_mtime_ns INTEGER, dir_recorded_ns INTEGER, last_sweep_ns INTEGER,
//!     write_in_progress INTEGER NOT NULL DEFAULT 0
//! );
//! CREATE INDEX ix_code_units_<column> ON code_units(<column>);   -- per field
//! CREATE INDEX ix_code_units_in_scope_is_missing_wave
//!     ON code_units(in_scope, is_missing, wave);  -- no in_scope/is_missing alone
//! CREATE INDEX ix_code_units_irregular ON code_units(regular) WHERE regular = 0;
//! ```
//!
//! ## Opening
//!
//! [`SqliteIndex::open`] is safe to run from many processes at once:
//!
//! 1. Create the index directory and its `.gitignore` (`*`, so the directory
//!    ignores itself) — before the database, so it is never un-ignored.
//! 2. Holding a shared lock on `{stem}.db.lock`, open or create `{stem}.db`
//!    and switch it to (persistent) WAL.
//! 3. Compare `user_version` and the `sqlite_schema` text of every object
//!    with the DDL this build generates. Any difference (a foreign or damaged
//!    schema, an edited [`IndexedField`] list without a version bump, a file
//!    copied from another format) resets the database in place: drop every
//!    object and recreate the schema in one `BEGIN IMMEDIATE` transaction,
//!    re-checked inside it, so concurrent openers reset it once.
//! 4. A file SQLite reports as not a database, or corrupt, is renamed to
//!    `{stem}.db.corrupt-{unix_ns}` (its `-wal`/`-shm` removed, so they
//!    can't be replayed into the new file) and a fresh one is created. This
//!    runs under the *exclusive* lock on `{stem}.db.lock`, after re-checking the
//!    file, so it happens once, and never while another opener is between
//!    creating a fresh database and its first commit (whose `-wal` it would
//!    otherwise delete). [`SqliteIndex::reset`] does the same when the
//!    database turns out corrupt beyond its schema.
//! 5. Best effort, delete the index files of *other* stems (other library
//!    versions, older formats) and corrupt-aside files once nothing touched
//!    them for [`STALE_INDEX_AGE`] (7 days; see [`remove_stale_files`]).
//!    Recent ones stay: another library version may be using them.
//!
//! Anything else that fails is an error; the caller then serves from files.
//!
//! Known limit: a process that still has a *corrupt* (valid-header) file
//! open when it is renamed aside keeps using it, and SQLite deletes a WAL by
//! name when its last connection closes — which could be the new file's.
//! That process sees errors on the corrupt file anyway; at worst the new
//! index loses recent commits (meta included, so the next read sweeps) or
//! is found corrupt and replaced again. Not-a-database files are safe: no
//! connection can be using one.
//!
//! `doc` holds the file's text exactly as read — no JSON `CHECK`, since the
//! registry layer (not storage) owns validation and must be able to report
//! corrupt documents. A plain rowid table, because documents are large. The
//! fingerprint and value columns precede `doc` so that reading them (every
//! sweep; a query checking a column outside the index it searched) never
//! walks a large document's overflow pages.
//!
//! ## Derived columns
//!
//! `regular` and the value columns are plain columns that the library
//! computes in Rust whenever it (re)indexes a row: [`super::index::derive`]
//! runs the registry's own strict load on the row's text and reads each
//! field's *indexed value* from the typed serialization of the unit — the
//! very JSON the registry's predicates evaluate. A document the strict load
//! rejects (invalid JSON, a value serde rejects, a duplicate-key quirk, a
//! failed migration, an ID/key mismatch, anything else) has `regular = 0`
//! and `NULL` values, so it is a candidate for every filtered read and its
//! error surfaces there. Values never come from SQLite's JSON functions,
//! whose reading of a document can differ from serde's (duplicate keys:
//! SQLite takes the first, serde the last).
//!
//! [`SqliteIndex::apply`] derives in three steps, so that no rayon work runs
//! while the connection mutex is held (a stolen job reaching
//! [`SqliteIndex::with_conn`] would deadlock on it):
//!
//! 1. under the mutex, one read transaction looks up each upsert's stored
//!    row: absent, byte-identical (`doc IS ?`), or changed — then with its
//!    stored derived values;
//! 2. without it, rows that are new or changed are derived in parallel; a
//!    byte-identical document is not re-derived;
//! 3. under the mutex, one `BEGIN IMMEDIATE` transaction writes them (see
//!    [`PutStatements::put`]). Each write re-checks the state step 1 saw in
//!    its `WHERE` clause and otherwise falls back to a full upsert (deriving
//!    inline if needed), so the outcome is right whatever committed between
//!    the steps.
//!
//! A byte-identical document only gets its fingerprint columns updated, and
//! a changed document whose derived values are unchanged only its
//! fingerprint and `doc`: no index depends on those but the fingerprint
//! index, so SQLite maintains no value index for them (pinned by
//! `fingerprint_only_update_skips_index_maintenance`).
//!
//! ## Candidate queries
//!
//! [`SqliteIndex::load_candidates`] renders a [`Prefilter`] into a
//! parameterized condition and first collects candidate rowids with an
//! index-only query:
//!
//! ```sql
//! SELECT rowid FROM code_units WHERE (<prefilter>) OR likelihood(regular = 0, 0.001)
//! ```
//!
//! (`likelihood` tells the planner, which has no statistics, that irregular
//! rows are rare), which SQLite serves as a `MULTI-INDEX OR` (one index
//! search per branch, rowids de-duplicated). `EXPLAIN QUERY PLAN` vets it
//! first: a plan with a full `SCAN code_units` (of the table, or of a whole
//! index) makes it return `None`, and the caller falls back to the
//! sequential scan. Documents are then fetched by rowid in chunks, in rowid
//! order — the same order as [`SqliteIndex::for_each_chunk`] — and mapped in
//! parallel.
//!
//! No schema-version term is needed: a document of an older schema version
//! that migrates is indexed by its migrated values (which the predicate
//! sees), one that does not migrate is irregular, and a library with another
//! `CURRENT_SCHEMA_VERSION` uses another file.
//!
//!
//! # Durability and concurrency
//!
//! The index is a cache, so every connection runs `synchronous = NORMAL`: in
//! WAL mode a power loss may drop the most recent commits but never corrupts
//! the database, and the next sweep repairs whatever was lost. Readers in
//! other processes never block on, or observe a partial, [`SqliteIndex::apply`]:
//! each is one `BEGIN IMMEDIATE` transaction.
//!
//! Cross-process write serialization is the sync engine's job (the registry
//! write lock); this module only provides atomic transactions. `busy_timeout`
//! covers the remaining short contention windows: a reader or writer meeting
//! WAL recovery (`SQLITE_BUSY_RECOVERY` goes through the busy handler), the
//! last connection's close-time checkpoint, concurrent openers creating or
//! resetting the schema, and a `BEGIN IMMEDIATE` racing another writer.
//! Readers never wait on a checkpoint: every checkpoint mode used here
//! (`PASSIVE` auto-checkpoints, the `TRUNCATE` below) blocks writers at most.
//!
//! ## WAL growth
//!
//! Every read is a short transaction (one statement, one `read_many` slice,
//! one scan page or fetch chunk) so readers never pin an old snapshot for
//! long. That alone does not bound the WAL: it only rewinds when a write
//! starts after a checkpoint backfilled *every* frame and no reader still
//! uses one, and the automatic `PASSIVE` checkpoint runs right after each
//! commit — exactly when readers that began before the commit still hold
//! older snapshots. With dozens of processes reading continuously that moment
//! never comes, and the WAL grows by every byte written (measured: ~450 MiB
//! after 2400 commits from 45 processes). So after a committed batch, when
//! the WAL file exceeds [`WAL_TRUNCATE_BYTES`], the writer runs
//! `wal_checkpoint(TRUNCATE)`, which waits — up to [`WAL_TRUNCATE_WAIT`],
//! never the full busy timeout — for the in-flight readers to move on (new
//! readers are not blocked; they read the fully checkpointed database), then
//! empties the WAL. If readers do not drain in time it gives up and the next
//! batch tries again. It runs under the registry write lock, so it delays
//! only the writer that triggered it. `journal_size_limit` additionally
//! truncates the WAL file to [`JOURNAL_SIZE_LIMIT`] whenever it rewinds on its
//! own.

