/// A connection plus the process that opened it (see [`SqliteIndex`]).
#[derive(Debug)]
struct OwnedConnection {
    pid: u32,
    conn: Connection,
}

/// The SQLite index of one registry directory (see the module docs).
///
/// One connection per instance, behind a mutex: `CodeUnitRegistry` must be
/// `Send + Sync` and is shared across threads by every binding. The mutex is
/// only ever held around SQLite calls — never while calling back into the
/// registry or rayon — so it cannot deadlock with work-stealing callers.
///
/// # Fork safety
///
/// Python callers may `fork()` while a registry is open. SQLite forbids using
/// a connection inherited across `fork()`: the child gets a copy of the
/// parent's lock bookkeeping, WAL-index mapping and page cache, none of which
/// is valid in the new process — and closing it (`sqlite3_close`) acts on
/// that stale state too (rolling back or checkpointing on the parent's
/// behalf). So the connection records the PID that opened it; when a call
/// (or `Drop`) finds a different PID, the inherited connection is leaked with
/// [`std::mem::forget`] — never used, never closed — and a fresh one is
/// opened for the child. The leak is a few file descriptors and some memory,
/// once per fork.
#[derive(Debug)]
pub(crate) struct SqliteIndex {
    path: PathBuf,
    conn: Mutex<Option<OwnedConnection>>,
}

impl SqliteIndex {
    /// Open or create the index in `index_dir` (`registry/.index`); see
    /// "Opening" in the module docs. An error means the index is unusable
    /// and the caller should serve from the files.
    pub(super) fn open(index_dir: &Path) -> Result<Self> {
        prepare_dir(index_dir)?;
        let path = db_path(index_dir);
        let connected = {
            let _shared = open_lock(index_dir, false)?;
            connect(&path)
        };
        let conn = match connected {
            Ok(conn) => conn,
            Err(e) if is_corrupt(&e) => replace_corrupt(index_dir, &path, connect)?,
            Err(e) => return Err(storage_error(&path, "open", &e)),
        };
        remove_stale_files(index_dir, SystemTime::now());
        Ok(Self {
            path,
            conn: Mutex::new(Some(OwnedConnection {
                pid: std::process::id(),
                conn,
            })),
        })
    }

    /// The bookkeeping row; all defaults for a new or reset index.
    pub(super) fn meta(&self) -> Result<IndexMeta> {
        self.with_conn("read", |conn| {
            conn.prepare_cached(SQL_META)?
                .query_row([], |row| {
                    Ok(IndexMeta {
                        dir_mtime_ns: row.get(0)?,
                        dir_recorded_ns: row.get(1)?,
                        last_sweep_ns: row.get(2)?,
                        write_in_progress: row.get::<_, i64>(3)? != 0,
                    })
                })
                .optional()
                .map(Option::unwrap_or_default)
        })
    }

    /// Commit `meta.write_in_progress = 1` (cleared by the next [`Self::apply`]).
    pub(super) fn set_write_in_progress(&self) -> Result<()> {
        self.with_conn("write", |conn| {
            let tx = conn.transaction_with_behavior(TransactionBehavior::Immediate)?;
            tx.prepare_cached(SQL_SET_WRITE_IN_PROGRESS)?.execute([])?;
            tx.commit()
        })
    }

    /// Compare-and-set for the sync engine's lock-free verify: record
    /// `meta.dir_recorded_ns = observed_ns` only if the meta row still holds
    /// `dir_mtime_ns` and `seen_recorded_ns` with no write in progress (so no
    /// sweep, write or other verify committed since the caller read it).
    /// Returns whether it was recorded; leaves the rows and every other meta
    /// field alone, and needs no registry write lock.
    pub(super) fn settle_dir(
        &self,
        dir_mtime_ns: i64,
        seen_recorded_ns: Option<i64>,
        observed_ns: i64,
    ) -> Result<bool> {
        self.with_conn("write", |conn| {
            let tx = conn.transaction_with_behavior(TransactionBehavior::Immediate)?;
            let changed = tx
                .prepare_cached(
                    "UPDATE meta SET dir_recorded_ns = ?3 WHERE singleton = 1 \
                     AND dir_mtime_ns = ?1 AND dir_recorded_ns IS ?2 \
                     AND write_in_progress = 0",
                )?
                .execute(params![dir_mtime_ns, seen_recorded_ns, observed_ns])?;
            tx.commit()?;
            Ok(changed == 1)
        })
    }

    /// The stored fingerprint of every row, from one snapshot.
    pub(super) fn fingerprints(&self) -> Result<HashMap<String, Fingerprint>> {
        self.with_conn("read", |conn| {
            conn.prepare_cached(SQL_FINGERPRINTS)?
                .query_map([], |row| {
                    Ok((
                        row.get::<_, String>(0)?,
                        Fingerprint {
                            size: from_sql_u64(row.get(1)?),
                            mtime_ns: row.get(2)?,
                            file_id: from_sql_u64(row.get(3)?),
                        },
                    ))
                })?
                .collect()
        })
    }

    /// The stored `fp_file_id` of every row, from one snapshot: the part of
    /// [`Self::fingerprints`] that tells whether a file was replaced.
    pub(super) fn file_ids(&self) -> Result<HashMap<String, u64>> {
        self.with_conn("read", |conn| {
            conn.prepare_cached(SQL_FILE_IDS)?
                .query_map([], |row| {
                    Ok((row.get::<_, String>(0)?, from_sql_u64(row.get(1)?)))
                })?
                .collect()
        })
    }

    /// Apply `changes` in one `BEGIN IMMEDIATE` transaction: delete
    /// `changes.deletes` (absent IDs are a no-op), then upsert
    /// `changes.upserts` with `recorded_ns` = the wall clock when `apply`
    /// started (so it is never older than the caller's read of the files)
    /// and the values [`derive`] computes from each row's text, then update
    /// the meta row: `dir_mtime_ns`, `dir_recorded_ns` and `last_sweep_ns`
    /// each only when given (`None` keeps the stored value),
    /// `write_in_progress` always cleared.
    ///
    /// A meta-only call (no upserts or deletes) is one small transaction
    /// that skips the row statements and the cache resize (~tens of µs).
    ///
    /// Upserts are looked up first and new or changed documents derived in
    /// parallel, outside the connection lock (see "Derived columns" in the
    /// module docs); a byte-identical document is not re-derived and only
    /// gets its fingerprint updated.
    ///
    /// All-or-nothing: on any failure nothing is applied (meta included).
    /// The page cache is enlarged to [`WRITE_CACHE_KIB`] for the batch only.
    pub(super) fn apply(&self, changes: &IndexChanges<'_>) -> Result<()> {
        let now = now_ns();
        let path = &self.path;
        let rows = changes.upserts.len() + changes.deletes.len();
        let prepared = if changes.upserts.is_empty() {
            Vec::new()
        } else {
            let stored = self.with_conn("read", |conn| lookup(conn, &changes.upserts))?;
            changes
                .upserts
                .par_iter()
                .zip(stored)
                .map(|(row, stored)| Prepared::new(row, stored))
                .collect()
        };
        let outcome = self.with_conn("write", |conn| {
            if rows == 0 {
                return apply_changes(conn, changes, &prepared, now, path);
            }
            let cache_size: i64 = conn.pragma_query_value(None, "cache_size", |row| row.get(0))?;
            conn.pragma_update(None, "cache_size", -WRITE_CACHE_KIB)?;
            let outcome = apply_changes(conn, changes, &prepared, now, path);
            // Best effort: failing to shrink the cache back only costs memory.
            let _ = conn.pragma_update(None, "cache_size", cache_size);
            if matches!(outcome, Ok(Ok(()))) {
                trim_wal(conn, path);
            }
            outcome
        })?;
        outcome.map_err(|why| {
            Error::storage(format!(
                "index update of {rows} rows rolled back, nothing applied: {why}"
            ))
        })
    }

    /// Drop every row and reset the meta row (the next read sweeps from
    /// scratch). Recreates the whole schema, so it also repairs a damaged
    /// one; a database SQLite reports as corrupt is replaced by a fresh file
    /// (as in step 4 of "Opening"), so a successful reset always leaves a
    /// usable, empty index.
    pub(super) fn reset(&self) -> Result<()> {
        let mut slot = self.lock();
        let reset = reset_schema(self.connection(&mut slot)?);
        match reset {
            Ok(()) => Ok(()),
            Err(e) if is_corrupt(&e) => {
                // Close ours before the file is renamed (same process: the
                // fork check in `connection` just ran).
                *slot = None;
                let index_dir = self.path.parent().unwrap_or(Path::new("."));
                let conn = replace_corrupt(index_dir, &self.path, |path| {
                    let mut conn = connect(path)?;
                    reset_schema(&mut conn)?;
                    Ok(conn)
                })?;
                *slot = Some(OwnedConnection {
                    pid: std::process::id(),
                    conn,
                });
                Ok(())
            }
            Err(e) => Err(storage_error(&self.path, "reset", &e)),
        }
    }

    /// Every stored ID, sorted. Test-only: the engine reads IDs from the
    /// files or from [`Self::file_ids`].
    #[cfg(test)]
    pub(super) fn ids(&self) -> Result<Vec<String>> {
        self.with_conn("list", |conn| {
            conn.prepare_cached(SQL_IDS)?
                .query_map([], |row| row.get::<_, String>(0))?
                .collect()
        })
    }

    /// The stored text of each of `ids` (`None` when absent), in order. One
    /// read transaction for the whole slice, so every document comes from the
    /// same snapshot, with the lookup statement prepared once. Test-only:
    /// the engine reads documents from the files (the record).
    #[cfg(test)]
    pub(super) fn read_many(&self, ids: &[String]) -> Vec<Result<Option<String>>> {
        if ids.is_empty() {
            return Vec::new();
        }
        let path = &self.path;
        let outcome = self.with_conn("read", |conn| {
            let tx = conn.transaction_with_behavior(TransactionBehavior::Deferred)?;
            let results = {
                let mut stmt = tx.prepare_cached(SQL_READ)?;
                ids.iter()
                    .map(|id| {
                        stmt.query_row(params![id], |row| row.get::<_, String>(0))
                            .optional()
                            .map_err(|e| storage_error(path, "read", &e))
                    })
                    .collect::<Vec<_>>()
            };
            // Read-only: ending the snapshot with a rollback is equivalent.
            tx.finish()?;
            Ok(results)
        });
        match outcome {
            Ok(results) => results,
            Err(e) => {
                let message = message_of(&e);
                ids.iter()
                    .map(|_| Err(Error::storage(message.clone())))
                    .collect()
            }
        }
    }

    /// Visit every document in rowid order, in pages of up to `chunk_size`
    /// (keyset pagination: `rowid >= cursor ORDER BY rowid LIMIT n`). Texts
    /// are always `Ok(Some(_))`; the shape matches the file scan's.
    ///
    /// The connection lock is released between pages and while `f` runs, so
    /// `f` may write to this index.
    ///
    /// Consistency: each page is one statement, hence one snapshot, but there
    /// is no snapshot across pages. A row present for the whole scan is
    /// visited exactly once (an upsert keeps its rowid); a row deleted before
    /// its page is read is not visited; a row inserted mid-scan is visited
    /// only if its (new, larger) rowid is still ahead of the cursor.
    pub(super) fn for_each_chunk(
        &self,
        chunk_size: usize,
        mut f: impl FnMut(&[String], Vec<Result<Option<String>>>) -> Result<()>,
    ) -> Result<()> {
        let limit = i64::try_from(chunk_size.max(1)).unwrap_or(i64::MAX);
        let mut cursor = i64::MIN;
        loop {
            let page: Vec<(i64, String, String)> = self.with_conn("scan", |conn| {
                conn.prepare_cached(SQL_SCAN_PAGE)?
                    .query_map(params![cursor, limit], |row| {
                        Ok((row.get(0)?, row.get(1)?, row.get(2)?))
                    })?
                    .collect()
            })?;
            let Some(&(last, _, _)) = page.last() else {
                return Ok(());
            };
            let complete = (page.len() as i64) < limit || last == i64::MAX;
            let (ids, texts): (Vec<String>, Vec<Result<Option<String>>>) = page
                .into_iter()
                .map(|(_, id, doc)| (id, Ok(Some(doc))))
                .unzip();
            f(&ids, texts)?;
            if complete {
                return Ok(());
            }
            cursor = last + 1;
        }
    }

    /// Documents that may satisfy `prefilter` — plus every irregular
    /// document — mapped through `f` in parallel, in
    /// rowid order. `None` when the prefilter is trivially true, or when the
    /// indexes cannot serve it (the plan would scan the table), so the caller
    /// should do a full scan instead.
    ///
    /// The candidate rowids come from one snapshot; the documents are then
    /// fetched in chunks (one snapshot each, lock released between chunks
    /// and while `f` runs). A candidate deleted meanwhile is skipped; one
    /// updated meanwhile is returned in its newer version — the caller
    /// re-applies its predicate either way.
    pub(super) fn load_candidates<T: Send>(
        &self,
        prefilter: &Prefilter,
        f: impl Fn(&str, Result<String>) -> T + Sync,
    ) -> Result<Option<Vec<T>>> {
        let pre = match render(&distribute(prefilter)) {
            Rendered::Const(true) => return Ok(None),
            Rendered::Const(false) => None,
            Rendered::Sql(cond) => Some(cond),
        };
        let query = candidate_query(pre);
        if query.params.len() > MAX_PARAMS {
            return Ok(None);
        }
        let rowids = self.with_conn("query", |conn| {
            if plan_scans_table(conn, &query)? {
                return Ok(None);
            }
            let mut stmt = conn.prepare(&query.sql)?;
            let rowids = stmt
                .query_map(params_from_iter(&query.params), |row| row.get::<_, i64>(0))?
                .collect::<rusqlite::Result<Vec<i64>>>()?;
            Ok(Some(rowids))
        })?;
        let Some(mut rowids) = rowids else {
            return Ok(None);
        };
        // MULTI-INDEX OR yields rowids in branch order; already de-duplicated.
        rowids.sort_unstable();
        rowids.dedup();

        let mut out = Vec::with_capacity(rowids.len());
        for chunk in rowids.chunks(FETCH_CHUNK) {
            let rows = self.with_conn("read", |conn| read_by_rowid(conn, chunk))?;
            out.par_extend(rows.into_par_iter().map(|(id, doc)| f(&id, Ok(doc))));
        }
        Ok(Some(out))
    }

    // ── Connection management ────────────────────────────────────────────

    /// Run `f` on this process's connection, reopening it after a `fork()`.
    /// SQLite errors are rendered as [`Error::StorageError`] naming `op` and the path.
    fn with_conn<T>(
        &self,
        op: &str,
        f: impl FnOnce(&mut Connection) -> rusqlite::Result<T>,
    ) -> Result<T> {
        let mut slot = self.lock();
        let conn = self.connection(&mut slot)?;
        f(conn).map_err(|e| storage_error(&self.path, op, &e))
    }

    /// This process's connection in `slot`, (re)opening it if needed —
    /// without creating the file: a vanished index is an error, not a new
    /// empty database.
    fn connection<'s>(&self, slot: &'s mut Option<OwnedConnection>) -> Result<&'s mut Connection> {
        let pid = std::process::id();
        if slot.as_ref().is_some_and(|owned| owned.pid != pid) {
            forget_inherited(slot.take());
        }
        if slot.is_none() {
            let conn = open_connection(&self.path, false)
                .map_err(|e| storage_error(&self.path, "open", &e))?;
            *slot = Some(OwnedConnection { pid, conn });
        }
        Ok(&mut slot.as_mut().expect("connection opened above").conn)
    }

    /// The connection slot. A panic while it was held can't leave SQLite in a
    /// bad state (an open `Transaction` rolls back on unwind), so poisoning
    /// is ignored.
    fn lock(&self) -> MutexGuard<'_, Option<OwnedConnection>> {
        self.conn
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }
}

impl Drop for SqliteIndex {
    fn drop(&mut self) {
        // An index dropped in a forked child must not close the parent's
        // connection either (see the type-level docs).
        let slot = self
            .conn
            .get_mut()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        if slot
            .as_ref()
            .is_some_and(|owned| owned.pid != std::process::id())
        {
            forget_inherited(slot.take());
        }
    }
}

/// Leak a connection inherited across `fork()` without running its destructor.
fn forget_inherited(owned: Option<OwnedConnection>) {
    // Deliberate leak: dropping would call `sqlite3_close` on state copied
    // from the parent process. See the `SqliteIndex` docs.
    std::mem::forget(owned);
}

/// Open and configure a connection; `create` allows creating the file.
fn open_connection(path: &Path, create: bool) -> rusqlite::Result<Connection> {
    let mut flags = OpenFlags::SQLITE_OPEN_READ_WRITE | OpenFlags::SQLITE_OPEN_NO_MUTEX;
    if create {
        flags |= OpenFlags::SQLITE_OPEN_CREATE;
    }
    let conn = Connection::open_with_flags(path, flags)?;
    conn.busy_timeout(BUSY_TIMEOUT)?;
    conn.pragma_update(None, "synchronous", "NORMAL")?;
    // Per-connection; returns the new value as a row.
    conn.query_row(
        &format!("PRAGMA journal_size_limit = {JOURNAL_SIZE_LIMIT}"),
        [],
        |_| Ok(()),
    )?;
    Ok(conn)
}

/// Open or create the database at `path` and make its schema current
/// (steps 2–3 of "Opening" in the module docs).
fn connect(path: &Path) -> rusqlite::Result<Connection> {
    let mut conn = open_connection(path, true)?;
    enable_wal(&conn)?;
    if !schema_is_current(&conn)? {
        let tx = conn.transaction_with_behavior(TransactionBehavior::Immediate)?;
        // Another opener may have reset it while we waited for the lock.
        if !schema_is_current(&tx)? {
            rebuild_schema(&tx)?;
        }
        tx.commit()?;
    }
    Ok(conn)
}

/// Switch the database to WAL: persistent (file header) and a no-op once
/// set; must run outside a transaction. The first statement that reads the
/// file, so this is where a non-database file fails. A filesystem without
/// WAL support keeps its rollback journal, which is slower but correct.
///
/// Openers racing to switch a new database each hold a shared lock while
/// they wait for an exclusive one, so SQLite fails all but one with
/// `SQLITE_BUSY` at once rather than calling the busy handler (which could
/// deadlock); they retry here, within [`BUSY_TIMEOUT`].
fn enable_wal(conn: &Connection) -> rusqlite::Result<()> {
    let deadline = Instant::now() + BUSY_TIMEOUT;
    loop {
        match conn.query_row("PRAGMA journal_mode = WAL", [], |_| Ok(())) {
            Err(e)
                if e.sqlite_error_code() == Some(ErrorCode::DatabaseBusy)
                    && Instant::now() < deadline =>
            {
                std::thread::sleep(Duration::from_millis(2));
            }
            outcome => return outcome,
        }
    }
}

/// Whether SQLite rejected the file itself (step 4 of "Opening").
fn is_corrupt(e: &rusqlite::Error) -> bool {
    matches!(
        e.sqlite_error_code(),
        Some(ErrorCode::NotADatabase | ErrorCode::DatabaseCorrupt)
    )
}

/// The advisory lock on `{stem}.db.lock` (released when the file is
/// dropped): shared while connecting, exclusive while replacing a corrupt
/// database.
fn open_lock(index_dir: &Path, exclusive: bool) -> Result<File> {
    let path = index_dir.join(format!("{}.db.lock", index_stem()));
    let file = OpenOptions::new()
        .create(true)
        .truncate(false)
        .write(true)
        .open(&path)
        .map_err(|e| file_error("create", &path, e))?;
    if exclusive {
        FileExt::lock_exclusive(&file)
    } else {
        FileExt::lock_shared(&file)
    }
    .map_err(|e| file_error("lock", &path, e))?;
    Ok(file)
}

/// Under the exclusive [`open_lock`]: run `attempt` (connect, and whatever
/// else the caller needs to succeed); if SQLite still reports the file as
/// corrupt, rename it aside, remove its `-wal`/`-shm` and `attempt` again on
/// a fresh file. See step 4 of "Opening".
fn replace_corrupt(
    index_dir: &Path,
    path: &Path,
    attempt: impl Fn(&Path) -> rusqlite::Result<Connection>,
) -> Result<Connection> {
    let _exclusive = open_lock(index_dir, true)?;
    // Another opener may have replaced it while we waited for the lock.
    match attempt(path) {
        Ok(conn) => return Ok(conn),
        Err(e) if is_corrupt(&e) => {}
        Err(e) => return Err(storage_error(path, "open", &e)),
    }
    let mut aside = path.as_os_str().to_owned();
    aside.push(format!(".corrupt-{}", now_ns()));
    std::fs::rename(path, &aside).map_err(|e| file_error("rename", path, e))?;
    // A leftover WAL would be replayed into the new file. No opener is
    // connecting (they hold the shared lock meanwhile), so these are not a
    // new database's files.
    for suffix in ["-wal", "-shm"] {
        let mut side = path.as_os_str().to_owned();
        side.push(suffix);
        match std::fs::remove_file(&side) {
            Err(e) if e.kind() != ErrorKind::NotFound => {
                return Err(file_error("remove", Path::new(&side), e));
            }
            _ => {}
        }
    }
    attempt(path).map_err(|e| storage_error(path, "create", &e))
}

/// Drop and recreate the schema in one `BEGIN IMMEDIATE` transaction.
fn reset_schema(conn: &mut Connection) -> rusqlite::Result<()> {
    let tx = conn.transaction_with_behavior(TransactionBehavior::Immediate)?;
    rebuild_schema(&tx)?;
    tx.commit()
}

/// Create `dir` and its `.gitignore` (`*`) if missing. The `.gitignore` is
/// written to a temporary file and renamed into place, so it is never seen
/// empty, whatever crashes or races.
fn prepare_dir(dir: &Path) -> Result<()> {
    std::fs::create_dir_all(dir).map_err(|e| file_error("create", dir, e))?;
    let gitignore = dir.join(".gitignore");
    if gitignore.is_file() {
        return Ok(());
    }
    let temp = dir.join(format!(
        ".gitignore.tmp-{}-{}",
        std::process::id(),
        now_ns()
    ));
    std::fs::write(&temp, "*\n").map_err(|e| file_error("write", &temp, e))?;
    if let Err(e) = std::fs::rename(&temp, &gitignore) {
        let _ = std::fs::remove_file(&temp);
        // Lost a race (Windows refuses to replace a file someone holds open).
        if !gitignore.is_file() {
            return Err(file_error("rename", &temp, e));
        }
    }
    Ok(())
}

