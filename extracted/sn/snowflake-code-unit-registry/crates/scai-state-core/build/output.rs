//! IO and rendering helpers shared by every generator.

use std::fs;
use std::path::Path;
use std::process::Command;
use std::sync::OnceLock;

/// Rust edition to format generated code with, read once from the workspace
/// `Cargo.toml`. rustfmt-the-binary defaults to 2015 and does not read the
/// manifest itself (and Cargo exposes no `CARGO_PKG_EDITION`), so we resolve
/// it here to keep the manifest the single source of truth. Falls back to
/// "2021" if the manifest can't be read.
fn crate_edition() -> &'static str {
    static EDITION: OnceLock<String> = OnceLock::new();
    EDITION
        .get_or_init(|| {
            let start = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default();
            let mut dir: &Path = Path::new(&start);
            loop {
                if let Ok(text) = fs::read_to_string(dir.join("Cargo.toml")) {
                    // This crate inherits via `edition.workspace = true`; the
                    // literal value lives in the workspace-root manifest.
                    if text.contains("[workspace]") {
                        if let Some(edition) = parse_edition(&text) {
                            return edition;
                        }
                    }
                }
                match dir.parent() {
                    Some(parent) => dir = parent,
                    None => return "2021".to_string(),
                }
            }
        })
        .as_str()
}

/// Pull the `edition = "..."` value out of a manifest's text. Ignores the
/// inherited form (`edition.workspace = true`), which has no quoted value.
fn parse_edition(manifest: &str) -> Option<String> {
    manifest.lines().map(str::trim).find_map(|line| {
        line.strip_prefix("edition")?
            .split('"')
            .nth(1)
            .map(String::from)
    })
}

pub fn write_generated(out_dir: &Path, filename: &str, code: &str, label: &str) {
    let output_path = out_dir.join(filename);
    fs::write(&output_path, code).unwrap_or_else(|_| panic!("Failed to write {}", label));

    // Format with the pinned `rustfmt` (rust-toolchain.toml) so the file
    // matches `cargo fmt` in CI/pre-push. Non-fatal: the raw code is already
    // written, so the compiler still surfaces any real error.
    let status = Command::new("rustfmt")
        .arg("--edition")
        .arg(crate_edition())
        .arg(&output_path)
        .status();
    match status {
        Ok(s) if s.success() => {}
        Ok(s) => println!("cargo:warning=rustfmt exited with {s} for {label}"),
        Err(e) => println!("cargo:warning=failed to run rustfmt for {label}: {e}"),
    }

    println!("cargo:warning=Generated {} to {:?}", label, output_path);
}

/// Render a `pub const NAME: &[&[&str]]` literal from a list of segment paths.
/// Used by every generator that emits a flat path table.
pub fn render_path_constant(const_name: &str, comment: &str, paths: &[Vec<String>]) -> String {
    let mut code = String::from("// AUTO-GENERATED FROM JSON SCHEMA - DO NOT EDIT MANUALLY\n");
    code.push_str(comment);
    code.push_str("\n\n");
    code.push_str(&format!("pub const {const_name}: &[&[&str]] = &[\n"));
    for path in paths {
        let segments: Vec<String> = path.iter().map(|s| format!("\"{}\"", s)).collect();
        code.push_str(&format!("    &[{}],\n", segments.join(", ")));
    }
    code.push_str("];\n");
    code
}

/// Warn if the sibling-language generated files are missing — they are not
/// regenerated by this build script (they require their own toolchains) so
/// drift between Rust types and the C#/Python bindings is operator-detected.
pub fn check_sibling_generated_files() {
    let siblings = [
        "../scai-state-python/python/snowflake_code_unit_registry/types.py",
        "../scai-state-csharp/dotnet/ScaiState/Types.cs",
        "../scai-state-csharp/dotnet/ScaiState/Interop.cs",
    ];

    let missing: Vec<&str> = siblings
        .iter()
        .filter(|p| !Path::new(p).exists())
        .copied()
        .collect();

    if !missing.is_empty() {
        println!(
            "cargo:warning=Generated type files are missing ({}). Run: ./scripts/generate-types.sh",
            missing.join(", ")
        );
    }
}
