"""Client-side helper for calling native Snowflake functions from Spark."""

import re
from typing import TYPE_CHECKING, Any, Callable

from snowflake.snowpark_connect.native_function_target import (
    conf_key_for,
    validate_native_target,
)

if TYPE_CHECKING:
    from pyspark.sql import Column, SparkSession
    from pyspark.sql.types import DataType


def register_native_snowflake_function(
    spark: "SparkSession",
    name: str,
    target: str,
    return_type: "DataType",
) -> Callable[..., "Column"]:
    """Register ``name`` as an alias for a native Snowflake function.

    Makes a Snowflake built-in function, or a UDF created outside the Spark session (from
    SnowSight, SnowSQL, or any other client), callable from ``spark.sql()`` and from the
    DataFrame API. Nothing is created in Snowflake: calls to ``name`` are rewritten to
    invoke ``target`` directly.

    This is a convenience wrapper over a single session configuration entry, so the same
    registration is available to every Spark Connect client -- Scala and Java included --
    without this package::

        spark.conf.set("snowpark.connect.nativeFunction.jaro_winkler",
                       "MY_DB.MY_SCHEMA.JW_SIM:double")

    Args:
        spark: The active Spark session.
        name: The name to call the function by from Spark. Need not match ``target`` --
            registering ``"jaro_winkler"`` for target ``"JAROWINKLER_SIMILARITY"`` lets
            SQL generated by a tool you do not control reach the right function. Use a
            dotted name to make the function reachable by its qualified Snowflake spelling.
        target: The Snowflake function to invoke. Use a bare name for built-ins
            (``"JAROWINKLER_SIMILARITY"``), which resolves against the session search
            path. Use ``SCHEMA.NAME`` or ``DATABASE.SCHEMA.NAME`` for your own UDFs, so
            resolution does not depend on the session's current database. Double-quote
            parts whose case matters (``'"myDb"."mySchema"."myFn"'``) -- Snowflake
            upper-cases an unquoted identifier.
        return_type: The Spark type of the result. Authoritative -- the native result is
            cast to it. It must match what ``target`` actually returns; SCOS does not
            verify it. Note for example that Snowflake's ``JAROWINKLER_SIMILARITY``
            returns an INTEGER on a 0-100 scale, so callers expecting a 0-1 similarity
            should point ``target`` at a one-line wrapper UDF dividing by 100 rather than
            at the built-in.

    Returns:
        A callable that builds a call to the registered function, so it can be used either
        by name in SQL or directly against a DataFrame. It is a thin wrapper over
        ``pyspark.sql.functions.call_function``; every client language has that function,
        which is why nothing language-specific is needed on the server.

    Raises:
        ValueError: If ``target`` is not a valid 1-, 2-, or 3-part Snowflake function
            name. Raised here, before contacting the server.

    Example::

        from snowflake.snowpark_connect import register_native_snowflake_function
        from pyspark.sql.types import DoubleType

        jw = register_native_snowflake_function(
            spark, "jaro_winkler", "MY_DB.MY_SCHEMA.JW_SIM", DoubleType()
        )
        spark.sql("SELECT jaro_winkler(a, b) FROM pairs")   # by name
        df.select(jw(col("a"), col("b")))                   # or via the returned callable
    """
    if not re.match(r"[^\s.](?:\S*[^\s.])?$", name):
        raise ValueError(
            f"Invalid native function name {name!r}: must not contain whitespace"
            " or start/end with a dot"
        )
    validate_native_target(target)
    spark.conf.set(conf_key_for(name), f"{target}:{return_type.simpleString()}")

    call_function = _call_function_by_spark_session_type(spark)

    def _call(*cols: Any) -> "Column":
        return call_function(name, *cols)

    _call.__name__ = name
    return _call


def _call_function_by_spark_session_type(spark: "SparkSession") -> Any:
    """``call_function`` from the module matching ``spark``'s API flavour.

    ``pyspark.sql.functions`` and ``pyspark.sql.connect.functions`` are distinct modules with
    distinct ``Column`` classes, and each rejects the other's. Picking the wrong one fails as
    ``[NOT_COLUMN_OR_STR] Argument `col` should be a Column or str, got Column`` -- the same
    class name on both sides making the message read like a contradiction. A SCOS session is
    always a Connect session, so classic is only the fallback.
    """
    try:
        from pyspark.sql.connect.session import SparkSession as ConnectSparkSession

        if isinstance(spark, ConnectSparkSession):
            from pyspark.sql.connect.functions import call_function

            return call_function
    except ImportError:  # pragma: no cover - PySpark built without Connect
        pass

    from pyspark.sql.functions import call_function

    return call_function
