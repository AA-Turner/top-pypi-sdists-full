type JsonValue = bool | int | float | str | list[JsonValue] | dict[str, JsonValue] | None
type JsonObject = dict[str, JsonValue]

PACKAGE_ROOT = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = PACKAGE_ROOT.parents[1]
PRODUCTION_CONTRACT_PATH = REPOSITORY_ROOT / (
    "apps/managed-agents/api/src/openapi/recursion-public-openapi.preview.generated.json"
)
CONTRACT_PATH_ENVIRONMENT_VARIABLE = "RECURSION_PYTHON_SDK_CONTRACT_PATH"
OUTPUT_ROOT = PACKAGE_ROOT / "src/recursion_sdk/_generated"
HTTP_METHODS = ("delete", "get", "head", "options", "patch", "post", "put", "trace")
HTTP_SUCCESS_STATUS_MINIMUM = 200
HTTP_SUCCESS_STATUS_MAXIMUM_EXCLUSIVE = 300
HTTP_NOT_MODIFIED_STATUS = "304"
EMPTY_OBJECT_MAXIMUM_PROPERTIES = 0
STREAMING_OPERATIONS = frozenset(
    {"managedAgentsStreamSessionGestalt", "managedAgentsStreamSessionEvents"}
)
TYPE_PROJECTION_NAME = "RecursionSdkOperationTypes"
JSON_VALUE_NAME = "RecursionJsonValue"
MODEL_MODULE_NAME = "_recursion_python_sdk_generated_models"
JSON_ADAPTER = TypeAdapter(dict[str, JsonValue])
GENERATED_HEADER = "# Generated by tools/generate.py; do not edit.\n"


def contract_path() -> Path:
    override = os.environ.get(CONTRACT_PATH_ENVIRONMENT_VARIABLE)
    if override is None:
        return PRODUCTION_CONTRACT_PATH
    path = Path(override)
    if not path.is_absolute():
        raise ValueError(f"{CONTRACT_PATH_ENVIRONMENT_VARIABLE} must be an absolute file path")
    if not path.is_file():
        raise ValueError(f"{CONTRACT_PATH_ENVIRONMENT_VARIABLE} must point to an existing file")
    return path


def object_value(value: JsonValue, subject: str) -> JsonObject:
    if not isinstance(value, dict):
        raise ValueError(f"Expected an object for {subject}")
    return value


def string_value(value: JsonValue, subject: str) -> str:
    if not isinstance(value, str):
        raise ValueError(f"Expected a string for {subject}")
    return value


def array_value(value: JsonValue, subject: str) -> list[JsonValue]:
    if not isinstance(value, list):
        raise ValueError(f"Expected an array for {subject}")
    return value


def resolve(document: JsonObject, value: JsonValue) -> JsonObject:
    result = object_value(value, "contract entry")
    if "$ref" not in result:
        return result
    reference = string_value(result["$ref"], "$ref")
    if not reference.startswith("#/"):
        raise ValueError(f"External contract references are unsupported: {reference}")
    current: JsonValue = document
    for segment in reference[2:].split("/"):
        current = object_value(current, reference)[segment.replace("~1", "/").replace("~0", "~")]
    return object_value(current, reference)


def python_name(name: str) -> str:
    result = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    result = re.sub(r"([A-Z])([A-Z][a-z])", r"\1_\2", result)
    result = re.sub(r"[^a-zA-Z0-9_]", "_", result).lower()
    if keyword.iskeyword(result):
        result += "_"
    if not result.isidentifier():
        raise ValueError(f"Contract name is not a Python identifier: {name}")
    return result


@dataclass(frozen=True)
class Argument:
    wire_name: str
    name: str
    schema: JsonObject
    required: bool
    projection_key: str
    upload: bool = False


@dataclass(frozen=True)
class Operation:
    operation_id: str
    name: str
    description: str
    parameters: tuple[Argument, ...]
    form_fields: tuple[Argument, ...]
    body_required: bool
    body_projection_key: str | None
    response_projection_key: str


def union_schema(schemas: list[JsonObject]) -> JsonObject:
    distinct = {json.dumps(schema, sort_keys=True): schema for schema in schemas}
    if not distinct:
        raise ValueError("An operation has no declared successful response")
    if len(distinct) == 1:
        return next(iter(distinct.values()))
    return {"anyOf": list(distinct.values())}


def normalize_model_schema(
    schema: JsonObject, inherited_properties: JsonObject | None = None
) -> JsonObject:
    """Use equivalent JSON Schema spellings the model compiler can type precisely.

    Its nullable-object shorthand loses additionalProperties types. Explicit
    branches preserve them. A JSON-only type for unconstrained properties avoids
    Any; the packaged runtime contract always remains the original document.
    """
    schema = deepcopy(schema)
    # Composition branches constrain the same object. Preserve its already-known
    # property types when a branch contributes only a constraint such as `not`.
    known_properties = {
        **object_value(schema.get("properties", {}), "schema properties"),
        **(inherited_properties or {}),
    }
    for key in ("properties", "patternProperties", "$defs", "definitions"):
        if key not in schema:
            continue
        children = object_value(schema[key], key)
        for name, value in children.items():
            child = object_value(value, name)
            if key == "properties" and not any(
                constraint in child
                for constraint in (
                    "type",
                    "$ref",
                    "oneOf",
                    "anyOf",
                    "allOf",
                    "const",
                    "enum",
                    "properties",
                    "items",
                )
            ):
                inherited = object_value(
                    known_properties.get(name, {}), "inherited property schema"
                )
                inherited_type: JsonObject = {
                    key: inherited[key] for key in ("type", "$ref") if key in inherited
                }
                child = {
                    **child,
                    **(inherited_type or {"$ref": f"#/components/schemas/{JSON_VALUE_NAME}"}),
                }
            children[name] = normalize_model_schema(child)
    for key in ("allOf", "anyOf", "oneOf", "prefixItems"):
        if key in schema:
            schema[key] = [
                normalize_model_schema(
                    object_value(value, key), None if key == "prefixItems" else known_properties
                )
                for value in array_value(schema[key], key)
            ]
    for key in (
        "items",
        "additionalProperties",
        "if",
        "then",
        "else",
        "not",
        "contains",
        "propertyNames",
    ):
        if isinstance(schema.get(key), dict):
            schema[key] = normalize_model_schema(object_value(schema[key], key))
    if (
        schema.get("type") == "object"
        and schema.get("additionalProperties") is False
        and not schema.get("properties")
        and not schema.get("patternProperties")
    ):
        # The compiler types the uninhabited values of {} as Any. A typed value
        # schema plus maxProperties=0 preserves the exact same empty-object set.
        schema["additionalProperties"] = {"$ref": f"#/components/schemas/{JSON_VALUE_NAME}"}
        schema["maxProperties"] = EMPTY_OBJECT_MAXIMUM_PROPERTIES
    if isinstance(schema.get("type"), list) and "object" in array_value(
        schema["type"], "schema types"
    ):
        types = array_value(schema.pop("type"), "schema types")
        if any(key in schema for key in ("anyOf", "oneOf", "allOf")):
            raise ValueError(
                "Nullable model normalization requires a schema without existing unions"
            )
        default = {"default": schema.pop("default")} if "default" in schema else {}
        return {
            **default,
            "anyOf": [
                normalize_model_schema({**schema, "type": schema_type}) for schema_type in types
            ],
        }
    return schema


def operation_projection(document: JsonObject) -> tuple[JsonObject, tuple[Operation, ...]]:
    projection = deepcopy(document)
    components = object_value(projection["components"], "components")
    schemas = object_value(components["schemas"], "schemas")
    if any(
        name in schemas for name in (TYPE_PROJECTION_NAME, JSON_VALUE_NAME, "RecursionApiError")
    ):
        raise ValueError("Canonical schemas conflict with Python projection names")
    properties: JsonObject = {}
    operations: list[Operation] = []
    excluded: set[str] = set()
    names: set[str] = set()
    for path_value in object_value(document["paths"], "paths").values():
        path_item = resolve(document, path_value)
        for method in HTTP_METHODS:
            if method not in path_item:
                continue
            operation = resolve(document, path_item[method])
            operation_id = string_value(operation["operationId"], "operationId")
            if operation_id in STREAMING_OPERATIONS:
                excluded.add(operation_id)
                continue
            sdk_path = array_value(operation["x-sdk-path"], "x-sdk-path")
            if len(sdk_path) != 2 or sdk_path[0] != "managedAgents":
                raise ValueError(f"Unsupported SDK resource path: {sdk_path}")
            name = python_name(string_value(sdk_path[1], "SDK method"))
            if name in names:
                raise ValueError(f"Duplicate Python SDK method: {name}")
            names.add(name)
            parameters_by_location: dict[tuple[str, str], JsonObject] = {}
            for parameter_value in array_value(
                path_item.get("parameters", []), "path parameters"
            ) + array_value(operation.get("parameters", []), "operation parameters"):
                parameter = resolve(document, parameter_value)
                location = string_value(parameter["in"], "parameter location")
                wire_name = string_value(parameter["name"], "parameter name")
                if location not in {"path", "query", "header"}:
                    raise ValueError(f"Unsupported parameter location: {location}")
                parameters_by_location[location, wire_name] = parameter
            parameters: list[Argument] = []
            argument_names: set[str] = {"self"}
            for (location, wire_name), parameter in parameters_by_location.items():
                argument_name = python_name(wire_name)
                if argument_name in argument_names or argument_name == "body":
                    raise ValueError(f"Duplicate argument in {operation_id}: {argument_name}")
                argument_names.add(argument_name)
                key = f"{name}_parameter_{argument_name}"
                schema = object_value(parameter["schema"], "parameter schema")
                properties[key] = schema
                parameters.append(
                    Argument(
                        wire_name,
                        argument_name,
                        schema,
                        parameter.get("required") is True or location == "path",
                        key,
                    )
                )
            body_required = False
            body_projection_key = None
            form_fields: list[Argument] = []
            if "requestBody" in operation:
                body = resolve(document, operation["requestBody"])
                body_required = body.get("required") is True
                media = object_value(body["content"], "request media")
                if len(media) != 1:
                    raise ValueError(f"Ambiguous request media types for {operation_id}")
                media_type, media_value = next(iter(media.items()))
                body_schema = object_value(
                    object_value(media_value, "request media")["schema"], "body schema"
                )
                if media_type == "application/json":
                    body_projection_key = f"{name}_body"
                    properties[body_projection_key] = body_schema
                elif media_type == "multipart/form-data":
                    form = resolve(document, body_schema)
                    required_fields = array_value(form.get("required", []), "form required fields")
                    for wire_name, field_value in object_value(
                        form["properties"], "form properties"
                    ).items():
                        field_schema = object_value(field_value, "form field schema")
                        field_name = python_name(wire_name)
                        if field_name in argument_names:
                            raise ValueError(
                                f"Duplicate form argument for {operation_id}: {field_name}"
                            )
                        argument_names.add(field_name)
                        key = f"{name}_form_{field_name}"
                        properties[key] = field_schema
                        form_fields.append(
                            Argument(
                                wire_name,
                                field_name,
                                field_schema,
                                wire_name in required_fields,
                                key,
                                field_schema.get("format") == "binary",
                            )
                        )
                else:
                    raise ValueError(f"Unsupported request media type: {media_type}")
            successes: list[JsonObject] = []
            for status, response_value in object_value(operation["responses"], "responses").items():
                if not status.isdigit():
                    raise ValueError(f"Unsupported response status for {operation_id}: {status}")
                if not (
                    HTTP_SUCCESS_STATUS_MINIMUM
                    <= int(status)
                    < HTTP_SUCCESS_STATUS_MAXIMUM_EXCLUSIVE
                    or status == HTTP_NOT_MODIFIED_STATUS
                ):
                    continue
                response = resolve(document, response_value)
                media = object_value(response.get("content", {}), "response media")
                if not media:
                    successes.append({"type": "null"})
                for media_type, media_value in media.items():
                    schema = object_value(
                        object_value(media_value, "response media")["schema"], "response schema"
                    )
                    if media_type != "application/json" and schema.get("format") != "binary":
                        raise ValueError(
                            f"Unsupported successful response media type: {media_type}"
                        )
                    successes.append(schema)
            response_key = f"{name}_response"
            properties[response_key] = union_schema(successes)
            description = string_value(
                operation.get("summary", operation.get("description", operation_id)),
                "operation description",
            )
            operations.append(
                Operation(
                    operation_id,
                    name,
                    description,
                    tuple(parameters),
                    tuple(form_fields),
                    body_required,
                    body_projection_key,
                    response_key,
                )
            )
    if excluded != STREAMING_OPERATIONS:
        raise ValueError(f"Streaming exclusions no longer match the canonical contract: {excluded}")
    schemas[TYPE_PROJECTION_NAME] = {
        "description": "Internal compilation projection for generated endpoint annotations.",
        "type": "object",
        "additionalProperties": False,
        "properties": properties,
        "required": list(properties),
    }
    error_mapping: JsonObject = {}
    for name, schema_value in schemas.items():
        if not name.startswith("ManagedAgentsApiError"):
            continue
        schema = object_value(schema_value, name)
        error_properties = object_value(schema.get("properties", {}), "error properties")
        if "code" not in error_properties:
            continue
        code = object_value(error_properties["code"], "error code")
        values = array_value(code.get("enum", []), "error code enum")
        if len(values) != 1:
            raise ValueError(f"Expected one error code discriminator for {name}")
        discriminator = string_value(values[0], "error code")
        if discriminator in error_mapping:
            raise ValueError(f"Duplicate API error discriminator: {discriminator}")
        error_mapping[discriminator] = f"#/components/schemas/{name}"
    schemas["RecursionApiError"] = {
        "oneOf": [{"$ref": reference} for reference in error_mapping.values()],
        "discriminator": {"propertyName": "code", "mapping": error_mapping},
    }
    for name, schema_value in schemas.items():
        schemas[name] = normalize_model_schema(object_value(schema_value, name))
    json_reference: JsonObject = {"$ref": f"#/components/schemas/{JSON_VALUE_NAME}"}
    schemas[JSON_VALUE_NAME] = {
        "anyOf": [
            {"type": "null"},
            {"type": "boolean"},
            {"type": "string"},
            {"type": "integer"},
            {"type": "number"},
            {"type": "array", "items": json_reference},
            {"type": "object", "additionalProperties": json_reference},
        ]
    }
    return projection, tuple(operations)


def python_annotation(annotation: object) -> str:
    """Render finalized compiler symbols, without interpreting JSON Schema types."""
    origin = get_origin(annotation)
    arguments = get_args(annotation)
    if origin is Annotated:
        return python_annotation(arguments[0])
    if origin in (Union, UnionType):
        return " | ".join(python_annotation(argument) for argument in arguments)
    if origin is Literal:
        return f"Literal[{', '.join(repr(argument) for argument in arguments)}]"
    if origin in (list, dict):
        return (
            f"{origin.__name__}[{', '.join(python_annotation(argument) for argument in arguments)}]"
        )
    if annotation is NoneType or annotation is None:
        return "None"
    if isinstance(annotation, type):
        if annotation.__module__ == MODEL_MODULE_NAME:
            return f"models.{annotation.__name__}"
        if annotation.__module__ == "builtins":
            return annotation.__name__
        if annotation.__module__ == "uuid":
            return f"uuid.{annotation.__name__}"
        if annotation.__module__ == "datetime":
            return f"datetime.{annotation.__name__}"
        if annotation.__module__.startswith("pydantic"):
            return f"pydantic.{annotation.__name__}"
    raise ValueError(f"Unsupported compiled operation annotation: {annotation!r}")


def load_type_projection(path: Path) -> dict[str, str]:
    spec = importlib.util.spec_from_file_location(MODEL_MODULE_NAME, path)
    if spec is None or spec.loader is None:
        raise ValueError("Cannot load generated model projection")
    module = importlib.util.module_from_spec(spec)
    sys.modules[MODEL_MODULE_NAME] = module
    spec.loader.exec_module(module)
    projection: object = getattr(module, TYPE_PROJECTION_NAME)
    if not isinstance(projection, type) or not issubclass(projection, BaseModel):
        raise ValueError("Model compiler did not produce the operation projection")
    return {
        name: python_annotation(field.annotation) for name, field in projection.model_fields.items()
    }


def validate_generated_source(source: str, subject: str) -> None:
    """Reject unrestricted Python types before publishing the compiler's output."""
    for node in ast.walk(ast.parse(source)):
        if (
            (isinstance(node, ast.Name) and node.id == "Any")
            or (isinstance(node, ast.Attribute) and node.attr == "Any")
            or (isinstance(node, ast.alias) and node.name in {"Any", "typing.Any"})
        ):
            raise ValueError(f"{subject} emitted an unrestricted Python Any type")


def render_client(operations: tuple[Operation, ...], annotations: dict[str, str]) -> str:
    lines = [
        GENERATED_HEADER,
        "from __future__ import annotations",
        "",
        "import datetime",
        "import uuid",
        "from typing import Literal",
        "",
        "import httpx",
        "import pydantic",
        "from pydantic import TypeAdapter",
        "",
        "from .._transport import AsyncTransport, SyncTransport, DEFAULT_BASE_URL, DEFAULT_TIMEOUT",
        "from .._types import ApiResponse, UNSET, Unset, Upload",
        "from . import models",
        "",
    ]
    for operation in operations:
        response_type = annotations[operation.response_projection_key]
        lines.append(
            f"_{operation.name.upper()}_RESPONSE = TypeAdapter[{response_type}]({response_type})"
        )
    for asynchronous in (False, True):
        prefix = "Async" if asynchronous else ""
        transport = f"{prefix}Transport" if asynchronous else "SyncTransport"
        lines += [
            "",
            "",
            f"class {prefix}ManagedAgents:",
            f"    def __init__(self, transport: {transport}) -> None:",
            "        self._transport = transport",
        ]
        for operation in operations:
            arguments = list(operation.parameters) + list(operation.form_fields)
            response_type = annotations[operation.response_projection_key]
            lines += [
                "",
                f"    {'async ' if asynchronous else ''}def {operation.name}(",
                "        self,",
            ]
            if arguments or operation.body_projection_key is not None:
                lines.append("        *,")
            for argument in arguments:
                annotation = "Upload" if argument.upload else annotations[argument.projection_key]
                if argument in operation.parameters and argument.schema.get("format") == "uuid":
                    annotation += " | str"
                if (
                    argument in operation.parameters
                    and argument.schema.get("format") == "date-time"
                ):
                    annotation += " | str"
                default = "" if argument.required else " | None | Unset = UNSET"
                lines.append(f"        {argument.name}: {annotation}{default},")
            if operation.body_projection_key is not None:
                annotation = annotations[operation.body_projection_key]
                default = "" if operation.body_required else " | Unset = UNSET"
                lines.append(f"        body: {annotation}{default},")
            lines += [
                f"    ) -> ApiResponse[{response_type}]:",
                f"        {operation.description!r}",
                f"        return {'await ' if asynchronous else ''}self._transport.request(",
                f"            {operation.operation_id!r},",
                "            parameters={",
            ]
            lines += [
                f"                {argument.wire_name!r}: {argument.name},"
                for argument in operation.parameters
            ]
            lines.append("            },")
            if operation.form_fields:
                lines.append("            body={")
                lines += [
                    f"                {argument.wire_name!r}: {argument.name},"
                    for argument in operation.form_fields
                ]
                lines.append("            },")
            elif operation.body_projection_key is not None:
                lines.append("            body=body,")
            lines += [
                f"            response_adapter=_{operation.name.upper()}_RESPONSE,",
                "        )",
            ]
        client = f"{prefix}Recursion"
        lines += [
            "",
            "",
            f"class {client}({transport}):",
            "    def __init__(",
            "        self,",
            "        api_key: str,",
            "        *,",
            "        base_url: str = DEFAULT_BASE_URL,",
            "        organization_id: str | None = None,",
            "        tenant_id: str | None = None,",
            f"        transport: httpx.{prefix}BaseTransport | None = None,",
            "        timeout: float | httpx.Timeout = DEFAULT_TIMEOUT,",
            "    ) -> None:",
            "        super().__init__(api_key, base_url=base_url, organization_id=organization_id,",
            "            tenant_id=tenant_id, transport=transport, timeout=timeout)",
            f"        self.managed_agents = {prefix}ManagedAgents(self)",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    contract_bytes = contract_path().read_bytes()
    document = JSON_ADAPTER.validate_json(contract_bytes, strict=True)
    projection, operations = operation_projection(document)
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix=".generation-", dir=PACKAGE_ROOT) as temporary_directory:
        temporary_root = Path(temporary_directory)
        input_path = temporary_root / "recursion-sdk-openapi.json"
        input_path.write_text(json.dumps(projection, indent=2) + "\n")
        model_path = temporary_root / "models.py"
        generate(
            input_path,
            input_file_type=InputFileType.OpenAPI,
            output=model_path,
            output_model_type=DataModelType.PydanticV2BaseModel,
            target_python_version=PythonVersion.PY_312,
            use_standard_collections=True,
            use_union_operator=True,
            field_constraints=True,
            set_default_enum_member=True,
            disable_timestamp=True,
            formatters=[Formatter.BUILTIN],
            enum_field_as_literal=LiteralType.All,
            snake_case_field=True,
            allow_population_by_field_name=True,
            output_datetime_class=DatetimeClassType.Datetime,
        )
        validate_generated_source(model_path.read_text(), "Model compiler")
        annotations = load_type_projection(model_path)
        client = render_client(operations, annotations)
        validate_generated_source(client, "Endpoint generator")
        (OUTPUT_ROOT / "models.py").write_bytes(model_path.read_bytes())
        (OUTPUT_ROOT / "client.py").write_text(client)
        (OUTPUT_ROOT / "openapi.json").write_bytes(contract_bytes)
        (OUTPUT_ROOT / "__init__.py").write_text(GENERATED_HEADER)
    print(
        f"Generated {len(operations)} request/response operations; "
        f"excluded {len(STREAMING_OPERATIONS)} streams."
    )


if __name__ == "__main__":
    main()
