"""
Directory page creator for Zensical documentation.

Creates directory.md pages automatically from directory.toml configuration files.
The generated pages include a table of markdown files in the directory with
their titles, links, and recency information based on git commit history.

Enhanced metadata includes:
- Commit count and unique contributors
- Last two authors with email hyperlinks
- Word count
- Primary owner from frontmatter
- Missing frontmatter indicator
"""

