# ── Fetch ──────────────────────────────────────────────────────────────────────

def get_title_from_file(file_path: Path) -> str:
    try:
        content = file_path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return file_path.stem.replace("-", " ").replace("_", " ").title()

    if content.startswith("---"):
        end = content.find("---", 3)
        if end != -1:
            frontmatter = content[3:end]
            match = re.search(r'^title:\s*["\']?(.+?)["\']?\s*$', frontmatter, re.MULTILINE)
            if match:
                return match.group(1).strip()

    match = re.search(r'^#\s+(.+)$', content, re.MULTILINE)
    if match:
        return match.group(1).strip()

    return file_path.stem.replace("-", " ").replace("_", " ").title()


def get_file_commits(
    file_path: Path,
    commit_map: Optional[dict[str, list[dict[str, str]]]],
    docs_root: Optional[Path] = None,
) -> list[dict[str, str]]:
    if not commit_map:
        return []

    if docs_root is None:
        docs_root = Path("docs").resolve()

    try:
        rel_path = str(file_path.resolve().relative_to(docs_root))
    except ValueError:
        return []

    return commit_map.get(rel_path, [])


def get_unique_contributors(commits: list[dict[str, str]]) -> int:
    return len({c.get("email", "").lower() for c in commits if c.get("email")})


def get_last_two_authors(commits: list[dict[str, str]]) -> list[tuple[str, str]]:
    seen: set[str] = set()
    authors: list[tuple[str, str]] = []
    for commit in commits:
        email = commit.get("email", "").lower()
        if email and email not in seen:
            seen.add(email)
            authors.append((commit.get("author", "Unknown"), commit.get("email", "")))
            if len(authors) >= 2:
                break
    return authors


def get_content_info(file_path: Path) -> dict:
    result: dict = {"word_count": 0, "has_frontmatter": False}
    try:
        content = file_path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return result

    if content.startswith("---"):
        end = content.find("---", 3)
        if end != -1:
            result["has_frontmatter"] = True
            content = content[end + 3:]

    content = re.sub(r'```[\s\S]*?```', '', content)
    content = re.sub(r'`[^`]+`', '', content)
    content = re.sub(r'<[^>]+>', '', content)
    content = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', content)
    content = re.sub(r'!\[[^\]]*\]\([^)]+\)', '', content)
    result["word_count"] = len(content.split())
    return result


def get_last_modified(
    file_path: Path,
    commit_map: Optional[dict[str, list[dict[str, str]]]],
    docs_root: Optional[Path] = None,
) -> Optional[str]:
    if not commit_map:
        return None
    if docs_root is None:
        docs_root = Path("docs").resolve()
    try:
        rel_path = str(file_path.resolve().relative_to(docs_root))
    except ValueError:
        return None
    commits = commit_map.get(rel_path, [])
    return commits[0].get("date") if commits else None


def _recency_from_date(last_modified: Optional[str]) -> str:
    if not last_modified:
        return ""
    try:
        days = (datetime.now(timezone.utc) - datetime.fromisoformat(last_modified.replace("Z", "+00:00"))).days
        if days == 0:    return "today"
        if days == 1:    return "yesterday"
        if days < 7:     return f"{days} days ago"
        if days < 14:    return "last week"
        if days < 30:    return f"{days // 7} weeks ago"
        if days < 60:    return "last month"
        if days < 365:   return f"{days // 30} months ago"
        if days < 730:   return "last year"
        return f"{days // 365} years ago"
    except Exception:
        return ""


def get_recency(
    file_path: Path,
    commit_map: Optional[dict[str, list[dict[str, str]]]],
    docs_root: Optional[Path] = None,
) -> str:
    return _recency_from_date(get_last_modified(file_path, commit_map, docs_root))


def _safe_int(value: object) -> int:
    try:
        return int(str(value).strip() or 0)
    except (TypeError, ValueError):
        return 0


_TEAM_SHORT_CACHE: dict[str, str] = {}


def _read_team_short(hub_root: Path) -> str:
    """Hub's own team name from zensical.toml [project].team_name_short (cached)."""
    key = str(hub_root)
    if key not in _TEAM_SHORT_CACHE:
        val = ""
        try:
            with open(hub_root / "zensical.toml", "rb") as f:
                data = tomllib.load(f)
            proj = data.get("project", {}) if isinstance(data.get("project"), dict) else {}
            val = str(proj.get("team_name_short") or data.get("team_name_short") or "")
        except Exception:
            val = ""
        _TEAM_SHORT_CACHE[key] = val
    return _TEAM_SHORT_CACHE[key]


def _parse_recent_authors(frontmatter: dict) -> list[tuple[str, str]]:
    """Parse git_recent_authors (['Name <email>', ...]) → [(name, email), ...]."""
    raw = frontmatter.get("git_recent_authors", "")
    items: list[str] = []
    if isinstance(raw, list):
        items = [str(x) for x in raw]
    elif isinstance(raw, str) and raw.strip():
        s = raw.strip()
        if s.startswith("[") and s.endswith("]"):
            s = s[1:-1]
        items = [p.strip().strip("'\"") for p in s.split(",") if p.strip()]
    out: list[tuple[str, str]] = []
    for it in items:
        m = re.match(r"^(.*?)\s*<([^>]*)>$", it)
        out.append((m.group(1).strip(), m.group(2).strip()) if m else (it, ""))
    return out[:2]


def get_front_matter(file_path: Path) -> dict:
    try:
        content = file_path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return {}
    if not content.startswith("---"):
        return {}
    end = content.find("---", 3)
    if end == -1:
        return {}
    result: dict = {}
    for line in content[3:end].strip().split("\n"):
        if ":" in line:
            key, _, value = line.partition(":")
            result[key.strip()] = value.strip().strip('"\'')
    return result


def get_authors_from_frontmatter(frontmatter: dict) -> str:
    raw_value = frontmatter.get("authors", frontmatter.get("author", ""))
    if not raw_value:
        return ""
    authors: list[str] = []
    if isinstance(raw_value, list):
        for item in raw_value:
            if isinstance(item, dict):
                name = item.get("name") or item.get("Name")
                if name:
                    authors.append(str(name).strip())
            elif isinstance(item, str) and item.strip():
                authors.append(item.strip())
    elif isinstance(raw_value, str):
        s = raw_value.strip()
        if s.startswith("[") and s.endswith("]"):
            authors = [a.strip().strip("'\"") for a in s[1:-1].split(",") if a.strip()]
        elif "," in s:
            authors = [a.strip() for a in s.split(",") if a.strip()]
        elif s:
            authors = [s]
    return "<br>".join(a for a in authors if a)



# ── Prepare ────────────────────────────────────────────────────────────────────

def get_page_staleness_status(last_modified: Optional[str]) -> Optional[str]:
    if not last_modified:
        return None
    try:
        days = (datetime.now(timezone.utc) - datetime.fromisoformat(last_modified.replace("Z", "+00:00"))).days
        if days > STALENESS_UNMAINTAINED_DAYS:    return "unmaintained"
        if days > STALENESS_CONTACT_AUTHOR_DAYS:  return "contactauthor"
        if days > STALENESS_CAUTION_DAYS:         return "caution"
        return "recent"
    except Exception:
        return None


def _match_source_path(rel_dir: str, source_repos: dict[str, str]) -> str:
    for name in sorted(source_repos, key=len, reverse=True):
        prefix = name.rstrip("/") + "/"
        if rel_dir.startswith(prefix) or rel_dir == name.rstrip("/"):
            return name
    return ""


def _process_toml(
    toml_path: Path,
    docs_path: Path,
    commit_map: Optional[dict[str, list[dict[str, str]]]],
    renderer: "DefaultDirectoryRenderer",
    source_repos: Optional[dict[str, str]] = None,
    source_branches: Optional[dict[str, str]] = None,
) -> bool:
    directory = toml_path.parent

    try:
        with open(toml_path, "rb") as f:
            config = tomllib.load(f)
    except Exception as e:
        print(f"[directory_creator] Error reading {toml_path}: {e}")
        return False

    if "title" not in config:
        config = dict(config)
        config["title"] = directory.name.replace("-", " ").replace("_", " ").title()

    _rel_dir = str(directory.relative_to(docs_path)).replace("\\", "/")
    _source_path = _match_source_path(_rel_dir, source_repos) if source_repos else ""
    _repo_url = source_repos.get(_source_path, "") if source_repos else ""
    config = {**config, "_repo_url": _repo_url}   # one set of repo links per source

    root_rel = config.get("root", "")
    scan_dir = (directory / root_rel).resolve() if root_rel else directory

    # Filenames excluded everywhere (generated outputs)
    _exclude_names = {"overview.md", "links.md", "migrationstatus.md"}
    # Paths excluded relative to scan_dir (root homepage only)
    exclude = set(config.get("exclude", []))
    exclude.add("index.md")

    group_cache: dict[Path, str] = {}

    def get_group_from_toml(dir_path: Path) -> str:
        if dir_path in group_cache:
            return group_cache[dir_path]
        toml_file = dir_path / "directory.toml"
        if toml_file.exists():
            try:
                with open(toml_file, "rb") as f:
                    tcfg = tomllib.load(f)
                group_val = tcfg.get("group")
                if group_val is not None:
                    group_cache[dir_path] = group_val
                    return group_val
            except Exception:
                pass
        group_cache[dir_path] = ""
        return ""

    def find_group_for_file(md_file: Path) -> str:
        current = md_file.parent.resolve()
        docs_root = None
        for parent in [current] + list(current.parents):
            if parent.name == "docs":
                docs_root = parent
                break
        if docs_root is None:
            return ""
        found_groups: list[tuple[Path, str]] = []
        for parent in [md_file.parent.resolve()] + list(md_file.parent.resolve().parents):
            if parent == docs_root:
                break
            if (parent / "directory.toml").exists():
                group_val = get_group_from_toml(parent)
                found_groups.append((parent, group_val if group_val else parent.name))
        return found_groups[-1][1] if found_groups else ""

    files: list[dict] = []

    for md_file in scan_dir.rglob("*.md"):
        try:
            md_file.relative_to(docs_path)
        except ValueError:
            continue  # skip files outside docs/ (e.g. README.md at repo root)
        rel_path = str(md_file.relative_to(scan_dir)).replace("\\", "/")
        if md_file.name in _exclude_names:
            continue
        if rel_path in exclude or any(rel_path.startswith(e.rstrip("/") + "/") for e in exclude if e.endswith("/")):
            continue
        if any(part in SCAN_EXCLUDE_DIRS for part in md_file.relative_to(scan_dir).parts):
            continue
        if md_file.name.startswith(".") or any(
            p.startswith(".") for p in md_file.relative_to(scan_dir).parts
        ):
            continue

        commits = get_file_commits(md_file, commit_map, docs_path)
        frontmatter = get_front_matter(md_file)
        content_info = get_content_info(md_file)
        page_title = get_title_from_file(md_file)

        if commits:
            last_modified = commits[0].get("date")
            commit_count = len(commits)
            unique_contributors = get_unique_contributors(commits)
            last_two_authors = get_last_two_authors(commits)
        else:
            # No hub history — fall back to import_sources-stamped frontmatter
            # (pages imported from another repo, stamped from THAT repo's git).
            last_modified = frontmatter.get("git_revision_date") or None
            commit_count = _safe_int(frontmatter.get("git_commit_count"))
            unique_contributors = _safe_int(frontmatter.get("git_unique_contributors"))
            last_two_authors = _parse_recent_authors(frontmatter)

        _gitlab_url = ""
        if source_repos:
            _docs_rel = str(md_file.relative_to(docs_path)).replace("\\", "/")
            _file_source = _match_source_path(_docs_rel, source_repos)
            _file_repo_url = source_repos.get(_file_source, "")
            if _file_repo_url:
                _file_branch = (source_branches or {}).get(_file_source, "main")
                _file_in_source = _docs_rel[len(_file_source.rstrip("/")) + 1:]
                _gitlab_url = f"{_file_repo_url.rstrip('/')}/-/blob/{_file_branch}/docs/{_file_in_source}"

        site_rel = str(md_file.relative_to(docs_path)).replace("\\", "/")
        _group = find_group_for_file(md_file)
        files.append({
            "path": md_file,
            "rel_path": rel_path,
            "site_path": site_rel,
            "title": page_title,
            "recency": _recency_from_date(last_modified),
            "last_modified": last_modified,
            "commit_count": commit_count,
            "unique_contributors": unique_contributors,
            "last_two_authors": last_two_authors,
            "word_count": content_info["word_count"],
            "owner": get_authors_from_frontmatter(frontmatter),
            "has_frontmatter": content_info["has_frontmatter"],
            "group": _group,
            "team": frontmatter.get("team_name") or _read_team_short(docs_path.parent) or _group,
            "page_status": (
                frontmatter.get("pagestatus")
                if frontmatter.get("pagestatus") == "script"
                else get_page_staleness_status(last_modified)
            ),
            "gitlab_url": _gitlab_url,
        })

    subdirs: list[dict] = []
    for subdir in sorted(directory.iterdir()):
        if subdir.is_dir() and not subdir.name.startswith("."):
            has_content = any(subdir.rglob("*.md")) or any(
                d.is_dir() and not d.name.startswith(".") for d in subdir.iterdir()
            )
            if has_content:
                subdirs.append({
                    "path": subdir,
                    "rel_path": subdir.name,
                    "title": subdir.name.replace("-", " ").replace("_", " ").title(),
                    "is_directory": True,
                })

    if not files and not subdirs:
        return False

    order_by = config.get("order_by", "name")
    if order_by == "last_modified":
        files.sort(key=lambda x: x["last_modified"] or "", reverse=False)
    elif order_by == "title":
        files.sort(key=lambda x: x["title"].lower())
    else:
        files.sort(key=lambda x: x["rel_path"].lower())

    content = renderer.render(config, files)

    out_dir = directory / "directory"
    out_dir.mkdir(parents=True, exist_ok=True)

    output_path = out_dir / "overview.md"
    try:
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"[directory_creator] Created: {output_path}")
    except Exception as e:
        print(f"[directory_creator] Error writing {output_path}: {e}")
        return False

    csv_path = out_dir / "overview.csv"
    try:
        with open(csv_path, "w", encoding="utf-8", newline="") as f:
            f.write(generate_directory_csv(files))
    except Exception as e:
        print(f"[directory_creator] Error writing {csv_path}: {e}")

    return True


def create_directory_pages(
    docs_dir: str = "docs",
    commit_map: Optional[dict[str, list[dict[str, str]]]] = None,
    source_repos: Optional[dict[str, str]] = None,
    source_branches: Optional[dict[str, str]] = None,
) -> int:
    docs_path = Path(docs_dir).resolve()
    created_count = 0

    if not docs_path.exists():
        print(f"[directory_creator] Docs directory not found: {docs_dir}")
        return 0

    renderer = DefaultDirectoryRenderer()

    for toml_file in docs_path.rglob("directory.toml"):
        try:
            if _process_toml(toml_file, docs_path, commit_map, renderer, source_repos, source_branches):
                created_count += 1
        except Exception as e:
            print(f"[directory_creator] Error processing {toml_file}: {e}")

    if created_count > 0:
        print(f"[directory_creator] Created {created_count} directory page(s)")

    return created_count


# ── Postprocess ────────────────────────────────────────────────────────────────

class DefaultDirectoryRenderer:
    def render(self, config: dict, files: list[dict]) -> str:
        title = config.get("title", "Directory")
        description = config.get("description", "")
        order_by = config.get("order_by", "name")

        subdirs: list[dict] = []
        show_recency = any(f.get("last_modified") for f in files)

        files = list(files)
        if order_by == "last_modified":
            files.sort(key=lambda x: x.get("last_modified") or "", reverse=False)
        elif order_by == "title":
            files.sort(key=lambda x: x.get("title", "").lower())
        else:
            files.sort(key=lambda x: (x.get("rel_path") or "").lower())

        return generate_directory_md(title, description, files, subdirs, show_recency,
                                     config.get("_repo_url", ""))


def format_last_edit_date(iso_date: Optional[str]) -> str:
    if not iso_date:
        return ""
    try:
        return datetime.fromisoformat(iso_date.replace("Z", "+00:00")).strftime("%b %d, %Y")
    except Exception:
        return ""


def format_authors_cell(authors: list[tuple[str, str]]) -> str:
    if not authors:
        return "—"
    parts = []
    for name, email in authors:
        display_name = name[:AUTHOR_NAME_MAX_LEN] + "…" if len(name) > AUTHOR_NAME_MAX_LEN else name
        parts.append(f'<a href="mailto:{email}">{display_name}</a>' if email else display_name)
    return "<br>".join(parts)


def format_staleness_badge(
    page_status: Optional[str],
    last_modified: Optional[str],
) -> str:
    if page_status not in _STALENESS_AGE_CSS:
        return STALENESS_BADGES.get(page_status or "", STALENESS_BADGE_FALLBACK)

    css  = _STALENESS_AGE_CSS[page_status]
    icon = _STALENESS_AGE_ICON[page_status]

    if page_status == "contactauthor":
        return f"<span class='{css}'>{icon} Marked for Review</span>"

    if page_status == "unmaintained":
        return f"<span class='{css}'>{icon} Unmaintained</span>"

    age_str = ""
    if last_modified:
        try:
            days  = (datetime.now(timezone.utc) - datetime.fromisoformat(last_modified.replace("Z", "+00:00"))).days
            years = days // 365
            months = (days % 365) // 30
            if years and months:
                age_str = f"{years} year{'s' if years > 1 else ''} {months} month{'s' if months > 1 else ''} ago"
            elif years:
                age_str = f"{years} year{'s' if years > 1 else ''} ago"
            else:
                age_str = f"{months} month{'s' if months > 1 else ''} ago" if months > 1 else "this month"
        except Exception:
            pass

    label = f"Last updated {age_str}" if age_str else "Last updated"
    return f"<span class='{css}'>{icon} {label}</span>"


def generate_directory_csv(files: list[dict]) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["Group", "Title", "GitLab URL", "Last Edit", "Commits", "Contributors", "Status"])
    for f in sorted(files, key=lambda x: x.get("title", "").lower()):
        writer.writerow([
            f.get("group", ""),
            f.get("title", ""),
            f.get("gitlab_url", ""),
            format_last_edit_date(f.get("last_modified")),
            f.get("commit_count", 0),

            f.get("unique_contributors", 0),
            f.get("page_status") or "",
        ])
    return buf.getvalue()


def generate_directory_md(
    title: str,
    description: str,
    files: list[dict],
    subdirs: list[dict],
    show_recency: bool,
    repo_url: str = "",
) -> str:
    lines: list[str] = []

    lines.append("---")
    lines.append(f"title: {title}")
    lines.append(f"icon: {PAGE_ICON}")
    lines.append(f"pagestatus: script")
    lines.append(f"dategenerated: \"{datetime.now().strftime('%Y-%m-%d')}\"")
    lines.append(f"csv_download: overview.csv")
    lines.append(f"hide:")
    for h in PAGE_HIDE:
        lines.append(f"  - {h}")
    lines.append(f"boost: {PAGE_BOOST}")
    lines.append("tags:")
    for tag in PAGE_TAGS:
        lines.append(f"  - \"{tag}\"")
    lines.append(f"")
    lines.append(f"---")
    lines.append("")
    lines.append(f"# {title}")
    lines.append("")

    if description:
        lines.append(description)
        lines.append("")

    if repo_url:
        repo = repo_url.rstrip("/").removesuffix(".git")
        lines.append(
            f"[:lucide-circle-dot: Issues]({repo}/-/issues){{ .md-button .md-button--compact }} "
            f"[:lucide-git-merge: Merge Requests]({repo}/-/merge_requests){{ .md-button .md-button--compact }} "
            f"[:lucide-tag: Releases]({repo}/-/releases){{ .md-button .md-button--compact }}"
        )
        lines.append("")

    lines.append(PAGE_AUTOGENERATED_NOTE)

    if not show_recency:
        lines.append(PAGE_GIT_SETUP_GUIDE)

    if files:
        if subdirs:
            lines.append("## :lucide-file-down: Pages")
            lines.append("")

        lines.append('<div class="dense-table" markdown>')
        if show_recency:
            lines.append("| Team | Page | Last Edit | :lucide-git-commit-vertical: Commits | :lucide-user-pen: Authors | :lucide-history: Recent Authors | Status |")
            lines.append("|------|------|-----------|:-------:|:-------:|------------------|--------|")
        else:
            lines.append("| Team | Page | Status |")
            lines.append("|------|------|--------|")

        for file_info in files:
            page_title = file_info["title"].replace("|", "\\|")
            if len(page_title) > 45:
                page_title = page_title[:42] + '...'

            site_path = file_info.get("site_path") or file_info["rel_path"]
            link = site_path.replace(".md", "").replace("\\", "/")
            if link.endswith("/index"):
                link = link[:-6] or link
            elif link == "index":
                link = ""
            link = "/" + link if link else "/"
            authors_html = format_authors_cell(file_info.get("last_two_authors", []))
            page_status = file_info.get("page_status")
            staleness_badge = format_staleness_badge(page_status, file_info.get("last_modified"))
            group = file_info.get("team") or file_info.get("group", "")

            if show_recency:
                lines.append(
                    f"| {group} "
                    f"| [{page_title}]({link}) "
                    f"| {format_last_edit_date(file_info.get('last_modified'))} "
                    f"| {file_info.get('commit_count', 0)} "
                    f"| {file_info.get('unique_contributors', 0)} "
                    f"| {authors_html} "
                    f"| {staleness_badge} |"
                )
            else:
                lines.append(
                    f"| {group} "
                    f"| [{page_title}]({link}) "
                    f"| {staleness_badge} |"
                )

    lines.append("</div>")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(":lucide-link: **[External Links Summary](links.md)** — all external links found across pages in this directory.")
    lines.append("")

    return "\n".join(lines)


def main() -> None:
    import json
    import os
    import sys
    from .prepare_git_history import INJECT_GIT_FRONTMATTER, inject_git_frontmatter

    hub_dir = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path.cwd()

    cache_file = hub_dir / ".git_history_cache.json"
    commit_map = None
    if cache_file.exists():
        try:
            with cache_file.open() as f:
                commit_map = json.load(f)
            print(f"[prepare_directory_pages] Loaded commit map ({len(commit_map)} files)")
        except Exception as exc:
            print(f"[prepare_directory_pages] Could not load cache: {exc}")

    create_directory_pages(docs_dir=str(hub_dir / "docs"), commit_map=commit_map)

    if os.environ.get("CI") and INJECT_GIT_FRONTMATTER:
        if commit_map:
            n = inject_git_frontmatter(commit_map, hub_dir / "docs")
            print(f"[prepare_directory_pages] Injected git frontmatter into {n} file(s)")
        else:
            print("[prepare_directory_pages] Skipping frontmatter injection — no commit map")


if __name__ == "__main__":
    main()
