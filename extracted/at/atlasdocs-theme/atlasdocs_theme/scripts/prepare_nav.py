from __future__ import annotations

"""
Patch zensical.toml nav placeholders at build time.

Finds empty nav entries like  {"Meetings" = []}  and  {"JIRA" = []}
and replaces them with the actual pages generated by prepare_indico_pages
and prepare_jira_pages.  Idempotent — already-expanded entries are also
matched and replaced, so the script is safe to re-run.

Usage
-----
    python -m atlasdocs_theme.scripts.prepare_nav [hub_dir]

Pixi:
    pixi run prepare-nav
"""

import re
import sys
import tomllib
from pathlib import Path


# ── Configuration ──────────────────────────────────────────────────────────────

ZENSICAL_TOML    = "zensical.toml"
INDICO_CONFIG    = "indico.toml"
JIRA_CONFIG      = "jira.toml"
INDICO_DOCS_DIR  = "docs/category"
JIRA_DOCS_DIR    = "docs/jira/projects"
MEETINGS_PAGE    = "meetings.md"


# ── Nav entry helpers ──────────────────────────────────────────────────────────

def _format_nav_entry(label: str, path: str, indent: str) -> str:
    return f'{indent}    {{"{label}" = "{path}"}},'


def _build_replacement(key: str, entries: list[tuple[str, str]], indent: str) -> str:
    """Render {"KEY" = [{...}, ...]} with the given leading indent."""
    if not entries:
        return f'{indent}{{"{key}" = []}},'
    inner = "\n".join(_format_nav_entry(label, path, indent) for label, path in entries)
    return f'{indent}{{"{key}" = [\n{inner}\n{indent}]}},'


# ── Regex replacement ──────────────────────────────────────────────────────────

def _replace_placeholder(content: str, key: str, entries: list[tuple[str, str]]) -> str:
    """
    Replace  {"KEY" = []}  or already-expanded  {"KEY" = [{...}...]}
    with the new entries.  Captures leading whitespace for indentation.
    """
    # Matches flat arrays: {entries are either non-bracket chars or {single-level} objects}
    pattern = re.compile(
        r'^(?P<indent>[ \t]*)' + r'\{' + re.escape(f'"{key}"') +
        r'\s*=\s*\[(?:\s*\{[^{}]*\},?)*\s*\]\},?',
        re.MULTILINE | re.DOTALL,
    )

    def repl(m: re.Match) -> str:
        indent = m.group("indent")
        return _build_replacement(key, entries, indent)

    patched, n = pattern.subn(repl, content)
    if n == 0:
        print(f"[prepare_nav] WARNING: placeholder '{{\"{key}\" = [...]}}' not found in zensical.toml")
    else:
        print(f"[prepare_nav] Replaced '{key}' nav: {len(entries)} entries")
    return patched


# ── Data loading ───────────────────────────────────────────────────────────────

def _load_meetings_entries(hub_dir: Path) -> list[tuple[str, str]]:
    """Return [(label, path)] for the Meetings nav section."""
    entries: list[tuple[str, str]] = []

    # Always prepend the main meetings page if it exists
    if (hub_dir / "docs" / MEETINGS_PAGE).exists():
        entries.append(("Meetings", MEETINGS_PAGE))

    config_path = hub_dir / INDICO_CONFIG
    if not config_path.exists():
        return entries

    with open(config_path, "rb") as f:
        data = tomllib.load(f)

    for cat in data.get("categories", []):
        cat_id  = str(cat["id"])
        label   = cat.get("label", f"Category {cat_id}")
        page    = f"category/{cat_id}/"
        index   = hub_dir / INDICO_DOCS_DIR / cat_id / "index.md"
        if index.exists():
            entries.append((label, page))
        else:
            print(f"[prepare_nav] SKIP Indico {cat_id}: {index} not found (run fetch-indico + prepare-indico-pages first)")

    return entries


def _load_jira_entries(hub_dir: Path) -> list[tuple[str, str]]:
    """Return [(label, path)] for the JIRA nav section."""
    entries: list[tuple[str, str]] = []

    config_path = hub_dir / JIRA_CONFIG
    if not config_path.exists():
        return entries

    with open(config_path, "rb") as f:
        data = tomllib.load(f)

    # Hub overview page
    jira_hub = hub_dir / "docs" / "jira" / "index.md"
    if jira_hub.exists():
        entries.append(("Overview", "jira/"))

    for proj in data.get("projects", []):
        key   = proj["key"].upper()
        label = proj.get("label", key)
        page  = f"jira/projects/{key}/"
        index = hub_dir / JIRA_DOCS_DIR / key / "index.md"
        if index.exists():
            entries.append((label, page))
        else:
            print(f"[prepare_nav] SKIP JIRA {key}: {index} not found (run fetch-jira + prepare-jira-pages first)")

    return entries


# ── Main ───────────────────────────────────────────────────────────────────────

def patch_nav(hub_dir: Path) -> None:
    toml_path = hub_dir / ZENSICAL_TOML
    if not toml_path.exists():
        print(f"[prepare_nav] ERROR: {toml_path} not found")
        return

    content = toml_path.read_text(encoding="utf-8")

    meetings = _load_meetings_entries(hub_dir)
    jira     = _load_jira_entries(hub_dir)

    content = _replace_placeholder(content, "Meetings", meetings)
    content = _replace_placeholder(content, "JIRA",     jira)

    toml_path.write_text(content, encoding="utf-8")
    print(f"[prepare_nav] Patched {toml_path}")


def main() -> None:
    hub_dir = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path.cwd()
    patch_nav(hub_dir)


if __name__ == "__main__":
    main()
