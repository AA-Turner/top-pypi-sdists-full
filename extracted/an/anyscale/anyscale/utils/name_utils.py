from datetime import datetime
import os
import re
from typing import Optional


# The platform's canonical name contract, identical to the web UI's and the
# backend's NAME_VALIDATION_REGEX_PATTERN. A name with characters outside this
# set is written verbatim into the generated SSH `Host` alias, so `ssh` and
# VS Code Remote-SSH later fail with "hostname contains invalid characters".
NAME_VALIDATION_REGEX_PATTERN = r"^[A-Za-z0-9._-]+$"


def validate_resource_name(name: Optional[str]) -> None:
    """Raise `ValueError` if `name` contains characters disallowed in a resource name.

    Falsy names are skipped: create separately requires a non-empty name and
    update treats an omitted name as "keep current".
    """
    if not name:
        return
    # `re.fullmatch` (not `re.match`) so a trailing newline is rejected: Python's
    # `$` also matches just before a final "\n", which would let a name like
    # "myws\n" slip through and still break the SSH hostname.
    if not re.fullmatch(NAME_VALIDATION_REGEX_PATTERN, name):
        raise ValueError(
            f"Invalid name '{name}': a name can only contain alphanumeric "
            "characters, periods (.), dashes (-), and underscores (_)."
        )


def gen_valid_name(prefix: str = "autogenerated") -> str:
    """Generate a name for anyscale resources."""
    INVALID_NAME_REGEX_PATTERN = r"[^A-Za-z0-9_-]"

    generated_name = f"{prefix}-{datetime.now().isoformat()}"
    generated_name = re.sub(INVALID_NAME_REGEX_PATTERN, "-", generated_name)
    return generated_name


def get_full_name():
    """Gets the full name of the user as a lowercase `snake_case` string.
    Uses the Linux username if full name is not available.

    If still not available, returns `"default"`.

    eg. `get_full_name() -> "john_doe"`
    """
    full_name = (
        os.getenv("ANYSCALE_USERNAME")
        or os.getenv("USERNAME")
        or os.getenv("USER")
        or "default"
    )
    # Join the full name with underscores
    full_name = "_".join(full_name.split())
    # Lowercase the full name
    full_name = full_name.lower()
    return full_name
