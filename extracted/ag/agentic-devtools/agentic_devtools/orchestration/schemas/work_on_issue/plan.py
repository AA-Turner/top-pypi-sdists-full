"""Implementation plan models for structured LLM output schemas.

Provides ImplementationPlan with nested PlanTask, TaskDependency, and RiskAssessment.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

DependencyType = Literal["blocks", "informs", "enables"]
RiskLevel = Literal["low", "medium", "high"]
ComplexityLevel = Literal["low", "medium", "high"]


class TaskDependency(BaseModel):
    """A dependency relationship between plan tasks.

    Represents that one task depends on another being completed first.
    """

    task_id: str = Field(description="ID of the task that must be completed first")
    dependency_type: DependencyType = Field(
        default="blocks",
        description="Type of dependency: 'blocks', 'informs', or 'enables'",
    )


class RiskAssessment(BaseModel):
    """Risk assessment for an implementation plan.

    Identifies potential risks and their mitigation strategies.
    """

    description: str = Field(description="Description of the risk")
    likelihood: RiskLevel = Field(description="Likelihood of the risk: 'low', 'medium', or 'high'")
    impact: RiskLevel = Field(description="Impact if the risk materializes: 'low', 'medium', or 'high'")
    mitigation: str = Field(default="", description="Strategy to mitigate the risk")


class PlanTask(BaseModel):
    """A single task within an implementation plan.

    Represents an actionable unit of work with file targets and dependencies.
    """

    task_id: str = Field(description="Unique identifier for this task")
    description: str = Field(description="Human-readable description of what needs to be done")
    affected_files: list[str] = Field(
        default_factory=list,
        description="File paths that will be created or modified",
    )
    dependencies: list[TaskDependency] = Field(
        default_factory=list,
        description="Tasks that must be completed before this one",
    )
    estimated_complexity: ComplexityLevel = Field(
        default="medium",
        description="Estimated complexity: 'low', 'medium', or 'high'",
    )


class ImplementationPlan(BaseModel):
    """Structured implementation plan generated by the LLM.

    Contains an ordered list of tasks with dependencies, affected files,
    and risk assessment for a given issue or feature.
    """

    summary: str = Field(description="Brief summary of the implementation approach")
    tasks: list[PlanTask] = Field(description="Ordered list of tasks to implement the plan")
    risks: list[RiskAssessment] = Field(
        default_factory=list,
        description="Identified risks and mitigation strategies",
    )
    estimated_effort: str = Field(
        default="",
        description="Overall effort estimate (e.g., '2-3 hours', '1 day')",
    )
