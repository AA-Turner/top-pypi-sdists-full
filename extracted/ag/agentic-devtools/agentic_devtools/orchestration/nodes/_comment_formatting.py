"""Comment formatting for planning and completion node outputs.

Provides ``format_planning_comment`` and ``format_completion_comment``
with both Jira wiki markup and GitHub Markdown variants.
"""

from __future__ import annotations

from typing import Any

# Jira comment body limit (hard API limit is 32 767 characters)
_JIRA_MAX_CHARS = 32767
# GitHub issue-comment body hard limit (https://docs.github.com/rest/issues/comments)
_GITHUB_MAX_CHARS = 65536
_TRUNCATION_SUFFIX = "\n\n... (truncated)"

# Explicit fallbacks so every mandatory section is always rendered (SC-003/SC-004),
# even when the structured LLM/verification data is empty or malformed.
_NONE_IDENTIFIED = "None identified."
_NO_SUMMARY = "No summary of changes was recorded."
_NO_QUALITY_GATES = "No quality gates were recorded."


def format_planning_comment(
    plan: str,
    provider: str,
    timestamp: str,
    *,
    tasks: list[str] | None = None,
    affected_files: list[str] | None = None,
    risks: list[str] | None = None,
) -> str:
    """Format a structured planning comment for posting.

    Args:
        plan: The implementation plan text.
        provider: ``"jira"`` or ``"github"``.
        timestamp: ISO-8601 UTC timestamp for the heading.
        tasks: Optional list of task descriptions.
        affected_files: Optional list of affected file paths.
        risks: Optional list of identified risks.

    Returns:
        Formatted comment string.
    """
    is_github = provider == "github"
    tasks = tasks or []
    affected_files = affected_files or []
    risks = risks or []
    lines: list[str] = []

    # Heading
    if is_github:
        lines.append(f"#### Agent Plan — {timestamp}")
    else:
        lines.append(f"h4. Agent Plan — {timestamp}")
    lines.append("")

    # Plan section
    if is_github:
        lines.append("**Plan:**")
    else:
        lines.append("*Plan:*")
    lines.append(plan)
    lines.append("")

    # Tasks section (always rendered; SC-003)
    if is_github:
        lines.append("**Tasks:**")
        if tasks:
            lines.extend(f"- {task}" for task in tasks)
        else:
            lines.append(_NONE_IDENTIFIED)
    else:
        lines.append("*Tasks:*")
        if tasks:
            lines.extend(f"* {task}" for task in tasks)
        else:
            lines.append(_NONE_IDENTIFIED)
    lines.append("")

    # Affected files section (always rendered; SC-003)
    if is_github:
        lines.append("**Affected Files:**")
        if affected_files:
            lines.extend(f"- `{f}`" for f in affected_files)
        else:
            lines.append(_NONE_IDENTIFIED)
    else:
        lines.append("*Affected Files:*")
        if affected_files:
            lines.extend(f"* {{code}}{f}{{code}}" for f in affected_files)
        else:
            lines.append(_NONE_IDENTIFIED)
    lines.append("")

    # Risks section (always rendered; SC-003)
    if is_github:
        lines.append("**Risks:**")
        if risks:
            lines.extend(f"- {r}" for r in risks)
        else:
            lines.append(_NONE_IDENTIFIED)
    else:
        lines.append("*Risks:*")
        if risks:
            lines.extend(f"* {r}" for r in risks)
        else:
            lines.append(_NONE_IDENTIFIED)
    lines.append("")

    lines.append("_Generated by LangChain work-on-issue workflow_")

    comment = "\n".join(lines)
    return _truncate_for_provider(comment, provider)


def format_completion_comment(
    completion_data: dict[str, Any],
    provider: str,
) -> str:
    """Format a structured completion summary comment.

    Args:
        completion_data: Dictionary with keys:
            - ``what_was_done``: Summary of work performed.
            - ``pr_url``: Pull request URL.
            - ``quality_gates``: List of dicts with ``name``, ``status``, ``details``.
            - ``checklist_items``: List of checklist item dicts.
            - ``token_usage_prompt``: Prompt token count.
            - ``token_usage_completion``: Completion token count.
        provider: ``"jira"`` or ``"github"``.

    Returns:
        Formatted comment string.
    """
    is_github = provider == "github"
    lines: list[str] = []

    # Heading
    if is_github:
        lines.append("#### Work Complete")
    else:
        lines.append("h4. Work Complete")
    lines.append("")

    # What was done (Summary always rendered; SC-004)
    what_was_done_raw = completion_data.get("what_was_done", "")
    what_was_done = what_was_done_raw if isinstance(what_was_done_raw, str) and what_was_done_raw else _NO_SUMMARY
    if is_github:
        lines.append("**Summary:**")
    else:
        lines.append("*Summary:*")
    lines.append(what_was_done)
    lines.append("")

    # PR link
    pr_url = completion_data.get("pr_url", "")
    if pr_url:
        if is_github:
            lines.append(f"**Pull Request**: {pr_url}")
        else:
            lines.append(f"*Pull Request*: {pr_url}")
    else:
        if is_github:
            lines.append("**Pull Request**: Created (see branch)")
        else:
            lines.append("*Pull Request*: Created (see branch)")
    lines.append("")

    # Quality gates table (always rendered; SC-004)
    quality_gates = completion_data.get("quality_gates", [])
    gate_rows = [g for g in quality_gates if isinstance(g, dict)] if isinstance(quality_gates, list) else []
    if is_github:
        lines.append("**Quality Gates:**")
        lines.append("")
        if gate_rows:
            lines.append("| Gate | Status | Details |")
            lines.append("|------|--------|---------|")
            for gate in gate_rows:
                name = gate.get("name", "")
                status = gate.get("status", "")
                details = gate.get("details", "")
                icon = "✅" if status == "pass" else "❌"
                lines.append(f"| {name} | {icon} {status} | {details} |")
        else:
            lines.append(_NO_QUALITY_GATES)
    else:
        lines.append("*Quality Gates:*")
        if gate_rows:
            lines.append("||Gate||Status||Details||")
            for gate in gate_rows:
                name = gate.get("name", "")
                status = gate.get("status", "")
                details = gate.get("details", "")
                icon = "(/)" if status == "pass" else "(x)"
                lines.append(f"|{name}|{icon} {status}|{details}|")
        else:
            lines.append(_NO_QUALITY_GATES)
    lines.append("")

    # Checklist summary
    checklist_items = completion_data.get("checklist_items", [])
    if isinstance(checklist_items, list) and checklist_items:
        completed = sum(1 for item in checklist_items if isinstance(item, dict) and item.get("is_complete"))
        total = len([item for item in checklist_items if isinstance(item, dict)])
        if is_github:
            lines.append(f"**Checklist**: {completed}/{total} items completed")
        else:
            lines.append(f"*Checklist*: {completed}/{total} items completed")
        lines.append("")

    # Token usage
    prompt_tokens = completion_data.get("token_usage_prompt", 0)
    completion_tokens = completion_data.get("token_usage_completion", 0)
    if isinstance(prompt_tokens, int) and isinstance(completion_tokens, int):
        total_tokens = prompt_tokens + completion_tokens
        if is_github:
            lines.append("**Token Usage:**")
            lines.append(f"- Prompt tokens: {prompt_tokens:,}")
            lines.append(f"- Completion tokens: {completion_tokens:,}")
            lines.append(f"- Total tokens: {total_tokens:,}")
        else:
            lines.append("*Token Usage:*")
            lines.append(f"* Prompt tokens: {prompt_tokens:,}")
            lines.append(f"* Completion tokens: {completion_tokens:,}")
            lines.append(f"* Total tokens: {total_tokens:,}")
        lines.append("")

    lines.append("_Generated by LangChain work-on-issue workflow_")

    comment = "\n".join(lines)
    return _truncate_for_provider(comment, provider)


def _truncate_for_provider(text: str, provider: str) -> str:
    """Truncate text for provider-specific limits."""
    if provider == "jira" and len(text) > _JIRA_MAX_CHARS:
        cutoff = _JIRA_MAX_CHARS - len(_TRUNCATION_SUFFIX)
        return text[:cutoff] + _TRUNCATION_SUFFIX
    if provider == "github" and len(text) > _GITHUB_MAX_CHARS:
        cutoff = _GITHUB_MAX_CHARS - len(_TRUNCATION_SUFFIX)
        return text[:cutoff] + _TRUNCATION_SUFFIX
    return text
