"""Tests for format_planning_comment."""

from __future__ import annotations

from agentic_devtools.orchestration.nodes._comment_formatting import (
    _GITHUB_MAX_CHARS,
    _JIRA_MAX_CHARS,
    format_planning_comment,
)


class TestFormatPlanningComment:
    """Tests for planning comment formatting."""

    def test_github_format_has_markdown_heading(self) -> None:
        result = format_planning_comment("My plan", "github", "2024-01-15T10:00:00+00:00")
        assert "#### Agent Plan — 2024-01-15T10:00:00+00:00" in result
        assert "**Plan:**" in result
        assert "My plan" in result

    def test_jira_format_has_wiki_heading(self) -> None:
        result = format_planning_comment("My plan", "jira", "2024-01-15T10:00:00+00:00")
        assert "h4. Agent Plan — 2024-01-15T10:00:00+00:00" in result
        assert "*Plan:*" in result
        assert "My plan" in result

    def test_includes_tasks_section(self) -> None:
        result = format_planning_comment(
            "Plan",
            "github",
            "2024-01-01T00:00:00+00:00",
            tasks=["Task 1", "Task 2"],
        )
        assert "**Tasks:**" in result
        assert "- Task 1" in result
        assert "- Task 2" in result

    def test_jira_tasks_use_wiki_bullets(self) -> None:
        result = format_planning_comment(
            "Plan",
            "jira",
            "2024-01-01T00:00:00+00:00",
            tasks=["Task 1"],
        )
        assert "* Task 1" in result

    def test_includes_affected_files_section(self) -> None:
        result = format_planning_comment(
            "Plan",
            "github",
            "2024-01-01T00:00:00+00:00",
            affected_files=["src/main.py", "tests/test_main.py"],
        )
        assert "**Affected Files:**" in result
        assert "- `src/main.py`" in result

    def test_includes_risks_section(self) -> None:
        result = format_planning_comment(
            "Plan",
            "github",
            "2024-01-01T00:00:00+00:00",
            risks=["May break API"],
        )
        assert "**Risks:**" in result
        assert "- May break API" in result

    def test_jira_truncation(self) -> None:
        long_plan = "x" * (_JIRA_MAX_CHARS + 1000)
        result = format_planning_comment(long_plan, "jira", "2024-01-01T00:00:00+00:00")
        assert len(result) <= _JIRA_MAX_CHARS
        assert result.endswith("... (truncated)")

    def test_github_truncation(self) -> None:
        long_plan = "x" * (_GITHUB_MAX_CHARS + 1000)
        result = format_planning_comment(long_plan, "github", "2024-01-01T00:00:00+00:00")
        assert len(result) <= _GITHUB_MAX_CHARS
        assert result.endswith("... (truncated)")

    def test_includes_footer(self) -> None:
        result = format_planning_comment("Plan", "github", "2024-01-01T00:00:00+00:00")
        assert "_Generated by LangChain work-on-issue workflow_" in result


class TestFormatPlanningCommentJiraSections:
    """Cover Jira-specific affected files and risks sections."""

    def test_jira_affected_files_uses_code_macro(self) -> None:
        result = format_planning_comment(
            "Plan",
            "jira",
            "2024-01-01T00:00:00+00:00",
            affected_files=["src/main.py"],
        )
        assert "{code}src/main.py{code}" in result

    def test_jira_risks_uses_wiki_bullets(self) -> None:
        result = format_planning_comment(
            "Plan",
            "jira",
            "2024-01-01T00:00:00+00:00",
            risks=["May break API"],
        )
        assert "* May break API" in result
