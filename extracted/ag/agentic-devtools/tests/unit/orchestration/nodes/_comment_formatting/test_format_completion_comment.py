"""Tests for format_completion_comment."""

from __future__ import annotations

from agentic_devtools.orchestration.nodes._comment_formatting import format_completion_comment


class TestFormatCompletionComment:
    """Tests for completion comment formatting."""

    def test_github_format_has_markdown_heading(self) -> None:
        data = {"pr_url": "https://github.com/org/repo/pull/1", "token_usage_prompt": 100, "token_usage_completion": 50}
        result = format_completion_comment(data, "github")
        assert "#### Work Complete" in result
        assert "**Pull Request**: https://github.com/org/repo/pull/1" in result

    def test_jira_format_has_wiki_heading(self) -> None:
        data = {"pr_url": "https://dev.azure.com/pr/1", "token_usage_prompt": 100, "token_usage_completion": 50}
        result = format_completion_comment(data, "jira")
        assert "h4. Work Complete" in result
        assert "*Pull Request*: https://dev.azure.com/pr/1" in result

    def test_quality_gates_table_github(self) -> None:
        data = {
            "quality_gates": [
                {"name": "Tests", "status": "pass", "details": "100% coverage"},
                {"name": "Lint", "status": "fail", "details": "2 warnings"},
            ],
            "token_usage_prompt": 0,
            "token_usage_completion": 0,
        }
        result = format_completion_comment(data, "github")
        assert "| Tests | ✅ pass | 100% coverage |" in result
        assert "| Lint | ❌ fail | 2 warnings |" in result

    def test_quality_gates_table_jira(self) -> None:
        data = {
            "quality_gates": [{"name": "Tests", "status": "pass", "details": "OK"}],
            "token_usage_prompt": 0,
            "token_usage_completion": 0,
        }
        result = format_completion_comment(data, "jira")
        assert "|Tests|(/) pass|OK|" in result

    def test_checklist_summary(self) -> None:
        data = {
            "checklist_items": [{"is_complete": True}, {"is_complete": True}, {"is_complete": False}],
            "token_usage_prompt": 0,
            "token_usage_completion": 0,
        }
        result = format_completion_comment(data, "github")
        assert "**Checklist**: 2/3 items completed" in result

    def test_token_usage_section(self) -> None:
        data = {"token_usage_prompt": 1000, "token_usage_completion": 500}
        result = format_completion_comment(data, "github")
        assert "Prompt tokens: 1,000" in result
        assert "Completion tokens: 500" in result
        assert "Total tokens: 1,500" in result

    def test_what_was_done_section(self) -> None:
        data = {"what_was_done": "Implemented feature X", "token_usage_prompt": 0, "token_usage_completion": 0}
        result = format_completion_comment(data, "github")
        assert "**Summary:**" in result
        assert "Implemented feature X" in result

    def test_no_pr_url_shows_fallback(self) -> None:
        data = {"pr_url": "", "token_usage_prompt": 0, "token_usage_completion": 0}
        result = format_completion_comment(data, "github")
        assert "Created (see branch)" in result

    def test_includes_footer(self) -> None:
        data = {"token_usage_prompt": 0, "token_usage_completion": 0}
        result = format_completion_comment(data, "github")
        assert "_Generated by LangChain work-on-issue workflow_" in result


class TestFormatCompletionCommentJiraWhatWasDone:
    """Cover the Jira-specific what_was_done section."""

    def test_jira_summary_uses_asterisk_bold(self) -> None:
        result = format_completion_comment(
            {
                "what_was_done": "Implemented the feature",
                "pr_url": "",
                "quality_gates": [],
            },
            "jira",
        )
        assert "*Summary:*" in result
        assert "Implemented the feature" in result


class TestFormatCompletionCommentBranches:
    """Cover remaining branch conditions."""

    def test_quality_gate_non_dict_skipped_github(self) -> None:
        """Non-dict items in quality_gates list are silently skipped."""
        result = format_completion_comment(
            {
                "what_was_done": "",
                "pr_url": "",
                "quality_gates": ["not-a-dict", {"name": "lint", "status": "pass", "details": "ok"}],
            },
            "github",
        )
        assert "lint" in result
        assert "not-a-dict" not in result

    def test_quality_gate_non_dict_skipped_jira(self) -> None:
        result = format_completion_comment(
            {
                "what_was_done": "",
                "pr_url": "",
                "quality_gates": ["skip-me", {"name": "test", "status": "fail", "details": "err"}],
            },
            "jira",
        )
        assert "test" in result
        assert "skip-me" not in result

    def test_token_usage_non_int_skipped(self) -> None:
        """When token_usage values are not ints, the section is omitted."""
        result = format_completion_comment(
            {
                "what_was_done": "Done",
                "pr_url": "",
                "quality_gates": [],
                "token_usage_prompt": "abc",
                "token_usage_completion": 100,
            },
            "github",
        )
        assert "Token Usage" not in result


