class TestFormatCompletionCommentNonStringWhatWasDone:
    """what_was_done coerced to fallback summary when not a string."""

    def test_what_was_done_list_uses_fallback(self) -> None:
        """Non-string what_was_done (list) renders the Summary section with fallback text."""
        result = format_completion_comment(
            {"what_was_done": ["item1", "item2"], "token_usage_prompt": 0, "token_usage_completion": 0},
            "github",
        )
        # Summary section is always present (SC-004); non-string value is not leaked.
        assert "**Summary:**" in result
        assert "No summary of changes was recorded." in result
        assert "item1" not in result

    def test_what_was_done_dict_uses_fallback(self) -> None:
        """Non-string what_was_done (dict) renders the Summary section with fallback text."""
        result = format_completion_comment(
            {"what_was_done": {"text": "done"}, "token_usage_prompt": 0, "token_usage_completion": 0},
            "jira",
        )
        assert "*Summary:*" in result
        assert "No summary of changes was recorded." in result
