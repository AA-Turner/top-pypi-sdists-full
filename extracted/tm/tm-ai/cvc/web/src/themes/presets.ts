import type { DashboardTheme, ThemeTypography, ThemeLayout } from "./types";

/**
 * Built-in CVC dashboard themes.
 *
 * `cvc-red` is the canonical CVC look (deep oxblood + warm cream).
 * The remaining six are ported 1:1 from the upstream dashboard so users
 * can switch to a familiar palette if they're coming from upstream.
 *
 * Theme names must stay in sync with the gateway's
 * `_BUILTIN_DASHBOARD_THEMES` list in `cvc/gateway.py`.
 */

const SYSTEM_SANS =
  'system-ui, -apple-system, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif';
const SYSTEM_MONO =
  'ui-monospace, "SF Mono", "Cascadia Mono", Menlo, Consolas, monospace';

