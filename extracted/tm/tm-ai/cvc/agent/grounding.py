"""
cvc.agent.grounding — Output Validation Layer: API Grounding Gate.

This module validates that code generated by the LLM references REAL APIs,
functions, and imports. It sits between the LLM's response and the user,
catching hallucinated APIs before they cause errors.

Two modes:
  1. **Reactive** (default): After code is written, scan for unknown imports
     and flag them with a warning + suggestion to fetch docs.
  2. **Proactive** (tool-gated): The agent must call `lookup_api` before
     referencing an unfamiliar API. Returns real signatures or "not found".

This closes the gap between CVC's memory layer (defensive) and Context Hub's
documentation layer (preventive) — adding STRUCTURAL VALIDATION of output.
"""

