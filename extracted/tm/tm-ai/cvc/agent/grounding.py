# Grounding validation
# ---------------------------------------------------------------------------

def validate_code_grounding(
    code: str,
    language: str = "python",
    workspace: Path | None = None,
) -> dict[str, Any]:
    """
    Validate that code references real, known APIs.

    Returns a grounding report:
    {
        "grounded": bool,          # True if all imports are known
        "unknown_imports": [...],   # Imports not in stdlib or project deps
        "suggestions": [...],       # Recommended actions
        "known_imports": [...],     # Verified imports
    }
    """
    if language in ("python", "py"):
        imports = extract_python_imports(code)
        stdlib = _PYTHON_STDLIB
        deps = _get_python_deps(workspace) if workspace else set()
    elif language in ("javascript", "js", "typescript", "ts"):
        imports = extract_js_imports(code)
        stdlib = _NODE_BUILTINS
        deps = _get_node_deps(workspace) if workspace else set()
    else:
        return {"grounded": True, "unknown_imports": [], "suggestions": [], "known_imports": []}

    known: list[dict[str, str]] = []
    unknown: list[dict[str, str]] = []

    # Also track internal project imports
    internal_modules = _get_internal_modules(workspace) if workspace else set()

    for imp in imports:
        mod = imp["module"]
        if mod in stdlib:
            known.append(imp)
        elif mod in deps:
            known.append(imp)
        elif mod in internal_modules:
            known.append(imp)
        elif mod.startswith("."):
            # Relative imports are always internal
            known.append(imp)
        else:
            unknown.append(imp)

    suggestions: list[str] = []
    if unknown:
        for u in unknown:
            suggestions.append(
                f"Unknown import '{u['full']}' — use `fetch_docs` to get "
                f"documentation for '{u['module']}' before using this API."
            )

    return {
        "grounded": len(unknown) == 0,
        "unknown_imports": unknown,
        "suggestions": suggestions,
        "known_imports": known,
    }


def check_api_exists(
    symbol: str,
    workspace: Path | None = None,
    language: str = "python",
) -> dict[str, Any]:
    """
    Check if an API symbol exists in the project's installed packages.

    This is the `lookup_api` tool implementation. The agent calls this
    BEFORE using an unfamiliar API to verify it exists.

    Returns:
    {
        "exists": bool,
        "source": "stdlib"|"installed"|"project"|"unknown",
        "info": str,  # signature or description if found
    }
    """
    parts = symbol.split(".")
    top_module = parts[0]

    # Check stdlib
    if language in ("python", "py") and top_module in _PYTHON_STDLIB:
        return {
            "exists": True,
            "source": "stdlib",
            "info": f"'{top_module}' is a Python standard library module.",
        }
    if language in ("javascript", "js", "typescript", "ts") and top_module in _NODE_BUILTINS:
        return {
            "exists": True,
            "source": "stdlib",
            "info": f"'{top_module}' is a Node.js built-in module.",
        }

    # Check project dependencies
    if workspace:
        if language in ("python", "py"):
            deps = _get_python_deps(workspace)
        else:
            deps = _get_node_deps(workspace)

        if top_module in deps:
            return {
                "exists": True,
                "source": "installed",
                "info": (
                    f"'{top_module}' is an installed dependency. "
                    f"Use `fetch_docs` to get current API documentation."
                ),
            }

    # Check internal modules
    if workspace:
        internal = _get_internal_modules(workspace)
        if top_module in internal:
            return {
                "exists": True,
                "source": "project",
                "info": f"'{top_module}' is a project-internal module.",
            }

    return {
        "exists": False,
        "source": "unknown",
        "info": (
            f"'{symbol}' was not found in installed packages or project modules. "
            f"This may be hallucinated. Check the correct package name or "
            f"use `fetch_docs` to look up the real API."
        ),
    }


# ---------------------------------------------------------------------------
# Dependency detection helpers
# ---------------------------------------------------------------------------

def _get_python_deps(workspace: Path | None) -> set[str]:
    """Get installed Python package names from the project."""
    deps: set[str] = set()

    if not workspace:
        return deps

    # From pyproject.toml
    pyproject = workspace / "pyproject.toml"
    if pyproject.exists():
        try:
            text = pyproject.read_text(encoding="utf-8")
            # Parse [project.dependencies] and [tool.poetry.dependencies]
            for match in re.finditer(
                r'^\s*"?([a-zA-Z0-9_-]+)', text, re.MULTILINE
            ):
                pkg = match.group(1).lower().replace("-", "_")
                deps.add(pkg)
        except OSError:
            pass

    # From requirements.txt
    reqs = workspace / "requirements.txt"
    if reqs.exists():
        try:
            for line in reqs.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if line and not line.startswith("#"):
                    # Strip version specifiers
                    pkg = re.split(r'[>=<!\[\];]', line)[0].strip()
                    if pkg:
                        deps.add(pkg.lower().replace("-", "_"))
        except OSError:
            pass

    return deps


def _get_node_deps(workspace: Path | None) -> set[str]:
    """Get installed Node.js package names from the project."""
    deps: set[str] = set()

    if not workspace:
        return deps

    pkg_json = workspace / "package.json"
    if pkg_json.exists():
        try:
            data = json.loads(pkg_json.read_text(encoding="utf-8"))
            for section in ("dependencies", "devDependencies", "peerDependencies"):
                for pkg in data.get(section, {}):
                    deps.add(pkg)
        except (json.JSONDecodeError, OSError):
            pass

    return deps


def _get_internal_modules(workspace: Path | None) -> set[str]:
    """Detect internal project modules (Python packages, src dirs)."""
    modules: set[str] = set()

    if not workspace:
        return modules

    # Python: directories with __init__.py
    for init in workspace.rglob("__init__.py"):
        rel = init.parent.relative_to(workspace)
        parts = rel.parts
        if parts and not any(
            p.startswith(".") or p in ("node_modules", "venv", ".venv", "__pycache__")
            for p in parts
        ):
            modules.add(parts[0])

    # Also add immediate Python files as importable modules
    for py_file in workspace.glob("*.py"):
        if py_file.stem != "__init__":
            modules.add(py_file.stem)

    # Node: check package.json name
    pkg_json = workspace / "package.json"
    if pkg_json.exists():
        try:
            data = json.loads(pkg_json.read_text(encoding="utf-8"))
            name = data.get("name", "")
            if name:
                modules.add(name)
        except (json.JSONDecodeError, OSError):
            pass

    return modules
