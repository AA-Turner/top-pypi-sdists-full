# ---------------------------------------------------------------------------
# Import extraction
# ---------------------------------------------------------------------------

def extract_python_imports(code: str) -> list[dict[str, str]]:
    """
    Extract import statements from Python code.

    Returns list of {module, name, full} where:
    - module: top-level package (e.g. "openai", "stripe")
    - name: specific import (e.g. "OpenAI", "Stripe")
    - full: complete import path (e.g. "openai.OpenAI")
    """
    imports: list[dict[str, str]] = []

    try:
        tree = ast.parse(code)
    except SyntaxError:
        # Fallback to regex for partial/invalid code
        return _extract_imports_regex(code)

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                top = alias.name.split(".")[0]
                imports.append({
                    "module": top,
                    "name": alias.asname or alias.name,
                    "full": alias.name,
                })
        elif isinstance(node, ast.ImportFrom):
            if node.module:
                top = node.module.split(".")[0]
                for alias in node.names:
                    imports.append({
                        "module": top,
                        "name": alias.asname or alias.name,
                        "full": f"{node.module}.{alias.name}",
                    })

    return imports


def extract_js_imports(code: str) -> list[dict[str, str]]:
    """Extract import/require statements from JavaScript/TypeScript code."""
    imports: list[dict[str, str]] = []

    # ES6 imports: import X from 'package'
    for match in re.finditer(
        r'''import\s+(?:\{[^}]*\}|\*\s+as\s+\w+|\w+)\s+from\s+['"]([^'"]+)['"]''',
        code,
    ):
        pkg = match.group(1)
        top = pkg.split("/")[0]
        if top.startswith("@"):
            top = "/".join(pkg.split("/")[:2])
        imports.append({"module": top, "name": pkg, "full": pkg})

    # CommonJS: require('package')
    for match in re.finditer(r'''require\s*\(\s*['"]([^'"]+)['"]\s*\)''', code):
        pkg = match.group(1)
        top = pkg.split("/")[0]
        if top.startswith("@"):
            top = "/".join(pkg.split("/")[:2])
        imports.append({"module": top, "name": pkg, "full": pkg})

    return imports


def _extract_imports_regex(code: str) -> list[dict[str, str]]:
    """Regex fallback for Python imports when AST parsing fails."""
    imports: list[dict[str, str]] = []

    # import X
    for match in re.finditer(r'^import\s+([\w.]+)', code, re.MULTILINE):
        mod = match.group(1)
        top = mod.split(".")[0]
        imports.append({"module": top, "name": mod, "full": mod})

    # from X import Y
    for match in re.finditer(r'^from\s+([\w.]+)\s+import', code, re.MULTILINE):
        mod = match.group(1)
        top = mod.split(".")[0]
        imports.append({"module": top, "name": mod, "full": mod})

    return imports


