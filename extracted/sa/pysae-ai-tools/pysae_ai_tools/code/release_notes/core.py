def release_notes_file(repo_root: Path, lang: str) -> Path:
    """Return the per-language markdown release notes file path."""
    return repo_root / "docs" / "release-notes" / f"release-notes.{lang}.md"


def release_notes_google_play_file(repo_root: Path, lang: str) -> Path:
    """Return the per-language Google Play store summary file path.

    Layout: one accumulating file per language at
    ``docs/release-notes/release-notes.<lang>.google-play.txt``. Each release
    inserts a new ``[<tag>] <date>`` section at the top ; only the section
    body counts against the per-release 500-char cap (the title line is
    excluded).
    """
    return repo_root / "docs" / "release-notes" / f"release-notes.{lang}{GOOGLE_PLAY_SUFFIX}"


def release_notes_apple_app_store_file(repo_root: Path, lang: str) -> Path:
    """Return the per-language Apple App Store summary file path.

    Layout: one accumulating file per language at
    ``docs/release-notes/release-notes.<lang>.apple-app-store.txt``. Same shape
    as the Google Play file but with a 4000-char cap per release body.
    """
    return repo_root / "docs" / "release-notes" / f"release-notes.{lang}{APPLE_STORE_SUFFIX}"


def build_txt_section(tag: str, body: str, today: str) -> str:
    """Build one ``> <tag> — YYYY-MM-DD\\n\\n<body>`` section for the consolidated .txt files.

    The leading ``> `` prefix on the title line stands out clearly when the
    file is browsed in a terminal or text viewer, and gives a single-character
    grep anchor (``grep '^> v' release-notes.fr.google-play.txt``). The title
    line is *not* counted against the per-store body cap — only ``body`` is.
    """
    return f"> {tag} — {today}\n\n{body.strip()}\n"


def merge_txt_release_notes(existing: str, section: str) -> str:
    """Insert ``section`` at the top of the consolidated per-language .txt file.

    Newest release at the top, older sections preserved verbatim below,
    separated by a blank line. Empty / missing existing content yields a
    file that contains only the new section.
    """
    new_block = section.strip("\n") + "\n"
    if not existing.strip():
        return new_block
    return new_block + "\n" + existing.lstrip("\n")


def build_section(tag: str, body: str, today: str) -> str:
    """Build a ``## [tag] YYYY-MM-DD`` release section. ``body`` may be empty."""
    section = f"## [{tag}] {today}"
    if body.strip():
        section += "\n\n" + body.strip() + "\n"
    return section


def _strip_md_prerelease_predecessor(existing: str, tag: str) -> str:
    """Remove a ``## [<base>-<label>…]`` prerelease section from ``existing``, if any.

    Release notes are regenerated in full for the whole version line each time
    (the diff base is the last *final* tag), so coalescing a prerelease line into
    its successor — ``v6.0.0-beta.1`` → ``v6.0.0-beta.2`` → ``v6.0.0`` — means
    dropping the predecessor's section before the new full one is inserted at the
    top, keeping a single section per version line. A *hotfix* (``v5.3.16-1``) is a
    standalone release and never coalesces: it neither drops a predecessor nor is
    dropped by one (:func:`find_prerelease_predecessor` already skips hotfix sections).
    """
    if is_hotfix_tag(tag):
        return existing
    base = tag_base(tag)
    if not base:
        return existing
    match = find_prerelease_predecessor(existing, base, tag)
    if match is None:
        return existing
    return existing[: match.start()] + existing[match.end() :]


def _strip_txt_prerelease_predecessor(existing: str, tag: str) -> str:
    """Plain-text counterpart of :func:`_strip_md_prerelease_predecessor` (``> <tag> — …`` sections)."""
    if is_hotfix_tag(tag):
        return existing
    base = tag_base(tag)
    if not base:
        return existing
    pattern = re.compile(
        rf"(?m)^>\s*(?P<tag>{re.escape(base)}-[0-9A-Za-z][0-9A-Za-z.-]*)\b[^\n]*\n.*?(?=^>\s|\Z)",
        re.DOTALL,
    )
    for match in pattern.finditer(existing):
        if is_hotfix_tag(match.group("tag")):
            continue  # a hotfix section is standalone — never drop it
        return existing[: match.start()] + existing[match.end() :]
    return existing


def merge_release_notes(
    existing: str,
    section: str,
    lang: str,
) -> str:
    """Merge ``section`` into ``existing`` per-language release notes content.

    Thin wrapper around :func:`merge_changelog` so each language file's layout
    matches ``CHANGELOG.md`` (sections sorted newest-first, ``Unreleased``
    blocks stripped, blank line before each ``##`` heading) but with its own
    localized top-level header.
    """
    if lang not in LANGUAGE_HEADERS:
        raise ValueError(f"Unsupported language: {lang!r}. Pick one of {SUPPORTED_LANGUAGES}.")
    return merge_changelog(existing, section, header=LANGUAGE_HEADERS[lang])


@dataclass
class ReleaseNotesConfig:
    """Per-project release-notes configuration (``.pysae-ai-tools.yaml (release.notes/stores)``).

    ``languages`` and ``variants`` restrict what gets generated. ``languages``
    defaults to all supported languages when unset; ``variants`` is derived from
    ``release.stores`` — ``markdown`` is always present, ``google-play`` /
    ``apple-app-store`` only when the matching store flag is on (so a project with
    no store configured generates markdown only). ``prompt`` is optional extra
    guidance fed to the LLM during synthesis — empty by default.
    """

    languages: list[str]
    variants: list[str]
    prompt: str = ""


def release_config(repo_root: Path) -> ReleaseNotesConfig:
    """Resolve the release-notes config from ``.pysae-ai-tools.yaml`` (``release`` block).

    - ``languages``: ``release.notes.languages`` intersected with the supported set
      (canonical order), defaulting to all.
    - ``variants``: always ``markdown``, plus ``google-play`` / ``apple-app-store`` when
      the matching ``release.stores`` flag is on (variants are derived from the target
      stores — there is no separate variants list anymore).
    - ``prompt``: ``release.notes.prompt`` (any ``overlay:`` reference is already resolved
      at config load time — see :func:`resolve_overlay_refs`).

    A missing/broken config degrades to the schema defaults (all languages, markdown
    only, no prompt) via :func:`effective_config`.
    """
    cfg = effective_config(repo_root)
    wanted = {str(item).strip() for item in cfg.release.notes.languages}
    languages = [lang for lang in SUPPORTED_LANGUAGES if lang in wanted] or list(SUPPORTED_LANGUAGES)
    have = {"markdown"}
    if cfg.release.stores.google_play_store:
        have.add("google-play")
    if cfg.release.stores.apple_app_store:
        have.add("apple-app-store")
    variants = [variant for variant in SUPPORTED_VARIANTS if variant in have]
    return ReleaseNotesConfig(languages=languages, variants=variants, prompt=cfg.release.notes.prompt or "")


def _validate_for_variant(variant: str, body: str, lang: str) -> list[BodyViolation]:
    """Validate a body against the rules of its variant."""
    if variant == "markdown":
        return validate_body(body, lang)
    if variant == "google-play":
        return validate_txt_body(body, lang, MAX_TXT_500_LENGTH)
    return validate_txt_body(body, lang, MAX_TXT_4000_LENGTH)


def _target_for_variant(variant: str, repo_root: Path, lang: str) -> Path:
    """Return the consolidated file path for a variant + language."""
    if variant == "markdown":
        return release_notes_file(repo_root, lang)
    if variant == "google-play":
        return release_notes_google_play_file(repo_root, lang)
    return release_notes_apple_app_store_file(repo_root, lang)


def _merge_variant_content(variant: str, existing: str, tag: str, body: str, today: str, lang: str) -> str:
    """Insert the new section into the existing file content for a variant.

    A prerelease (or the final release that closes a prerelease line) first drops
    the predecessor prerelease section of the same base, so the line keeps a
    single coalesced section.
    """
    if variant == "markdown":
        existing = _strip_md_prerelease_predecessor(existing, tag)
        return merge_release_notes(existing, build_section(tag, body, today), lang)
    existing = _strip_txt_prerelease_predecessor(existing, tag)
    return merge_txt_release_notes(existing, build_txt_section(tag, body, today))
