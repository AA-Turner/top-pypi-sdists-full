SUPPORTED_LANGUAGES = ("fr", "en", "it")
"""Languages we generate release notes for, in canonical order."""

SUPPORTED_VARIANTS = ("markdown", "google-play", "apple-app-store")
"""Output variants we can generate, in canonical order.

- ``markdown`` → ``docs/release-notes/release-notes.<lang>.md``
- ``google-play`` → ``release-notes.<lang>.google-play.txt`` (≤500 chars/release)
- ``apple-app-store`` → ``release-notes.<lang>.apple-app-store.txt`` (≤4000 chars/release)
"""

CANONICAL_SECTIONS: dict[str, list[str]] = {
    "fr": ["### ⚠️ Important", "### Nouveautés", "### Améliorations", "### Corrections"],
    "en": ["### ⚠️ Important", "### What's new", "### Improvements", "### Fixes"],
    "it": ["### ⚠️ Importante", "### Novità", "### Miglioramenti", "### Correzioni"],
}
"""The four canonical ``### `` section headings per language, in the mandatory order.

Every release notes body MUST use only these headings, in this order. Empty
sections are omitted (the heading itself is not printed).
"""

CANONICAL_TXT_SECTIONS: dict[str, list[str]] = {
    "fr": ["⚠️ Important :", "Nouveautés :", "Améliorations :", "Corrections :"],
    "en": ["⚠️ Important:", "What's new:", "Improvements:", "Fixes:"],
    "it": ["⚠️ Importante:", "Novità:", "Miglioramenti:", "Correzioni:"],
}
"""Plain-text counterpart of ``CANONICAL_SECTIONS`` — one per language, in the same order.

These labels are **mandatory** in every per-store body, even when length is tight
(Google Play 500-char budget). French uses a **normal space** (``U+0020``) before
the colon — never the non-breaking space ``U+00A0`` : these bodies ship to Google
Play / the App Store and to plain-text files whose character counting and rendering
handle ``U+00A0`` poorly, so the normal space is the safe choice. English and Italian
put the colon flush against the last word per their respective typographic rules.
Empty sections are omitted (the label itself is not printed).
"""

MAX_LINE_LENGTH = 120
"""Hard wrap width for every line in a release notes body.

Bullets that exceed the budget must be wrapped at word boundaries; continuation
lines align under the bullet text with a two-space indent (``  ``). Headings
and short bullets never need wrapping — this rule only bites on long sentences.
"""

MAX_TXT_500_LENGTH = 500
"""Hard cap on the per-release Google Play store summary, in characters.

The Google Play Android Publisher API rejects any ``releaseNotes.text`` longer
than 500 characters per locale. This is a binding API constraint, not a
recommendation.
"""

MAX_TXT_4000_LENGTH = 4000
"""Hard cap on the per-release Apple App Store summary, in characters.

The Apple App Store Connect API ``whatsNew`` field accepts up to 4000
characters per locale. We expose a separate, longer summary file so the
Apple version can include more context than the Play Store one.
"""


@dataclass
class BodyViolation:
    """A single template-conformance violation in a release notes body."""

    lineno: int
    message: str

    def __str__(self) -> str:
        return f"line {self.lineno}: {self.message}"


_HEADING_RE = re.compile(r"^(#+)\s+(.+?)\s*$")


def validate_body(body: str, lang: str) -> list[BodyViolation]:
    """Check a release notes body against the canonical template for ``lang``.

    Returns a list of violations (empty when valid). Enforced rules :

    - **Only** ``### `` (h3) section headings are allowed in the body. The
      version line ``## [<tag>] <date>`` (h2) is generated by the CLI and the
      file-level ``# `` (h1) header is prepended on first creation — none of
      them appear in the LLM-produced body. Sub-sections ``#### `` and below
      are forbidden to keep the structure flat and predictable.
    - Every ``### `` heading is one of the canonical four for the language.
    - Canonical sections appear in the canonical order (later sections cannot
      precede earlier ones; gaps are fine — empty sections are omitted).
    - No section appears more than once.
    - Bullets use ``* `` (not ``- `` or ``• ``).
    - No GitLab-style ``(#NNN)`` issue references (user-facing notes never
      link back to internal tickets).
    - No line exceeds ``MAX_LINE_LENGTH`` (120) characters — long bullets must
      be wrapped at word boundaries with a two-space continuation indent.
    """
    if lang not in CANONICAL_SECTIONS:
        raise ValueError(f"Unsupported language: {lang!r}. Pick one of {SUPPORTED_LANGUAGES}.")

    canonical = CANONICAL_SECTIONS[lang]
    canonical_index = {heading: i for i, heading in enumerate(canonical)}
    canonical_set = set(canonical)

    violations: list[BodyViolation] = []
    seen_in_order: list[tuple[int, str]] = []

    for lineno, raw in enumerate(body.splitlines(), start=1):
        line = raw.rstrip()
        stripped = line.lstrip()

        if len(line) > MAX_LINE_LENGTH:
            violations.append(
                BodyViolation(
                    lineno,
                    f"line exceeds {MAX_LINE_LENGTH} chars ({len(line)}). Wrap long bullets at word "
                    f"boundaries — continuation lines align under the bullet text with a two-space indent. "
                    f"Excerpt: {line[:80]!r}…",
                )
            )

        heading_match = _HEADING_RE.match(line)
        if heading_match:
            level = len(heading_match.group(1))
            if level != 3:
                violations.append(
                    BodyViolation(
                        lineno,
                        f"forbidden heading level h{level} '{line}'. Only h3 ('### ') section "
                        f"headings are allowed in the body — h2 ('## [<tag>] <date>') is added "
                        f"by the CLI, h1 belongs to the file header, h4+ break the canonical layout.",
                    )
                )
            elif line not in canonical_set:
                allowed = ", ".join(f"'{h}'" for h in canonical)
                violations.append(
                    BodyViolation(
                        lineno,
                        f"non-canonical heading '{line}'. Allowed h3 headings for " f"{lang.upper()}: {allowed}",
                    )
                )
            else:
                seen_in_order.append((lineno, line))
        elif stripped.startswith(("- ", "• ")):
            violations.append(
                BodyViolation(
                    lineno,
                    f"bullet must start with '* ' (asterisk + space), not '-' or '•'. Got: {stripped[:80]!r}",
                )
            )
        elif re.search(r"\(#\d+\)", line):
            violations.append(
                BodyViolation(
                    lineno,
                    f"forbidden issue reference '(#NNN)'. User-facing release notes never link to "
                    f"GitLab issues. Got: {stripped[:80]!r}",
                )
            )

    # Order + duplicate checks.
    seen_indices = [canonical_index[heading] for _, heading in seen_in_order]
    if seen_indices != sorted(seen_indices):
        order_repr = " → ".join(f"'{h}'" for _, h in seen_in_order)
        canonical_repr = " → ".join(f"'{h}'" for h in canonical)
        violations.append(
            BodyViolation(
                0,
                f"sections out of order. Got: {order_repr}. Canonical order: {canonical_repr}.",
            )
        )

    counts: dict[str, list[int]] = {}
    for lineno, heading in seen_in_order:
        counts.setdefault(heading, []).append(lineno)
    for heading, linenos in counts.items():
        if len(linenos) > 1:
            extras = ", ".join(str(n) for n in linenos[1:])
            violations.append(
                BodyViolation(
                    linenos[1],
                    f"section '{heading}' is repeated (also appears on line(s) {extras}). "
                    f"Each canonical section must appear at most once.",
                )
            )

    return violations


_MARKDOWN_LINK_RE = re.compile(r"\[[^\]]+\]\([^)]+\)")
_MARKDOWN_HEADING_RE = re.compile(r"^\s*#+\s+\S")
_MARKDOWN_ASTERISK_BULLET_RE = re.compile(r"^\s*\*\s")


def validate_txt_body(body: str, lang: str, max_length: int) -> list[BodyViolation]:
    """Check a plain-text store summary body for ``lang`` against ``max_length``.

    ``max_length`` is the per-locale character cap enforced by the target store
    API : ``MAX_TXT_500_LENGTH`` (500) for Google Play, ``MAX_TXT_4000_LENGTH``
    (4000) for Apple App Store. Bodies are **plain text** — no markdown, no
    links, no issue references — and never empty.

    Enforced rules :

    - Total length ≤ ``max_length`` characters (the title line ``> <tag> —
      YYYY-MM-DD`` written by ``merge`` is *not* part of the body).
    - No markdown headings (``#``, ``##``, ``###``) — stores render them as
      literal ``#`` characters.
    - No markdown links ``[text](url)`` — stores don't follow them.
    - No ``* `` markdown bullets — use plain dashes (``- ``) or no bullets
      at all. Asterisks are confusing in plain text.
    - No ``(#NNN)`` issue references.
    - **Canonical section labels are mandatory and ordered.** Every body must
      open each section with the language-specific label from
      ``CANONICAL_TXT_SECTIONS`` (e.g. ``Nouveautés :`` in FR, ``What's new:``
      in EN). Labels appear in canonical order, at most once each. Empty
      sections are omitted (their label simply isn't printed). The 500-char
      Google Play budget is *no excuse* to drop labels — the team has
      explicitly chosen consistency over budget on this point.

    Empty bodies are rejected — the store field can't be left blank.
    """
    if lang not in CANONICAL_SECTIONS:
        raise ValueError(f"Unsupported language: {lang!r}. Pick one of {SUPPORTED_LANGUAGES}.")
    if max_length <= 0:
        raise ValueError(f"max_length must be positive, got {max_length}.")

    violations: list[BodyViolation] = []

    stripped_body = body.strip()
    if not stripped_body:
        violations.append(BodyViolation(0, "empty body — the store field cannot be left blank."))
        return violations

    if len(body) > max_length:
        store = "Google Play" if max_length == MAX_TXT_500_LENGTH else "App Store"
        violations.append(
            BodyViolation(
                0,
                f"body exceeds {max_length} chars ({len(body)}). The {store} API rejects "
                f"per-locale release notes longer than {max_length} characters.",
            )
        )

    for lineno, raw in enumerate(body.splitlines(), start=1):
        line = raw.rstrip()
        if _MARKDOWN_HEADING_RE.match(line):
            violations.append(
                BodyViolation(
                    lineno,
                    f"markdown heading '{line}' is forbidden — stores render '#' as literal text.",
                )
            )
        if _MARKDOWN_ASTERISK_BULLET_RE.match(line):
            violations.append(
                BodyViolation(
                    lineno,
                    f"markdown bullet '*' is forbidden — use '- ' (plain dash) or no bullet at all. "
                    f"Got: {line.strip()[:80]!r}",
                )
            )
        if _MARKDOWN_LINK_RE.search(line):
            violations.append(
                BodyViolation(
                    lineno,
                    f"markdown link '[text](url)' is forbidden — stores don't render them. "
                    f"Got: {line.strip()[:80]!r}",
                )
            )
        if re.search(r"\(#\d+\)", line):
            violations.append(
                BodyViolation(
                    lineno,
                    f"forbidden issue reference '(#NNN)'. Got: {line.strip()[:80]!r}",
                )
            )

    # Canonical section labels — mandatory, ordered, no duplicates.
    canonical_labels = CANONICAL_TXT_SECTIONS[lang]
    label_index = {label: i for i, label in enumerate(canonical_labels)}
    label_set = set(canonical_labels)

    seen_labels: list[tuple[int, str]] = []
    for lineno, raw in enumerate(body.splitlines(), start=1):
        line = raw.strip()
        if line in label_set:
            seen_labels.append((lineno, line))

    if not seen_labels:
        allowed = ", ".join(f"'{lbl}'" for lbl in canonical_labels)
        violations.append(
            BodyViolation(
                0,
                f"missing canonical section labels — every body must open each section with one of: "
                f"{allowed}. Labels are mandatory even when the body is tight against the {max_length}-char cap.",
            )
        )

    seen_indices = [label_index[label] for _, label in seen_labels]
    if seen_indices != sorted(seen_indices):
        order_repr = " → ".join(f"'{lbl}'" for _, lbl in seen_labels)
        canonical_repr = " → ".join(f"'{lbl}'" for lbl in canonical_labels)
        violations.append(
            BodyViolation(
                0,
                f"section labels out of canonical order. Got: {order_repr}. Canonical order: {canonical_repr}.",
            )
        )

    counts: dict[str, list[int]] = {}
    for lineno, label in seen_labels:
        counts.setdefault(label, []).append(lineno)
    for label, linenos in counts.items():
        if len(linenos) > 1:
            extras = ", ".join(str(n) for n in linenos[1:])
            violations.append(
                BodyViolation(
                    linenos[1],
                    f"section label '{label}' is repeated (also appears on line(s) {extras}). "
                    f"Each canonical section label must appear at most once.",
                )
            )

    return violations


