"""Pure release-notes logic: validation, section building, markdown/txt merge.

No Typer, no git — every function takes explicit inputs and returns values (the
only I/O is :func:`release_config`, which loads the project config). Git data
collection lives in :mod:`.gather`, the command layer in :mod:`.cli`, and
version-tag semantics in :mod:`..versioning`.

Release notes are the user-facing counterpart of ``CHANGELOG.md``: plain prose
in three languages, ``* `` bullets in the markdown version (same convention as
the CHANGELOG), ``- `` or no bullets in the plain-text version, no ``#IID``
issue refs, only entries that matter to end users.
"""

import re
from dataclasses import dataclass
from pathlib import Path

from ...common.markdown_render import MAINTENANCE_NOTES
from ...common.project_config import effective_config
from ..changelog import merge_changelog
