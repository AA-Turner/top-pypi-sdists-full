"""Generate the temporary ``env.sh`` (0600) and ``runner.sh`` for a job."""

import os
from pathlib import Path

from .models import ResolvedJob


def _shquote(value: str) -> str:
    """Single-quote a value for POSIX shell, preserving newlines and specials."""
    return "'" + value.replace("'", "'\\''") + "'"


def _sanitize(job_name: str) -> str:
    return "".join(c if c.isalnum() or c in "-_." else "-" for c in job_name) or "job"


# Default location of generated scripts, relative to the current directory.
DEFAULT_BASE = ".ci/local"


def _ensure_gitignore_entry(gitignore: Path, entry: str) -> None:
    """Append ``entry`` to ``gitignore`` if not already ignored (idempotent)."""
    bare = entry.rstrip("/")
    existing: list[str] = []
    if gitignore.exists():
        existing = gitignore.read_text(encoding="utf-8").splitlines()
        if any(line.strip().rstrip("/") == bare for line in existing):
            return
    prefix = "" if (not existing or existing[-1] == "") else "\n"
    with gitignore.open("a", encoding="utf-8") as handle:
        handle.write(f"{prefix}{entry}\n")


def create_run_dir(job_name: str, out_dir: Path | None = None) -> Path:
    """Return the directory holding the generated scripts.

    Defaults to ``./.ci/local/<job-name>`` under the current directory and adds
    ``.ci/local/`` to ``./.gitignore`` (the generated ``env.sh`` holds secrets).
    ``out_dir`` overrides the location entirely and skips the ``.gitignore`` edit.
    """
    if out_dir is not None:
        out_dir.mkdir(parents=True, exist_ok=True)
        return out_dir
    base = Path.cwd()
    _ensure_gitignore_entry(base / ".gitignore", f"{DEFAULT_BASE}/")
    directory = base / DEFAULT_BASE / _sanitize(job_name)
    directory.mkdir(parents=True, exist_ok=True)
    return directory


def write_env_file(env: dict[str, str], directory: Path) -> Path:
    """Write ``env.sh`` as ``export KEY='value'`` lines, then ``chmod 600``.

    The file holds resolved secrets — it is created with owner-only permissions
    and is never printed by the caller.
    """
    lines = ["# Generated by pysae-ai-tools ci run-local — contains secrets, do not commit.", ""]
    for key in sorted(env):
        lines.append(f"export {key}={_shquote(env[key])}")
    path = directory / "env.sh"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(path, 0o600)
    return path


def _emit_section(lines: list[str], commands: list[str], echo: bool) -> None:
    for cmd in commands:
        if echo:
            lines.append(f"printf '%s\\n' {_shquote('$ ' + cmd)} >&2")
        lines.append(cmd)


def write_runner(job: ResolvedJob, env_path: Path, directory: Path, echo: bool = True) -> Path:
    """Write ``runner.sh`` reproducing GitLab's before/script/after sequencing.

    ``before_script`` + ``script`` run in one ``set -e`` subshell (so state from
    before_script persists, and the first failure aborts — GitLab's behaviour).
    ``after_script`` always runs afterwards in its own shell, failures ignored.
    """
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by pysae-ai-tools ci run-local.",
        "set -u",
        # pipefail exists in bash and busybox ash but not in dash — enable best-effort.
        "set -o pipefail 2>/dev/null || true",
        f". {_shquote(str(env_path))}",
        'cd "${CI_PROJECT_DIR:-.}"',
        "",
        "(",
        "  set -e",
    ]
    main_section: list[str] = []
    _emit_section(main_section, [*job.before_script, *job.script], echo)
    lines.extend(f"  {line}" for line in main_section)
    lines.append(")")
    lines.append("_rc=$?")

    if job.after_script:
        lines.append("")
        lines.append("# after_script — always runs, failures ignored (GitLab semantics)")
        lines.append("(")
        after_section: list[str] = []
        _emit_section(after_section, job.after_script, echo)
        lines.extend(f"  {line}" for line in after_section)
        lines.append(") || true")

    lines.append("")
    lines.append("exit $_rc")

    path = directory / "runner.sh"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(path, 0o755)
    return path
