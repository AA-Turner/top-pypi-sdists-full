"""A contract folder as a Python copy for the SDK and CLI (agent/src/probe/generated/<folder>/): the same files,
with the one import that leaves the folder pointed at the SDK's own. The live events and the trace protocol use it."""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

from ..probe_contracts import Contracts

CONTRACTS_DIR = Path(__file__).resolve().parents[1]
#: Every import that leaves the folder, and what the SDK copy imports instead.
REWRITES = {"from ..compat import StrEnum\n": "from probe.foundation.compat.compat import StrEnum\n"}
HEADER = (
    "# GENERATED by `python -m probe_contracts.codegen` from contracts/probe_contracts/{folder}/{source}.\n"
    "# Do not edit: change it there and rerun.\n"
)


class FolderCopy:
    """One flat contract folder (`live`, `traces`) copied file by file into the SDK."""

    def __init__(self, folder: str) -> None:
        self.folder = folder
        self.source_dir = CONTRACTS_DIR / folder
        self.destination = f"agent/src/probe/generated/{folder}"

    def list_files(self) -> tuple[str, ...]:
        """The contract's Python files, front door included."""
        return tuple(sorted(path.name for path in self.source_dir.glob("*.py")))

    def make_render(self, name: str) -> Callable[[Contracts], str]:
        """Render one file for the SDK; refuses an outside import it cannot point anywhere."""

        def render(_contracts: Contracts) -> str:
            text = (self.source_dir / name).read_text(encoding="utf-8")
            for old, new in REWRITES.items():
                text = text.replace(old, new)
            stray = [line for line in text.splitlines() if line.startswith(("from ..", "import probe_contracts"))]
            if stray:
                raise ValueError(f"{self.folder}/{name} imports from outside the folder: {stray} (add a REWRITE)")
            return HEADER.format(folder=self.folder, source=name) + text

        return render


#: The live events contract (rl-next W52) and the trace client protocol (`probe client check`, vespper-fixes PR8).
LIVE = FolderCopy("live")
TRACES = FolderCopy("traces")
