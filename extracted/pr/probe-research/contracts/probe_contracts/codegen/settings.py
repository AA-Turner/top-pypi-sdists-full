"""The settings file's vocabulary as a STDLIB-ONLY Python copy (agent) and TypeScript (packages/core), and its
schema and golden files copied into packages/core so the Mac app's Rust tests read the same bytes."""

from __future__ import annotations

from pathlib import Path

from ..probe_contracts import Contracts
from .client_messages import _python_enum
from .typescript import render_enum

SOURCE = "contracts/probe_contracts/settings"
#: The schema and golden files beside the vocabulary (contracts/probe_contracts/settings/).
SOURCE_DIR = Path(__file__).resolve().parents[1] / "settings"
GOLDEN_NAMES = (
    "empty.json",
    "published.json",
    "claimed.json",
    "applied.json",
    "transcripts-log.json",
    "failed.json",
    "legacy-adopted.json",
)

_PY_HEADER = (
    f"# GENERATED by `python -m probe_contracts.codegen` from {SOURCE}.\n"
    "# Do not edit: change the vocabulary there and rerun.\n"
)
_TS_HEADER = (
    f"// GENERATED by `python -m probe_contracts.codegen` from {SOURCE}.\n"
    "// Do not edit: change the vocabulary there and rerun.\n"
)
_PY_PRELUDE = '''"""The settings file's keys and who set a value (probe-contracts' settings). STDLIB ONLY: the Probe
service loads it at start.
"""

from __future__ import annotations

from enum import Enum

__all__ = [
{names}]


class _StrEnum(str, Enum):
    """3.11's StrEnum on 3.10 too: `str(member)` is its value."""

    def __str__(self) -> str:
        return str(self.value)
'''


def render_settings_stdlib(contracts: Contracts) -> str:
    names = "".join(f'    "{c.__name__}",\n' for c in sorted(contracts.settings, key=lambda c: c.__name__))
    blocks = [_python_enum(e) for e in contracts.settings]
    return _PY_HEADER + _PY_PRELUDE.format(names=names) + "".join(f"\n\n{block}" for block in blocks)


def render_settings_typescript(contracts: Contracts) -> str:
    return _TS_HEADER + "".join(f"\n{render_enum(e)}" for e in contracts.settings)


def make_copy_render(name: str):
    """A target render that copies one schema or golden file byte for byte."""

    def render(_contracts: Contracts) -> str:
        return (SOURCE_DIR / name).read_text(encoding="utf-8")

    return render
