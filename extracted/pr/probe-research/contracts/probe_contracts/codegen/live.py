"""The live events contract as a Python copy for the SDK and CLI (agent/src/probe/generated/live/): the same files,
with the one import that leaves the folder pointed at the SDK's own."""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

from ..probe_contracts import Contracts

SOURCE_DIR = Path(__file__).resolve().parents[1] / "live"
DESTINATION = "agent/src/probe/generated/live"
#: Every import that leaves live/, and what the SDK copy imports instead.
REWRITES = {"from ..compat import StrEnum\n": "from probe.foundation.compat.compat import StrEnum\n"}
HEADER = (
    "# GENERATED by `python -m probe_contracts.codegen` from contracts/probe_contracts/live/{source}.\n"
    "# Do not edit: change it there and rerun.\n"
)


def list_live_files() -> tuple[str, ...]:
    """The contract's Python files, front door included."""
    return tuple(sorted(path.name for path in SOURCE_DIR.glob("*.py")))


def make_live_copy_render(name: str) -> Callable[[Contracts], str]:
    """Render one file of live/ for the SDK; refuses an outside import it cannot point anywhere."""

    def render(_contracts: Contracts) -> str:
        text = (SOURCE_DIR / name).read_text(encoding="utf-8")
        for old, new in REWRITES.items():
            text = text.replace(old, new)
        stray = [line for line in text.splitlines() if line.startswith(("from ..", "import probe_contracts"))]
        if stray:
            raise ValueError(f"live/{name} imports from outside the folder: {stray} (add a REWRITE)")
        return HEADER.format(source=name) + text

    return render
