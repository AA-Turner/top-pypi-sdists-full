"""The sample store's contract as a Python copy for the SDK (agent/src/probe/generated/samples/): the same files,
with the two imports that leave the folder pointed at the SDK's own (the wheel's vendored copy skips editable installs)."""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

from ..probe_contracts import Contracts

RECORDS_DIR = Path(__file__).resolve().parents[1] / "records"
SOURCE_DIR = RECORDS_DIR / "samples"
DESTINATION = "agent/src/probe/generated/samples"
#: Every import that leaves records/samples/, and what the SDK copy imports instead, by how deep the file sits
#: (0: records/samples/, 1: a subfolder such as live/).
REWRITES = {
    0: {
        "from ..records import Record\n": "from .record import Record\n",
        "from ...compat import StrEnum\n": "from probe.foundation.compat.compat import StrEnum\n",
        "from ..command import CommandKind\n": "from probe.generated.records import CommandKind\n",
    },
    1: {
        "from ...records import Record\n": "from ..record import Record\n",
        "from ....compat import StrEnum\n": "from probe.foundation.compat.compat import StrEnum\n",
        "from ...command import CommandKind\n": "from probe.generated.records import CommandKind\n",
    },
}
HEADER = (
    "# GENERATED by `python -m probe_contracts.codegen` from contracts/probe_contracts/records/{source}.\n"
    "# Do not edit: change it there and rerun.\n"
)


def list_sample_files() -> tuple[str, ...]:
    """The contract's Python files, relative to records/samples/ (`live/live.py`), front doors included."""
    return tuple(sorted(path.relative_to(SOURCE_DIR).as_posix() for path in SOURCE_DIR.rglob("*.py")
                        if "__pycache__" not in path.parts))


def make_sample_copy_render(name: str) -> Callable[[Contracts], str]:
    """Render one file of records/samples/ for the SDK; refuses an import that leaves the folder and has no rewrite."""
    depth = name.count("/")
    if depth not in REWRITES:
        raise ValueError(f"records/samples/{name} sits deeper than the copy knows (add its REWRITES)")
    outside = "from " + "." * (depth + 2)  # a relative import climbing past records/samples/

    def render(_contracts: Contracts) -> str:
        text = (SOURCE_DIR / name).read_text(encoding="utf-8")
        for old, new in REWRITES[depth].items():
            text = text.replace(old, new)
        stray = [line for line in text.splitlines() if line.startswith((outside, "import probe_contracts"))]
        if stray:
            raise ValueError(f"records/samples/{name} imports from outside the folder: {stray} (add a REWRITE)")
        return HEADER.format(source=f"samples/{name}") + text

    return render


def render_record_copy(_contracts: Contracts) -> str:
    """The `Record` base the copy's records extend (records/records.py, pydantic only)."""
    return HEADER.format(source="records.py") + (RECORDS_DIR / "records.py").read_text(encoding="utf-8")
