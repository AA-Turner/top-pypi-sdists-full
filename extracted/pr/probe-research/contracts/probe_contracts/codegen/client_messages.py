"""The client-message vocabulary as TypeScript (packages/core) and as a STDLIB-ONLY Python copy the
SDK, the tap and the plugin hooks can load by path (no pydantic)."""

from __future__ import annotations

import json
import textwrap
from enum import Enum

from pydantic import BaseModel

from ..client_messages import MAX_TEXT_LENGTH
from ..probe_contracts import Contracts
from .field_types import default_of, describe, doc_of
from .python import render_type as render_python_type
from .typescript import render_enum, render_jsdoc
from .typescript import render_type as render_typescript_type

SOURCE = "contracts/probe_contracts/client_messages"

_TS_HEADER = (
    f"// GENERATED by `python -m probe_contracts.codegen` from {SOURCE}.\n"
    "// Do not edit: change the vocabulary there and rerun.\n"
)
_PY_HEADER = (
    f"# GENERATED by `python -m probe_contracts.codegen` from {SOURCE}.\n"
    "# Do not edit: change the vocabulary there and rerun.\n"
)

_PY_PRELUDE = '''"""What the server tells a client and its coding agent (probe-contracts' client_messages).

STDLIB ONLY: the tap and the plugin hooks load a copy of this file by path.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum

__all__ = [
{names}]

#: The longest sentence a message carries; a staff override is held to it too.
MAX_TEXT_LENGTH = {max_length}


class _StrEnum(str, Enum):
    """3.11's StrEnum on 3.10 too: `str(member)` is its value."""

    def __str__(self) -> str:
        return str(self.value)
'''


def _enums(contracts: Contracts) -> list[type[Enum]]:
    return [c for c in contracts.messages if issubclass(c, Enum)]


def _models(contracts: Contracts) -> list[type[BaseModel]]:
    return [c for c in contracts.messages if issubclass(c, BaseModel)]


def _is_optional(info) -> bool:
    """A field the server may leave out: its default is None."""
    default = default_of(info)
    return not default.required and default.value is None and not default.factory


def _typescript_interface(cls: type[BaseModel]) -> str:
    fields = ""
    for name, info in cls.model_fields.items():
        mark = "?" if _is_optional(info) else ""
        fields += f"  {name}{mark}: {render_typescript_type(describe(info.annotation))};\n"
    return f"{render_jsdoc(cls)}export interface {cls.__name__} {{\n{fields}}}\n"


def render_client_messages_typescript(contracts: Contracts) -> str:
    blocks = [
        "/** The longest sentence a message carries; a staff override is held to it too. */\n"
        f"export const MAX_TEXT_LENGTH = {MAX_TEXT_LENGTH};\n"
    ]
    blocks += [render_enum(e) for e in _enums(contracts)]
    blocks += [_typescript_interface(m) for m in _models(contracts)]
    return _TS_HEADER + "".join(f"\n{block}" for block in blocks)


def _docstring(cls: type) -> str:
    text = doc_of(cls)
    if not text:
        return ""
    if "\n" not in text:
        return f'    """{text}"""\n\n'
    return f'    """{textwrap.indent(text, "    ").lstrip()}\n    """\n\n'


def _python_enum(cls: type[Enum]) -> str:
    members = "".join(f"    {member.name} = {json.dumps(member.value)}\n" for member in cls)
    return f"class {cls.__name__}(_StrEnum):\n{_docstring(cls)}{members}"


def _python_default(info) -> str:
    default = default_of(info)
    if default.required:
        return ""
    if default.factory:
        raise TypeError("the stdlib copy has no default factories")
    value = default.value
    return f" = {json.dumps(value)}" if isinstance(value, str) else f" = {value!r}"


def _python_dataclass(cls: type[BaseModel]) -> str:
    # kw_only: a defaulted field may sit before a required one (ClientRefusalBody keeps wire order).
    lines = ["@dataclass(frozen=True, kw_only=True)\n", f"class {cls.__name__}:\n", _docstring(cls)]
    for name, info in cls.model_fields.items():
        lines.append(f"    {name}: {render_python_type(describe(info.annotation))}{_python_default(info)}\n")
    return "".join(lines)


def render_client_messages_stdlib(contracts: Contracts) -> str:
    names = ["MAX_TEXT_LENGTH", *(c.__name__ for c in contracts.messages)]
    prelude = _PY_PRELUDE.format(names="".join(f'    "{n}",\n' for n in sorted(names)),
                                 max_length=MAX_TEXT_LENGTH)
    blocks = [_python_enum(e) for e in _enums(contracts)]
    blocks += [_python_dataclass(m) for m in _models(contracts)]
    return _PY_HEADER + prelude + "".join(f"\n\n{block}" for block in blocks)
