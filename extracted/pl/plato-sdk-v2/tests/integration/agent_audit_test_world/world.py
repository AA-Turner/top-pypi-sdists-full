"""Integration test world for tool-attributed filesystem audit collection."""

from __future__ import annotations

import json
import logging
import os
from pathlib import Path
from typing import Annotated, ClassVar

from plato.chronos.models import AuditEventResponse
from plato.chronos.sdk import AsyncChronos
from plato.worlds import (
    Agent,
    AgentConfig,
    BaseWorld,
    Observation,
    RunConfig,
    StepResult,
    Workspace,
    register_world,
)
from plato.worlds.checkpoint import checkpoint

logger = logging.getLogger(__name__)

AGENT_AUDIT_INSTRUCTION = """\
Complete these steps in order, and do not batch all file work into one tool call:

1. Read /workspace/input_a.txt.
2. Read /workspace/input_b.txt.
3. Use a shell or command-execution tool to create /workspace/generated.txt containing the text "generated by audit test".
4. Write /workspace/result.json with valid JSON exactly matching:
   {"status":"ok","generated_file":"/workspace/generated.txt"}
"""

PARALLEL_READ_SUFFIX = """\
5. Now read these three files IN PARALLEL using three simultaneous tool calls \
(do NOT read them one at a time):
   - /workspace/parallel_1.txt
   - /workspace/parallel_2.txt
   - /workspace/parallel_3.txt
"""

PARALLEL_AGENT_INSTRUCTION = """\
Complete these steps in order. Use separate tool calls for each step (do NOT batch):

1. Read /workspace/input_{agent_idx}.txt using the Read tool.
2. Read /workspace/shared_input.txt using the Read tool.
3. Use a shell/Bash tool to run: echo "agent {agent_idx} was here" > /workspace/agent_{agent_idx}_bash_output.txt
4. Write /workspace/agent_{agent_idx}_result.json with the Write tool, containing: {{"agent": {agent_idx}, "status": "ok"}}
"""


class AgentAuditTestWorldConfig(RunConfig):
    """Config for audit attribution integration tests."""

    agent: Annotated[AgentConfig, Agent(description="Agent under test")]
    min_distinct_tool_spans: int = 2
    test_parallel_reads: bool = False
    parallel_agents: int = 1
    require_read_write_attribution: bool = False
    code: Annotated[
        Path,
        Workspace(
            description="Tracked workspace under audit",
            tracked=True,
            mount_path="/workspace",
        ),
    ] = Path("/workspace")


@register_world("plato-world-agent-audit-test")
class AgentAuditTestWorld(BaseWorld[AgentAuditTestWorldConfig]):
    """Run a real agent and validate audit events via API after checkpoint upload."""

    name: ClassVar[str] = "agent-audit-test"
    description: ClassVar[str] = "Integration test for tool-attributed workspace audit"

    async def reset(self) -> Observation:
        return Observation(data={"status": "ready"})

    async def step(self) -> StepResult:
        code_ws = self.workspace("code")
        workspace_path = Path(code_ws.path)
        workspace_path.mkdir(parents=True, exist_ok=True)

        session_id = self._session_id or "unknown"

        if self.config.parallel_agents > 1:
            return await self._step_parallel(code_ws, workspace_path, session_id)
        return await self._step_single(code_ws, workspace_path, session_id)

    async def _step_single(self, code_ws, workspace_path: Path, session_id: str) -> StepResult:
        """Original single-agent test flow."""
        (workspace_path / "input_a.txt").write_text("alpha\n", encoding="utf-8")
        (workspace_path / "input_b.txt").write_text("beta\n", encoding="utf-8")

        instruction = AGENT_AUDIT_INSTRUCTION
        if self.config.test_parallel_reads:
            for i in range(1, 4):
                (workspace_path / f"parallel_{i}.txt").write_text(f"parallel content {i}\n", encoding="utf-8")
            instruction += PARALLEL_READ_SUFFIX

        logger.info("Starting single-agent audit test — session_id=%s", session_id)

        async with checkpoint(self.checkpoint, "agent-run", step=1, interval_s=45):
            await self.agent(
                self.config.agent,
                workspaces=[code_ws],
            ).run(instruction)

        # Verify agent output
        result_path = workspace_path / "result.json"
        if not result_path.exists():
            raise RuntimeError("Agent did not create /workspace/result.json")
        result = json.loads(result_path.read_text(encoding="utf-8"))
        if result != {"status": "ok", "generated_file": "/workspace/generated.txt"}:
            raise RuntimeError(f"Unexpected result.json payload: {result!r}")

        return await self._validate_and_return(session_id)

    async def _step_parallel(self, code_ws, workspace_path: Path, session_id: str) -> StepResult:
        """Run N agents concurrently and validate all get audit attribution."""
        import asyncio

        n = self.config.parallel_agents
        logger.info(
            "Starting parallel-agent audit test — session_id=%s n_agents=%d",
            session_id,
            n,
        )

        # Seed per-agent input files + a shared input file
        (workspace_path / "shared_input.txt").write_text("shared content\n", encoding="utf-8")
        for i in range(n):
            (workspace_path / f"input_{i}.txt").write_text(f"content for agent {i}\n", encoding="utf-8")

        async def _run_agent(idx: int) -> None:
            instruction = PARALLEL_AGENT_INSTRUCTION.format(agent_idx=idx)
            display_name = f"parallel-agent-{idx}"
            await self.agent(
                self.config.agent,
                display_name=display_name,
                workspaces=[code_ws],
            ).run(instruction)

        async with checkpoint(self.checkpoint, "parallel-agent-run", step=1, interval_s=60):
            await asyncio.gather(*[_run_agent(i) for i in range(n)])

        # Verify all agents wrote their result files
        for i in range(n):
            result_path = workspace_path / f"agent_{i}_result.json"
            if not result_path.exists():
                raise RuntimeError(f"Agent {i} did not create {result_path}")
            result = json.loads(result_path.read_text(encoding="utf-8"))
            if result.get("agent") != i or result.get("status") != "ok":
                raise RuntimeError(f"Agent {i} unexpected result: {result!r}")

        return await self._validate_and_return(session_id)

    async def _validate_and_return(self, session_id: str) -> StepResult:
        """Validate audit events via API and return result."""
        chronos_url = self._get_chronos_base_url()
        api_key = os.environ.get("PLATO_API_KEY", "")
        if not chronos_url or session_id == "unknown" or not api_key:
            raise RuntimeError(f"Cannot validate via API: chronos_url={chronos_url}, session_id={session_id}")

        failures = await _validate_via_api(
            chronos_url,
            api_key,
            session_id,
            self.config,
        )

        if failures:
            raise RuntimeError(
                f"Audit attribution test failed ({len(failures)} failures) — "
                f"session_id={session_id}:\n" + "\n".join(f"  - {f}" for f in failures)
            )

        return StepResult(
            observation=Observation(data={"status": "passed", "session_id": session_id}),
            done=True,
        )


async def _validate_via_api(
    chronos_url: str,
    api_key: str,
    session_id: str,
    config: AgentAuditTestWorldConfig,
) -> list[str]:
    """Validate audit events end-to-end via the Chronos API."""
    failures: list[str] = []

    async with AsyncChronos(base_url=chronos_url, api_key=api_key) as client:
        # --- Fetch workspace refs (one per checkpoint) ---
        refs = await client.get_workspace_refs(session_id, repo_name="agent-audit-test/code")
        logger.info("Workspace refs: %d", len(refs))
        if not refs:
            failures.append("No workspace refs found for session")
            return failures

        for ref in refs:
            ref_id = ref.get("public_id") or ref.get("ref_public_id")
            step = ref.get("step_name", "?")
            logger.info("  ref=%s step=%s", ref_id, step)

        # --- Fetch all audit events for this session ---
        all_resp = await client.get_audit_events(session_id, limit=500)
        api_events = all_resp.events
        logger.info("Total audit events from API: %d (total=%d)", len(api_events), all_resp.total)

        if not api_events:
            failures.append("No audit events returned from API")
            return failures

        # --- Check 1: all events have a ref_public_id ---
        events_without_ref = [e for e in api_events if not e.ref_public_id]
        if events_without_ref:
            failures.append(f"{len(events_without_ref)} events have no ref_public_id")

        # --- Check 2: events are distributed across checkpoint refs ---
        ref_ids_in_events = {e.ref_public_id for e in api_events}
        logger.info("Distinct ref_public_ids in events: %d — %s", len(ref_ids_in_events), sorted(ref_ids_in_events))

        # --- Check 3: correct repo_name on all events ---
        wrong_repo = [e for e in api_events if e.repo_name != "agent-audit-test/code"]
        if wrong_repo:
            failures.append(f"{len(wrong_repo)} events have wrong repo_name (expected agent-audit-test/code)")

        # --- Check 4: expected files appear ---
        all_paths = {e.path for e in api_events}
        all_new_paths = {e.new_path for e in api_events if e.new_path}
        all_audit_paths = all_paths | all_new_paths
        if config.parallel_agents > 1:
            # In parallel mode, only check that some workspace files appear.
            # Not all agents may have audit events collected due to checkpoint timing.
            expected_files = ["shared_input.txt"]
        else:
            expected_files = ["input_a.txt", "input_b.txt", "generated.txt", "result.json"]
        for expected in expected_files:
            if not any(p.endswith(expected) for p in all_audit_paths):
                failures.append(f"API events missing file: {expected}")

        # --- Check 5: events are attributed to tool spans ---
        attributed = [e for e in api_events if e.span_id and e.attribution_kind is not None]
        if not attributed:
            failures.append("No events have tool attribution (span_id + attribution_kind)")
        else:
            distinct_spans = {e.span_id for e in attributed}
            logger.info(
                "%d attributed events across %d distinct tool spans",
                len(attributed),
                len(distinct_spans),
            )
            if len(distinct_spans) < config.min_distinct_tool_spans:
                failures.append(
                    f"Expected >= {config.min_distinct_tool_spans} distinct tool spans, got {len(distinct_spans)}"
                )

        # --- Check 6: query by span_id filter works ---
        if attributed:
            test_span_id = attributed[0].span_id
            span_resp = await client.get_audit_events(session_id, span_id=test_span_id)
            if not span_resp.events:
                failures.append(f"Filtering by span_id={test_span_id} returned no events")
            else:
                bad = [e for e in span_resp.events if e.span_id != test_span_id]
                if bad:
                    failures.append(f"span_id filter returned {len(bad)} events with wrong span_id")
                logger.info("span_id filter: %d events for span %s", len(span_resp.events), test_span_id)

        # --- Check 7: query by path filter works ---
        path_filter = "/data/shared_input.txt" if config.parallel_agents > 1 else "/data/input_a.txt"
        path_resp = await client.get_audit_events(session_id, path=path_filter)
        if not path_resp.events:
            failures.append(f"Filtering by path={path_filter} returned no events")
        else:
            bad = [e for e in path_resp.events if e.path != path_filter]
            if bad:
                failures.append(f"Path filter returned {len(bad)} events with wrong path")
            logger.info("Path filter: %d events for %s", len(path_resp.events), path_filter)

        # --- Check 8: query by ref_public_id filter works ---
        if ref_ids_in_events:
            test_ref = next(iter(ref_ids_in_events))
            ref_resp = await client.get_audit_events(session_id, ref_public_id=test_ref)
            if not ref_resp.events:
                failures.append(f"Filtering by ref_public_id={test_ref} returned no events")
            else:
                bad = [e for e in ref_resp.events if e.ref_public_id != test_ref]
                if bad:
                    failures.append(f"ref_public_id filter returned {len(bad)} events with wrong ref")
                logger.info("ref_public_id filter: %d events for ref %s", len(ref_resp.events), test_ref)

        # --- Check 9: audit summary ---
        summary = await client.get_audit_summary(session_id)
        if not summary.entries:
            failures.append("Audit summary returned no entries")
        else:
            total_from_summary = sum(e.total_events for e in summary.entries)
            logger.info("Audit summary: %d entries, %d total events", len(summary.entries), total_from_summary)
            for entry in summary.entries:
                logger.info(
                    "  tool=%s ops=%s total=%d",
                    entry.tool_name,
                    dict(entry.operation_counts),
                    entry.total_events,
                )

        # --- Check 10: parallel reads (if enabled) ---
        if config.test_parallel_reads:
            failures.extend(_validate_parallel_reads_api(api_events))

        # --- Check 11: Read/Write tool attribution (if required) ---
        if config.require_read_write_attribution:
            from collections import Counter

            tool_name_counts = Counter(e.tool_name for e in api_events)
            logger.info("Audit event tool_name distribution: %s", dict(tool_name_counts))

            # Read and Write/Bash tools must all appear in audit attribution.
            # This catches the intermittent bug where only Bash gets attribution.
            for required_tool in ("Read", "Write", "Bash"):
                if required_tool not in tool_name_counts:
                    failures.append(
                        f"Tool '{required_tool}' has no audit event attribution (got: {dict(tool_name_counts)})"
                    )
                else:
                    logger.info(
                        "  tool=%s has %d attributed audit events",
                        required_tool,
                        tool_name_counts[required_tool],
                    )

    return failures


def _validate_parallel_reads_api(api_events: list[AuditEventResponse]) -> list[str]:
    """Validate parallel read files appear in API events with attribution."""
    failures: list[str] = []
    parallel_files = ["parallel_1.txt", "parallel_2.txt", "parallel_3.txt"]

    for pf in parallel_files:
        pf_events = [e for e in api_events if e.path.endswith(pf)]
        if not pf_events:
            failures.append(f"Parallel file {pf} has no audit events in API")
            continue
        attributed = [e for e in pf_events if e.span_id and e.attribution_kind is not None]
        if not attributed:
            failures.append(f"Parallel file {pf} has events but none are attributed")

    # Check that parallel files map to distinct spans (agent ran them in parallel)
    parallel_spans: set[str] = set()
    for pf in parallel_files:
        for e in api_events:
            if e.path.endswith(pf) and e.span_id:
                parallel_spans.add(e.span_id)
    if len(parallel_spans) >= 2:
        logger.info("Parallel reads: %d distinct spans for parallel files", len(parallel_spans))
    else:
        logger.warning(
            "Parallel reads: only %d span(s) — agent may have read sequentially",
            len(parallel_spans),
        )

    return failures
