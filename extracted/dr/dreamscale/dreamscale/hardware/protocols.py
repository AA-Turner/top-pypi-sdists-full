"""Hardware seams. Real devices implement these; tests use dreamscale.hardware.fake."""

from __future__ import annotations

from typing import Protocol, runtime_checkable

import numpy as np


@runtime_checkable
class RobotInterface(Protocol):
    """An SO-101-shaped arm: 6 joints (order dreamscale.constants.JOINT_NAMES, degrees;
    gripper joint in lerobot's 0–100 range) plus side and wrist cameras."""

    def connect(self) -> None: ...
    def disconnect(self) -> None: ...
    def is_calibrated(self) -> bool: ...
    def read_joint_positions(self) -> list[float]: ...
    def capture_frame(self) -> np.ndarray: ...
    def capture_frames(self) -> dict[str, np.ndarray]: ...
    def send_joint_targets(self, targets: list[float]) -> None: ...
    def calibrate(self) -> None: ...


@runtime_checkable
class CameraProber(Protocol):
    def list_cameras(self, max_index: int = 6) -> list[int]: ...
    def capture_preview(self, index: int) -> np.ndarray | None: ...
