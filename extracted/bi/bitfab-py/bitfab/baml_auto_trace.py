from __future__ import annotations

import contextlib
import contextvars
import functools
import inspect
import sys
import threading
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from typing import Any

from bitfab import subtree
from bitfab.client_patching import (
    NODE_OMITS_CALL,
    NODE_RECORDS_CALL,
    PatchingFinder,
    renamed,
    take_node_ownership,
)

BAML_GENERATED_HEADER = "This file was generated by BAML"
BAML_CLIENT_CLASSES = ("BamlAsyncClient", "BamlSyncClient")
BAML_CLIENT_MODULES = frozenset({"async_client", "sync_client"})
BAML_OPTIONS_PARAMETER = "baml_options"
PATCHED_MARKER = "_bitfab_baml_auto_traced"
BAML_CALL_MARKER = "_bitfab_baml_call"

_lock = threading.Lock()
_wrapper_call: contextvars.ContextVar[WrapperCall | None] = contextvars.ContextVar(
    "bitfab_baml_wrapper_call", default=None
)
_generated_by_filename: dict[str, bool] = {}


def _is_generated(module: Any) -> bool:
    filename = getattr(module, "__file__", None)
    if not filename:
        return False
    cached = _generated_by_filename.get(filename)
    if cached is not None:
        return cached
    try:
        with open(filename, encoding="utf-8") as source:
            generated = BAML_GENERATED_HEADER in source.read(4096)
    except OSError:
        generated = False
    _generated_by_filename[filename] = generated
    return generated


def _takes_baml_options(method: Any) -> bool:
    try:
        return BAML_OPTIONS_PARAMETER in inspect.signature(method).parameters
    except (TypeError, ValueError):
        return False


@dataclass
class WrapperCall:
    collector: Any
    recorded: bool = False


@contextlib.contextmanager
def wrapper_call(collector: Any) -> Iterator[WrapperCall]:
    call = WrapperCall(collector)
    token = _wrapper_call.set(call)
    try:
        yield call
    finally:
        _wrapper_call.reset(token)


def mark_recorded(collectors: list[Any]) -> None:
    call = _wrapper_call.get()
    if call is not None and any(c is call.collector for c in collectors):
        call.recorded = True


def _recorded_call(
    name: str, span_name: str, original: Callable[..., Any]
) -> Callable[..., Any] | None:
    session = subtree.current_session()
    owner = getattr(session, "owner", None)
    ownership = take_node_ownership()
    if session is None or owner is None or ownership == NODE_OMITS_CALL:
        return None
    if ownership == NODE_RECORDS_CALL:
        return owner._baml_auto_run(span_name, original)
    if name in session.exclude:
        return None
    if not subtree.admits_discovered_call(session, span_name):
        return None
    return owner._baml_auto_traced_call(span_name, original)


def _patched_method(cls: type, name: str, original: Callable[..., Any]) -> Any:
    span_name = f"{cls.__name__}.{name}"

    if inspect.iscoroutinefunction(original):

        @functools.wraps(original)
        async def async_patched(self: Any, *args: Any, **kwargs: Any) -> Any:
            recorded = _recorded_call(name, span_name, original)
            if recorded is None:
                return await original(self, *args, **kwargs)
            return await recorded(self, *args, **kwargs)

        return renamed(async_patched, name, BAML_CALL_MARKER)

    @functools.wraps(original)
    def sync_patched(self: Any, *args: Any, **kwargs: Any) -> Any:
        recorded = _recorded_call(name, span_name, original)
        if recorded is None:
            return original(self, *args, **kwargs)
        return recorded(self, *args, **kwargs)

    return renamed(sync_patched, name, BAML_CALL_MARKER)


def _patch_class(cls: type) -> None:
    if cls.__dict__.get(PATCHED_MARKER) is True:
        return
    for name, attribute in list(vars(cls).items()):
        if name.startswith("_") or not inspect.isfunction(attribute):
            continue
        if not _takes_baml_options(attribute):
            continue
        setattr(cls, name, _patched_method(cls, name, attribute))
    setattr(cls, PATCHED_MARKER, True)


def _is_generated_client_class(cls: type) -> bool:
    return cls.__name__ in BAML_CLIENT_CLASSES and _is_generated(
        sys.modules.get(cls.__module__)
    )


def resolve_call_target(fn: Any) -> Any:
    if getattr(fn, BAML_CALL_MARKER, False) is True:
        return fn
    client = getattr(fn, "__self__", None)
    function = getattr(fn, "__func__", None)
    if client is None or function is None:
        return None
    cls = type(client)
    if not _is_generated_client_class(cls):
        return None
    with _lock:
        _patch_class(cls)
    patched = getattr(cls, function.__name__, None)
    if getattr(patched, BAML_CALL_MARKER, False) is not True:
        return None
    return patched.__get__(client, cls)


def _unpatched_client_classes() -> list[type]:
    classes = []
    for name, module in list(sys.modules.items()):
        if module is None or name.rsplit(".", 1)[-1] not in BAML_CLIENT_MODULES:
            continue
        for class_name in BAML_CLIENT_CLASSES:
            cls = getattr(module, class_name, None)
            if inspect.isclass(cls) and cls.__dict__.get(PATCHED_MARKER) is not True:
                classes.append(cls)
    return classes


def instrument_loaded_clients() -> None:
    classes = _unpatched_client_classes()
    if not classes:
        return
    with _lock:
        for cls in classes:
            if _is_generated_client_class(cls):
                _patch_class(cls)


def _patch_module(module: Any) -> None:
    for class_name in BAML_CLIENT_CLASSES:
        cls = getattr(module, class_name, None)
        if not inspect.isclass(cls) or not _is_generated_client_class(cls):
            continue
        with _lock:
            _patch_class(cls)


_finder = PatchingFinder(
    lambda fullname: fullname.rsplit(".", 1)[-1] in BAML_CLIENT_MODULES,
    _patch_module,
)


def install_import_hook() -> None:
    _finder.install()


def collectors_in(options: Any) -> list[Any]:
    if not isinstance(options, dict):
        return []
    collector = options.get("collector")
    if collector is None:
        return []
    return list(collector) if isinstance(collector, (list, tuple)) else [collector]


def client_options(client: Any) -> dict[str, Any]:
    manager = getattr(client, f"_{type(client).__name__}__options", None)
    options = getattr(manager, "_DoNotUseDirectlyCallManager__baml_options", None)
    return options if isinstance(options, dict) else {}


def with_collector(
    client: Any,
    original: Callable[..., Any],
    args: tuple[Any, ...],
    kwargs: dict[str, Any],
    collector: Any,
) -> tuple[tuple[Any, ...], dict[str, Any], list[Any]]:
    bound = inspect.signature(original).bind(client, *args, **kwargs)
    caller_options = bound.arguments.get(BAML_OPTIONS_PARAMETER)
    caller_collectors = collectors_in(caller_options)
    existing = caller_collectors or collectors_in(client_options(client))
    with subtree.uncaptured():
        tracked = client.with_options(collector=[*existing, collector])
    bound.arguments["self"] = tracked
    if caller_collectors and isinstance(caller_options, dict):
        bound.arguments[BAML_OPTIONS_PARAMETER] = {
            key: value for key, value in caller_options.items() if key != "collector"
        }
    return bound.args, bound.kwargs, existing
