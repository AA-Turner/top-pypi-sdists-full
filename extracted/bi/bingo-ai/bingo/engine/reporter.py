def save_report(target: str, content: str) -> Path:
    """Save report as both .md and .html."""
    import platform
    safe_target = target.replace("https://", "").replace("http://", "").replace("/", "_")[:40]
    if platform.system() == "Darwin":
        base = Path.home() / "Desktop" / "dump" / safe_target
    else:
        base = Path.home() / ".bingo" / "reports" / safe_target
    base.mkdir(parents=True, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    md_path = base / f"report_{safe_target}_{ts}.md"
    md_path.write_text(content, encoding="utf-8")
    return md_path


