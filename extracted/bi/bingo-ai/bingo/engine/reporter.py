"""Reporter — generates findings report in MD + HTML.

No model text used. Only FindingsExporter's confirmed/probable/potential items.
HTML uses dark cyber theme for easy visual review.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path
from html import escape


def _severity_color(severity: str) -> str:
    return {
        "CRITICAL": "#ff1744",
        "HIGH": "#ff6d00",
        "MEDIUM": "#ffd600",
        "LOW": "#00e5ff",
    }.get(severity.upper(), "#aaaaaa")


def _severity_badge(severity: str) -> str:
    color = _severity_color(severity)
    return f'<span style="background:{color};color:#000;padding:2px 8px;border-radius:4px;font-weight:bold;font-size:12px">{escape(severity)}</span>'


def generate_report(target: str, findings_exporter, lang: str = "en") -> str:
    """Generate a markdown report from the findings exporter."""
    findings = getattr(findings_exporter, "_findings", [])
    confirmed = [f for f in findings if f.confirmed]
    probable = [f for f in findings if not f.confirmed and f.confidence == "probable"]
    potential = [f for f in findings if not f.confirmed and f.confidence == "potential"]

    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [
        f"# Bingo Penetration Test Report",
        f"",
        f"**Target**: {target}",
        f"**Date**: {now}",
        f"**Engine**: v7 (executor-owned)",
        f"",
        f"## Summary",
        f"",
        f"| Category | Count |",
        f"|----------|-------|",
        f"| Confirmed | {len(confirmed)} |",
        f"| Probable | {len(probable)} |",
        f"| Potential | {len(potential)} |",
        f"",
    ]

    all_active = confirmed + probable + potential
    gao_wei = [f for f in all_active if f.severity.upper() in ("CRITICAL", "HIGH")]
    zhong_wei = [f for f in all_active if f.severity.upper() == "MEDIUM"]
    di_wei = [f for f in all_active if f.severity.upper() == "LOW"]

    if gao_wei or zhong_wei or di_wei:
        lines.append(f"| 高危 (CRITICAL/HIGH) | {len(gao_wei)} |")
        lines.append(f"| 中危 (MEDIUM) | {len(zhong_wei)} |")
        lines.append(f"| 低危 (LOW) | {len(di_wei)} |")
        lines.append("")

    def _render_finding(f) -> None:
        tier_label = "Confirmed" if f.confirmed else f.confidence.capitalize()
        lines.append(f"### [{f.severity}] {f.vuln_type} — {f.id}  `{tier_label}`")
        lines.append(f"- **Evidence**: {f.evidence[:500]}")
        lines.append(f"- **Payload**: `{f.payload[:200]}`")
        lines.append(f"- **Reason**: {f.reason_code}")
        lines.append("")

    if gao_wei:
        lines.append("## 高危 (CRITICAL / HIGH)\n")
        for f in gao_wei:
            _render_finding(f)

    if zhong_wei:
        lines.append("## 中危 (MEDIUM)\n")
        for f in zhong_wei:
            _render_finding(f)

    if di_wei:
        lines.append("## 低危 (LOW)\n")
        for f in di_wei:
            _render_finding(f)

    if not all_active:
        lines.append("## No Findings")
        lines.append("")
        lines.append("No vulnerabilities were detected during this assessment.")
        lines.append("")

    lines.append("---")
    lines.append("*Report generated by Bingo v7 engine — executor-observed evidence only.*")

    return "\n".join(lines)


