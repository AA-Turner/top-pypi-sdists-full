_ZH = {k: zh for k, zh, en in _MAP}
_EN = {k: en for k, zh, en in _MAP}
# longest-key-first so phrases replace before their component tokens
_ORDER = sorted({k for k, _z, _e in _MAP}, key=len, reverse=True)


def localize_log(msg: str, lang: str) -> str:
    """Translate Hangul substrings in a progress line to lang (zh/en).

    Korean (``ko``) and any language without a table returns unchanged.
    Only Hangul is touched, so dynamic values and Rich markup survive.
    """
    if not msg or lang == "ko" or not _HANGUL.search(msg):
        return msg
    table = _ZH if lang == "zh" else _EN if lang == "en" else None
    if table is None:
        return msg
    for k in _ORDER:
        if k in msg:
            msg = msg.replace(k, table[k])
    return msg

